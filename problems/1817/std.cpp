// 一本通 1817《染色游戏》标程（C++17，stdin -> stdout）
//
// ============================ 参考来源（联网检索） ============================
// 本题按任务书要求先联网检索 C++ 解法（搜狗「一本通 1817 染色游戏 题解」首条即中）：
//   [1] https://blog.csdn.net/weixin_44346868/article/details/103603689
//       《染色游戏's 题解》—— 文首明确标注「来自 信息学奥赛一本通T1817」，题面与本题逐字一致。
//       结论：设 d_v 为点 v 的度数，sum = Σ_{v∈蓝} d_v - Σ_{v∈红} d_v，
//       答案 = (sum >> 1) + (n & 1)；双方最优策略均为「每步取当前度数最小的未染色点」，
//       故度数升序排序后 Alice 取第 1,3,5,... 个、Bob 取第 2,4,6,... 个。
//       该文代码与本标程同构（排序 + 交替加减 + (sum>>1)+(n&1)）。
//       样例 1（n=4 星）-> 1、样例 2（n=5 星）-> -1 均吻合（本机实测见 gen-report.md）。
// 来源唯一，且与题面两组样例一致，无冲突；未再检索到其他独立题解。
// =============================================================================
//
// 推导（用于复核，非盲抄；小例手验见 gen-report.md）：
//   K_A = n_A - e_A，K_B = n_B - e_B（连通块数 = 块内点数 - 块内边数），
//   于是 K_A - K_B = (n_A - n_B) + (e_B - e_A) = (n mod 2) + (e_B - e_A)。
//   对每条边：两端同蓝贡献 +2、同红贡献 -2、异色贡献 0（双重计数），
//   即 2(e_B - e_A) = Σ_{v∈B} d_v - Σ_{v∈A} d_v = sum。
//   又 sum = 2(n-1) - 2Σ_{v∈A} d_v，故 Alice 等价于最小化自己点集的度数和，
//   Bob 同理最小化自己点集的度数和：两人对同一组数「都抢小值」轮流取数，
//   贪心（每步取最小）最优（归纳/交换论证：先取最大者不劣，得先手取奇数位、
//   后手取偶数位之和），故升序排序后按下标奇偶交替加减。
//
// 题面数据范围：N ≤ 100000（40% N ≤ 20；另有 10% 保证是链）。限制 1000 ms / 256 MB。
// 复杂度 O(n log n)。|sum| ≤ 2(n-1) ≤ 2·10^5，int 足够，此处仍用 long long。
//
// 注意：题面【输入】写「接下来 N 行」为笔误——N 个点的树只有 N-1 条边，
//       题面两组样例均为 N-1 行，标程按样例读 N-1 条边（详见 gen-report.md 风险点）。

#include <cstdio>
#include <vector>
#include <algorithm>
using namespace std;

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;
    vector<int> deg(n + 1, 0);
    for (int i = 0; i < n - 1; ++i) {
        int u, v;
        scanf("%d %d", &u, &v);
        ++deg[u];
        ++deg[v];
    }
    sort(deg.begin() + 1, deg.end());          // 升序：deg[1] <= ... <= deg[n]
    long long sum = 0;
    for (int i = 1; i <= n; ++i)
        sum += (i & 1) ? -deg[i] : deg[i];     // Alice（先手）取奇数位：减；Bob 取偶数位：加
    printf("%lld\n", sum / 2 + (n & 1));       // sum 恒为偶数，整除无误差
    return 0;
}
