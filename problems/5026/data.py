#!/usr/bin/env python
# -*- coding: utf-8 -*-
#
# 一本通 2024《【例4.10】末两位数》分层数据生成器（cyaron）
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py、staging/2070/data.py
#
# 题意：输入 n，输出 n 个 1992 的乘积的末两位数。
# 数据范围（官方题面【提示】）：n < 2000，即 n ∈ [1, 1999]（本题输入只有一个整数 n）。
# 限制：time 1000 ms / memory 64 MB —— 规模极小，std 为 O(n) 单循环，无压力。
#
# 答案序列性质（用于设计极端数据）：
#   1992^n mod 100 的周期为 20（92^k mod 100 周期 20），末两位可能取值
#   {4,8,12,16,24,28,32,36,44,48,52,56,64,68,72,76,84,88,92,96}；
#   - 值恒为 4 的倍数（gcd(1992,100)=4），**永远不可能为 0 或 1**：
#     所以题面语境下"答案为 0/1 的极端"不存在，本题的答案极值是 4（理论最小）
#     与 96（理论最大），且 4、8 会退化成一个十进制位（末两位数字串是 "04"/"08"）。
#   - 首位出现 4 的 n：14、34、…、1994；首位出现 8 的 n：11、31、…、1991。
#
# 分层表（10 组，单组输入题：一个测试点 = 一个 n；每层从最小铺到顶格）：
#   点 1      边界层：n = 1（最小输入，答案 92）
#   点 2      边界层：n = 2（最小非平凡输入，答案 64）
#   点 3      小规模：n = 3（题面样例，答案 88，可手算）
#   点 4      小规模随机：n ∈ [4,13]，可手算验证
#   点 5      中等规模随机：n ∈ [40,120]（多个完整周期，范围中间档）
#   （点 4/5/7 的随机抽取避开已被固定点用过的答案值，使 10 个点的答案值尽量分散）
#   点 6      中等规模结构：n = 111（中档 + 前导零陷阱：答案 8，末两位数字串为 "08"）
#   点 7      大规模随机：n ∈ [500,1900]（接近上限随机）
#   点 8      大规模结构：n = 1984（上限邻域 + 答案最大值 96）
#   点 9      顶格层：n = 1999（n<2000 的最大合法输入，答案 28）
#   点 10     顶格层：n = 1994（上限邻域最坏结构：答案 4 = 理论最小值，且退化为一位数 "04"）

from cyaron import *  # 引入CYaRon的库

import random

random.seed(2024)  # 固定种子，便于复现

MAXN = 1999  # n < 2000，合法输入上确界


def gen_case(i, n, note):
    """写出第 i 组：输入 n，输出由 std 生成的末两位数。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(n)
    io.output_gen("../std")
    print("problem%d: n=%d -- %s" % (i, n, note))


# ---- 点 1-2：边界层（最小输入 / 最小非平凡输入）----
gen_case(1, 1, "边界层：最小输入 n=1，答案 92（1992 本身）")

gen_case(2, 2, "边界层：最小非平凡输入 n=2，答案 64（1992*1992=3968064）")

# 已由固定点覆盖的答案（92/64/88/8/96/28/4）；随机点在抽取时避开它们，
# 使 10 个测试点在「答案值」维度上的覆盖尽量分散（每个周期 20 个可能值）。
USED_ANSWERS = {92, 64, 88, 8, 96, 28, 4}


def rand_n_avoiding_used(lo, hi):
    """在 [lo,hi] 内随机抽 n，要求答案值未被占且未重复；入池后返回 n。"""
    while True:
        n = random.randint(lo, hi)
        v = pow(1992, n, 100)
        if v not in USED_ANSWERS:
            USED_ANSWERS.add(v)
            return n


# ---- 点 3-4：小规模（题面样例 + 10 个周期内的随机，均可手算）----
gen_case(3, 3, "小规模：题面样例 n=3 -> 88（1992^3=7904383488）")

n4 = rand_n_avoiding_used(4, 13)
gen_case(4, n4, "小规模随机：n ∈ [4,13]（覆盖第一个乘法周期的其余取值，可手算验证）")

# ---- 点 5-6：中等规模随机 + 中档前导零结构 ----
n5 = rand_n_avoiding_used(40, 120)
gen_case(5, n5, "中等规模随机：n ∈ [40,120]（覆盖两个以上完整周期，范围中间档）")

# 点 6：n=111 = 11 + 5*20，答案 8 —— 末两位数字串为 "08"，
# 是"输出是否补前导零"这一语义陷阱在中档规模上的代表数据（与点 10 的高位呼应）。
gen_case(6, 111, "中等规模结构：n=111（同周期位置 11），答案 8，末两位数字串 \"08\"（前导零陷阱）")

# ---- 点 7-8：大规模随机 + 上限邻域答案极值 ----
n7 = rand_n_avoiding_used(500, 1900)
gen_case(7, n7, "大规模随机：n ∈ [500,1900]（接近上限随机）")

# 点 8：n=1984 = 4 + 99*20，答案 96 —— 答案理论上界，考察接近上限时的大数取模是否稳定。
gen_case(8, 1984, "大规模结构：n=1984（上限邻域，答案 96 = 理论最大值）")

# ---- 点 9-10：顶格层（最大合法输入 + 上限邻域最坏退化结构）----
gen_case(9, MAXN, "顶格层：n=1999（n<2000 的最大合法输入，答案 28）")

# 点 10：n=1994 = 14 + 99*20，答案 4 —— 答案理论最小值，且末两位数字串 "04" 退化为
# 一个十进制位；这是"补零 / 定宽输出"语义最坏的一组数据（与点 6 的 8 成对覆盖）。
gen_case(10, 1994, "顶格层：n=1994（上限邻域最坏结构，答案 4 = 理论最小值，末两位串 \"04\" 退化一位）")
