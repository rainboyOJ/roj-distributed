// 一本通 2024《【例4.10】末两位数》标程（目标 ROJ 题号 5026）
// ---------------------------------------------------------------------------
// 题意：求 n 个 1992 的乘积的末两位数。输入一行整数 n，输出该乘积的末两位数。
//       官方题面（原站页，已实测核对题意/样例/范围）：n<2000，输入样例 3 -> 输出 88。
//
// 做法（同余定理 / 幂取模递推）：
//       (a*b) % m = (a%m * b%m) % m，故 1992^n % 100 可以每步只保留末两位：
//           res = 1;  for (i = 1..n) res = res * 1992 % 100;   输出 res。
//       中间结果恒 < 100*1992，int 足够；复杂度 O(n)，n<2000 时瞬间完成。
//
// 输出语义（前导零 / 定宽）：**按整数输出，不补前导零**。
//       n=11 时 1992^11 = 1959668785170020262049860833570193408，末两位数字串为 "08"，
//       但题面只写「如题述的末两位数」（输出一个数），且所查全部独立来源的 AC 代码
//       均为 `cout << res` / `printf("%d", ans)`（无 %02d / setw(2) / setfill 用法），
//       故本标程按整数输出 8。（该分歧已在 gen-report.md「风险点」中明确记录。）
//
// 参考来源 URL（网络检索本题 C++ 解法，多来源结论互通，无冲突；代码为本包自写，
// 只保留「每步对 100 取模」的核心语义）：
//   [1] https://blog.csdn.net/lq1990717/article/details/120972915
//       《信息学奥赛一本通 2024：【例4.10】末两位数》—— 给出三种解法（迭代 / 递推 /
//       递归），核心均为 res = (res * 1992) % 100，输出用 cout << res（未补零）。
//   [2] https://blog.csdn.net/dllglvzhenfeng/article/details/141176059
//       《3178：练29.2 末两位数》（同题练习，编程启蒙版）—— 三种实现，
//       其中一版 printf("%d", ans)，同样不补零。
//   [3] https://blog.csdn.net/lvcheng0309/article/details/116718804
//       《信息学奥赛一本通（2024：【例4.10】末两位数）》—— C 语言参考代码，取模 100。
//   [4] 官方题面 / 限制核对（原站页，n<2000，样例 3 -> 88，time 1000 ms / 65536 KB）：
//       http://ybt.ssoier.cn:8088/problem_show.php?pid=2024
// ---------------------------------------------------------------------------
#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;

    int res = 1;                        // 乘法单位元（n=0 的空乘积约定，官方范围 n>=1 不会出现）
    for (int i = 1; i <= n; ++i) {
        res = res * 1992 % 100;         // 同余定理：末两位只依赖上一次的末两位
    }

    printf("%d\n", res);                // 按整数输出末两位数，不补前导零
    return 0;
}
