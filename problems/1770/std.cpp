// 一本通 1770《跳跳棋》标程
//
// 来源说明：本题（一本通·高手训练篇·动态规划·1770）在网络上未检索到公开题解
// （已用题面特征句在 Bing / CSDN 站内 / 博客园方向多次精确检索，均无结果，
//   详见 gen-report.md 的“检索记录”一节），故本标程为**自研**，
// 依据题面规则从零推导博弈模型，并用题面两组样例（6 / 47）验证。
//
// ---------------------------------------------------------------------------
// 规则梳理与模型推导
// ---------------------------------------------------------------------------
// 棋盘 n 行 m 列。Alice 在第 1 行某列放下棋子（付该格数字），随后每轮：
//   ① Bob 可在任意一对上下相邻格之间造墙（一轮可造多堵），但必须保证
//      “Alice 当前所在格仍与第 n 行连通”；墙只挡上下走，不挡左右走。
//   ② Alice 上下左右走一步（撞墙不可走），付新格子的数字；若走到第 n 行结束。
// Alice 最小化罚分，Bob 最大化罚分。
//
// 关键事实：
//   * 行内左右移动永不被墙阻挡，故同一行内任意两列互通。
//   * 记 f[i][j] = Alice 位于 (i,j)（该格数字已付）时，此后还需付出的罚分
//     （双方最优）。则 f[n][*] = 0。
//   * 令 T[c] = a[i+1][c] + f[i+1][c]，表示“在 (i,c) 向下走一格”的总代价
//     （落格数字 + 之后的最优代价）。第 i 行的问题化为：
//       一维 m 个格子，走一步付 a[i][k]，走到 c 可“离开”并付 T[c]。
//
//   * 在 (i,j) 处，Bob 的最优策略是：把 Alice 当前列下方的竖边堵上
//     （不堵则 Alice 可立刻以 T[j] 离开，这对 Bob 不利；留下别的列开口）。
//     于是 Alice 被迫在该行内走动；Bob 每轮堵住她刚踏上的新列。
//     因此 Alice 必须把某一段连续列区间扫完（除最后一个），最后在
//     “唯一还没被堵”的那一列离开。又因 Alice 行走使访问过的列始终构成
//     一个连续区间，最后剩下的一列必是 Bob 留下的列集合的两个端点之一。
//   * Bob 留下开口列集合 S，只有 min(S)、max(S) 影响结果（中间列 Bob 一律
//     随走随堵，不会影响结局）——等价于 Bob 选择区间 [l,r] ⊇ {j}，迫使 Alice
//     在 [l,r] 内做一次“扫荡”：
//        · 若 l<j<r：Alice 可先走到左端 l 再折返到 r（在 r 离开），或
//          先到右端 r 再折返到 l（在 l 离开），她取较小的那个：
//            V = min( 左-右: (sum_{k=l}^{j-1}a[k]) + (sum_{k=l+1}^{r}a[k]) + T[r],
//                     右-左: (sum_{k=j+1}^{r}a[k]) + (sum_{k=l}^{r-1}a[k]) + T[l] )
//        · 若 l=j：起点列被 Bob 立刻堵死，只能向右扫到 r：
//            V = (sum_{k=j+1}^{r}a[k]) + T[r]
//        · 若 r=j：同理只能向左扫到 l：
//            V = (sum_{k=l}^{j-1}a[k]) + T[l]
//     Bob 选区间 [l,r] 使 V 最大，故
//        f[i][j] = max_{l<=j<=r} V(l,r,j)   （含 l=r=j 的退化情形 T[j]）
//   * 答案 = min_j ( a[1][j] + f[1][j] )；n=1 时 Alice 一开始就在第 n 行，
//     答案 = min_j a[1][j]。
//
// 复杂度：每组数据 O(n*m^3/6)，n,m<=100、T<=10 时约 1.7e8 次简单运算，可过。
//
// 样例校验（见 gen-report.md）：样例1 -> 6，样例2 -> 47，均与题面一致。
//   （对照：若误用“Bob 只留一列”的朴素 max_c(walk+T) 写法，样例2 会得到 36，
//     故本模型并非朴素写法；样例2 的 47 是判别正误的关键。）
// ---------------------------------------------------------------------------
#include <cstdio>
#include <algorithm>

typedef long long ll;

const int MAXN = 105;   // 题面上限 n,m<=100，留安全余量

int n, m;
ll a[MAXN][MAXN];
ll f[MAXN][MAXN];       // f[i][j]: (i,j) 之后 Alice 还需付的最小罚分
ll S[MAXN];             // 第 i 行的前缀和
ll T[MAXN];             // T[c] = a[i+1][c] + f[i+1][c]

int main()
{
    int TC;
    if (scanf("%d", &TC) != 1) return 0;
    while (TC--) {
        scanf("%d %d", &n, &m);
        for (int i = 1; i <= n; i++)
            for (int j = 1; j <= m; j++)
                scanf("%lld", &a[i][j]);

        if (n == 1) {                       // Alice 一开始已在第 n 行
            ll ans = a[1][1];
            for (int j = 2; j <= m; j++) ans = std::min(ans, a[1][j]);
            printf("%lld\n", ans);
            continue;
        }

        for (int j = 1; j <= m; j++) f[n][j] = 0;

        for (int i = n - 1; i >= 1; i--) {
            S[0] = 0;
            for (int k = 1; k <= m; k++) S[k] = S[k - 1] + a[i][k];
            for (int c = 1; c <= m; c++) T[c] = a[i + 1][c] + f[i + 1][c];

            for (int j = 1; j <= m; j++) {
                ll best = T[j];                       // 区间 [j,j]
                for (int l = 1; l <= j; l++) {
                    for (int r = j; r <= m; r++) {
                        ll val;
                        if (l == j) {
                            // 只能向右扫到 r（起点列已被堵）
                            val = (S[r] - S[l]) + T[r];
                        } else if (r == j) {
                            // 只能向左扫到 l
                            val = (S[r - 1] - S[l - 1]) + T[l];
                        } else {
                            ll v1 = (S[j - 1] - S[l - 1]) + (S[r] - S[l]) + T[r];       // 先左后右，在 r 离开
                            ll v2 = (S[r] - S[j]) + (S[r - 1] - S[l - 1]) + T[l];       // 先右后左，在 l 离开
                            val = std::min(v1, v2);
                        }
                        if (val > best) best = val;
                    }
                }
                f[i][j] = best;
            }
        }

        ll ans = a[1][1] + f[1][1];
        for (int j = 2; j <= m; j++) ans = std::min(ans, a[1][j] + f[1][j]);
        printf("%lld\n", ans);
    }
    return 0;
}
