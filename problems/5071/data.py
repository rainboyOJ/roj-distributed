#!/usr/bin/env python
# -*- coding: utf-8 -*-
#
# 一本通 2070《【例2.13】数字对调》分层数据生成器（cyaron）
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py
#
# 题意：输入三位数 n，把百位与个位对调后输出（对调后前导零不输出），题面样例 123 -> 321。
# 数据范围：题面只写"三位数"（官方 OJ 页同），本包取工作范围 100 <= n <= 999。
# 值为 0/1/2 个位、十位的情形是本题唯一的结构陷阱，因此分层把
# 「量级」与「前导零结构」交叉铺设。
#
# 分层表（10 组，单组输入题：一个测试点 = 一个三位数）：
#   点 1     边界层：n=100（最小三位数，答案 1 = 最小值，对调后退化为一位数）
#   点 2     边界层：n=999（最大三位数顶格，全相同数字，对调后不变，答案 999 = 最大值）
#   点 3     小规模随机：n=123（题面样例，可手算 -> 321）
#   点 4     小规模随机：n ∈ [100,199]（百位固定 1，可手算）
#   点 5-6   中等规模随机：点 5 n ∈ [200,599] 普通随机；
#                         点 6 十位固定 0（n = h*100+t*10+u, t=0）——中档前导零结构，
#                               答案 = u*100+h，u=0 时答案再退化为一位数
#   点 7-8   大规模随机：点 7 n ∈ [600,899] 普通随机；
#                         点 8 个位固定 0（n = h*100+t*10）——接近上限的前导零结构，
#                               答案 = t*10+h 两位数；本包取 t=9 得 96（该层答案上确界）
#   点 9     顶格层：n ∈ [900,999] 随机（贴上限随机）
#   点 10    顶格层：n=900（上限邻域最坏退化结构：个位、十位全 0，答案 9 一位数）
#
# 说明：本题输入只有一个三位数，不存在"多组数据按组数分层"，故规模分层体现为
# 数值量级（百位档位）+ 数字结构（前导零陷阱、全相同、上限邻域）。

from cyaron import *  # 引入CYaRon的库

import random

random.seed(2070)  # 固定种子，便于复现

MAX = 999  # 三位数上限
MIN = 100  # 三位数下限


def gen_case(i, n, note):
    """写出第 i 组：输入 n，输出由 std 生成的对调结果（去前导零）。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(n)
    io.output_gen("../std")
    print("problem%d: n=%d -- %s" % (i, n, note))


# ---- 点 1-2：边界层（最小 / 最大三位数，答案同时取最小 / 最大值）----
gen_case(1, MIN,
         "边界层：最小三位数 100，答案 1（对调后前导零不输出，退化为一位数，答案最小值）")

gen_case(2, MAX,
         "边界层：最大三位数 999（顶格），全相同数字，对调后不变，答案 999（答案最大值）")

# ---- 点 3-4：小规模随机（百位为 1 的档位，可手算核对）----
gen_case(3, 123,
         "小规模随机：题面样例 123 -> 321")

n4 = random.randint(100, 199)
gen_case(4, n4,
         "小规模随机：n ∈ [100,199]（百位固定 1），可手算核对")

# ---- 点 5-6：中等规模随机（百位 2~5 档位）----
n5 = random.randint(200, 599)
gen_case(5, n5,
         "中等规模随机：n ∈ [200,599] 普通随机")

# 点 6：十位固定 0 的中档前导零结构；用固定种子在 h∈[2,5]、u∈[0,9] 中抽取，
# 若 u=0 则答案退化为一位数，正是本题最需要覆盖的陷阱形态。
h6 = random.randint(2, 5)
u6 = random.randint(0, 9)
n6 = h6 * 100 + 0 * 10 + u6
gen_case(6, n6,
         "中等规模结构：十位为 0（n=%d00+%d），答案 %d*100+%d=%d，前导零陷阱" %
         (h6, u6, u6, h6, u6 * 100 + h6))

# ---- 点 7-8：大规模随机（百位 6~8 档位，接近上限）----
n7 = random.randint(600, 899)
gen_case(7, n7,
         "大规模随机：n ∈ [600,899]，接近上限")

# 点 8：个位固定 0 的大规模前导零结构，固定取 t=9（该层最大十位），
# 即 n = h*100+90，答案 = 9*10+h = 90+h，用来覆盖两位数答案的上确界形态。
h8 = random.randint(6, 8)
n8 = h8 * 100 + 9 * 10 + 0
gen_case(8, n8,
         "大规模结构：个位为 0 且十位为 9（n=%d90），答案 9*10+%d=%d（两位数）" %
         (h8, h8, 90 + h8))

# ---- 点 9-10：顶格层（贴上限随机 + 上限邻域最坏结构）----
n9 = random.randint(900, 999)
gen_case(9, n9,
         "顶格层：n ∈ [900,999] 贴上限随机")

gen_case(10, 900,
         "顶格层：上限邻域最坏退化结构——个位、十位全 0（900），答案 9（一位数）")
