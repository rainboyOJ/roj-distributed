// 一本通 2070《【例2.13】数字对调》标程（目标 ROJ 题号 5071）
// ---------------------------------------------------------------------------
// 题意：输入一个三位数 n，把它的百位数与个位数对调，输出对调后的数。
//       题面未显式给出范围，按"三位数"取 100 <= n <= 999。
//       关键点（多个来源一致确认）：对调后若最高位变成 0，则**不输出前导零**，
//       即把对调后的数按整数输出：100 -> 1，110 -> 11，120 -> 21，123 -> 321。
//       题面样例 123 -> 321。
// 做法：算术拆分三位数字 h=百位、t=十位、u=个位，重新组合为 u*100+t*10+h，
//       按整数输出，前导零由整数格式化自然消失。时间复杂度 O(1)。
// ---------------------------------------------------------------------------
// 参考来源 URL（已搜索核对，结论互通，无冲突；代码为本包自写，仅保留语义）：
//   [1] https://blog.csdn.net/lq1990717/article/details/120165368
//       信息学奥赛一本通 2070：【例2.13】数字对调。明确"题目补充：假设输入的都是
//       合法的三位整数，不会存在 001 这种；个位和百位对调后，如果数字前几位是 0，
//       那么不输出前几位的 0"，并给出整数拆分版 / 字符版两种 AC 解法。
//   [2] https://blog.csdn.net/lvcheng0309/article/details/118050762
//       C 语言参考代码 printf("%d\n", c*100+b*10+a) —— 与本标程结论一致。
//   [3] https://blog.csdn.net/qq_59918355/article/details/121844549
//       printf("%d", a + b*10 + c*100) —— 交叉印证。
//   [4] https://blog.csdn.net/flower_vegetable/article/details/118963798
//       printf("%d", a/10/10 + a/10%10*10 + a%10%10*100) —— 交叉印证。
//   [5] https://blog.csdn.net/lwx3289765163/article/details/120872737
//       讨论"个位为 0 时不能直接放到百位"的陷阱，其分支写法
//       （u!=0 -> u*100+t*10+h；u==0,t!=0 -> t*10+h；否则 h）与整数输出完全等价。
//   [6] 官方题面（核对输入输出格式与限制）：
//       http://ybt.ssoier.cn:8088/problem_show.php?pid=2070
// ---------------------------------------------------------------------------
#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;

    int h = n / 100;         // 百位
    int t = n / 10 % 10;     // 十位
    int u = n % 10;          // 个位

    // 对调百位与个位后按整数输出：最高位为 0 时前导零不显示。
    printf("%d\n", u * 100 + t * 10 + h);
    return 0;
}
