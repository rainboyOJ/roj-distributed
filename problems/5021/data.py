#!/usr/bin/env python

from cyaron import *  # 引入CYaRon的库

# 一本通 2019：【例4.4】求阶乘
# 输入：一个正整数 n（1 ≤ n ≤ 20）；输出：n!（20! = 2432902008176640000 < 2^63-1）。
#
# 输入域只有 1..20 共 20 个合法取值，每个测试点 1 组数据。按“边界 → 小规模 →
# 中等规模 → 大规模 → 顶格”分层取点，10 个点取值互不相同（可枚举域内不浪费测试点）：
#   1  : n=1      下边界，最小合法值，答案 = 1（“答案为 1”的极端）
#   2  : n=2      最小非平凡，可手算
#   3  : n=3      小规模，可手算
#   4  : n=4      小规模，题面【输入样例】取值（样例同时另行独立喂给 std 验证）
#   5  : n=6      小规模偏中（答案 720，仍在 int 范围内）
#   6  : n=10     中等规模（10! = 3628800，int 仍不溢出）
#   7  : n=13     大规模起点（13! = 6227020800 > 2^31-1，int 溢出档）
#   8  : n=16     大规模（16! 仍接近上限以内）
#   9  : n=19     顶格前一档（19! = 121645100408832000，18 位数）
#   10 : n=20     顶格层·题面上限（20! = 2432902008176640000，long long 顶格）
# 注：域内取值固定而非随机——题面输入域 20 个值可完全枚举，固定取值保证数据可复现、
# 覆盖可核对；分层的意义在该题体现在“规模分档”而非“组内随机”。

plan = [
    # (测试点, n, 设计意图)
    (1, 1, "边界层·下界：最小合法值，答案 = 1，验证循环边界与累乘初值必须为 1"),
    (2, 2, "边界层：最小非平凡输入，答案 2，可手算"),
    (3, 3, "小规模随机档：可手算（3! = 6）"),
    (4, 4, "小规模：题面【输入样例】取值，答案 24，与样例对照"),
    (5, 6, "小规模偏中：6! = 720，int 范围内，验证累乘正确性"),
    (6, 10, "中等规模：10! = 3628800，int 仍不溢出，验证中档累乘"),
    (7, 13, "大规模起点：13! = 6227020800 > 2^31-1，int 溢出档，必须 long long"),
    (8, 16, "大规模：16! = 20922789888000（14 位数），接近上限"),
    (9, 19, "顶格层·上限前一档：19! = 121645100408832000（18 位数）"),
    (10, 20, "顶格层·题面上限：20! = 2432902008176640000，long long 顶格最坏值"),
]

for i, n, why in plan:
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(n)                          # 单整数输入
    io.output_gen("../std")
    print(f"problem{i}: n={n}  # {why}")
