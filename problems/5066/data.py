# 一本通 2065《【例2.2】整数的和》数据生成器（目标 ROJ 题号 5066）
#
# 题面：输入 a、b、c 这 3 个整数（一行），输出它们的和。单组输入。
# 题面与官方题库页均**未声明数据范围**，也无特殊值声明；
# 按自定工作范围造数据并如实记录（同仓先例：problems/1000 A+B 用 1..10^6，
# staging/2068 用自定 x≤10^6）：
#     -10^6 <= a, b, c <= 10^6
# 此时 |a+b+c| <= 3*10^6，即使 a,b,c 与答案都在 int32 内；
# 本标程用 long long 读写，是 int 解的超集，对本题数据安全。
#
# 分层设计（10 个测试点，从最小铺到顶格）：
#   点 1-2  边界层：全最小值 / 全最大值（题面未声明特殊值，取自定范围两端）
#   点 3-4  小规模（可手算）：小随机 |值|<=20 / 题面【输入样例】1 2 3
#   点 5-6  中等规模随机：|值| 1e3~1e4 / 1e4~1e5，随机符号
#   点 7-8  大规模随机：|值| 1e5~5e5 / 5e5~1e6，随机符号，接近上限
#   点 9-10 顶格层：三数全取上限 +-10^6，正负相消（进位/借位最坏结构）
#           点 10 同时覆盖「答案为 0 的极端」（1e6 + (-1e6) + 0）

from cyaron import *  # 引入CYaRon的库

import random
random.seed(2065)  # 固定种子，便于复现

MAXV = 1000000  # 自定工作范围上限（题面未声明）


def signed(lo, hi):
    """返回绝对值在 [lo, hi]、随机正负的整数。"""
    return randint(lo, hi) * choice([-1, 1])


def gen(i, a, b, c, note):
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(a, b, c)
    io.output_gen("../std")
    print("problem%d: %d %d %d -- %s" % (i, a, b, c, note))


# ---- 点 1-2：边界层 ----
gen(1, -MAXV, -MAXV, -MAXV,
    "边界层：全最小值三个 -1e6，答案 -3000000")
gen(2, MAXV, MAXV, MAXV,
    "边界层：全最大值三个 +1e6，答案 3000000")

# ---- 点 3-4：小规模随机 + 题面声明值（均可手算验证） ----
gen(3, signed(1, 20), signed(1, 20), signed(1, 20),
    "小规模随机：|值|∈[1,20]，符号随机，量级小到可心算")
gen(4, 1, 2, 3,
    "小规模：题面【输入样例】1 2 3，答案 6（可手算；题面唯一声明值）")

# ---- 点 5-6：中等规模随机 ----
gen(5, signed(1000, 10000), signed(1000, 10000), signed(1000, 10000),
    "中等规模随机：|值|∈[1e3,1e4]，符号随机")
gen(6, signed(10000, 100000), signed(10000, 100000), signed(10000, 100000),
    "中等规模随机：|值|∈[1e4,1e5]，符号随机")

# ---- 点 7-8：大规模随机（接近上限） ----
gen(7, signed(100000, 500000), signed(100000, 500000), signed(100000, 500000),
    "大规模随机：|值|∈[1e5,5e5]，符号随机")
gen(8, signed(500000, MAXV), signed(500000, MAXV), signed(500000, MAXV),
    "大规模随机：|值|∈[5e5,1e6]，贴近上限，符号随机")

# ---- 点 9-10：顶格层（全部取上限，构造相消最坏结构） ----
gen(9, MAXV, MAXV, -MAXV,
    "顶格层：三数全取 |1e6|，两正一负相消，答案 1000000（进位最坏结构）")
gen(10, MAXV, -MAXV, 0,
    "顶格层：三数全取 |1e6| 上限，相消得 0（答案为 0 的极端 + 借位最坏结构）")
