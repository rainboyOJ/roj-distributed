// 一本通 2038《【例5.5】最大数位置》（目标 ROJ 题号 5040）标程
//
// 题意：输入 n 个整数，存放在数组 a[1] 至 a[n] 中，输出最大数所在位置（1-based 下标）。
//   输入：第一行，数的个数 n（n <= 1000）；第二行，n 个正整数，每个数在 2^32-1 之内。
//   输出：最大数所在位置。
//
// ── 参考来源（均经实抓正文核对，按题面语义改写，非盲抄）─────────────────
//   1. https://blog.csdn.net/lq1990717/article/details/121639224
//      《信息学奥赛一本通 2038：【例5.5】最大数位置》（君义_noip）
//      思路：设变量 mxi 表示最大值下标（初值 = 首元素下标），单遍扫描，
//            `if(a[i] > a[mxi]) mxi = i;`，循环结束后 a[mxi] 即最大值、mxi 即位置。
//      代码（原文）：int n, a[1005], mxi = 1; cin >> n; for(i=1..n) cin >> a[i];
//                    for(i=1..n) if(a[i] > a[mxi]) mxi = i; cout << mxi;
//   2. https://www.cnblogs.com/xxsy387/p/16286285.html
//      《2038：【例5.5】最大数位置》（博客园 xxsy387）
//      等价写法：先读入首个数作为当前最大值 m，d 记位置（初值 1），
//                随后边读边比：`if(t > m){ m = t; d = i; }`，最后输出 d。
//      考点总结（与来源 1 一致）：一次遍历、严格大于才更新位置。
//   3. 官方题面（题目描述/输入/输出/输入样例/输出样例/限制）
//      http://ybt.ssoier.cn:8088/problem_show.php?pid=2038
//      （实抓核对：与本目录 content.md 逐字一致；时间限制 1000 ms，内存 65536 KB）
//   4. https://blog.csdn.net/2402_84298973/article/details/146230794
//      《最大数位置（信息学奥赛一本通-2038）》（Doopny@）
//      代码：`int max_v = 0, max_id = 0; for(i=1..n){ cin >> nums[i];
//              if(nums[i] > max_v){ max_v = nums[i]; max_id = i; } } cout << max_id;`
//      —— 同样是「严格大于才更新」⇒ 多个最大值时输出**第一个**位置（tie 语义第三重佐证）。
//      注：该文用 `int` 读入，在题面上限 2^32-1 上会失败（见下「冲突与处置」）。
//   5. 搜索引擎摘要（360 搜索「最大数位置 信息学奥赛一本通-2038」结果描述，
//      https://www.so.com/s?q=%E6%9C%80%E5%A4%A7%E6%95%B0%E4%BD%8D%E7%BD%AE%20%E4%B8%80%E6%9C%AC%E9%80%9A：
//      「若最大值有多个，通常输出第一个出现的位置」），与来源 1、2、4 的语义一致。
//
// ── 来源冲突与处置（以题面为准）──────────────────────────────────────
//   冲突点：**数值类型**。来源 1（`int a[1005]`）、来源 2（`int m,t`）、来源 4（`int max_v`）
//   都用 32 位有符号 int；但题面明确写「每个数在 2^32-1 之内」，而 2^32-1 = 4294967295
//   > INT_MAX = 2147483647，用 int 读入超过 2^31-1 的数会溢出/未定义行为。按任务书要求
//   「多个来源结论冲突时以题面为准」，本标程统一用 **long long（int64）** 读入与比较，
//   覆盖题面声明的全值域。（来源代码在「值 <= 2^31-1」的实际数据上同样正确，
//   本标程是其安全放宽版；实测 int 版在本组数据的点 5/6/8/10 被判错。）
//   一致点：tie 处理（多个最大值取**最左/第一个**的位置）在来源 1、2、4、5 中一致，无歧义。
//
// ── 实现说明（相对来源的改写点）──────────────────────────────────────
//   - 单遍扫描、严格大于（`>`）才更新，故多个最大值时保留**第一个**出现的位置；
//   - 用 long long 读入每个数，兼容题面上限 2^32-1；用 `i == 1 ||` 初始化，
//     不依赖「值恒为正」的前提（题面说正整数，此处更稳健）；
//   - 仅 O(1) 额外空间（题面说"存放在数组 a[1]..a[n]"），用流式读取即可，
//     等价于先存数组再扫一遍；
//   - stdin -> stdout，scanf/printf 风格参考 problems/1000/std.cpp；输出带换行。
//
// ── 复杂度 ───────────────────────────────────────────────────────────
//   O(n) 时间、O(1) 空间；n <= 1000，远低于 1000 ms / 64 MB 限制。

#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;  // 第一行：数的个数 n

    long long best = 0;  // 当前最大值（题面值域 1..2^32-1，int64 安全）
    int pos = 1;         // 当前最大值所在位置（1-based）

    for (int i = 1; i <= n; ++i) {
        long long x;
        if (scanf("%lld", &x) != 1) return 0;  // 第二行：n 个正整数
        // 严格大于才更新 => 多个最大值时保留第一个（最左）出现的位置
        if (i == 1 || x > best) {
            best = x;
            pos = i;
        }
    }

    printf("%d\n", pos);
    return 0;
}
