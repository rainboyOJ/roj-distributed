#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2020《【例4.5】第几项》数据生成器（目标 ROJ 题号 5022）
#
# 题意：输入 m，输出最小的 n 使得 s = 1 + 2 + ... + n > m。数据范围：1 <= m <= 40000。
#   样例：m = 1000 -> 45（S_44 = 990 <= 1000 < 1035 = S_45）。
#
# 【关键结论，决定分层设计】
#   - 答案 n 的取值范围：m ∈ [1, 40000] 时，n ∈ [2, 283]。
#     S_1 = 1 <= m 恒成立（m >= 1），故 n 最小只能取到 2（答案为 0/1 在本题结构上不可能）；
#     S_283 = 40186 > 40000 >= S_282 = 39903，故 n 最大取到 283。
#   - 本题最刁的两个临界构造是**精确三角数 m = S_k**（和为 m 恰等，必须继续加下一项）：
#       m = 990  = S_44  -> 答案 45（若循环条件误写成 `sum < m` 会输出 44）
#       m = 39903 = S_282 -> 答案 283（同上，且在题面上限附近）
#   - 次临界 m = S_282 - 1 = 39902 -> 答案 282，是"答案仍为 282"的最大 m，再加 1 就跳到 283。
#
# 分层（10 个测试点，单组输入；从最小铺到顶格）：
#   点 1   边界层：m = 1（全最小值）；答案 2 即本题**可能的最小答案**
#   点 2   边界层：m = 40000（全最大值 / 题面上限）
#   点 3   小规模：m = 1000（题面【输入样例】——题面唯一声明的特殊值，可手算核对）
#   点 4   小规模·临界：m = 990 = S_44（精确三角数，专杀 sum<m / sum<=m 类 off-by-one）
#   点 5   小规模随机：m ∈ [2, 100]
#   点 6   中等规模随机：m ∈ [100, 3000]
#   点 7   中偏大规模随机：m ∈ [3000, 20000]
#   点 8   大规模随机（贴近上限）：m ∈ [20000, 39999]
#   点 9   顶格层·临界上侧：m = 39902 = S_282 − 1（答案为 282 的最大 m）
#   点 10  顶格层·极限临界：m = 39903 = S_282（最大精确三角数；和恰等于 m 必须继续 -> 283）
#
# 与任务书通用分层清单的对照（越界项如实说明，不强行凑数）：
#   - 「n=1 / n=2」：本题为**单组输入**（一个测试点一个整数 m），无数据组数可分层，不适用。
#   - 「答案为 0 或 1 的极端」：**本题结构上不存在**——m >= 1 时 S_1 = 1 永不 > m，
#     故答案恒 >= 2；改用"全局最小答案（点 1，答案 2）"与"全局最大答案（点 2/9/10，答案 283）"两端覆盖。
#   - 「有序/逆序/链/重复值」等结构项：本题输入是单个整数，无数组/序列结构可构造，不适用。
#
# 随机性：每个随机点使用独立 Random(2020 + 点号)，与调用顺序无关、逐字节可复现。

from cyaron import *  # 引入CYaRon的库

import random

M_MIN, M_MAX = 1, 40000  # 题面数据范围（content.md【提示】）

# 已生成测试点的 (m, 期望答案) 记录，用于末尾自检
_pts = []


def s_n(n):
    """等差数列前缀和 S_n = n(n+1)/2（纯整数运算，独立于 std 的累加写法）。"""
    return n * (n + 1) // 2


def expect(m):
    """按题面定义直接求答案：最小的 n 使 S_n > m。"""
    n = 1
    while s_n(n) <= m:
        n += 1
    return n


def gen(i, m, note):
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(m)
    io.output_gen("../std")
    _pts.append((i, m, expect(m)))
    print("problem%-2d: m=%-6d 期望答案=%-4d -- %s" % (i, m, expect(m), note))


def rnd(i, lo, hi):
    """按点号取独立随机数，与调用顺序无关、可精确复现。"""
    return random.Random(2020 + i).randint(lo, hi)


# ---- 点 1-2：边界层（全最小 / 全最大） ----
gen(1, M_MIN,
    "边界层：m=1（全最小值）；答案为 2，即本题可能的最小答案（n=0/1 在结构上不可能）")
gen(2, M_MAX,
    "边界层：m=40000（全最大值 = 题面上限）；S_282=39903 < 40000 < 40186=S_283")

# ---- 点 3-4：小规模（题面样例 + 精确三角数临界） ----
gen(3, 1000,
    "小规模：题面【输入样例】m=1000；S_44=990<=1000<1035=S_45 -> 45（可手算）")
gen(4, 990,
    "小规模·临界：m=990=S_44 精确三角数（和恰等于 m，必须继续加 -> 45；sum<m 写法会错得 44）")

# ---- 点 5-6：小 / 中等规模随机 ----
gen(5, rnd(5, 2, 100),
    "小规模随机：m∈[2,100]，量级小到可手算验证")
gen(6, rnd(6, 100, 3000),
    "中等规模随机：m∈[100,3000]，范围中间档")

# ---- 点 7-8：大 / 贴近上限随机 ----
gen(7, rnd(7, 3000, 20000),
    "中偏大规模随机：m∈[3000,20000]")
gen(8, rnd(8, 20000, 39999),
    "大规模随机（贴近上限）：m∈[20000,39999]")

# ---- 点 9-10：顶格层（临界构造） ----
gen(9, 39902,
    "顶格层·临界下侧：m=S_282-1=39902，是答案仍为 282 的最大 m（m+1 就跳到 283），差额仅 1")
gen(10, 39903,
    "顶格层·极限临界：m=S_282=39903 为 <=40000 的最大精确三角数，和恰等于 m 必须继续 -> 283")

# ---- 自检：取值域、答案域、临界点正确性、输出一致性 ----
# 本脚本按仓库惯例在 data/ 目录内运行（mkdir -p data && cd data && python3 ../data.py），
# 故输入/输出文件与当前目录同级。
for i, m, n in _pts:
    assert M_MIN <= m <= M_MAX, "problem%d: m=%d 越出题面范围 [1,40000]" % (i, m)
    assert 2 <= n <= 283, "problem%d: 答案 %d 越出 [2,283]（题型外）" % (i, n)
    assert s_n(n) > m and s_n(n - 1) <= m, \
        "problem%d: n=%d 不是最小满足 S_n>m 的项数" % (i, n)
    # 与生成出的 .in/.out 逐字节核对（防 output_gen 失败或错配）
    with open("problem%d.out" % i, encoding="utf-8") as f:
        got = f.read().strip()
    assert got == str(n), "problem%d: .out=%r 与期望 %d 不符" % (i, got, n)
    with open("problem%d.in" % i, encoding="utf-8") as f:
        assert f.read().strip() == str(m), "problem%d: .in 与 m=%d 不符" % (i, m)

# 临界点公式自证（解释器内独立验证设计意图，而非套用 std）
assert expect(990) == 45 and s_n(44) == 990, "m=990 的三角数临界设计有误"
assert expect(39902) == 282, "m=39902 的次临界设计有误"
assert expect(39903) == 283 and s_n(282) == 39903, "m=39903 的极限临界设计有误"
assert expect(1) == 2 and expect(40000) == 283, "两端边界设计有误"

print("自检通过：%d 个测试点均在 m∈[1,40000] 内，答案落在 [2,283]，"
      ".in/.out 与期望值逐点一致。" % len(_pts))
print("答案分布：", sorted(m for _, m, _ in _pts))
