// 一本通 2041《【例5.9】新矩阵》标程（目标 ROJ 题号 5043）
// ---------------------------------------------------------------------------
// 题意（本包 content.md；官方页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2041
// 本轮已实抓核对，题面【题目描述】【输入】【输出】【输入样例】【输出样例】与本目录
// content.md 逐字一致，页面显示「时间限制: 1000 ms 内存限制: 65536 KB」，
// 与 config.json 的 time=1000 / memory=64MB 一致）：
//   【题目描述】已知一个 n×n (2≤n≤20) 的矩阵（方阵），把矩阵二条对角线上的元素值
//               加上 10，然后输出这个新矩阵。
//   【输入】第一行为 n; 下面为一个 n×n 矩阵，矩阵中各正整数小于 100。
//   【输出】输出新的矩阵。共 n 行，每行 n 数，各数之间用一个空格隔开。
//   【输入样例】5 / 13 66 53 89 55 / ... 【输出样例】23 66 53 89 65 / ...
//
// 关键判读（本包对题面的确定性解读，依据样例逐格反推，无歧义）：
//   * 元素值域：题面写「各正整数小于 100」⇒ 1 ≤ a[i][j] ≤ 99（正整数且 < 100）。
//     本包数据严格落在此区间内（点 1 用最小值 1、点 2/8/9 用临界值 99）。
//   * 「二条对角线」= 主对角线 (i==j) 与 副对角线 (i+j==n-1, 0-indexed)。
//     两条对角线在 **n 为奇数** 时于中心格 ((n-1)/2, (n-1)/2) **重合**，
//     该格只能加一次 10 —— 样例证实：n=5 时中心 (3,3)=38 → 48（+10），
//     而不是 58（+20）。这是本题唯一且最经典的坑（来源 [1] 解法 2 专门用
//     「若该位置已有值则不再加 10」来防重复；来源 [1] 解法 1 与 [2][3] 则用
//     `i==j || i+j==n-1` 的 or 条件天然只加一次）。
//   * 输出格式：n 行、每行 n 个数、数与数之间恰一个空格。样例正文前 4 行
//     行末各带一个空格、第 5 行行末无空格（原始字节见 gen-report.md），题面
//     只说「各数之间用一个空格隔开」，故本包按题面字面取「行末不留空格」的
//     严格形态（与仓库语料惯例一致：staging/2034、2036、2053 的 std.cpp 同样
//     取无行末空格，见 gen-report.md 风险点 4）。
//
// 参考来源（网络题解，本轮均实取正文核对后按题面改写，非盲抄）：
//   [1] https://blog.csdn.net/lq1990717/article/details/122095549
//       君义_noip《信息学奥赛一本通 2041：【例5.9】新矩阵》
//       解法 1「利用二维数组中斜线上的坐标规律」：左上右下斜线行列坐标差为定值
//         （主对角线 i==j），右上左下斜线行列坐标和为定值（i+j==n+1，1-indexed）；
//         遍历时 `if (i==j || i+j==n+1) a[i][j] += 10;`。
//       解法 2「移动焦点位置，遍历对角线」：焦点 (1,1) 每次右下移一格加 10；
//         焦点 (1,n) 每次左下移一格，**加之前先判 a[i][j]==0 防重复**，再叠加输入值。
//       该文点明考点 = 二维数组 + 同一斜线上的坐标规律；两条解法都隐含「只加一次」。
//   [2] https://www.cnblogs.com/zheng1945/p/16298516.html
//       禹城我的家《2041：【例5.9】新矩阵》（博客园，本轮实取正文）
//       与 [1] 解法 1 同构：1-indexed 下 `if (i==j || i+j==n+1) a[i][j] += 10;`，
//       输出 `cout << a[i][j] << " ";`（每个元素后都跟空格，故行末带空格）。
//   [3] https://www.cfanz.cn/resource/detail/xQKwvARpMQwPp
//       ZGtheGreat《信奥赛一本通 C++题解 2041【例5.9】新矩阵》（CFANZ 编程社区，本轮实取正文，
//       正文含官方时间/内存/提交数截图文字与完整代码）
//       0-indexed 写法：`if (i==j || i+j == n-1) a[i][j] += 10;`（与 [1][2] 等价，
//       只是下标起点不同），输出同样 `cout << a[i][j] << " ";`。
//   [4] https://blog.csdn.net/lvcheng0309/article/details/116927942
//       橙子教师《信息学奥赛一本通（2041：【例5.9】新矩阵）》（CSDN 站内搜索命中的 C 参考代码，
//       本包通过 translate 代理实取正文）：`#define N 30 int a[N][N];` 的 C 写法，
//       结论同 [1][2][3]（对角线加 10、逐格输出）。
//
// 多来源结论核对（无冲突）：四个来源的算法完全一致 —— 遍历矩阵，凡落在主对角线
//   (i==j) 或副对角线 (i+j==n-1, 0-indexed) 的元素 +10，其余不动；n 为奇数时中心格
//   因 or 短路/防重复判断只加一次。差异仅在下标起点（1-indexed vs 0-indexed）与
//   行末是否多一个空格（判题器按空白容忍比较时等价）。**题面本身无歧义**（样例逐格
//   反推唯一确定"中心只加一次"与"其余格不变"），未触发任务书的「停下报告」条件。
//
// 本标程相对来源的改写点：
//   * 统一用 0-indexed（来源 [3] 的路线）+ `i==j || i+j==n-1` 的 or 判定
//     （来源 [1][2] 的判定语义），结构上与 [1] 解法 2 的「焦点移动 + 防重复」正交，
//     本包另用 work/brute.cpp 实现解法 2 的那条路线做交叉对拍（见 gen-report.md）；
//   * 输出用「先判断再输出分隔符」的写法：元素之间恰一个空格、**行末无多余空格**，
//     每行补一个 '\n'（来源 [1][2][3] 的 `cout<<a[i][j]<<" "` 会留行末空格，
//     本包取更严格形态，与题面「各数之间用一个空格隔开」的字面要求一致）；
//   * 输入容错：scanf 读到 n 且矩阵读满才处理，未读满则静默退出（题面保证不会发生）；
//     n 域外（n<1 或 n>MAXN）时不越界访问；
//   * stdin→stdout，scanf/printf 风格对齐 problems/1000/std.cpp。
// 复杂度：O(n²) 时间、O(n²) 空间；n=20 时 400 格，耗时 < 1 ms，远低于 1000 ms / 64 MB。
// ---------------------------------------------------------------------------
#include <cstdio>

const int MAXN = 25;  // 题面上限 n ≤ 20，留 5 格余量

int a[MAXN][MAXN];

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;   // 无输入：静默退出
    if (n < 1 || n > MAXN) return 0;      // 题面保证 2 ≤ n ≤ 20；域外防御，不越界

    for (int i = 0; i < n; ++i)
        for (int j = 0; j < n; ++j)
            if (scanf("%d", &a[i][j]) != 1) return 0;  // 矩阵读满才继续

    // 两条对角线：主对角线 i==j；副对角线 i+j==n-1。
    // 用 or 连写（来源 [1] 解法 1 / [2] / [3] 的判定）：n 为奇数时中心格
    // 同时满足两个条件，但因为只判断一次、只加一次 10，天然不会重复加。
    for (int i = 0; i < n; ++i)
        for (int j = 0; j < n; ++j)
            if (i == j || i + j == n - 1)
                a[i][j] += 10;

    // 输出：n 行、每行 n 个数、数与数之间恰一个空格、行末不留多余空格
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < n; ++j) {
            if (j) putchar(' ');
            printf("%d", a[i][j]);
        }
        putchar('\n');
    }
    return 0;
}
