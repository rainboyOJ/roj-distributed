// ==================== 关键语义考证：整段计费 vs 分段累加 ====================
// 题面原文：「当乘客行李小于等于20公斤时，按每公斤1.68元收费，大于20公斤时，
//            按每公斤1.98元收费」。
// 读作「整段按所属档位单价计费」：w <= 20 -> 1.68*w；w > 20 -> 1.98*w。
// 判决性证据：
//   (a) 题面**没有**「超过 20 公斤的**部分**按……」的措辞。本仓库同批语料中，
//       凡表达「超出部分另外计费」的题面都会写「……的部分」（已全库检索确认）；
//       本题用的是「按每公斤 1.98 元收费」，即整段改按新单价。
//   (b) 本轮取到的全部可读代码（来源 1、2 全文 + 来源 3-4 摘要）**无一例外**是
//       整段计费（`a*1.98`），没有任何一份写 `20*1.68+(a-20)*1.98`。
//   (c) 教材定位支持整段计费：本题是「第三章 第一节 if 选择结构」的例 3.5，
//       教学点是**单层 if-else 二分支**；分段累加会让两个分支都变成
//       「乘法 + 加法」的复合表达式，与本节例题的难度定位不符。
//   (d) 题面样例 20.00 -> 33.60：两种读法在 w=20 处取值相同（都等于 20*1.68），
//       **样例本身不能区分**这两种读法；故本包不靠样例定夺，而靠 (a)(b)(c)。
// 本包据此采用**整段计费**。该歧义已在 gen-report.md 风险点 2 明确记录。
//
// 实现说明（本标程相对来源的改写点，非盲抄）：
//   - 读入用 double（scanf "%lf"，兼容整数与小数形式的重量，与全部来源一致），
//     std->stdout，scanf/printf 风格参考 problems/1000/std.cpp。
//   - 档位判定 `w <= 20.0`（含等于），与题面「小于等于 20 公斤」逐字对应，
//     也与来源 1、2 一致；样例 20.00 -> 33.60 正是这一判定的检验点
//     （若写成 w < 20.0 会得到 39.60，与样例不符）。
//   - 输出 printf("%.2f\n")：2 位小数 + 行末单个换行（与题面【输出样例】一致）。
//     不用 cout << setprecision 是为了与仓库 1000/2071/2073 等的 cstdio 风格统一。
//   - **不加任何浮点补偿/零归一化**：经全域穷举核验（见 gen-report.md 第 5 节），
//     在本包自定工作范围（0.00 <= w <= 1000.00 公斤，2 位小数）内，
//     `printf("%.2f", (w<=20?1.68:1.98)*w)` 与精确十进制运算逐位一致
//     （唯一例外是「数学答案恰为 x.xx5」的舍入中点，属于题目本身不可判定点，
//      本包数据已用 assert 排除，见 data.py）。因此保持最朴素的官方写法，
//     不做任何额外处理，以免与题解口径产生偏差。
//
// 复杂度：O(1)（一次比较 + 一次乘法 + 一次格式化输出）。

#include <cstdio>

int main() {
    double w;  // w：行李重量（公斤）
    if (scanf("%lf", &w) != 1) return 0;  // 单组输入：一行一个实数
    // 档位单价：<=20 公斤按 1.68 元/公斤；>20 公斤按 1.98 元/公斤（整段计费）。
    double fee = (w <= 20.0) ? w * 1.68 : w * 1.98;
    printf("%.2f\n", fee);  // 保留 2 位小数，与题面【输出样例】33.60 一致
    return 0;
}
