#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2055《【例3.5】收费》分层数据生成器（cyaron，目标 ROJ 题号 5057）
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py；
# 自定范围与"排除舍入中点"的口径参考同批 .ybt-import/staging/2071、2073 的 data.py。
#
# ---------------------------------------------------------------------------
# 题意（content.md 逐字）
# ---------------------------------------------------------------------------
#   乘坐飞机时，当乘客行李小于等于 20 公斤时，按每公斤 1.68 元收费；
#   大于 20 公斤时，按每公斤 1.98 元收费，编程计算收费（保留 2 位小数）。
#   输入：行李重量（一行一个实数）。输出：费用（保留 2 位小数，一行）。
#   题面样例：20.00 -> 33.60。
#   本题是**单组输入**（一个测试点 = 一个重量），无多组数据、无测试组数 T。
#
# ---------------------------------------------------------------------------
# 计费口径（本题唯一的语义歧义，已在 gen-report.md 风险点 2 记录）
# ---------------------------------------------------------------------------
#   题面「按每公斤 X 元收费」= **整段按所属档位的单价计费**：
#       w <= 20.0  ->  fee = 1.68 * w
#       w >  20.0  ->  fee = 1.98 * w
#   （**不是**分段累加 20*1.68 + (w-20)*1.98。）
#   判决性证据：① 题面没有「超过 20 公斤的**部分**按……」的措辞（本仓库同批语料中，
#   凡表达"超出部分另计"的题面都会写「……的部分」，全库检索确认）；② 本轮取到的
#   全部可读网络题解代码无一例外是整段计费（详见 std.cpp 头部注释的来源清单）；
#   ③ 教材定位是"第三章第一节 if 选择结构"例 3.5，教学点是单层 if-else 二分支。
#   注意：题面样例 20.00 -> 33.60 对**两种**读法都成立（w=20 时两者相等），
#   样例不能区分二者，故不靠样例定夺。
#
# ---------------------------------------------------------------------------
# 数据范围（题面【未声明】，本生成器自定并如实记录）
# ---------------------------------------------------------------------------
#   题面、config.json 与官方 OJ 页（http://ybt.ssoier.cn:8088/problem_show.php?pid=2055，
#   本轮实抓核对：只有标题/时间/内存/样例，正文为空，见 gen-report.md 风险点 1）
#   **均未声明**行李重量的取值范围、类型与小数位数。按仓库惯例自定工作范围：
#       0.00 <= w <= 1000.00   （公斤，恰好 2 位小数）
#   三条依据：
#     1) 下界取 0.00：题面只说「行李重量」，未声明正数下界；取 0 既覆盖
#        「答案为 0 的极端」（任务书要求），也是最保守的自然下界。
#     2) 上界取 1000.00：题面样例是 2 位小数（20.00），故统一用 2 位小数；
#        1000 公斤对"乘客行李"是可解释的量级，且与同章自定上限的保守口径一致。
#     3) **关键公平性**：1000.00 kg 以内，单精度 float 写法与 double 写法的
#        2 位小数结果**逐点一致**（本机全域穷举验证：float 首个分歧点在
#        2068.74 kg，即 w=206874 时 4096.11 vs 4096.10）。因此本包数据
#        不会把官方题解常见的 float 写法卡成 WA —— 取 1000.00 是"对 float 解也公平"
#        的范围；若把上限放到 2000 以上，就会出现 float/double 口径分歧点。
#        详见 gen-report.md 第 5 节（本轮已做全域穷举核验）。
#
# ---------------------------------------------------------------------------
# 分层设计（10 个测试点，单组输入题的"规模"= 数值量级与档位结构）
# ---------------------------------------------------------------------------
#   点 1  边界层：w=0.00 —— 自定范围下界（全最小值），答案恰为 0 的极端
#   点 2  边界层：w=20.00 —— **题面声明的特殊值（【输入样例】）**，
#                          同时是**档位临界点**（<=20 分支的右端点；写成 w<20 会错）
#   点 3  小规模定点：w=19.99 —— 临界点**下侧一格**（档位边界值构造），答案可手算 33.58
#   点 4  小规模定点：w=20.01 —— 临界点**上侧一格**（档位边界值构造），答案可手算 39.62
#   点 5  小规模随机：w∈[1.00,10.00]，2 位小数，量级小到可手算核对
#   点 6  中等规模随机：w∈[10.00,100.00]，范围中间档
#   点 7  中等规模随机：w∈[100.00,500.00]，范围中间档偏大
#   点 8  大规模随机：w∈[500.00,999.99]，接近上限
#   点 9  顶格层：w=1000.00 —— 自定范围上界（全最大值），答案最大 1980.00
#   点 10 顶格层：w=999.99 —— 上限附近 + 2 位小数满位的最坏舍入结构；
#                            与点 9 的"恰好整元"形成 1980.00 / 1979.98 对照
#
#   档位结构覆盖：<=20 档（点 1、2、3、5 的一部分）与 >20 档（点 4、6-10）均覆盖；
#   临界点三连（19.99 / 20.00 / 20.01）把档位判定的边界精确夹住 ——
#   无论把边界写成 <20、<=20、<20.01 还是 >20，都至少有一个点会判错。
#
#   舍入结构覆盖：点 3（33.5832 -> 33.58，需舍）与点 4（39.6198 -> 39.62，需入）
#   构成一对"向下/向上"舍入检验；点 1（0.00 精确）检验零值输出形态。
#
#   越界/中点自检：文件末尾用精确整数运算复核 10 个点 —— ① 全部落在自定范围内；
#   ② 全部**不落在 2 位小数的舍入中点**（fee*10000 的分数部分恰为 ...5），
#   即数学答案在小数第 3 位不是"恰好 5"，避免 double 舍入方向不唯一的不可判点。

from cyaron import *  # 引入CYaRon的库

import random

W_MIN_KG = 0.00        # 自定范围下界（题面未声明）
W_MAX_KG = 1000.00     # 自定范围上界（题面未声明；见文件头"三条依据"第 3 条）
TIER_KG = 20.00        # 题面档位临界点：<=20 按 1.68，>20 按 1.98
RATE_LO = 168          # 1.68 元/公斤 = 168/100（用整数"分/公斤"做精确复核）
RATE_HI = 198          # 1.98 元/公斤 = 198/100


def exact_fee_str(W):
    """输入 W = 重量 * 100（即"0.01 公斤"为单位的整数）时，精确的 2 位小数答案。

    精确费用 = (RATE/100) * (W/100) 元 = RATE*W/10000 元。
    保留 2 位小数（四舍五入，half-up）：先算 RATE*W（单位 1/10000 元），
    再 (RATE*W + 50) // 100 得到"分"，最后格式化成 `X.XX`。
    这是与 std 的浮点路线**完全独立**的整数路线，用作生成期自检。
    """
    rate = RATE_LO if W <= 2000 else RATE_HI   # W<=2000 即 w<=20.00
    num = rate * W                             # 单位：1/10000 元
    cents = (num + 50) // 100                  # 单位：分（half-up 到 2 位小数）
    return "%d.%02d" % (cents // 100, cents % 100)


def is_midpoint(W):
    """数学答案是否恰好落在 2 位小数的舍入中点（小数第 3 位 = 5 且后面无其他位）。

    fee*1000 = RATE*W/10，其小数部分恰为 0.5 <=> RATE*W ≡ 50 (mod 100)，
    即 RATE*W 的分数为 ...50（单位 1/10000 元）。这类点的舍入方向不唯一，
    属于题目本身不可判定的点，本包数据一律排除（末尾有 assert 强制校验）。
    """
    rate = RATE_LO if W <= 2000 else RATE_HI
    return (rate * W) % 100 == 50


# 已生成测试点的 W（= 重量 * 100，整数），供文件末尾统一自检
_pts = []


def gen(i, W, note):
    """写出第 i 组：输入重量（2 位小数），由 std 生成 .out，并用精确整数路线回读自检。"""
    w = W / 100.0                                   # 以"0.01 公斤"整数 W 驱动，避免浮点误差
    assert 0 <= W <= int(W_MAX_KG * 100), "problem%d: 超出自定范围" % i
    assert not is_midpoint(W), "problem%d: w=%.2f 落在 2 位小数舍入中点（不可判点）" % (i, w)

    io = IO(file_prefix="problem", data_id=i)       # problem{i}.in / problem{i}.out
    io.input_writeln("%.2f" % w)                    # 与题面样例同格式：恰好 2 位小数
    io.output_gen("../std")                         # 用 std 产出输出
    io.close()                                      # 关闭缓冲，保证下方回读的是落盘内容

    expect = exact_fee_str(W)
    got = open("problem%d.out" % i).read().strip()
    assert got == expect, \
        "problem%d 自检失败: std=%r 精确整数期望=%r" % (i, got, expect)
    _pts.append((i, W))
    tier = "<=20 档" if W <= 2000 else ">20 档"
    print("problem%-2d: w=%-9s (%s) 期望=%-9s -- %s" % (i, "%.2f" % w, tier, expect, note))


def rand_W(i, lo_kg, hi_kg):
    """按点号取"0.01 公斤"为单位的随机整数，独立种子、可逐字节复现；
    极小概率落到舍入中点时重抽（保证数据可判）。"""
    rng = random.Random(2055 + i)
    lo, hi = int(round(lo_kg * 100)), int(round(hi_kg * 100))
    while True:
        W = rng.randint(lo, hi)
        if not is_midpoint(W):
            return W


# ---- 点 1-2：边界层（下界/答案为 0 的极端 + 题面声明的特殊值=档位临界点）----
gen(1, 0,
    "边界层：w=0.00 下界（全最小值），答案恰为 0 的极端（零值输出形态）")

gen(2, 2000,
    "边界层：w=20.00 题面【输入样例】值 = 档位临界点（<=20 的右端点，"
    "写成 w<20 则此处输出 39.60 而非 33.60）")

# ---- 点 3-4：小规模定点（档位边界值构造，恰好临界点两侧一格，可手算）----
gen(3, 1999,
    "小规模定点：w=19.99 临界点下侧一格（需舍：1.68*19.99=33.5832 -> 33.58）")

gen(4, 2001,
    "小规模定点：w=20.01 临界点上侧一格（需入：1.98*20.01=39.6198 -> 39.62）")

# ---- 点 5：小规模随机（可手算核对量级）----
gen(5, rand_W(5, 1.00, 10.00),
    "小规模随机：w∈[1.00,10.00]，2 位小数，量级小到可手算核对")

# ---- 点 6-7：中等规模随机（范围中间档）----
gen(6, rand_W(6, 10.00, 100.00),
    "中等规模随机：w∈[10.00,100.00]，范围中间档")

gen(7, rand_W(7, 100.00, 500.00),
    "中等规模随机：w∈[100.00,500.00]，范围中间档偏大")

# ---- 点 8：大规模随机（接近上限）----
gen(8, rand_W(8, 500.00, 999.99),
    "大规模随机：w∈[500.00,999.99]，接近自定上限")

# ---- 点 9-10：顶格层（上限 + 上限附近最坏舍入结构）----
gen(9, 100000,
    "顶格层：w=1000.00 自定范围上界（全最大值），答案最大 1980.00（恰好整元）")

gen(10, 99999,
    "顶格层：w=999.99 上限附近 + 2 位小数满位（最坏舍入结构），"
    "答案 1979.98（非整元，与点 9 形成对照）")

# ---------------- 自检 ----------------
assert len(_pts) == 10, "应恰好生成 10 个测试点"
pts = [W for _, W in _pts]

# ① 全部落在自定范围 [0, 1000.00] 内
for i, W in enumerate(pts, 1):
    assert W_MIN_KG * 100 <= W <= W_MAX_KG * 100, "problem%d: w 越出自定范围" % i
# ② 全部不落在 2 位小数舍入中点（不可判点）
for i, W in enumerate(pts, 1):
    assert not is_midpoint(W), "problem%d: 落在舍入中点" % i
# ③ 档位边界三连齐备：19.99 / 20.00 / 20.01 必须同时出现
assert {1999, 2000, 2001} <= set(pts), "档位临界点三连（19.99/20.00/20.01）未齐备"
# ④ 两个档位都被覆盖
assert any(W <= 2000 for W in pts), "<=20 档未被覆盖"
assert any(W > 2000 for W in pts), ">20 档未被覆盖"
# ⑤ 上界/下界极端确实出现在数据里
assert min(pts) == 0 and max(pts) == 100000, "未覆盖自定范围的两端（0.00 / 1000.00）"
# ⑥ 逐点用精确整数路线复算，且与 std 生成的 .out 文件逐字节一致
for i, W in enumerate(pts, 1):
    got = open("problem%d.out" % i).read().strip()
    assert got == exact_fee_str(W), \
        "problem%d: 文件内容 %r 与精确期望 %r 不一致" % (i, got, exact_fee_str(W))

print("自检通过：10 个点均在自定范围 [0.00, 1000.00] 内、均非舍入中点；"
      "档位临界点三连 19.99/20.00/20.01 齐备；<=20 与 >20 两档均覆盖；"
      "范围两端 0.00 与 1000.00 均出现；全部 .out 与精确整数路线逐字节一致。")
