// 一本通 2044《【例5.12】回文字串》标程（目标 ROJ 题号 5046）
// ---------------------------------------------------------------------------
// 题意（本包 content.md；官方页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2044
// 本轮已实抓核对，题面五节与 content.md 逐字一致，页面显示「时间限制: 1000 ms
// 内存限制: 65536 KB」、提交数 67960 / 通过数 29255，与 config.json 的
// time=1000 / memory=64MB 一致）：
//   【题目描述】输入一串字符,字符个数不超过 100,且以"."结束。判断它们是否构成回文。
//   【输入】一行字符串。
//   【输出】是否为回文串。是输出"Yes"，否输出"No"。
//   【输入样例】abccb    【输出样例】No
//
// 关键判读（本包对题面的确定性解读，逐条给依据）：
//   * 结尾的 '.' 是**终止符**、不计入回文判断 —— 题面「以"."结束」+ 全部网络来源
//     一致（[1] 明确写「输入的字符串最后有一个'.'，而判断回文串时不考虑这个'.'，
//     需要先将其从字符串中移除」，各来源代码统一做 `len = strlen(s) - 1`）。
//   * 「字符个数不超过 100」本包取**含终止符在内的整行 ≤ 100 字符**（⇒ 主体 ≤ 99），
//     这是最严格的一种读法；本标程缓冲区远超该值，即使真实数据按另一种读法
//     （主体 ≤ 100，整行 ≤ 101）也正确，故对两种读法都安全（见 gen-report.md 风险点）。
//   * 字符集：题面只说「一串字符」。全部来源的 AC 代码都用 `cin >> s` / `scanf("%s")`
//     读取，⇒ 官方数据**不含空白符**（否则那些代码全错，与它们通过的事实矛盾）。
//     本包数据因此只用可打印非空白 ASCII（主体以 a-z 为主，另有一组定向覆盖
//     大写/数字），不含空格；也不含内嵌 '.'（'.' 只会作为终止符出现）。
//   * 空主体（输入恰为 "."）按**空串是回文**判 Yes；这与全部来源实现的退化行为一致
//     （去掉 '.' 后长度为 0，比较循环 0 次，输出 Yes；例如 [2] 的双指针版对 "." 也输出
//     Yes）。该情形是本包点 1 的边界设计。
//   * 样例异常（重要，如实记录）：题面【输入样例】写作 `abccb`，**并未带结尾的 '.'**
//     （官方页 <pre> 里也只有 abccb），而【题目描述】要求输入以 '.' 结束。这是题面
//     自身的排版/漏字瑕疵，不是语义歧义：按题意正确数据的每一行都应以 '.' 结束。
//     本标程对「结尾有无 '.'」两种形态都能算对（末尾是 '.' 则去掉，否则整行即为主体），
//     所以无论官方数据是哪种写法，本标程都给出同一个（正确的）答案；点 4 的数据就是
//     题面样例原样 `abccb`（做样例回归），其余 9 点均按题意以 '.' 结束。
//
// 参考来源 URL（本轮均用 curl 实取正文核对后改写，非盲抄；正文留存见 work/sources/）：
//   [1] https://blog.csdn.net/lq1990717/article/details/122518970
//       君义_noip《信息学奥赛一本通 2044：【例5.12】回文字串》。给出三种解法：
//       解法 1「遍历一半字符串」：`len = strlen(s) - 1;`（去掉最后的 '.'）后
//         逐对比较 `s[i] != s[len-i-1]`，出现不等即 No，全等则 Yes；
//       解法 2「构造逆序字符串」（char 数组版）：去掉末尾 '.' 后构造逆序串 r，
//         `strcmp(s, r) == 0 ? "Yes" : "No"`；
//       解法 2'（string 版）：`s.pop_back()` 去掉末尾 '.'，复制后 `reverse`，
//         比较相等性。该文并明确点出考点 =「遍历字符串的一半」以及「先移除 '.'」。
//   [2] https://blog.csdn.net/2301_80096514/article/details/135036426
//       玖剹《2044回文字符串（C语言）》。双指针 `i=0, j=len-2`（跳过 '.'）
//       相向而行，相遇前字符不等即输出 No，否则 Yes；对 "." / 单字符等退化输入
//       同样落在 Yes 分支（本包据此确认空主体判 Yes 的退化行为）。
//   [3] https://blog.csdn.net/ffsdfg/article/details/127626824
//       《信息学奥赛一本通：2044：【例5.12】回文字串》。`m = strlen(a);` 后用
//       `for (i=0, j=m-2; i<j; i++, j--)`、标志位 k 记录是否有不对称字符，
//       `k==0 ? "Yes" : "No"`；注释写明「长度减 2，包括了一个 "."」。
//   [4] https://blog.csdn.net/2402_84298973/article/details/146269354
//       Doopny@《回文字串（信息学奥赛一本通-2044）》。`cin >> s1; s1.pop_back();`
//       再去掉终止符 '.'，复制后 reverse，比较 `s1 == s2`。
//   [5] https://blog.csdn.net/jntmjntm114514/article/details/136071385
//       《2044：【例5.12】回文字串》。逐个读字符 `for (; b != '.'; cin >> b)` 收主体，
//       构造逆序数组后逐位比较（该路线即本包 work/brute.cpp 的输入处理路线）。
//   [6] https://blog.csdn.net/2301_80084031/article/details/135721310
//       茶夜。《2044回文字符串》官方题面转载 + 参考代码；代码同 [1] 解法 1，
//       注释强调「最后的 '.' 要去掉！！！！」。
//   [7] https://blog.csdn.net/zxm__sunny/article/details/146438394
//       《一本通 2044 【例5.12】回文字串》。`getline(cin, n); reverse(n.begin(), n.end()-1);`
//       —— 反向区间刻意排除末位 '.'；该文证明「按行读入 + 只处理除终止符外的部分」
//       也被视为可接受实现（本标程正是 getline/fgets 路线 + 显式剥终止符）。
//   [8] http://ybt.ssoier.cn:8088/problem_show.php?pid=2044
//       官方题面：核对题目描述/输入/输出/样例/限制（1000 ms / 65536 KB）。
//
// 多来源结论核对（无冲突）：七个来源的算法完全一致 —— 去掉结尾的 '.' 后逐对比较，
//   全部对称则 Yes，否则 No。差异仅在：① 输入读取方式（cin>>s / getline / 逐字符读到 '.'）；
//   ② 去除终止符的写法（-1 / pop_back / 反向区间 end()-1）；③ 提前 return 还是标志位。
//   这些差异在「数据每行以 '.' 结束」的前提下完全等价（本包数据保证无内嵌 '.'、无空白符）。
//   题面唯一可讨论之处是【输入样例】漏了结尾的 '.'（见上文判读），本标程对两种形态都正确，
//   故未触发任务书的「题面歧义 → 停下报告」条件。
//
// 本标程相对来源的改写点：
//   * 输入用 `fgets` 读**整行**（来源 [7] 的 getline 路线），先剥行尾 '\r'/'\n'
//     （CRLF 容错，来源均未处理），再剥结尾的 '.'（若存在）；
//     比 `cin >> s` 更强：即使数据里出现空白字符也按题面「一行字符串」处理。
//   * 回文判定用**双指针原地比较**（来源 [1] 解法 1 / [2] 的路线），不构造逆序串，
//     O(n) 时间、O(1) 额外空间（除输入缓冲）。
//   * `work/brute.cpp` 实现来源 [5] 的「逐字符读到 '.' + 构造逆序数组」路线做交叉对拍；
//     `data.py` 内另附 Python 直译题面作为第三条独立路线复核输出。
//   * 缓冲区取 1 MiB 并全程带长度保护：题面上限 100 字符，远超；任何超长/空输入
//     都不越界、不崩溃。
//   * 头部注释逐条写明来源 URL 与判读依据；代码未逐字复制任何一份来源。
// ---------------------------------------------------------------------------
#include <cstdio>
#include <cstring>

int main() {
    static char buf[1 << 20];  // 题面保证 ≤ 100 字符；1 MiB 远超，防御性

    if (fgets(buf, sizeof(buf), stdin) == NULL) {
        return 0;  // 空输入：无数据可判，静默退出（题面保证有一行）
    }

    size_t n = strlen(buf);
    // 剥行尾空白（'\n'/CRLF 容错；空格/制表符也剥 —— 题面数据不含空白符，
    // 这是针对「'.' 之后误留空格」的防御，使行为与主流来源的 cin >> s 读取一致）
    while (n > 0 && (buf[n - 1] == '\n' || buf[n - 1] == '\r' ||
                     buf[n - 1] == ' ' || buf[n - 1] == '\t')) {
        buf[--n] = '\0';
    }
    if (n > 0 && buf[n - 1] == '.') {
        buf[--n] = '\0';  // 剥终止符 '.'：判断回文时不考虑它
    }

    // 双指针：i 从左端、j 从右端相向比较，任一对不同即非回文
    int i = 0, j = (int)n - 1;
    bool palindrome = true;
    while (i < j) {
        if (buf[i] != buf[j]) {
            palindrome = false;
            break;
        }
        ++i;
        --j;
    }

    puts(palindrome ? "Yes" : "No");
    return 0;
}
