#!/usr/bin/env python3
# 一本通 2045《【例5.13】蛇形填数》分层测试数据生成器（cyaron）
# 用法：g++ -O2 -std=c++17 std.cpp -o std && mkdir -p data && cd data && python3 ../data.py
#
# 题面数据范围（content.md / 官方页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2045）：
#   题面原文只给上界「其中，n ≤ 20」；未写明下界（方阵阶数的语义下界为 n = 1）。
#   单组输入：只给一个整数 n，无多组数据、无测试组数 T、无其它参数。
#   官方页限制：时间 1000 ms，内存 65536 KB（与 config.json 的 time=1000 / memory=64MB 一致）。
#
# 本题特性：**输出是 n 的确定函数**（n 定了方阵就定了），输入里唯一可变的量就是 n；
# 因此"随机化"没有发挥空间，分层策略只能是 **n 的量级分层 + 结构临界 n 的覆盖**：
#   * 量级：把 n 从下界 1 一路铺到顶格 20；
#   * 结构临界：n 的奇偶（奇数 n 最内圈退化为 1 格，n² 恰好落在正中心；
#     偶数 n 最内圈是 2×2 环，n² 落在该环的左上格 (n/2-1, n/2-1)，右下角恒为 n）、
#     最小非退化 n=2、题面样例 n=4；
#   * 每个点的输出方阵互不相同（n 不同则方阵与数字排布均不同，见 gen-report 的清单），
#     可有效检出"起点/走向写反""行末格式错""奇数中心处理错""上限差一"等实现错误。
#
# 分层表（10 组，n 互不相同，全部落在题面合法范围 1..20 内）：
#   点 1  边界层：n=1（最小合法方阵 1×1；题面未写下界，本包取 1 为下界并作为
#                      "答案为 1 的极端"——整个输出只有 1 个字符 '1'）
#   点 2  边界层：n=2（最小非退化方阵，"4 1 / 3 2"；起点/走向写反可即时暴露）
#   点 3  小规模手算：n=3（最小奇数>1；中心格 = 9 = n²，锁定"奇数 n 最大值在中心"性质）
#   点 4  小规模手算：n=4（**题面样例原样**，逐格可手算，做样例回归）
#   点 5  中等规模随机档：n=8（8×8=64 格，中档偶数，最内圈为 2×2 环）
#   点 6  中等规模随机档：n=11（11×11=121 格，中档奇数，中心格 = 121 = n²）
#   点 7  大规模随机档：n=17（17×17=289 格，接近上限的奇数）
#   点 8  大规模随机档：n=18（18×18=324 格，接近上限的偶数）
#   点 9  顶格层：n=19（19×19=361 格，上限内最大奇数；中心格 = 361 = n²，
#                     并覆盖 ⌈n/2⌉=10 层环的最深递归；与点 10 配对覆盖奇偶两极）
#   点 10 顶格层：n=20（**题面上限顶格**，20×20=400 格，全题最长输出；
#                     偶数上限，最内圈 2×2 环，n²=400 落在该环左上格 (9,9)，右下角为 20）
#
# 分层项适用性说明（题面性质决定，详见 gen-report.md「分层对照」）：
#   * 「多组数据按组数分层」不适用 —— 单组输入；
#   * 「随机化数据」不适用 —— 唯一输入量 n 的取值范围只有 20 个取值，输出与 n 一一对应，
#     故随机档以"量级档位"代替随机（不在同一 n 上重复造点，10 个点 n 两两不同）；
#   * 「卡常结构」不适用 —— n ≤ 20 至多 400 格，任何 O(n²) 写法都远低于 1000 ms
#     （std 最大点实测 < 1 ms），顶格层按"规模顶格 + 最长输出量"设计；
#   * 「链/逆序/重复值」等图论或权值结构不适用 —— 本题无第二输入量；
#   * 「答案为 0 或 1 的极端」在本题即 n=1 的单个 '1'（点 1），已覆盖；
#   * 「题面声明的特殊值」即样例 n=4（点 4），已覆盖。

from cyaron import IO  # 引入CYaRon的库

# (n, 层次描述)：10 个点 n 两两不同，1..20 内从下界铺到顶格。
CASES = [
    (1,  "边界层（下界）：n=1，1×1 方阵，输出仅一个数 1 —— 全题唯一"
         "\"答案为 1\"的极端；题面未写下界，本包以 1 为方阵阶数下界"),
    (2,  "边界层（最小非退化）：n=2，输出 4 1 / 3 2 —— 起点与走向写反的"
         "实现会在此点即暴露（如误填 1 2 / 4 3）"),
    (3,  "小规模手算：n=3（最小奇数>1），中心格恰为 9 = n²，锁定"
         "\"奇数 n 最大值落在正中心\"的结构性质；逐格可手算"),
    (4,  "小规模手算：n=4 —— **题面【输入样例】原样**，输出与题面"
         "【输出样例】逐字节一致，做样例回归"),
    (8,  "中等规模随机档：n=8（8×8=64 格，中档偶数，最内圈为 2×2 环，n²=64 在环左上格 (3,3)）"),
    (11, "中等规模随机档：n=11（11×11=121 格，中档奇数，中心格 = 121 = n²）"),
    (17, "大规模随机档：n=17（17×17=289 格，接近上限的奇数）"),
    (18, "大规模随机档：n=18（18×18=324 格，接近上限的偶数，n²=324 在环左上格 (8,8)）"),
    (19, "顶格层（上限邻域）：n=19（19×19=361 格，上限内最大奇数；"
         "中心格 = 361 = n²；⌈19/2⌉=10 层环为全题最深递归）"),
    (20, "顶格层（题面上限顶格）：n=20（20×20=400 格，全题最长输出；"
         "偶数上限；最内圈 2×2 环，n²=400 落在环左上格 (9,9)，右下角为 20；"
         "与点 9 配对覆盖奇偶两极）"),
]

for idx, (n, note) in enumerate(CASES, start=1):
    io = IO(file_prefix="problem", data_id=idx)  # problem{idx}.in / problem{idx}.out
    io.input_writeln(n)                          # 单组输入：一行一个整数 n
    io.output_gen("../std")
    print("problem%-2d: n=%-2d -- %s" % (idx, n, note))
