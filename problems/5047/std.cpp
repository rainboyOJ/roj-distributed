// 多来源结论核对（无冲突）：[1]–[4] 的算法族（焦点+转向 / 方向数组 / 按圈）虽实现手法
//   不同，但**起点、走向、填数顺序完全一致**，输出方阵逐格相同；差异仅在下标起点
//   （1-indexed vs 0-indexed）与是否行末带空格（判题器按空白容忍比较时等价）。
//   无来源与题面冲突的实质结论；[2] 标题的 n<50 只是该博主自留的数组尺寸，不改题意，
//   本包仍以题面 n ≤ 20 为准（并在数据中把 10 个点铺满 1..20 全域）。
//
// 本标程相对来源的改写点：
//   * 采用来源 [1](b) 的「方向数组 + 预测下一格」范式，但重写为 0-indexed、
//     显式写出「越界或已填 → 顺时针转向」的判定，结构清晰且不依赖 1-indexed 哨兵；
//   * I/O 用 cstdio 的 scanf/printf（来源 [1]–[4] 用 cin/cout），风格对齐
//     problems/1000/std.cpp；输出显式控制「数间一个空格、行末无空格」；
//   * 数组用 std::vector 动态分配 (n+2)×(n+2)（外围留一圈哨兵位），而非固定 a[25][25]，
//     使实现不依赖任何题面外的尺寸假设；n ≤ 20 时占用 (22×22) 个 int ≈ 1.9 KB；
//   * 加入防御性处理：输入失败 / n < 1 安静退出（无输出），n 超过自定工作上限
//     （1000，远超题面 20）也安静退出，保证任意输入不越界、不崩溃；
//   * 复杂度 O(n²)：n ≤ 20 时 400 次填格 + 400 次输出，微秒级；n = 1000 时
//     (1000²=10⁶ 格) 亦仅数毫秒，留足余量。

#include <cstdio>
#include <vector>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;   // 空输入 / 非法输入：安静退出
    if (n < 1 || n > 1000) return 0;      // 越出题面范围（n ≥ 1、n ≤ 20）的防御性处理

    // (n+2)×(n+2) 的网格，下标 0..n+1；第 0 行/列与第 n+1 行/列作为**哨兵围墙**，
    // 预先标记为非 0（-1），使「下一格越界或已填」统一退化为检查 a[..] != 0。
    const int W = n + 2;
    std::vector<int> a((size_t)W * W, 0);
    for (int i = 0; i < W; ++i) {
        a[0 * W + i] = a[(W - 1) * W + i] = -1;       // 首行 / 末行围墙
        a[i * W + 0] = a[i * W + (W - 1)] = -1;       // 首列 / 末列围墙
    }
    // 0-indexed 访问：a[x * W + y]，其中 1 <= x, y <= n 为有效格。
    const int dx[4] = {1, 0, -1, 0};   // 下、左、上、右（顺时针）
    const int dy[4] = {0, -1, 0, 1};

    int x = 1, y = n, d = 0;           // 起点：第 1 行（0-indexed 0）第 n 列（0-indexed n-1）
    for (int v = 1; v <= n * n; ++v) {
        a[x * W + y] = v;
        if (v == n * n) break;         // 最后一格填完即停，无需再转向
        int nx = x + dx[d], ny = y + dy[d];
        if (a[nx * W + ny] != 0) {     // 下一格越界（哨兵）或已填：顺时针转向
            d = (d + 1) % 4;
            nx = x + dx[d];
            ny = y + dy[d];
        }
        x = nx;
        y = ny;
    }

    for (int i = 1; i <= n; ++i) {     // 逐行输出：数间一个空格、行末无空格
        for (int j = 1; j <= n; ++j) {
            if (j > 1) putchar(' ');
            printf("%d", a[i * W + j]);
        }
        putchar('\n');
    }
    return 0;
}
