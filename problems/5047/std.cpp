//   【题目描述】在 n×n 方阵里填入 1,2,3,…,n×n，要求填成蛇形。例如 n=4 时方阵为：
//                 10 11 12 1
//                  9 16 13 2
//                  8 15 14 3
//                  7  6  5 4
//               其中，n ≤ 20。
//   【输入】输入 n。（单组输入，只有一个整数 n；题面只给上界 n ≤ 20）
//   【输出】输出题述方阵。n 行，每行各数之间用一个空格隔开。
//   【输入样例】4
//   【输出样例】10 11 12 1 / 9 16 13 2 / 8 15 14 3 / 7 6 5 4
//
// 关键判读（本包对题面的确定性解读，依据样例逐格反推，无歧义）：
//   * 填充走向：数字 1 恒在**右上角**（第 0 行第 n-1 列），随后按「下 → 左 → 上 → 右」
//     顺时针循环，走到边界或已填格即换向。样例 n=4 唯一确定了这条走向与起点：
//     (0,3)=1, (1,3)=2, (2,3)=3, (3,3)=4, (3,2)=5, …, (0,0)=10, (0,1)=11, (0,2)=12,
//     (1,2)=13, …, 与题面样例 4×4 逐格吻合。
//   * n 的下界：题面只写 n ≤ 20，未写 n ≥ 1。方阵阶数的最小合法值是 n=1（在 1×1 方阵
//     里填 1，输出一行一个数 1），本包据此把 n=1 作为**下界边界点**（测试点 1）并让
//     std 正确处理；n=2 作为最小非退化点（输出「4 1 / 3 2」，能一击暴露起点/走向写反）。
//   * 输出格式：n 行、每行 n 个数、数与数之间恰一个空格，**行末不留空格**（题面字面
//     「各数之间用一个空格隔开」，官方页 <pre> 样例原始字节同样无行末空格），
//     每行以 '\n' 结束（含最后一行）。与仓库语料惯例一致（problems/1000、problems/5006，
//     以及同章的 staging/2041、staging/2034 等同样取「行末不留空格 + '\n'」）。
//   * 单组输入：无多组数据、无测试组数 T，题面未声明其它特殊值，不存在语义歧义，
//     未触发任务书的「停下报告」条件。
//
// 参考来源（网络题解，本轮均实取正文核对后按题面改写，非盲抄；证据留存见
// work/sources/ 与 work/fetch_evidence_extracted_code.txt）：
