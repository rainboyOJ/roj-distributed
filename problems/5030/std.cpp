// ============================ 数学建模 ============================
// 设鸡翁 a 只、鸡母 b 只、鸡雏 c 只（均为非负整数），题面两条约束：
//     (1) 百鸡：a + b + c = 100
//     (2) 百钱：5a + 3b + c/3 = 100，且鸡雏「三只值一钱」不可拆卖 ⇒ c 必须是 3 的倍数
// 取值范围：5a ≤ 100 ⇒ 0 ≤ a ≤ 20；3b ≤ 100 ⇒ 0 ≤ b ≤ 33；0 ≤ c ≤ 100 且 c ≡ 0 (mod 3)。
// 由 (1) 有 c = 100 - a - b，故只需枚举 a、b 两重循环（这也是 O(21×34) 的教学写法）。
// 注意整数除法坑：c/3 在 C/C++ 中会截断，所以必须先判 c % 3 == 0 再判钱数；
// 本实现把 c 与钱的判定都写成纯整数运算，不引入浮点误差。
//
// 答案（枚举结果）：
//     0 25 75
//     4 18 78
//     8 11 81
//     12 4 84
// 恰好 4 组解；按 (鸡翁, 鸡母, 鸡雏) 字典序（= 鸡翁从小到大）输出，符合题面
// 「依次由小到大」；第三列 75/78/81/84 均为 3 的倍数，钱数逐项复核：
//     0*5 + 25*3 + 75/3 = 75 + 25 = 100 ✔（只数 100）
//     4*5 + 18*3 + 78/3 = 20 + 54 + 26 = 100 ✔
//     8*5 + 11*3 + 81/3 = 40 + 33 + 27 = 100 ✔
//     12*5 + 4*3 + 84/3 = 60 + 12 + 28 = 100 ✔
