// 相对来源的改写点：
//   - 循环边界用常量 20 / 33 并在注释中给出推导（来源多为字面量 100/5、100/3，等价）；
//   - 由「百鸡」等式直接 c = 100 - a - b（来源 [3][5][6] 同款化简），省去第三重循环，
//     枚举量 21×34 = 714 次，远低于 1000 ms；
//   - 钱数判定用纯整数 5*a+3*b+c/3（先判 c%3==0），不用浮点（来源 [8] 提醒过
//     int 除法/浮点比较的坑；来源 [11] 用 double 亦可，但整数更稳）；
//   - stdin→stdout，printf 风格对齐 problems/1000/std.cpp；输出无行尾多余空格 + '\n' 换行。
//
// 用法：g++ -O2 -std=c++17 std.cpp -o std && ./std   →  4 行 4 组解

#include <cstdio>

int main() {
    for (int a = 0; a <= 20; ++a) {            // 鸡翁：5 钱一只，百钱最多 20 只
        for (int b = 0; b <= 33; ++b) {        // 鸡母：3 钱一只，百钱最多 33 只
            int c = 100 - a - b;               // 由「百鸡」a+b+c=100 直接定出鸡雏数
            if (c < 0) continue;               // 只数不够分，剪掉
            if (c % 3 != 0) continue;          // 鸡雏三只一钱，不可拆卖 ⇒ c 必须是 3 的倍数
            if (5 * a + 3 * b + c / 3 == 100) { // 百钱（纯整数运算，无浮点误差）
                printf("%d %d %d\n", a, b, c);  // a、b 递增枚举 ⇒ 输出「依次由小到大」
            }
        }
    }
    return 0;
}
