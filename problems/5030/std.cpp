//             百钱买百鸡，问鸡翁、鸡母、鸡雏各几何？
// 【输入】无
// 【输出】输出各种鸡翁、鸡母、鸡雏的数量，依次由小到大，每种情况各占一行,
//         每行三个数之间用一个空格隔开。
// 【输入样例】无    【输出样例】无（本题无输入，官方页亦无样例）
// 【限制】time 1000 ms / memory 64 MB（config.json；官方页 65536 KB）
