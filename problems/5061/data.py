#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2059《【例3.11】买笔》数据生成器（cyaron）
#
# 题意：x 元全部花完买 4/5/6 元笔，笔数尽量多；输出「6元、5元、4元」笔数。
# 题面样例：10 -> "1 0 1"。
#
# 数据范围：题面（content.md）与官方 OJ 页均【未声明 x 的上限】，只有
# 1000 ms / 65536 KB 限制；也没有【提示】节。为分层造数据，本包自定工作范围
#     x >= 4 且 x <= 10^6
# 依据：同仓先例 problems/1000/data.py（A+B）与同批次 staging/2065 均取 10^6 量级；
# 计数至多 250000，任意 int 版本题解都不会溢出，数据对官方常见解是公平的。
# 刻意排除 x ∈ {1,2,3,7}：这四值无法用 4/5/6 元恰好凑出（7 = 4a+5b+6c 无解），
# 题面未定义其输出，属无定义输入，不造（详见 gen-report.md 风险点 2）。
#
# 分层设计（单组输入题：10 个测试点 = 10 个 x 取值，按 x 的量级与 x%4 分支铺开）：
#   点 1     边界层：x = 4  自定工作范围下界 / 最小可行值 / 最小 r=0 整除点
#   点 2     边界层：x = 10 题面样例（r=2 分支的最小代表，且是唯一样例）
#   点 3     小规模：x = 5  r=1 最小代表（"1 支 4 元换 1 支 5 元"的最小触发值）
#   点 4     小规模：x = 11 r=3 最小代表（"2 支 4 元换 6 元+5 元"的最小触发值）
#   点 5     小规模随机：x ∈ [8, 300]
#   点 6     中等规模随机：x ∈ [300, 10^4]
#   点 7     大规模随机：构造 r=1 的大值 x = 4q+1, q ∈ [10^4, 2*10^5]
#   点 8     顶格附近：x = 999998（r=2 分支在最大 k 处；答案 1 0 249998）
#   点 9     顶格附近：x = 999999（r=3 分支在最大 k 处，需"两支 4 元换成 5+6"）
#   点 10    顶格层：x = 1000000 自定工作范围上界（r=0，答案 0 0 250000）
#
# 覆盖矩阵（x%4 四种余数 × 最小/最大两档量级全部覆盖）：
#   r=0：x=4（最小）+ x=10^6（上界）
#   r=1：x=5（最小）+ 点 7 构造大值 4q+1
#   r=2：x=10（样例）+ x=999998（顶格附近）
#   r=3：x=11（最小）+ x=999999（顶格附近）

from cyaron import *  # 引入CYaRon的库

import random
random.seed(2059)  # 固定种子，便于复现

MAX_X = 1000000  # 自定工作范围上界（题面未声明，见文件头说明）


def gen_case(i, x, note):
    """写出第 i 组：输入 'x'，输出由 std 生成的最优买笔方案。

    注意：cyaron 的 IO 对输出文件做了缓冲，必须等 IO 对象析构（缓冲区 flush）后
    才能读回 .out 做自检，因此这里只写文件，自检在函数返回后进行。
    """
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(x)
    io.output_gen("../std")


def expected(x):
    """按题面公式独立算出期望输出（x%4 四分支；与标程写法独立，用于生成器自检）。"""
    k, r = x // 4, x % 4
    if r == 0:
        return "0 0 %d" % k
    if r == 1:
        return "0 1 %d" % (k - 1)
    if r == 2:
        return "1 0 %d" % (k - 1)
    return "1 1 %d" % (k - 2)


CASES = []


def add(i, x, note):
    CASES.append((i, x, note))
    gen_case(i, x, note)


# ---- 点 1：边界层，工作范围下界 / 最小可行值 / r=0 ----
add(1, 4, "边界层：x=4 下界最小可行值，全买 1 支 4 元笔")

# ---- 点 2：边界层，题面样例 ----
add(2, 10, "边界层：题面样例，答案 1 0 1")

# ---- 点 3：小规模，r=1 最小代表 ----
add(3, 5, "小规模：r=1 最小代表（1 支 4 元换成 1 支 5 元）")

# ---- 点 4：小规模，r=3 最小代表 ----
add(4, 11, "小规模：r=3 最小代表（2 支 4 元换成 1 支 6 元 + 1 支 5 元）")

# ---- 点 5：小规模随机 ----
add(5, randint(8, 300), "小规模随机：x∈[8,300]")

# ---- 点 6：中等规模随机 ----
add(6, randint(300, 10000), "中等规模随机：x∈[300,10^4]")

# ---- 点 7：大规模随机，构造保证 r=1 ----
add(7, 4 * randint(10000, 200000) + 1,
    "大规模随机：x=4q+1, q∈[10^4,2*10^5]，显式覆盖大值 r=1 分支")

# ---- 点 8：顶格附近，r=2 分支在最大 k 处 ----
add(8, 999998, "顶格附近：x=999998（r=2，最大 k 处的 4 元换 6 元分支）")

# ---- 点 9：顶格附近，r=3 分支在最大 k 处 ----
add(9, 999999, "顶格附近：x=999999（r=3，最大 k 处两支 4 元换 5+6 元）")

# ---- 点 10：顶格层，工作范围上界 ----
add(10, MAX_X, "顶格层：x=10^6 上界，答案 0 0 250000")

# ---- 生成器自检：IO 对象均已析构（.out 已 flush），逐组读回比对 ----
print("--- self-check (read back from data/ after flush) ---")
bad = 0
for i, x, note in CASES:
    with open("problem%d.out" % i) as f:
        ans = f.read().strip()
    exp = expected(x)
    tag = "OK" if ans == exp else "!! MISMATCH, expected %s" % exp
    if ans != exp:
        bad += 1
    print("problem%-2d: x=%-8d out=%-16s [%s] -- %s" % (i, x, ans, tag, note))
print("self-check: %d/%d OK" % (len(CASES) - bad, len(CASES)))
if bad:
    raise SystemExit("generator self-check FAILED")
