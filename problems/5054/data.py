#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2052《【例3.2】范围判断》—— 测试数据生成器（cyaron，仓库惯例）
# 用法：mkdir -p data && cd data && python3 ../data.py
#
# 题意：读入一个整数 a；若 a > 1 且 a < 100 则输出 yes，否则不输出任何内容。
#      区间为开区间 (1, 100)，即 a ∈ {2, 3, ..., 99} 时输出 yes。
# 样例：输入 76 => 输出 yes（题面【输入样例】/【输出样例】）。
#
# 数据范围：题面（含官方 OJ 页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2052）
#   **未声明** a 的取值范围，只有 1000 ms / 65536 KB 限制。
#   按语料惯例（参考 .ybt-import/staging/2062、2064 等）自定工作范围：
#       -2147483648 <= a <= 2147483647       （自然的有符号 32 位 int 全域）
#   std 用 long long 读写，即使超出 32 位也不会截断。
#
# 本题为**单组输入**（一个测试点就是一个整数），不存在"多组数据的组数分层"，
# 故分层按 a 与判定区间 (1,100) 的相对位置 + a 的量级铺开：
#   点 1-5  边界层：题面样例值 / 区间下界端点与内侧 / 上界内侧与端点
#   点 6    小规模随机：区间内 [3,98]，可手算核对
#   点 7    中等规模随机：区间外正值 [101,10^6]，判定分支的上界外侧中间档
#   点 8    大规模随机：区间外正值 [10^6, 2^31-2]，贴近自定上限
#   点 9-10 顶格层：自定范围两端 —— 2^31-1（全最大值）/ -2^31（全最小值）
# 说明：a <= 1 的全部取值（含 0 与负数）走同一条分支（不输出），故不单独铺点，
#       由 work/stress.py 的穷举对拍覆盖（含 0、-1、-2^31 等）。

from cyaron import *  # 引入CYaRon的库

import random
random.seed(2052)  # 固定种子，便于复现

A_MAX = 2147483647   # 自定工作范围上限（int 全域最大值）
A_MIN = -2147483648  # 自定工作范围下限（int 全域最小值）


def gen_case(i, a, note):
    """写出第 i 组：输入 a；输出由 std 生成（满足条件为 'yes'，否则空文件）。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(a)  # 行末带换行（与 2064/2070 等包一致，最兼容）
    io.output_gen("../std")
    exp = "yes" if 1 < a < 100 else "(空输出)"
    print("problem%d: a=%-12d 期望 %-8s -- %s" % (i, a, exp, note))


# ---- 点 1-5：边界层 ----
# 点 1：题面【输入样例】声明的特殊值 a=76（区间内典型值，答案 yes）
gen_case(1, 76, "边界层：题面【输入样例】特殊值 76（区间内典型值）")

# 点 2：区间下界端点 a=1 —— a>1 严格不成立（开区间下界，防 '<=' / '<' 写错）
gen_case(2, 1, "边界层：区间下界端点 a=1，a>1 严格不成立 => 不输出")

# 点 3：下界内侧最小满足值 a=2 —— 最小输出 yes 的取值
gen_case(3, 2, "边界层：下界内侧最小满足值 a=2（最小 yes）")

# 点 4：上界内侧最大满足值 a=99 —— 最大输出 yes 的取值
gen_case(4, 99, "边界层：上界内侧最大满足值 a=99（最大 yes）")

# 点 5：区间上界端点 a=100 —— a<100 严格不成立（开区间上界）
gen_case(5, 100, "边界层：区间上界端点 a=100，a<100 严格不成立 => 不输出")

# ---- 点 6：小规模随机（区间内，可手算验证） ----
a = random.randint(3, 98)
gen_case(6, a, "小规模随机：a∈[3,98] 区间内随机，可手算核对（输出 yes）")

# ---- 点 7：中等规模随机（区间外正值，中间档） ----
a = random.randint(101, 1000000)
gen_case(7, a, "中等规模随机：a∈[101,10^6]，区间外正值中间档（不输出）")

# ---- 点 8：大规模随机（贴近自定上限） ----
a = random.randint(1000000, A_MAX - 1)
gen_case(8, a, "大规模随机：a∈[10^6,2^31-2]，贴近自定上限（不输出）")

# ---- 点 9-10：顶格层（自定范围两端） ----
# 点 9：自定上限 a=2^31-1（int 全域最大值；10 位数解析 + 溢出边界）
gen_case(9, A_MAX, "顶格层：a=2^31-1 自定上限（int 全域最大值，不输出）")

# 点 10：自定下限 a=-2^31（int 全域最小值；INT_MIN 的负号/溢出边界）
gen_case(10, A_MIN, "顶格层：a=-2^31 自定下限（int 全域最小值，不输出）")
