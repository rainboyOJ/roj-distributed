#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2071《【例2.14】平均分》数据生成器（目标 ROJ 题号 5072）
#
# 题面：已知某班有男同学 x 位、女同学 y 位，x 位男生平均分 87 分，y 位女生平均分 85 分，
#       求全体同学平均分（保留 4 位小数）。输入一行两个整数 x y；单组输入，无多组数据。
#       答案 = (87x + 85y) / (x + y)，按题面保留 4 位小数。
#
# 【关键：题面未声明数据范围】
#   题面与官方 OJ 页（http://ybt.ssoier.cn:8088/problem_show.php?pid=2071）均**未声明**
#   x、y 的取值范围，也没有声明任何特殊值。故按仓库惯例自定工作范围并如实记录：
#       0 <= x, y <= 10^6,  x + y >= 1   （总人数至少 1，否则平均分分母为 0）
#   取 10^6 的依据：同章同级题的自定上限均为 10^6（staging/2065、staging/2068、
#   problems/1000 A+B）；且此时中间量 87x + 85y <= 1.72e8、x+y <= 2e6，
#   int64 安全（本题即使 int32 也不溢出，用 int 的常见写法同样可 AC）。
#   边界纳入 x=0 或 y=0（单一性别班级）：题面语义下平均分仍唯一确定
#   （x=0 时"x 位男生平均分 87"对全体平均分无贡献，答案即 85）。已作为风险点记录。
#
# 分层设计（10 个测试点，从最小铺到顶格）：
#   点 1-2  边界层：最少人数 n=1（x=y=1，答案恰为整数 86）、单一性别极端 x=0（答案退化为区间端点 85）
#   点 3-4  小规模随机（可手算验证量级）：题面【输入样例】2 3 / x,y∈[2,20]
#   点 5-6  中等规模随机：x,y∈[1e3,1e4] / [1e4,1e5]，范围中间档
#   点 7-8  大规模随机：x,y∈[1e5,5e5] / [5e5,1e6]，接近上限
#   点 9-10 顶格层：单一性别顶格（x=1e6,y=0 → 答案退化为极端权值 87）、
#                   男女各 1e6（总人数 2e6 为最大规模，答案为整数 86）
#
# 与任务书分层清单的对照（越界项如实说明，不强行凑数）：
#   - "答案为 0 或 1 的极端"：**本题结构上不存在**。x,y>=0 时答案恒落在 [85, 87] 闭区间
#     （两人群均分 85、87 的加权平均），只能是 85（全女生）或 87（全男生）为极端端点，
#     故用点 2（x=0 全女 → 85）与点 9（y=0 全男 → 87）覆盖两个端点极端。
#   - "n=1 / n=2 的组数分层"：本题为**单组输入**（一个测试点一对 (x,y)），无组数可分层，
#     不适用；任务书该项针对多组数据题。
#   - "题面声明的特殊值"：题面除样例外未声明任何特殊值，故点 3 直接采用【输入样例】2 3。
#
# 数据稳定性自检：**排除答案恰好落在 printf 4 位小数进位中点的输入**
#   （数学值既约分母 = 20000，即形如 x.xxxx5），这类点 double 无法精确表示，
#   不同实现的舍入方向可能不同（属于题目本身的不可判点）。生成器末尾有 assert 强制校验。
#
# 随机性：每个随机点使用独立 Random(2071 + 点号)，与调用顺序无关、可精确复现。

from cyaron import *  # 引入CYaRon的库

import random

MAXV = 10 ** 6  # 自定工作范围上限（题面未声明 x/y 范围；见文件头说明）

# 已生成测试点的 (x, y) 记录，用于末尾的"非舍入中点"自检
_pts = []


def gen(i, x, y, note):
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(x, y)
    io.output_gen("../std")
    _pts.append((i, x, y))
    print("problem%-2d: x=%-7d y=%-7d -- %s" % (i, x, y, note))


def rnd2(i, lo, hi):
    """按点号取独立随机数对，与调用顺序无关、可精确复现。

    注意：必须用同一个 Random 实例连续取两个数，否则两次
    `Random(seed).randint(...)` 会返回相同的值（序列被重置）。
    """
    rng = random.Random(2071 + i)
    return rng.randint(lo, hi), rng.randint(lo, hi)


# ---- 点 1-2：边界层（最小规模 / 答案端点极端） ----
gen(1, 1, 1,
    "边界层：n=1 人数最少（x=y=1），答案恰为整数 86（自定范围最小点）")
gen(2, 0, 1,
    "边界层：单一性别极端 x=0（仅 1 位女生），答案退化为区间端点 85（覆盖 0 值退化情形）")

# ---- 点 3-4：小规模随机（可手算验证量级） ----
gen(3, 2, 3,
    "小规模：题面【输入样例】2 3，答案 85.8000（题面唯一声明值，可手算核对）")
gen(4, *rnd2(4, 2, 20),
    "小规模随机：x,y∈[2,20]，量级小到可心算验证")

# ---- 点 5-6：中等规模随机 ----
gen(5, *rnd2(5, 1000, 10000),
    "中等规模随机：x,y∈[1e3,1e4]，范围中间档")
gen(6, *rnd2(6, 10000, 100000),
    "中等规模随机：x,y∈[1e4,1e5]，范围中间档偏大")

# ---- 点 7-8：大规模随机（接近上限） ----
gen(7, *rnd2(7, 100000, 500000),
    "大规模随机：x,y∈[1e5,5e5]，接近上限")
gen(8, *rnd2(8, 500000, MAXV),
    "大规模随机：x,y∈[5e5,1e6]，贴近上限")

# ---- 点 9-10：顶格层（上限 + 最坏结构） ----
gen(9, MAXV, 0,
    "顶格层：x=1e6 顶格 + y=0 单一性别极端，答案退化为区间端点 87（极端权值结构）")
gen(10, MAXV, MAXV,
    "顶格层：x=y=1e6 双顶格，总人数 2e6 为本题最大规模，答案恰为整数 86")

# ---- 自检：逐点校验取值范围与"非舍入中点" ----
from fractions import Fraction  # noqa: E402

for i, x, y in _pts:
    assert x + y >= 1, "problem%d: 总人数必须 >= 1" % i
    assert 0 <= x <= MAXV and 0 <= y <= MAXV, "problem%d: 超出自定上限" % i
    v = Fraction(87 * x + 85 * y, x + y)
    assert v * 10000 % 1 != Fraction(1, 2), \
        "problem%d: (%d,%d) 答案落在 4 位小数舍入中点，舍入方向不唯一" % (i, x, y)
    assert 85 <= v <= 87, "problem%d: 答案越出 [85,87] 区间（题型不可能）" % i
print("自检通过：%d 个测试点均在自定范围内，答案均落在 [85,87] 且未落在 4 位小数舍入中点。"
      % len(_pts))
