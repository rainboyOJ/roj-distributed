// 一本通 2071《【例2.14】平均分》（目标 ROJ 题号 5072）标程
//
// 题意：已知某班有男同学 x 位、女同学 y 位，x 位男生的平均分是 87 分，
//       y 位女生的平均分是 85 分，求全体同学的平均分（保留 4 位小数）。
//       —— 单组输入：一行两个整数 x y；一行一个实数，保留 4 位小数。
//
// 参考来源（本题的 C++ / C 题解与 AC 代码，均经本机编译验证后**改写**，非盲抄）：
//   1. https://blog.csdn.net/lq1990717/article/details/120170760
//      《信息学奥赛一本通 2071：【例2.14】平均分》（君义NOIP）
//      给出两解：(a) cin >> x >> y; cout << fixed << setprecision(4)
//                     << double(x*87+y*85)/(x+y);
//               (b) double x,y; scanf("%lf %lf",&x,&y);
//                     printf("%.4f",(x*87+y*85)/(x+y));
//      并点明考点：算术表达式 + 输出浮点数保留 x 位小数。
//      —— 与本题面/样例结论一致。
//   2. https://blog.csdn.net/sohf777/article/details/132031483
//      《【信息奥赛一本通】2071：【例2.14】平均分》
//      方法一 double s = (double)(x*87 + y*85)/(x+y); cout << fixed << setprecision(4) << s;
//      方法二 double s = 1.0*(x*87 + y*85)/(x+y); printf("%.4lf", s);
//      并强调「两个整数相除是整除，需先转实数」这一关键点。
//      —— 与来源 1 结论一致（同一公式的两种写法）。
//   3. https://blog.csdn.net/weixin_70576261/article/details/161261764
//      《【算平均分】信息学奥赛一本通C语言解法（题号2071）》
//      公式同为 all = 85*y + 87*x; printf("%.4f", all/(x+y));
//      **但该文代码有笔误**（`scanf("%d %d", &a, &y);` 里 a 未定义/应为 x），
//      故不采用其代码，只取其与来源 1、2 相同的公式结论；以题面语义为准用 x。
//   4. 官方题面（题目描述/输入/输出/输入样例/输出样例）
//      http://ybt.ssoier.cn:8088/problem_show.php?pid=2071
//      题面**未声明** x、y 的数据范围，也未声明任何特殊值。
//
// 冲突与处置：三个来源的核心公式完全一致（加权平均 = (87x+85y)/(x+y)），
// 仅来源 3 的代码有变量名笔误，按题面语义取 x；不存在语义歧义，故继续。
//
// 实现说明（本标程相对来源的改写点）：
//   - 用 long long 读入 x、y（来源 1 解法 a、来源 2 用 int），使中间量
//     87*x + 85*y 在自定工作范围（1 <= x,y <= 10^6 时约 1.72e8）及更大范围内都
//     不会溢出；先做整数乘法再转 double 除法，避免「整数整除」这一本题最经典的坑
//     （来源 2 的「知识点一：/」所强调的问题）。
//   - 输出用 printf("%.4f\n")，与样例 `85.8000` 完全一致（来源 1 解法 b）。
//   - I/O 形式为 stdin -> stdout，scanf/printf 风格参考 problems/1000/std.cpp。
//
// 复杂度：O(1)（一次乘法、一次加法、一次除法、一次格式化输出）。

#include <cstdio>

int main() {
    long long x, y;
    if (scanf("%lld %lld", &x, &y) != 2) return 0;
    // 加权平均：全体总分 = 87*x + 85*y，总人数 = x + y。
    // 分子为整数运算（long long），除法前转 double，保证结果是实数除法。
    double avg = (double)(87 * x + 85 * y) / (double)(x + y);
    printf("%.4f\n", avg);  // 保留 4 位小数，与题面【输出样例】一致
    return 0;
}
