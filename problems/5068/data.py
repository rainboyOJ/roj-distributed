#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2067《【例2.5】圆》数据生成器
#
# 题意：输入半径 r（实数），输出圆的直径、周长、面积；数与数之间一个空格，
#       每个数保留小数点后 4 位。
# 输入：一行一个实数 r。输出：一行三个数 d c s，各保留 4 位小数。
#
# π 取值（本题唯一歧义点，详见 std.cpp 头部考证与 gen-report.md）：
#     π = 3.14159。依据：同题 1014/洛谷 B2014/OpenJudge 1.3-09 的官方题面均
#     明确写「圆周率取值为3.14159」，且 1014 样例 r=3.0 -> 18.8495 唯一指向
#     3.14159（真 π 得 18.8496）。2067 自己的样例 r=1.0 对两种取值都成立，
#     无法判别，故以题源约定为准。
#
# 数据范围：题面【未声明】r 的范围（只说"输入半径"）。同题 1014 / 洛谷 B2014 /
#     OpenJudge 1.3-09 声明 `0 < r <= 10,000`，本题沿用该工作范围：
#         0 < r <= 10000，r 为至多 4 位小数的实数（例 1.0 即一位小数）。
#     上限下面积 ≈ 3.14e8、周长 ≈ 6.28e4，double 完全无精度/溢出风险。
#
# 单组输入题目：一个测试点即一个 r，规模=数值量级，分层按 r 的大小与取位铺开：
#   点 1     边界层：最小刻度 0.0001（4 位小数最小正值），面积为 0 的极端
#   点 2     边界层：题面【输入样例】1.0（题面声明的特殊值，必须出现）
#   点 3     边界层/口径：同题源样例 3.0 —— π 判别点（3.14159 与真 π 在此分道）
#   点 4     小规模定点：0.5 / 1.5（可手算，答案含 1.0000、3.1416 等整齐值）
#   点 5-6   小规模随机：可手算验证量级
#   点 7-8   中/大规模随机：范围中间档与接近上限
#   点 9     顶格层：r = 10000.0 取上限（全最大值）
#   点 10    顶格层：r = 9999.9239 —— 全定义域内**最贴近 4 位小数进位边界**的
#             4 位小数半径（周长距 tie 仅 2e-5），舍入最敏感的极端点
#
# 注：所有测试点的 r 都经过断言检查，保证 d/c/s 三项都不落在「第 4 位小数
#     恰好为 .5」的舍入 tie 上——tie 处 double 与精确十进制 half-up 可能分歧
#     （例如 r=7.5 的周长精确值 47.12385 恰为 tie），会让评测口径无谓变脆。

from cyaron import *  # 引入CYaRon的库

import random
from fractions import Fraction

random.seed(2067)  # 固定种子，便于复现

RMAX = 10000        # 自定工作范围上限（题面未声明，沿用同题 1014/洛谷 B2014 口径）
PI_EXACT = Fraction(314159, 100000)   # π = 3.14159（题源约定）


def _tie(r):
    """判断 2r、2πr、πr² 是否有任一项在第 4 位小数上恰为 .5（舍入 tie）。"""
    for v in (2 * r, 2 * PI_EXACT * r, PI_EXACT * r * r):
        x = v * 10000
        _, rem = divmod(x.numerator, x.denominator)
        if rem * 2 == x.denominator:
            return True
    return False


def gen_case(i, r_str, note):
    """写出第 i 组输入 r（字符串，保留解析所需的小数位），并由 std 生成 .out。"""
    r = Fraction(r_str)
    assert 0 < r <= RMAX, "r 超出自定工作范围 (0, 10000]: %s" % r_str
    assert not _tie(r), "r=%s 落在 4 位小数舍入 tie 上，会引入评测口径歧义" % r_str
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(r_str)
    io.output_gen("../std")
    print("problem%-2d: r=%-12s -- %s" % (i, r_str, note))


def rand_r(lo, hi, dec):
    """在 [lo, hi] 内随机取保留 dec 位小数的 r，跳过 4 位小数舍入 tie 的点。"""
    while True:
        k = random.randint(int(lo * 10 ** dec), int(hi * 10 ** dec))
        r_str = "%.*f" % (dec, k / 10 ** dec)
        r = Fraction(r_str)
        if 0 < r <= RMAX and not _tie(r):
            return r_str


# ---- 点 1：边界层（最小刻度，面积为 0 的极端） ----
# r=0.0001 是 4 位小数下的最小正值；面积 3.14159e-8 -> 输出 0.0000，
# 直径 0.0002、周长 0.0006，是"答案含 0"的极端。
gen_case(1, "0.0001", "边界层：4 位小数最小正值，面积四舍五入为 0.0000（答案 0 的极端）")

# ---- 点 2：边界层（题面样例，题面声明的特殊值） ----
# 题面【输入样例】1.0 -> 2.0000 6.2832 3.1416，题面声明的特殊值必须出现在数据里。
gen_case(2, "1.0", "边界层：题面【输入样例】1.0 -> 2.0000 6.2832 3.1416")

# ---- 点 3：边界层 / π 口径判别点 ----
# r=3.0 是同题 1014（与本题题面逐字相同）的【输入样例】，也是唯一能区分
# π=3.14159 与真 π 的经典判别点：3.14159 -> 18.8495，真 π -> 18.8496。
gen_case(3, "3.0", "π 判别点：同题 1014 样例 r=3.0 -> 18.8495（真 π 会得 18.8496）")

# ---- 点 4：小规模定点（可手算，答案整齐） ----
# 0.5 -> 1.0000 3.1416 0.7854；1.5 -> 3.0000 9.4248 7.0686，均可手算核对。
gen_case(4, "1.5", "小规模定点：r=1.5 -> 3.0000 9.4248 7.0686（可手算核对）")

# ---- 点 5-6：小规模随机（可手算验证量级） ----
gen_case(5, rand_r(1, 200, 2), "小规模随机：r∈(0,200]，2 位小数，可手算核对")
gen_case(6, rand_r(1, 2000, 3), "小规模随机：r∈(0,2000]，3 位小数，可手算核对")

# ---- 点 7-8：中 / 大规模随机 ----
gen_case(7, rand_r(1000, 10000, 4), "中等规模随机：r∈[1000,10000]，4 位小数")
gen_case(8, rand_r(5000, 9999, 4), "大规模随机：r∈[5000,9999]，4 位小数，贴近上限")

# ---- 点 9-10：顶格层（取上限 / 舍入最敏感极端） ----
gen_case(9, "10000.0", "顶格层：r=10000 取工作范围上限（全最大值）")
# r=9999.9239 是全定义域内最贴近 4 位小数进位边界的 4 位小数半径
# （周长精确值 62831.32185…，距 .5 边界仅 2e-5）：极端舍入权值，卡精度结构。
gen_case(10, "9999.9239", "顶格层极端权值：全定义域最贴近 4 位小数进位边界（距 tie 2e-5）")
