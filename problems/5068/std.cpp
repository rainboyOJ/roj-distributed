// 一本通 2067《【例2.5】圆》（目标 ROJ 题号 5068）标程
//
// 题意：输入圆的半径 r（实数），输出圆的直径、周长、面积；数与数之间以一个空格
//       分开，每个数保留小数点后 4 位。单组输入（一行一个实数 r）。
// 限制（config.json 与官方 OJ 页一致）：time 1000 ms，memory 64 MB（65536 KB）。
//
// ==================== π 取值考证（本题唯一歧义点） ====================
// 结论：π = 3.14159（题面未写出，由同题题源与教材同节题确证）。
// 证据（按强度排序）：
//
//  1)【决定性】同一道题在一本通另一题号 1014《与圆相关的计算》中给出**逐字相同**
//    的题面，并显式写明「圆周率取值为3.14159」；且 1014 的【输入样例】3.0 →
//    「6.0000 18.8495 28.2743」**唯一确定** π=3.14159：
//        3.14159 : 2π·3 = 18.84954   → 18.8495（与样例一致）
//        真 π    : 2π·3 = 18.84955.. → 18.8496（与样例不符）
//    1014 与本仓库 problems/1014（std.cpp 即 `pi=3.14159`）完全对得上。
//    来源 URL：
//      http://ybt.ssoier.cn:8088/problem_show.php?pid=1014
//        （题面含「圆周率取值为3.14159」，同题同样例）
//      https://www.luogu.com.cn/problem/B2014 （洛谷 B2014 同题，题面含 3.14159）
//      http://noi.openjudge.cn/ch0103/09/ （OpenJudge NOI 1.3 09，本题原始出处，
//        提示明确写「其中约定pi＝3.14159」）
//
//  2) 本题官方页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2067 的题面与样例
//     都**没有**写出 π，且 r=1.0 →「2.0000 6.2832 3.1416」对两种取值**都成立**：
//        3.14159 : 2π·1 = 6.28318 → 6.2832 ；面积 3.14159 → 3.1416
//        真 π    : 2π·1 = 6.28318 → 6.2832 ；面积 3.14159 → 3.1416
//     故【本题样例不能唯一确定 π】（反推可得 π ∈ [3.141575, 3.141625)，
//     3.14159 与真 π 都落在区间内）。任何「用 2067 样例定 π」的说法都推不出结论，
//     只能靠题源/教材约定。
//
//  3) 多篇 2067 题解直接写明 π 取 3.14159（这是本题唯一有明说的口径）：
//      https://blog.csdn.net/lvcheng0309/article/details/118049490
//        《信息学奥赛一本通（2067：【例2.5】圆）》：「由于题目中未给出π的值，
//        需要使用3.14159来代替」，参考代码 `#define PI 3.14159`
//      https://blog.csdn.net/m0_74116287/article/details/127849940
//        `c=2*3.14159*r; s=3.14159*r*r;`
//      https://blog.csdn.net/qinzhen20100224/article/details/122274598
//        `S=r*r*3.14159; l=r*2*3.14159;`
//      https://blog.csdn.net/tflstjs/article/details/119815298
//        `c=3.14159*2*r; s=3.14159*r*r;`
//
//  4)【反面口径，不作为结论】少数题解用 acos(-1)/M_PI（即真 π）：
//      https://blog.csdn.net/lq1990717/article/details/119963026
//        （该文主旨是演示「π 的多种定义法」——3.141592653589793/acos(-1)/
//          4*atan(1)/M_PI；同作者在 1014 题解中沿用 3.14159）
//      https://blog.csdn.net/sohf777/article/details/132075767 （M_PI）
//     两种口径在 r 稍大时几乎处处不同（如 r=3.0：18.8495 vs 18.8496），
//     不可能同时满足官方数据，必须择一。本标程取 3.14159：因为题源 1014 / 洛谷
//     B2014 / OpenJudge 的**官方题面**明确约定 3.14159，且本题位于教材
//     「第二章 第二节 常量和变量」，例题教学点正是「符号常量」——书上 π 写作
//     3.14159（与同节的 1014 一致）。
//
//  数据侧自检：data/ 全部 .out 由本 std 生成，π 口径全数据一致；data 中还特意
//  放了 r=3.0（1014 样例值），它是能把 3.14159 与真 π 区分开的判别点。
// ====================================================================
//
// 实现说明：改写自上述题解（非盲抄），风格参考 problems/1000/std.cpp。
//   double 读入 r，d=2r、c=2*PI*r、s=PI*r*r，printf("%.4f %.4f %.4f\n")。
//   乘法次序按题解主流写法 (2*PI)*r 与 (PI*r)*r，保证与参考实现逐位一致；
//   PI 用 const double = 3.14159（教材口径的符号常量）。
//   题面未声明 r 的范围；按同题 1014（及原题 OpenJudge）采用的 0 < r ≤ 10^4
//   作为工作范围，double 全程无精度/溢出风险（面积最大约 3.14e8）。
// 复杂度：O(1)。
#include <cstdio>

int main() {
    const double PI = 3.14159;  // 教材/题源约定的圆周率取值（题面未写出）
    double r;
    if (scanf("%lf", &r) != 1) return 0;  // 单组输入：一行一个实数半径
    double d = 2 * r;                     // 直径
    double c = 2 * PI * r;                // 周长 = (2*PI)*r，与参考实现同序
    double s = PI * r * r;                // 面积 = (PI*r)*r
    printf("%.4f %.4f %.4f\n", d, c, s);  // 四舍五入保留四位小数
    return 0;
}
