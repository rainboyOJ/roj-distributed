// 一本通 1222《放苹果》标程（C++17，stdin -> stdout）
//
// ============================ 参考来源（联网检索） ============================
// 本题按任务书要求先联网检索 C++ 解法（CSDN 站内搜索「一本通 1222 放苹果 题解」），
// 下列来源思路一致，代码按题面口径改写为「自底向上打表」版本（非盲抄）：
//   [1] https://blog.csdn.net/ryan1229/article/details/135878238
//       《信息奥赛一本通1222：放苹果》—— 给出递归式：
//       f(m,n) = f(m,n-1) + f(m-n,n)（n>=1, m>=n）；m<n 时 f(m,n)=f(m,m)；
//       m==0 或 m==1 时返回 1。样例 7 3 -> 8。
//   [2] https://blog.csdn.net/mengdicfm/article/details/90027074
//       《信息奥赛一本通1222：放苹果》—— DFS 按「盘子内苹果数非降」枚举去重，
//       结论与 [1] 一致（7 个苹果 3 个盘的 8 种放法逐条列出）。
//   [3] https://blog.csdn.net/ptyz306/article/details/132500877
//       《信息学奥赛一本通——1222：放苹果》—— DFS 逐盘不降枚举（last 参数），同上。
//   [4] https://blog.csdn.net/weixin_46272402/article/details/105995469
//       《信息学奥赛一本通C++语言——1222：放苹果》—— 递推写法。
// 来源结论无冲突，且与题面一致（盘子相同 -> 非降序列去重；允许空盘）。
// =============================================================================
//
// 题面数据范围：第一行 t（0 <= t <= 20）；随后 t 行每行 M N（1 <= M, N <= 10）。
// 限制：1000 ms / 64 MB（config.json，与官方页 1000 ms / 65536 KB 一致）。
//
// 算法：整数分拆计数。ways[m][n] = 把 m 个相同苹果放进 n 个相同盘（允许空盘）的分法数。
//   ways[0][n] = 1                                  （0 个苹果只有一种放法）
//   ways[m][n] = ways[m][n-1] + (m >= n ? ways[m-n][n] : 0)
//   含义：按「是否每个盘子都非空」分类 ——
//     * 至少一个空盘：等价于把 m 个放进 n-1 个盘，ways[m][n-1]；
//     * 每盘都非空：每盘先各取 1 个，剩 m-n 个再放进 n 个盘（仍允许空），ways[m-n][n]。
// 范围极小（答案最大值 K = ways[10][10] = 42），一次 O(MAXM*MAXN) 打表，
// 之后每组查询 O(1)，t 组共 O(t)。int 足够（K <= 42 << 2^31-1）。

#include <cstdio>

int main() {
    const int MAXM = 10, MAXN = 10;  // 题面取值上限 1 <= M, N <= 10

    static int ways[MAXM + 1][MAXN + 1];
    for (int n = 0; n <= MAXN; n++) ways[0][n] = 1;  // m = 0：唯一放法；该行仅为递推边界
    for (int m = 1; m <= MAXM; m++) {
        ways[m][0] = 0;  // 没有盘子放不下苹果；n >= 1 才可能非零（题面保证 n >= 1）
        for (int n = 1; n <= MAXN; n++)
            ways[m][n] = ways[m][n - 1] + (m >= n ? ways[m - n][n] : 0);
    }

    int t;
    if (scanf("%d", &t) != 1) return 0;  // 无输入时安全退出
    while (t-- > 0) {
        int m, n;
        if (scanf("%d %d", &m, &n) != 2) return 0;
        printf("%d\n", ways[m][n]);
    }
    return 0;
}
