// 题意：牧场牧草每天匀速生长。可供 15 头牛吃 20 天，或可供 20 头牛吃 10 天，
//       问每天新生的草量可供几头牛吃 1 天？（输入：无）
//
// 推导（设每头牛每天吃草 1 单位，A 为初始草量，g 为每天新生草量）：
//    15 * 20 = A + 20g            （1）
//    20 * 10 = A + 10g            （2）
//   (1) - (2): 300 - 200 = 10g  =>  g = 10
//   即每天新生的草量可供 10 头牛吃 1 天，答案唯一为 10。
//
// 参考来源（本轮逐篇实际抓取核验，改写而非盲抄）：
//   官方题面（输入/输出/样例、1000ms/65536KB 限制，本轮实测可访问）：
//     http://ybt.ssoier.cn:8088/problem_show.php?pid=2063
//     （页面原文：【输出】如题述，牛的数量。【输入样例】（无）【输出样例】（无））
//   输出“纯数字 10”的多数来源（与题面一致，采用）：
//     1. https://blog.csdn.net/qiaoweichen/article/details/119494461
//        标题「信息学奥赛一本通题库2063 【例1.4】牛吃牧草」，
//        参考代码 `int a=15*20; int b=20*10; cout<<(a-b)/(20-10);` → 10
//     2. https://blog.csdn.net/u014117969/article/details/135354877
//        标题「信息学奥赛一本通：2063：【例1.4】牛吃牧草」，
