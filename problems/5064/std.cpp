//        标题「信息学奥赛一本通--2063牛吃牧草」（参考代码同 1）→ 10
//   输出“s=10”的少数来源（与题面【输出】不符，不采用，详见 gen-report.md 冲突说明）：
//     5. https://blog.csdn.net/zjq7811/article/details/140805938
