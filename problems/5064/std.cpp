//          该行与本问题（答案 10）无关，属其他题的输出格式模板，判定为误抄）
//   旁证（镜像站，输出纯数字）：
//     8. https://www.dotcpp.com/oj/problem2999.html
//        （题面原文：「输出格式 如题所述，牛的数量。」样例（无））
//     9. https://blog.csdn.net/yaosichengalpha/article/details/143390962
//        （编程启蒙版「练4.4 牛吃牧草」：「输出一个自然数，表示每天新生的草量
//          可供几头牛吃 1 天。」→ 纯自然数，无前缀）
//
// 判定：题面【输出】为「如题述，牛的数量。」——即牛的数量本身，无 "s=" 前缀；
//       多个来源结论冲突时以题面为准（任务书要求），故输出纯数字 10。
//
// 实现：无输入题，不读取任何输入；常量直算后输出 10 并换行。
// 复杂度 O(1)，运行时间远小于 1000 ms 限制。
#include <cstdio>

int main() {
    const int s1 = 15 * 20;               // 15 头牛 20 天的总食草量
    const int s2 = 20 * 10;               // 20 头牛 10 天的总食草量
    const int ans = (s1 - s2) / (20 - 10);  // 每天新生草量 = (300-200)/(20-10) = 10

    printf("%d\n", ans);
    return 0;
}
