// 一本通 1811《多项式相乘》标程
//
// 题意：展开 (x+a_1)(x+a_2)...(x+a_n)，按题面写法统计展开式的总长 t，
//       输出 t mod 10000。输入一个整数 n，1 <= n <= 10^9。
//
// 展开式的书写形式（以题面 n=3 为例，其总长为 40）：
//   x^3 + x^2(a_1+a_2+a_3) + x(a_1a_2+a_1a_3+a_2a_3) + a_1a_2a_3
// 即：指数 e 从 n 降到 0，每个指数项把"同次系数"写成所有 C(n,e) 个
//     k=n-e 个 a 的乘积之和，用括号括起、内部用 '+' 连接；系数为 1 的
//     最高次项 x^n 省略系数、也不带括号；常数项（e=0，系数只有 1 个单项式）
//     不带括号。
//
// 计长规则（题面明确）：字符 x、a、(、)、+ 各计 1；指数的每个数字计 1；
//   下标的每个数字计 1。注意 '^' 不计长（题面枚举的计数字符里没有 '^'，
//   且只有"指数的数字"计长）；x^1 写作 "x"（不写 ^1）；x^0 不写 x。
//
// ---- 公式推导（设 d(i)=十进制位数, D = Σ_{i=1}^n d(i)）----
// 记 ΣP(e) 为所有单项式自身的长度之和：
//   Σ_{e=0}^n P(e) = Σ_{e=0}^n C(n,e)(n-e) + D * Σ_{e=0}^n C(n-1,n-e-1)
//                  = n*2^{n-1} + D*2^{n-1}
//   （每个 a_i 在大小为 k 的单项式集合中出现 C(n-1,k-1) 次，对 k 求和得 2^{n-1}）
// 结构字符长度：
//   最高次项 x^n：1 + d(n)（n>=2；n=1 时为 1）
//   中间项 0<e<n：x 的 1 个字符 + (e>=2 ? d(e) : 0) + 左右括号 2 + 内部 C(n,e)-1 个 '+'
//   常数项 e=0：无结构字符
//   各项之间的 n 个 '+'
//   求和化简后 d(n) 恰好抵消，得
//     t(n) = 2^{n-1} * (n + D) + 2^n + 3n + D - 4
// 已用题面样例与手算逐项核对：
//   n=1 -> 4 ; n=2 -> 16 ; n=3 -> 40（题面样例）; n=4 -> 92（手数展开式）.
//
// 复杂度 O(log n)（快速幂）+ O(log10 n)（按位数统计 D），内存 O(1)。
// 无解/空输出点：本题对任意合法 n 均有输出，不存在空输出。
//
// 来源说明：题面为《信息学奥赛一本通·高手训练》原创题（作者署名 FireDancer），
//   联网以题面特征句（"多项式相乘的展开是一件相当烦琐的工作"、
//   "展开式的总长"、"n<=10^9" 等）在必应/CSDN 多轮检索均未找到公开题解，
//   故本标程依据题面定义自行推导并逐点核验（见上）。
#include <cstdio>

typedef long long ll;

const int MOD = 10000;

// 快速幂：b^e mod m
static ll power_mod(ll b, ll e, ll m)
{
    ll r = 1 % m;
    b %= m;
    while (e > 0) {
        if (e & 1LL)
            r = r * b % m;
        b = b * b % m;
        e >>= 1;
    }
    return r;
}

int main()
{
    ll n;
    if (scanf("%lld", &n) != 1)
        return 0;

    // D = Σ_{i=1}^{n} d(i) mod MOD，按十进制位数分段统计（O(log n)）
    ll D = 0;
    ll lo = 1;
    for (int len = 1; len <= 18 && lo <= n; ++len) {
        ll hi = lo * 10 - 1;
        if (hi > n)
            hi = n;
        ll cnt = hi - lo + 1;
        D = (D + (cnt % MOD) * (len % MOD)) % MOD;
        lo = hi + 1;
    }

    ll nm = n % MOD;
    ll p1 = power_mod(2, n - 1, MOD);   // 2^{n-1} mod MOD
    ll p2 = power_mod(2, n, MOD);       // 2^n   mod MOD

    ll res = p1 * ((nm + D) % MOD) % MOD;      // 2^{n-1} * (n + D)
    res = (res + p2) % MOD;                    // + 2^n
    res = (res + 3 * nm) % MOD;                // + 3n
    res = (res + D) % MOD;                     // + D
    res = ((res - 4) % MOD + MOD) % MOD;       // - 4
    printf("%lld\n", res);
    return 0;
}
