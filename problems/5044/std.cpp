// 一本通 2042《【例5.10】稀疏矩阵》（目标 ROJ 题号 5044）标程
//
// 题意：读入 n 行 m 列的矩阵（元素为非负整数，非 0 元素为正整数且 < 1000），
//       把矩阵的非 0 元素按「行号 列号 值」（均 1 起）逐行输出——即稀疏矩阵的
//       K×3 简记形式。题面明确「简记形式有多种形式，输出一种正确形式即可」，
//       故这里采用与本包所有测试数据一致的**行主序（先按行号、再按列号）**输出：
//       （1）题面正文中的「如」示例正是行主序：
//              0 0 0 5 / 0 2 0 0 / 0 1 0 0  ->  1 4 5 / 2 2 2 / 3 2 1
//       （2）行主序是网络 AC 代码（见下）的一致写法，也是本包 std 生成 .out 的
//           口径，用户提交行主序解法即可与本包数据严格比对通过。
//       题面【输出样例】的四行是同一批三元组的另一种排列（把 3 5 1 提到了最前），
//       同样合法；本包按题面约定以「三元组多重集合相等」验证（见 work/check_sample.py、
//       gen-report.md §3 与风险点）。
//
// 输入：第一行 n m；接下来 n×m 个整数（按行给出）。输出：每个非 0 元素一行
//       「行号 列号 值」；矩阵全 0 时无任何输出。输入输出均为 stdin -> stdout。
//
// 参考来源（均已用 curl 取回正文逐行核对过，本文件为改写实现，非盲抄）：
//   [1] 官方 OJ 页《2042：【例5.10】稀疏矩阵》
//       http://ybt.ssoier.cn:8088/problem_show.php?pid=2042
//       —— 题面、样例、时间 1000 ms / 内存 65536 KB 的唯一权威口径；
//          正文「如」示例为行主序，且未声明 n、m 的取值范围。
//   [2] 博客园《2042：【例5.10】稀疏矩阵 - 禹城我的家》
//       https://www.cnblogs.com/zheng1945/p/16298549.html
//       —— 参考代码：int a[100][100]; cin>>n>>m; 两层循环 i=1..n、j=1..m 读入，
//          再两层循环，if(a[i][j]!=0) cout<<i<<" "<<j<<" "<<a[i][j]<<endl;
//          即行主序输出；数组开 100×100 说明其认定的规模上界是 n,m<=100。
//   [3] CSDN《【信奥赛一本通】2042：【例5.10】稀疏矩阵（详细代码）》
//       https://blog.csdn.net/qq_40802813/article/details/119725773
//       （原站返回 TLS 错误，本包经 Wayback 快照实取正文核对：
//        http://web.archive.org/web/20250717003326/https://blog.csdn.net/qq_40802813/article/details/119725773）
//       —— 参考代码：int a[100][100]={0},n,m; cin>>n>>m; 读入后两层循环，
//          if(a[i][k]!=0) cout<<i+1<<" "<<k+1<<" "<<a[i][k]<<endl;（0 起下标 +1）。
//   [4] CSDN《2042：【例5.10】稀疏矩阵》
//       https://blog.csdn.net/HAFT41016/article/details/122635665
//       （原站 TLS 错误，经 Wayback 快照实取核对：
//        http://web.archive.org/web/20250717003425/https://blog.csdn.net/HAFT41016/article/details/122635665）
//       —— 参考代码：int a[100][100],n,m; 1 起下标读入读满，再 if(a[i][j]!=0)
//          cout<<i<<" "<<j<<" "<<a[i][j]<<endl;（与来源 [2] 同构）。
//   三个代码来源结论完全一致（行主序、1 起行列号、无表头/无计数行），与题面正文
//   示例一致，不存在需要停下的题面歧义；唯一分歧是官方【输出样例】的行序（属题面
//   明文允许的多解），已在风险点中记录。
//
// 实现说明（本标程相对来源的改写点）：
//   - 不落 2D 数组，边读边判边输出（O(1) 额外空间），故不受参考代码 a[100][100]
//     的规模上界约束；本包数据仍按 1<=n,m<=100 造（见 data.py 说明与风险点 1）。
//   - 用 scanf/printf（风格对齐 problems/1000/std.cpp），避免 iostream 同步开销。
//   - 读到输入不足时直接结束（防止越界读）；输出每个非 0 元素一行，行末换行。
//
// 复杂度：O(n·m) 时间、O(1) 额外空间；顶格 100×100 数据远低于 1000 ms 限制。

#include <cstdio>

int main() {
    int n = 0, m = 0;
    if (scanf("%d %d", &n, &m) != 2) return 0;  // 无输入/格式异常时安全退出
    for (int i = 1; i <= n; ++i) {
        for (int j = 1; j <= m; ++j) {
            int v;
            if (scanf("%d", &v) != 1) return 0;
            if (v != 0) {
                // 行主序输出「行号 列号 值」，行列号均为 1 起（题面示例口径）
                printf("%d %d %d\n", i, j, v);
            }
        }
    }
    return 0;
}
