// 来源一致性（无冲突）：9 个来源的两种算法路线完全等价——
//   (A) 枚举 aabb 结构（a∈[1,9], b∈[0,9]）判是否完全平方；
//   (B) 枚举 [1000,9999] 内的完全平方数（i=32..99，因为 31^2=961<1000、100^2=10000）
//       再判四个数位是否满足 aabb。
//   两条路线在 1000..9999 内的解集相同，只有唯一解 7744 = 88^2（来源 [3] 直接注明）。
//   题面本身无歧义，未触发「停下报告」条件。
//
// 本标程的改写点（相对来源，非盲抄）：
//   - 取来源 [1] 解法1 / [6] 的「构造 aabb + 判完全平方」路线，但**完全不用浮点**：
//     平方根用 `while (r*r < n) ++r;` 的自增整数求法（n ≤ 9999，r ≤ 99，代价可忽略），
//     规避 sqrt/floor 的浮点取整边界问题（来源 [6] 用 floor(sqrt(x)+0.5) 是常见写法，
//     本题数值下也正确，此处只做等价的稳健化改写）；
//   - 头文件按仓库 problems/1000/std.cpp 的风格用 <cstdio> + printf，并显式 return 0；
//   - 输入为「无」，故不读任何输入；每个命中数单独一行输出（与题面「每个数占一行」一致）。
//
// 复杂度 O(9*10*100) ≈ 常数；实测远低于 1000 ms / 64 MB。

#include <cstdio>

int main() {
    for (int a = 1; a <= 9; ++a) {          // 首位 a：保证是四位数（a != 0）
        for (int b = 0; b <= 9; ++b) {      // 次位 b：可为 0
            int n = a * 1100 + b * 11;      // 形如 aabb 的整数（a*1000+a*100+b*10+b）
            int r = 0;
            while (r * r < n) ++r;          // 整数平方根（无浮点误差）
            if (r * r == n) {               // 完全平方数 ⇒ 命中一个解
                printf("%d\n", n);
            }
        }
    }
    return 0;
}
