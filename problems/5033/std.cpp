//       —— for(n=32;n<=99;n++){ c=n*n; a=c/100; b=c%100; if(a%11==0 && b%11==0) 输出; }
//          （两位数字相同 ⇔ 该两位数是 11 的倍数）。
//   [6] 我是凌一LY《信息学奥赛一本通C++语言-----2031：【例4.17】四位完全平方数》
//       https://blog.csdn.net/wzq_wzq123/article/details/122910450
//       —— 枚举 i=1..9, j=1..9 构造 x=i*1100+j*11，m=floor(sqrt(x)+0.5)，
//          if(m*m==x) 输出 x。
