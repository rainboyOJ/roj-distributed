// 一本通 2031《【例4.17】四位完全平方数》（目标 ROJ 题号 5033）—— 标程
//
// 题意：输出所有形如 aabb 的四位完全平方数（前两位数字相等、后两位数字也相等）。
//       输入：无。输出：由小到大输出，每个数占一行。
// 数据范围：无输入量（输出恒定）；时间限制 1000 ms / 内存 64 MB（config.json，
//       与官方题面页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2031
//       实测显示的「时间限制: 1000 ms 内存限制: 65536 KB」一致）。
// 答案：7744（88^2），唯一解——见下方来源一致结论与 work/ 下的独立复核。
//
// 参考来源（本轮均用 curl 实取页面正文/代码块核对，非盲抄搜索摘要）：
//   [1] 君义_noip《信息学奥赛一本通 2031：【例4.17】四位完全平方数》
//       https://blog.csdn.net/lq1990717/article/details/121274803
//       —— 给出两种解法：解法1「分别枚举 a∈[1,9], b∈[0,9]，num=i*1000+i*100+j*10+j，
//          d=sqrt(num)，if(num==d*d) 输出」；解法2「遍历 1000..9999 做数字拆分，
//          千位==百位且十位==个位后再判完全平方」。并给出完全平方数的判法
//          （开方取整后自乘回比）。
//   [2] 《四位完全平方数（信息学奥赛一本通-2031）》
//       https://blog.csdn.net/2402_84298973/article/details/146204247
//       —— for i = ceil(sqrt(1000)) .. floor(sqrt(9999))（即 32..99），拆 i*i 的四个数位，
//          a==b && c==d 则输出 i*i。
//   [3] 南沙信C++陈老师《2031：【例4.17】四位完全平方数》
//       https://blog.csdn.net/chinajsczlymyc/article/details/122741152
//       —— 说明「31*31=961、32*32=1024，从 33 起穷举到 99（100^2=10000）」，并直接在
//          代码注释中写明「答案为 7744（88^2）」。
//   [4] 《信息学奥赛一本通（2031：【例4.17】四位完全平方数）》
//       https://blog.csdn.net/lvcheng0309/article/details/116719436
//       —— C 语言参考：for(i=31;i<=99;i++){ n=i*i; a=n/100; b=n%100;
//          if(a/10==a%10 && b/10==b%10) 输出 n; }（前两位作为两位数 a、后两位作为 b）。
//   [5] 《2031：【例4.17】四位完全平方数 原创分析，内含源代码》
