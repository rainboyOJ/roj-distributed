// 一本通 2034《【例5.1】反序输出》（目标 ROJ 题号 5036）标程
//
// 题意（本包 content.md；官方页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2034
// 于本轮实测抓取核对，题面逐字一致，页面显示「时间限制: 1000 ms 内存限制: 65536 KB
// 提交数: 149891 通过数: 70734」）：
//   【题目描述】输入 n 个数，要求程序按输入时的逆序把这 n 个数打印出来，
//               已知整数不超过 100 个。也就是说，按输入相反顺序打印这 n 个数。
//   【输入】输入一行共有 n 个数，每个数之间用空格隔开。
//   【输出】如题要求：一行，共有 n 个数，每个数之间用一个空格隔开。
//   【输入样例】1 7 3 4 5   【输出样例】5 4 3 7 1
//   限制：time 1000 ms / memory 64 MB（config.json；官方页 65536 KB，一致）。
//
// 关键判读（本包对题面的确定性解读，见 gen-report.md）：
//   * 输入中**不单独给出 n**（题面输入只有「一行 n 个数」），故 n 必须由「读到文件末尾」
//     或「读到行末」得到 —— 这正是本题（数组章第 1 例）的考点（来源 [1][2][3] 的题解
//     都在讲 "while(cin>>x)" / "while(scanf(...)!=EOF)" 的读法）。
//   * 「整数不超过 100 个」只约束**个数** n ≤ 100，未约束每个数值的大小；本包工作范围
//     取 int32 可表示的全部整数（主档 0..10000，另设值域两极测试点）。
//   * 数据与输出均为**一行**、元素之间**单个空格**（输出行末不留多余空格，行末换行）。
//
// 参考来源（网络题解 / 参考代码，本包已逐篇 curl 实取正文核对，随后按题面改写，非盲抄）：
//   [1] https://blog.csdn.net/lq1990717/article/details/121544760
//       君义_noip《信息学奥赛一本通 2034：【例5.1】反序输出》：
//         解法1：填充到下标 0~n-1 ——
//           int a[105], ai = 0, x;
//           while (cin >> x) a[ai++] = x;
//           for (int i = ai - 1; i >= 0; --i) cout << a[i] << ' ';
//         并讲解「输入不确定个数的数字」：OJ 上从文件输入，读到文件末尾 EOF 时
//         cin >> a 返回 false、scanf("%d", &a) 返回 EOF，循环跳出。
//   [2] https://blog.csdn.net/lvcheng0309/article/details/116780357
//       橙子教师《信息学奥赛一本通（2034：【例5.1】反序输出）》（C）：
//           #include <stdio.h>
//           #define N 100
//           int a[N];
//           int main() { int i = 0, n;
//               while (scanf("%d", &a[i]) != EOF) { i++; }
//               n = i;
//               for (i = n - 1; i >= 0; i--) printf("%d ", a[i]);
//               printf("\n"); return 0; }
//       （该实现每个元素后都跟一个空格，末元素后多一个空格 —— 本包按题面
//         「每个数之间用一个空格隔开」输出**无行末空格**的版本，判题器 diff -b 下两版等价。）
//   [3] https://blog.csdn.net/2402_84298973/article/details/146229849
//       Doopny@《反序输出（信息学奥赛一本通-2034）》：
//           const int N = 1e2 + 10; int nums[N];
//           int n, m = 1; while (cin >> n) { nums[m++] = n; }
//           for (int i = m - 1; i >= 1; i--) cout << nums[i] << ' ';
//       （下标 1~m 的填充方式；同样用 EOF 结束读入。）
//   [4] https://blog.csdn.net/strawberrytreea/article/details/124337320
//       橙子教师《信息学奥赛一本通（c++）：2034：【例5.1】反序输出》：
//           int a[100];
//           for (i = 0; i < 100; i++) { cin >> a[i]; if (getchar() == '\n') break; }
//           for (int j = i; j >= 0; j--) cout << a[j] << " ";
//       ★ 该写法用「读到换行符」判定结束 —— 要求测试数据把 n 个数**放在同一行**。
//         （本包 data.py 因此强制「单行 + 空格分隔 + 行末换行」，与题面【输入】一致。）
//   [5] https://blog.csdn.net/xiang20100794/article/details/123458301
//       墨衍《信奥赛一本通 C++题解 2034【例5.1】反序输出》：
//           int n; int i = 0; cin >> n; a[i] = n;
//           while (cin >> n) { ++i; a[i] = n; }
//           for (int j = i; j >= 0; j--) cout << a[j] << " ";
//       （先单独读第 1 个数、再循环读其余；对任何个数 ≥1 的输入都正确。）
//   另有 https://blog.csdn.net/m0_71459256/article/details/128461270 复述题面
//   （正文需付费/登录，未取到代码，仅作题面核对来源，未采用）。
//
// 多来源结论核对（无冲突）：所有来源算法一致 —— 顺次读入所有整数存入数组（容量 ~10^2+ε），
//   再从最后一个读到第一个、按单个空格分隔输出。差异仅在「读入终止条件」（EOF / '\n'）
//   与「行末是否多一个空格」，前者由数据「单行」满足，后者对 diff -b 判题器等价。
//   题面本身无歧义（输入/输出格式明确且给出样例），未触发任务书的「停下报告」条件。
//
// 本包实现（C++17，stdin→stdout，风格参考 problems/1000/std.cpp）：
//   * 用 scanf("%d") != EOF 读到文件末尾（来源 [1][2] 的路线），数组容量 105（题面 n ≤ 100 留余量），
//     循环条件再加 n < MAXN 防御越界输入（题面保证不会发生，仅避免 UB）；
//   * 逆序打印，元素间**单个空格**、行末无多余空格、结尾补一个 '\n'
//     （与题面「每个数之间用一个空格隔开」的字面要求一致，且对行末空格敏感的严格判题器也安全）；
//   * 复杂度 O(n) 时间、O(n) 空间（n ≤ 100）；实测最大点（n=100）耗时 < 3 ms、内存 ~1 MB，
//     远低于 1000 ms / 64 MB。

#include <cstdio>

const int MAXN = 105;  // 题面：整数不超过 100 个，留 5 个余量

int a[MAXN];

int main() {
    int n = 0, x;
    // 读到文件末尾（题面不单独给出 n，须按 EOF 结束读入；见文件头判读说明）
    while (n < MAXN && scanf("%d", &x) == 1) {
        a[n++] = x;
    }

    // 逆序输出：元素之间用单个空格隔开，行末不留多余空格
    for (int i = n - 1; i >= 0; --i) {
        if (i != n - 1) putchar(' ');
        printf("%d", a[i]);
    }
    if (n > 0) putchar('\n');  // 行末换行（题面保证 n ≥ 1；空输入时零输出，防御性处理）

    return 0;
}
