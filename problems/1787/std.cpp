/*
 * 一本通 1787《保龄球》  （ROJ 1787，来源：信息学奥赛一本通 · 高手训练篇 · 五、动态规划）
 *
 * ── 题意（据 content.md 与官方题面）───────────────────────────────────────────
 * 一排 n 个球瓶，第 i 个分值 a[i]（可为负）。有 k 个保龄球，每个球宽度 w：
 * 一个球恰好占据「连续 w 个位置」的一段区间，把这些位置上「仍立着」的球瓶全部击倒
 * 并得到它们的分值之和。被击倒的球瓶留下空位，球可以经过空位（空位上不得分）；
 * 球瓶 1 左边、球瓶 n 右边也都有足够的空位（球可以越出整排球瓶的边界）。
 * 求投完 k 个球后能得到的最大总分。多组数据，第一行 t。
 *
 * ── 标程来源（网络检索，均以 curl 实取正文核对）──────────────────────────────
 * [1] https://blog.csdn.net/qq_43857314/article/details/107717189
 *     《【upc】保龄球 (bowling) | 单调队列优化dp》（chen03）
 *     —— 同一道题的原始版本（n,k,w + n 个分值，样例同为 39 / 38，样例 2 解释逐字一致：
 *        「第一次击打区间[1,2]…用了球瓶1左边的空位…第三次击打区间[7,8]…用了球瓶6留下的空位」）。
 *        给出状态 dp[i][k][0/1] + 单调队列优化，并把枚举范围扩到 n+w-1
 *        （`for(int i=n+1;i<=n+p-1;i++) f[i]=f[n];`）来处理「球越出右边界」。
 * [2] https://blog.csdn.net/wu_yihao/article/details/6954637 《【保龄球】解题报告》
 *     —— 同题，明确写出两条转移：
 *        f[i][j] = max{ f[i-1][l] + sum[j]-sum[j-w]   , l ∈ [0, j-w]   （新开一段，打满 w 个）
 *                     , f[i-1][l] + sum[j]-sum[l]     , l ∈ [j-w, j-1]（与上一段重叠，只算新增部分）}
 *        并指出「右边界用和青蛙过河一样的处理，将枚举范围扩大为 n+w」。
 *     该文给出的实现是 O(k·n·w)（自述「目前40分，超时6组」），本标程按 [1] 的思路改成
 *     单调队列 O(k·n)。
 * [3] 官方题面（用于核对输入格式与数据范围）：
 *     http://ybt.ssoier.cn:8088/problem_show.php?pid=1787
 *     注：本题在 1787 中加了多组数据（t ≤ 10），原始版本 [1][2] 为单组。
 *
 * ── 算法（本标程的推导，等价于 [1] 的 dp[i][k][0/1] + 单调队列）────────────────
 * 记位置 1..n 为球瓶，把数组向右补 w-1 个 0（位置 n+1..n+w-1）来模拟「球越出右边界」；
 * 记 N = n+w-1，P[i] = 前缀和（补 0 部分 P 不增）。
 *
 * 关键点（也是本题唯一的坑）：**重叠**转移要求「本球窗口压住的那几个位置本来就已经被
 * 上一球打空」。若只用「前 i 个位置里用 j 个球的最优值」这一状态，就可能把「其实还立着
 * 的负分球瓶」当成空位跳过，从而算大（例如 n=24,w=6 的随机数据上会多算出 2000 多分）。
 * 因此状态必须记录「最后一个球的窗口右端点恰在 i」：
 *
 *   A[i][j] = 用 j 个球、且第 j 个球的窗口右端点恰为 i（窗口 = 位置 i-w+1..i，
 *             若 i-w+1 ≤ 0 则球从球瓶 1 左侧的空位伸进来，只打 1..i）时的最大得分。
 *             A[0][*] = -∞；A[i][0] = -∞。
 *   B[i][j] = 用「至多」j 个球、所有窗口右端点都 ≤ i 时的最大得分（i 号位置可打可不打）。
 *             B[0][j] = 0，B[i][j] = max(B[i-1][j], A[i][j]) ≥ B[i-1][j]（对 i 单调不减）。
 *
 * 转移（A[i][j] 的两种情况）：
 *   (1) 首尾相接：本球窗口与上一球窗口不重叠，上一球窗口右端点 p = i-w（若 i-w<0 则
 *       p = 0，即球从左边界外伸进来）。此时上一球只需「右端点 ≤ p」，取 B[p][j-1]：
 *         A[i][j] ← B[max(0,i-w)][j-1] + (P[i] - P[max(0,i-w)])
 *   (2) 重叠：上一球窗口右端点 p ∈ [max(0,i-w+1), i-1]。因为上一球窗口覆盖 [p-w+1, p]
 *       而 i-w+1 ≥ p-w+1，所以本球窗口压在 [i-w+1, p] 上的那几个位置**确实已被打空**，
 *       本球只新增 p+1..i 这些球瓶：
 *         A[i][j] ← P[i] + max_{p ∈ [max(0,i-w+1), i-1]} ( A[p][j-1] - P[p] )
 *       内层是固定 j-1、随 i 滑动的长度 w-1 的区间最大值 → 单调队列 O(1) 摊还。
 *
 * 答案：B[N][k]（B 对 j 单调不减，故「至多 k 个球」即用 ≤ k 个球的最大值；
 *       因为可以把球扔到空位/界外，答案 ≥ 0，全负数据下答案就是 0）。
 *
 * 复杂度：O(t · k · (n+w)) 时间，O(n+w) 额外空间（滚动数组）。
 * 自检：题面样例 39 / 38 均通过；样例 2 的最优解 (2+8)+(3+5+8)+(4+8)=38 正是靠
 *       「左溢出」与「重叠窗口复用空位」两种转移，本标程能复现。
 */
#include <cstdio>
#include <vector>
#include <algorithm>
using namespace std;
typedef long long ll;

int main() {
    int T;
    if (scanf("%d", &T) != 1) return 0;
    while (T--) {
        int n, k, w;
        scanf("%d %d %d", &n, &k, &w);
        int N = n + w - 1;                      // 右边界外补 w-1 个空位
        vector<ll> P(N + 1, 0);
        for (int i = 1; i <= n; i++) {
            ll v;
            scanf("%lld", &v);
            P[i] = P[i - 1] + v;
        }
        for (int i = n + 1; i <= N; i++) P[i] = P[n];   // 补 0：前缀和不变

        const ll NEG = -(1LL << 60);                    // 远小于任何真实得分（|得分| ≤ 10^8）
        vector<ll> prevA(N + 1, NEG), curA(N + 1, NEG); // A[*][j-1] / A[*][j]
        vector<ll> prevB(N + 1, 0), curB(N + 1, 0);     // B[*][j-1] / B[*][j]
        vector<int> dq(N + 1);                          // 单调队列（下标）
        for (int j = 1; j <= k; j++) {
            int head = 0, tail = 0;                     // dq[head..tail-1]
            curB[0] = 0;
            curA[0] = NEG;
            for (int i = 1; i <= N; i++) {
                int p = i - 1;                          // 先把 p = i-1 放入队列
                ll v = prevA[p] - P[p];
                while (tail > head && prevA[dq[tail - 1]] - P[dq[tail - 1]] <= v) tail--;
                dq[tail++] = p;
                int lo = i - w + 1;                     // 队列里只保留 p ∈ [lo, i-1]
                if (lo < 0) lo = 0;
                while (head < tail && dq[head] < lo) head++;
                ll best = NEG;
                if (head < tail) {                      // (2) 重叠：上一球窗口右端点为 p
                    best = P[i] + prevA[dq[head]] - P[dq[head]];
                }
                int q = i - w;                          // (1) 首尾相接 / 左溢出
                if (q < 0) q = 0;
                best = max(best, prevB[q] + P[i] - P[q]);
                curA[i] = best;
                curB[i] = max(curB[i - 1], best);
            }
            prevA.swap(curA);
            prevB.swap(curB);
        }
        printf("%lld\n", prevB[N]);
    }
    return 0;
}
