#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2062《【例1.3】电影票》—— 测试数据生成器（cyaron，仓库惯例）
# 用法：mkdir -p data && cd data && python3 ../data.py
#
# 题意：一位小朋友票价 10 元，输入人数 x，输出「人数 总票价」（x 与 x*10，一个空格隔开）。
# 样例：输入 2 => 输出 2 20。
#
# 数据范围：题面与官方 OJ 页面（https://ybt.ssoier.cn/problem_show.php?pid=2062）
#   **均未声明 x 的取值范围**。按语料惯例（参考 .ybt-import/staging/2068）自定工作范围：
#       1 <= x <= 10^8   （此时总票价 x*10 <= 10^9，仍在 int32 安全范围内，
#                         书中 int 写法的 AC 程序亦不会被卡；std 用 long long 仅作保险）
#   x 下界取 1：题面描述为"x 位小朋友"，隐含至少有 1 位小朋友；
#   "答案为 0 或 1 的极端"在本域内不可达（答案 = 10x，最小为 10），见 gen-report.md 说明。
# 本题为单组输入（一个测试点即一个整数 x），不存在多组数据的"组数分层"，
# 分层按 x 的量级从最小铺到自定上限：
#   点 1-2  边界层（全最小值 x=1；题面声明的特殊值 x=2）
#   点 3-4  小规模随机（可手算验证的量级）
#   点 5-6  中等规模随机（范围中间档）
#   点 7-8  大规模随机（接近上限）
#   点 9-10 顶格层（全最大值 x=10^8；顶格附近的 9 连位数进位结构）
from cyaron import *  # 引入CYaRon的库

import random
random.seed(2062)  # 固定种子，便于复现

XMAX = 100000000  # 自定工作范围上限（题面未声明）


def gen_case(i, x, note):
    """写出第 i 组：输入 x，用 std 生成输出；并打印手工可核对的期望值。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(x)
    io.output_gen("../std")
    print("problem%d: x=%d => %d %d -- %s" % (i, x, x, x * 10, note))


# ---- 点 1-2：边界层 ----
# 点 1：全最小值 x=1（题面未声明特殊值；答案 10 为本域内最小答案，答案含 0 的极端不可达）
gen_case(1, 1, "边界层：全最小值 x=1，最小答案 10")

# 点 2：题面【输入样例】声明的特殊值 x=2（对应【输出样例】2 20）
gen_case(2, 2, "边界层：题面声明的特殊值 x=2（样例值），答案 20")

# ---- 点 3-4：小规模随机（可手算验证的量级） ----
# 点 3：x ∈ [3,100] —— 一位/两位量级，可手工乘 10 核对
x = random.randint(3, 100)
gen_case(3, x, "小规模随机：x∈[3,100]，可手算核对")

# 点 4：x ∈ [101,5000] —— 小量级上沿，手算可行
x = random.randint(101, 5000)
gen_case(4, x, "小规模随机：x∈[101,5000]，可手算核对")

# ---- 点 5-6：中等规模随机（范围中间档） ----
# 点 5：x ∈ [5001,10^5]
x = random.randint(5001, 100000)
gen_case(5, x, "中等规模随机：x∈[5e3,1e5]，范围中间档")

# 点 6：x ∈ [10^5,10^6]
x = random.randint(100000, 1000000)
gen_case(6, x, "中等规模随机：x∈[1e5,1e6]，范围中间档偏上")

# ---- 点 7-8：大规模随机（接近上限） ----
# 点 7：x ∈ [10^6,10^7]
x = random.randint(1000000, 10000000)
gen_case(7, x, "大规模随机：x∈[1e6,1e7]，接近上限")

# 点 8：x ∈ [10^7,10^8)
x = random.randint(10000000, XMAX - 1)
gen_case(8, x, "大规模随机：x∈[1e7,1e8)，逼近上限")

# ---- 点 9-10：顶格层 ----
# 点 9：自定上限 x=10^8（全最大值；10 的幂结构，答案 10^9，检验 int32 边界的进位）
gen_case(9, XMAX, "顶格层：全最大值 x=1e8（自定上限，10 的幂结构），答案 10^9")

# 点 10：x=99999999（上限-1）—— 全 9 结构，乘法进位传播极端（10x=999999990）
gen_case(10, XMAX - 1, "顶格层：x=99999999（9 连位、上限减一），乘法进位传播极端")
