// 相对来源的改写点：
//   - 用 long long 枚举（来源多为 int）；本题答案 301 时 int 亦足够，long long
//     为零成本健壮性冗余，防止将来题面上限放宽时溢出；
//   - 用「先检查 2..6 的余数、再检查 7 的整除性」的显式双层循环 + break 早退，
//     与来源 [1] 解法1 / [7] 的判定结构一致，但把重复的 && 链改成 for 循环，
//     避免手写链漏项；
//   - 输出一行整数 + 换行（语料惯例，见 problems/1000、problems/5006）。
//
// 用法：g++ -O2 -std=c++17 std.cpp -o std && ./std   →  301

#include <cstdio>

int main() {
    // 从 1 开始从小到大找首个满足全部条件的 n（首个命中即「至少多少人」）
    for (long long n = 1; ; ++n) {
        bool ok = true;
        for (int k = 2; k <= 6; ++k) {   // 每行 2..6 人都多出 1 人 ⇒ n % k == 1
            if (n % k != 1) { ok = false; break; }
        }
        if (ok && n % 7 == 0) {          // 每行 7 人正好 ⇒ n 是 7 的倍数
            printf("%lld\n", n);
            return 0;
        }
    }
    return 0;  // 不会到达
}
