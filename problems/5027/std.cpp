// 题面：校体操队排成每行 2 人、3 人、4 人、5 人、6 人时都多出 1 人，
//       排成每行 7 人时正好不多，求校体操队至少多少人。
// 输入：无（题面【输入】原文「如题述，无。」）。输出：一个整数，答案唯一确定。
//
// 数学表述：求最小的正整数 n，使 n % k == 1（k = 2,3,4,5,6）且 n % 7 == 0。
//   记 L = lcm(2,3,4,5,6) = 60（其中 2|4、3|6，故只需看 4、5、6），
//   前 5 个条件等价于 n ≡ 1 (mod 60)；在 n = 60k + 1 (k=0,1,2,...) 中找
//   第一个 7 的倍数：k = 5 时 n = 301，且 301 = 7 × 43，故答案为 301；
//   全部可行解为 n ≡ 301 (mod 420)（420 = lcm(60, 7)），最小正解即 301。
//   本实现按定义从小到大枚举（教学写法），首个满足全部条件的 n 必为最小解，
//   枚举 301 次即命中，远低于 1000 ms 限制。
//
// 参考来源（本轮均以 curl 实取页面正文核对，本文件为改写实现，非盲抄）：
