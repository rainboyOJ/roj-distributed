#!/usr/bin/env python
# -*- coding: utf-8 -*-
# 一本通 2018《【例4.3】输出奇偶数之和》数据生成器（cyaron 惯例，参考 problems/1000/data.py）
#
# 题意：输入一个整数 n（1 ≤ n ≤ 100），用 for 循环分别统计 1~n 中偶数之和与奇数之和，
#       输出一行两个整数：偶数之和 空格 奇数之和（样例 10 -> "30 25"）。
#
# 分层设计（输入量只有 n 一个，取值域仅 1..100，故按“规模档位 + 极值结构”铺满 10 组，
# 每个取值都人工可算；随机档位使用固定随机种子保证数据可复现）：
#   点 1-2  边界层   ：n=1（下界，唯一的偶数和=0 答案）、n=2（下界附近，偶数之和首次反超奇数之和）
#   点 3-4  小规模   ：n∈[3,9] 随机（可手算）；n=10 题面样例（30 25）
#   点 5-6  中等规模 ：n∈[25,50] 随机、n∈[51,80] 随机
#   点 7-8  大规模   ：n∈[81,96] 随机（接近上限）
#   点 9-10 顶格层   ：n=99（上限-1 且为奇数：奇数和取到最大值 50²=2500）、
#                      n=100（题面上限：偶数和最大 50*51=2550、两和总和最大 5050）
#
# int32 溢出边界说明：偶数和 = k(k+1)（k=⌊n/2⌋）≈ n²/4，在 n≈92682 时首次越过 int32 上限
# 2147483647；题面 n≤100 时最大仅 2550，远无溢出风险（详见 gen-report.md 风险点一节）。

import random

from cyaron import *  # 引入CYaRon的库

random.seed(20180101)  # 固定种子，保证随机档位可复现

for i in range(1, 11):
    io = IO(file_prefix="problem", data_id=i)  # problem1.in / problem1.out …

    if i == 1:
        # 边界层：最小输入 n=1，唯一使“偶数之和=0”的测试点
        n = 1
    elif i == 2:
        # 边界层：最小的偶数 n=2，答案 "2 1"，偶数之和首次大于奇数之和
        n = 2
    elif i == 3:
        # 小规模随机：n ∈ [3,9]，量级极小可手算验证
        n = random.randint(3, 9)
    elif i == 4:
        # 题面样例：n=10，期望输出 "30 25"
        n = 10
    elif i == 5:
        # 中等规模随机：n ∈ [25,50]
        n = random.randint(25, 50)
    elif i == 6:
        # 中等规模随机：n ∈ [51,80]
        n = random.randint(51, 80)
    elif i == 7:
        # 大规模随机：n ∈ [81,96]，接近题面上限
        n = random.randint(81, 96)
    elif i == 8:
        # 大规模随机：n ∈ [81,96]，与点 7 独立取一组
        n = random.randint(81, 96)
    elif i == 9:
        # 顶格层（临界）：n=99 是上限-1 的最大奇数值，
        # 奇数个数 = 50 取满，奇数和达到全局最大值 50² = 2500
        n = 99
    else:
        # 顶格层（上限）：n=100，偶数和最大 2550，且两和总和最大 5050
        n = 100

    io.input_write(n)
    io.output_gen("../std")
