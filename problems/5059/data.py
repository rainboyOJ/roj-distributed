#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2057《【例3.9 】星期几》—— 测试数据生成器（cyaron，仓库惯例）
# 用法：mkdir -p data && cd data && python3 ../data.py
#       （前置：g++ -O2 -std=c++17 std.cpp -o std）
#
# 题意：读入表示星期几的数字，输出对应英文名称：
#       1->Monday 2->Tuesday 3->Wednesday 4->Thursday 5->Friday 6->Saturday 7->Sunday；
#       其它任何输入 -> `input error!`（题面明文声明的错误提示，含感叹号）。
#       样例：输入 1 -> 输出 Monday。
#
# 数据范围（题面【未声明】，本生成器自定并如实记录）：
#   题面（content.md）与官方 OJ 页（本轮实抓：
#   http://ybt.ssoier.cn:8088/problem_show.php?pid=2057 ，页面仅剩标题/限制/样例，
#   正文各节被站点清空）均未给出输入数字的取值范围，只有 1000 ms / 65536 KB 限制。
#   按仓库/同批 staging 惯例（2051、2052、2053、2054 均如此）自定工作范围：
#       -2147483648 <= n <= 2147483647     （有符号 32 位整数全域，int32 全域）
#   依据：① 本题是纯比较 / 查表输出，不产生任何算术中间量，int32 全域内所有
#   「按 int 读入」的网络题解都不溢出、不会因范围被误判（见 std.cpp 头注释的 12 个来源）；
#   ② std 用 long long 读入，是该范围的超集；③ 与同章同批包（2052/2053/2054）口径一致。
#
# ============================ 分层设计（10 个测试点）============================
# 本题的【输入】是一个表示星期几的数字，题面给定的一一对应表只有 1..7 共 7 个值，
# 判定域是**有限的离散集合**：有效域 {1..7}（7 个不同输出串）+ 补集（1 个输出串
# `input error!`），共 8 个不同输出分支。因此「从最小铺到顶格」在本树上就体现为：
#
#   点 1-2   边界层：有效域**两端点** —— n=1（下界，同时是题面【输入样例】声明的
#            特殊值 -> Monday）/ n=7（上界 -> Sunday）。这是官方数据里必须钉住的两端。
#   点 3-7   有效域内部逐值全覆盖（小规模、可手算的量级）：n=2/3/4/5/6，输出
#            Tuesday/Wednesday/Thursday/Friday/Saturday。**每个英文名都必须在正式
#            数据里出现过一次**——网络来源 [2]（博客园 xuchaoyue）特别提醒本题
#            「易错点是大小写」，只有 7 个串都出现在数据里，拼写/大小写写错的解才会被评掉；
#            这比重复铺无意义的量级随机更有价值（见下方「为什么不做量级随机层」）。
#   点 8-9   临界层（边界外一步）：n=0（下界外邻值）/ n=8（上界外邻值），均为
#            `input error!`。防把 `n>=1` 写成 `n>=0`、把 `n<=7` 写成 `n<=8`，
#            或 switch 少写 default、if 链漏掉 else 等典型错误。
#   点 10    顶格层：n=2147483647（2^31-1，自定工作范围上界 / int 全域最大值，
#            `input error!`）——十位数解析 + 有符号溢出边界。
#
# 为什么不做「中等/大规模随机」的重复量级层（如实记录设计取舍）：
#   本题判定函数只依赖「n 属于 {1..7} 中的哪一个」或「n 落在补集里」，**与数值量级
#   无关**：n=8 与 n=10^9 走的是同一条比较路径、同一个输出串；n=-1 与 n=-2^31 同理。
#   量级唯一真正影响的是**输入的解析宽度**（int / long long），由点 10 的 2^31-1
#   钉住；负数/大负数的解析与分支则由 work/stress.py 的穷举 + 全域随机对拍覆盖
#   （数千组，其中包含 -2^31、-2^31+1 等）。把宝贵的测试点花在重复量级随机上会挤掉
#   「上午/下午五个不同英文串」的全覆盖，得不偿失。
#   对照任务书口径：点 1-2 边界层 ✅；点 3-7 承担「小规模（可手算）」并按本题有限域
#   把**内部逐值铺满** ✅（对本题而言这就是「从最小铺到顶格」的正解）；点 8-9 承担
#   「临界构造」（边界外一步）✅；点 10 顶格 ✅。10 个点**不是**全小随机——
#   每点的输入与输出分支都是**唯一且刻意选定**的，互不重复，8 个输出分支全覆盖。
#
# 分支覆盖自检（文件末尾 assert）：
#   7 个英文名 + `input error!` 在 10 个点里各出现 ≥1 次；
#   输出串集合 == 题面给出的 8 个串（逐字符核对）。
# ==============================================================================

from cyaron import *  # 引入CYaRon的库

import random
random.seed(2057)  # 固定种子，便于复现（本文件为确定性数据，种子仅作惯例保留）

INT_MIN = -2147483648  # 自定工作范围下界（int32 全域）
INT_MAX = 2147483647   # 自定工作范围上界（int32 全域）

# 题面给出的 8 个输出串（逐字符抄自 content.md，含大小写与感叹号）
NAMES = {
    1: "Monday",
    2: "Tuesday",
    3: "Wednesday",
    4: "Thursday",
    5: "Friday",
    6: "Saturday",
    7: "Sunday",
}
ERR = "input error!"


def answer(n):
    """独立真值（python 侧，与 std 的实现路径不同，用于断言与打印期望）。"""
    return NAMES.get(n, ERR)


def gen_case(i, n, note):
    """写出第 i 组：输入 n；输出由 std 生成（io.output_gen 调 ../std）。"""
    assert INT_MIN <= n <= INT_MAX, "点 %d 的值 %d 越出自定工作范围" % (i, n)
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(n)         # 行末带换行（与 2051/2052/2054 等包一致，最兼容）
    io.output_gen("../std")     # 期望输出 = std 运行结果
    print("problem%-2d: n=%-12d 期望输出=%-14s -- %s" % (i, n, answer(n), note))


# ---- 点 1-2：边界层（有效域两端点；点 1 兼题面样例） ----
# 点 1：n=1 —— 有效域下界，且是题面【输入样例】声明的特殊值（-> Monday）。
gen_case(1, 1, "边界层：有效域下界 + 题面【输入样例】特殊值 1 -> Monday")

# 点 2：n=7 —— 有效域上界（-> Sunday）；防把 `n<=7` 写成 `n<7`。
gen_case(2, 7, "边界层：有效域上界 7 -> Sunday（防 '<' 与 '<=' 写错）")

# ---- 点 3-7：有效域内部逐值全覆盖（小规模、可手算；每个英文串都必须被评到） ----
# 点 3：n=2 -> Tuesday（最小非样例有效值，与点 1 相邻，防串位移）
gen_case(3, 2, "有效域逐值：2 -> Tuesday（最小非样例有效值）")

# 点 4：n=3 -> Wednesday（唯一 9 字母、拼写最易错的一个）
gen_case(4, 3, "有效域逐值：3 -> Wednesday（最长/最易拼错）")

# 点 5：n=4 -> Thursday
gen_case(5, 4, "有效域逐值：4 -> Thursday")

# 点 6：n=5 -> Friday
gen_case(6, 5, "有效域逐值：5 -> Friday")

# 点 7：n=6 -> Saturday（最大非样例有效值，与点 2 相邻，防串位移）
gen_case(7, 6, "有效域逐值：6 -> Saturday（最大非样例有效值）")

# ---- 点 8-9：临界层（有效域外一步，走错误分支） ----
# 点 8：n=0 —— 下界外邻值（防 `n>=1` 写成 `n>=0`）-> input error!
gen_case(8, 0, "临界层：下界外邻值 0（防下界写成 '>='）-> input error!")

# 点 9：n=8 —— 上界外邻值（防 `n<=7` 写成 `n<=8`）-> input error!
gen_case(9, 8, "临界层：上界外邻值 8（防上界写成 '<='）-> input error!")

# ---- 点 10：顶格层 ----
# 点 10：n=2^31-1 —— 自定工作范围上界 / int 全域最大值（十位数解析 + 有符号边界）。
gen_case(10, INT_MAX, "顶格层：2^31-1 自定上限（十位数解析 + int 溢出边界）-> input error!")

# ---------------- 自检 ----------------
pts = [(1, 1), (2, 7), (3, 2), (4, 3), (5, 4), (6, 5), (7, 6), (8, 0), (9, 8), (10, INT_MAX)]

# 1) 全部落在自定工作范围内，且 10 个点的输入互不相同（无冗余重复点）
for i, n in pts:
    assert INT_MIN <= n <= INT_MAX, "点 %d 的值 %d 越出自定范围" % (i, n)
assert len({n for _, n in pts}) == 10, "存在重复输入点，测试点应互不冗余"

# 2) 8 个输出分支全部出现，且输出串集合恰为题面给出的 8 个串（逐字符）
outs = [answer(n) for _, n in pts]
assert set(outs) == set(NAMES.values()) | {ERR}, "输出分支未全覆盖：%r" % sorted(set(outs))
assert all(answer(d) == s for d, s in NAMES.items()), "有效值映射错位"
assert answer(0) == ERR and answer(8) == ERR and answer(INT_MAX) == ERR, "错误分支判定错"
assert outs[0] == "Monday", "点 1 必须是题面样例 Monday"
assert outs[1] == "Sunday" and outs[len(pts) - 1] == ERR, "点 2/点 10 设计错位"

print("自检通过：10 点输入互不重复且均在 [-2^31, 2^31-1] 内；"
      "7 个英文名 + 'input error!' 共 8 个输出分支全覆盖；"
      "有效域 1..7 逐值出现在数据中；0/8 临界外邻与 2^31-1 顶格齐备。")
