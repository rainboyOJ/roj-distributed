#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2027《【例4.13】三角形》（目标 ROJ 题号 5029）—— 测试数据生成器（cyaron，仓库惯例）
# 用法：mkdir -p data && cd data && python3 ../data.py
#
# 题意：输入自然数 n(n<20)，输出 n 行、仅由 '*' 构成的直角三角形：
#       第 i 行恰好 i 个 '*'，左对齐，逐行输出。
# 样例：输入 5 => 输出 5 行（1、2、3、4、5 个星，行末单个换行）。
# 数据范围：题面明文 n < 20；下界由「自然数」一词给出（本包取含 0 口径，见下）。
# 限制：time 1000 ms / memory 65536 KB（config.json 与官方 OJ 页一致）。
#
# 「空输出」分支（本题唯一口径分歧，照实生成并显式记录，处置参考 2017 包）：
#   教材（信奥一本通配套课件）中「自然数」按现行国内口径含 0 => n=0 合法，
#   且「n 行三角形」在 n=0 时是 0 行 => 期望输出 **0 字节空文件**（绝不是空行，
#   两者在 diff -b 下不等价，本包已用 work/format_matrix.py 实测确认）。
#   若主控判读「自然数不含 0」，只需把点 1 换成未覆盖值（如 n=3）重跑即可，
#   其余 9 点完全不受影响；且两种判读下，任何「for(i=1;i<=n;i++) 输出 n 行」的
#   正规写法对 n=0 都输出 0 字节，故该点不会误伤任何正确解。
#   依据、影响面与回退方法详见 gen-report.md 风险点 1。
#
# 分层设计（10 组；单组输入题：一个测试点 = 一个整数 n。题面上限 19 很小，
# 故「大规模/顶格」即接近或等于 19。10 组取值互不相同，从最小铺到顶格，
# 且不是「10 组全小随机」）：
#   点 1     边界层：n=0（「自然数含 0」口径下的全最小值；**空输出分支** -> 0 字节 .out）
#   点 2     边界层：n=1（最小非空输出：1 行 1 个星；验证循环下界与行末换行）
#   点 3     小规模定点：n=5（题面【输入样例】声明的特殊值，与样例逐字节一致）
#   点 4     小规模定点：n=2（最小两行三角形，可逐格手算；补「n=2」边界要求）
#   点 5     小规模随机：n ∈ [3,6]（避开样例值 5，输出 ≤27 字节，可人工数清）
#   点 6     中等规模随机：n ∈ [7,10]（范围中间档）
#   点 7     中等规模随机：n ∈ [11,13]（中间偏上档）
#   点 8     大规模随机：n ∈ [14,17]（接近上限；18/19 留给点 9-10 的顶格对比）
#   点 9     顶格层：n=19（题面上限 / 全最大值，最长输出：190 个星 + 19 个换行 = 209 字节）
#   点 10    顶格层：n=18（上限 −1，与点 9 相邻，检验循环终止条件 row<=n vs row<n）
#
# 分层覆盖对照任务书要求：
#   * 边界层（点 1-2）：全最小值 ✅（点 1，n=0）、n=1 ✅（点 2）；
#     另有 n=2 ✅、题面特殊值 n=5 ✅（点 3-4）、全最大值 ✅（点 9，n=19）；
#   * 「答案为 0 或 1 的极端」在本题型不适用（输出是图形而非数值），与之等价的极端
#     是「空输出」（点 1，0 行）与「最小非空输出」（点 2，1 行 1 星），均已覆盖；
#   * 小/中/大规模随机（点 5-8）：可手算量级（n≤6）铺到逼近上限（n≤17），
#     区间互不重叠、取值互不相同，不是「10 组全小随机」；
#   * 顶格层（点 9-10）：n=19（上限）与 n=18（上限−1）；按本题型「最坏结构」即
#     最长输出（点 9：190 星 + 19 换行 = 209 字节）与「上限邻域的终止条件」（点 10）。
#   * 本题有输入且输出随 n 变化，故生成 10 组（仅无输入题才按语料惯例只生成 1 组）；
#     本题为单组输入，不存在多组数据的「组数分层」。
#
# 生成方式：IO(file_prefix="problem", data_id=i) + io.output_gen("../std")，
#           与 problems/1000/data.py、problems/5006/data.py 及 staging 既有包一致。
# 固定随机种子，数据可复现（本轮实测两次运行 diff -r 逐字节一致）。
from cyaron import *  # 引入CYaRon的库

import random

random.seed(2027)  # 固定种子，便于复现

NMIN = 0   # 下界：「自然数」取含 0 口径（见文件头与 gen-report.md 风险点 1）
NMAX = 19  # 上限：题面明文 n < 20 的最大整数


def expect(n):
    """独立参照（纯字符串拼装，与 std 的双重计数循环是两条不同实现路径）：
    n<=0 时为 0 字节；否则第 i 行恰好 i 个 '*'，每行以单个 '\\n' 结束。"""
    if n <= 0:
        return b""
    return "".join("*" * i + "\n" for i in range(1, n + 1)).encode()


def gen_case(i, n, note):
    """写出第 i 组：输入 n，用 std 生成输出；并打印独立参照核对的规格。"""
    assert NMIN <= n <= NMAX, "n=%d 超出题面范围 [%d,%d]" % (n, NMIN, NMAX)
    assert n not in SEEN, "n=%d 与已生成的点重复" % n
    SEEN.add(n)
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(n)  # 单个整数 + 换行（与 2052/2064/2070 等较新包一致）
    io.output_gen("../std")
    ref = expect(n)
    print("problem%-2d: n=%-3d 行数=%-3d 期望输出=%-4d 字节（末行 %s 个星） -- %s"
          % (i, n, max(n, 0), len(ref), n if n > 0 else 0, note))


SEEN = set()  # 已生成点取值去重（10 组取值必须互不相同）


# ---- 点 1：边界层（全最小值 n=0；自然数含 0 -> 0 行三角形 => 空输出分支） ----
gen_case(1, 0, "边界层：全最小值 n=0（自然数含 0），空输出分支，.out 为 0 字节")

# ---- 点 2：边界层（最小非空输出：1 行 1 星） ----
gen_case(2, 1, "边界层：n=1，最小非空输出，验证循环下界与行末换行")

# ---- 点 3：小规模定点（题面声明的特殊值 = 输入样例值 5） ----
gen_case(3, 5, "小规模定点：题面【输入样例】值 n=5（与样例逐字节一致）")

# ---- 点 4：小规模定点（最小两行三角形，可逐格手算） ----
gen_case(4, 2, "小规模定点：n=2（最小两行三角形），补「n=2」边界要求")

# ---- 点 5：小规模随机 n ∈ [3,6]（避开样例值 5，保证 10 组互不相同） ----
n5 = random.randint(3, 6)
while n5 == 5:
    n5 = random.randint(3, 6)
gen_case(5, n5, "小规模随机：n∈[3,6]，输出 ≤27 字节，可人工数清")

# ---- 点 6：中等规模随机 n ∈ [7,10] ----
n6 = random.randint(7, 10)
gen_case(6, n6, "中等规模随机：n∈[7,10]，范围中间档")

# ---- 点 7：中等规模随机 n ∈ [11,13] ----
n7 = random.randint(11, 13)
gen_case(7, n7, "中等规模随机：n∈[11,13]，中间偏上档")

# ---- 点 8：大规模随机 n ∈ [14,17]（18/19 留给点 9-10 的顶格对比） ----
n8 = random.randint(14, 17)
gen_case(8, n8, "大规模随机：n∈[14,17]，接近上限")

# ---- 点 9：顶格层 n=19（题面上限 / 全最大值，最长输出 209 字节） ----
gen_case(9, NMAX, "顶格层：n=19（题面上限/全最大值），最长输出（190 星 + 19 换行）")

# ---- 点 10：顶格层 n=18（上限 −1，与点 9 相邻对比循环终止条件） ----
gen_case(10, NMAX - 1, "顶格层：n=18（上限−1），与点 9 相邻，检验 row<=n vs row<n")
