// 题意（.ybt-import/staging/2027/content.md）：
//   对于给定的自然数 n(n<20)，在屏幕上输出仅由 "*" 构成的 n 行的直角三角形。
//   输入：n；输出：题述三角形（第 i 行恰好 i 个 '*'，左对齐，逐行输出）。
//   样例：输入 5 =>
//         *
//         **
//         ***
//         ****
//         *****
//   数据范围：题面明文 n < 20；n 为自然数（教材口径含 0，见下）。
//   限制：time 1000 ms，memory 65536 KB（config.json；与官方 OJ 页一致：
//   https://ybt.ssoier.cn/problem_show.php?pid=2027 ，2026-10 本轮实测可访问，
//   页面显示「时间限制: 1000 ms 内存限制: 65536 KB 提交数:79559 通过数: 61713」，
//   题面【题目描述】【输入】【输出】与样例与本包 content.md 逐字一致，无歧义）。
//
// 参考来源 URL（本包均已逐篇实际抓取核验，然后按题面改写，非盲抄）：
//   [1] https://blog.csdn.net/lq1990717/article/details/121021870
//       《信息学奥赛一本通 2027：【例4.13】三角形》【题目考点】循环嵌套；
//       【解题思路】“每一行上 * 的个数恰好是行数，第 i 行输出 i 个星号”；
//       【题解代码】for(int i=1;i<=n;++i){ for(int j=1;j<=i;++j) cout<<'*'; cout<<endl; }
//   [2] https://blog.csdn.net/lvcheng0309/article/details/116719226
//       《信息学奥赛一本通（2027：【例4.13】三角形）》C 版参考代码：
//       for(i=1;i<=n;i++){ for(j=1;j<=i;j++) printf("*"); printf("\n"); }
//   [3] https://blog.csdn.net/strawberrytreea/article/details/124312756
//       《信息学奥赛一本通（c++）：2027：【例4.13】三角形》：思路“双层 for 循环，
//       内层输出第 j 行有 j 个星号，外层控制行数”；代码同 [1]。
//   [4] https://blog.csdn.net/2301_80313293/article/details/135734607
//       《2027：【例4.13】三角形 c语言》：C 版参考代码，同上。
//   [5] 教材原始出处（信奥一本通配套课件「第4章 循环结构(C++版).ppt」的例 4.13 页，
//       GitHub 镜像：https://github.com/Lucifer-ww/NOIP_ReC/tree/main/3.%20教程ppt课件(第五版)/
//       第一部分%20%20语言C++ ，文件「第4章  循环结构(C++版).ppt」，本轮已下载并解出正文）：
//       例 4.13 原文“对于给定的自然数 n(n<20)，在屏幕上输出仅由“*”构成的 n 行的
//       直角三角形。例如：当 n=5 时，输出：…”，【分析】“打印图形总是逐行进行的…
//       构成了一个两层循环：外层循环是 1 至 n 行的处理，而内层循环，则是输出同一行上
//       的每一列。分析样例，不难发现，每一行上 * 的个数恰好是行数。因此对于第 i 行，
//       内层循环可以设置重复 i 次。”
//
// 多来源结论核对（无冲突）：
//   * 全部来源算法一致：外层 i 枚举 1..n 行，内层输出 i 个 '*'，行末换行；
//     两种等价写法——① 双重计数循环直接输出；② 预构造行串 / 递归按行输出。
//   * 输出格式一致：左对齐、行内无空格、每行以换行结束（与题面【输出样例】
//     逐字节一致，本包已实测比对）。
//   * n 的取值：题面写“自然数 n(n<20)”。国内教材现行口径自然数含 0：
//     1993 年颁布的《中华人民共和国国家标准》（GB 3100~3102-93）《量和单位》
//     第 311 页规定“自然数包括 0”，此后中小学教材依此修订（人教社官方答疑原文，
//     见 https://blog.csdn.net/a1023182899/article/details/73350856 ，本轮已抓取核验：
//     “0 也是自然数”）。故 n=0 是合法输入：0 行三角形 -> **0 字节空输出**
//     （本包按此判读生成点 1，口径分歧与依据见 gen-report.md 风险点 1）。
//     若 n 退化为 0 或（域外的）负数，循环体一次都不执行，自然输出为空，不崩溃；
//     这与所有写成 `for(i=1;i<=n;i++)` 的网络/教材写法在 n=0 上完全一致。
//
// 本包实现（C++17，stdin→stdout，风格参考 problems/1000/std.cpp）：
//   * 采用来源 [1][3] 的双重计数循环直接输出（putchar，O(n^2) 时间、O(1) 额外空间），
//     与暴力参照 work/brute.cpp（递归路线，逐行先定长再输出）构成两条独立实现路径，
//     供对拍交叉验证。
//   * 行末**没有**多余空格；每行以单个 '\n' 结束（非空输出），n<=0 时输出 0 字节。
//   * n <= 19，总输出 <= 190 星 + 19 换行 = 209 字节，耗时远低于 1 ms / 1000 ms、
//     内存 ~1 MB / 64 MB。

#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;  // 读入 n；无输入时静默退出（题面保证有输入）

    for (int row = 1; row <= n; ++row) {      // 外层：第 row 行（教材例4.13「重复 n 行操作」）
        for (int col = 1; col <= row; ++col) { // 内层：第 row 行恰好 row 个 '*'
            putchar('*');
        }
        putchar('\n');                         // 每行以换行结束（样例逐行输出）
    }
    return 0;  // n <= 0（自然数含 0 的下界）：两层循环均不执行，输出 0 字节
}
