// 一本通 2039《【例5.6】冒泡排序》标程（目标 ROJ 题号 5041）
//
// 题意：读入 n (1 <= n <= 20) 个小于 1000 的非负整数，按从大到小输出，每个数占一行。
//       输入格式：第一行 n；第二行 n 个非负整数。即为「降序冒泡排序」。
// 数据范围（题面原文）：n ∈ [1, 20]；每个数 0 <= a[i] < 1000（非负整数，小于 1000）。
// 限制：time 1000 ms / memory 64 MB（config.json 与官方 OJ 页 65536 KB 一致）。
//
// 参考来源（均为一次直取正文核对；本文件是**改写**实现，未逐字复制）：
//   [1] https://blog.csdn.net/lq1990717/article/details/121641205
//       《信息学奥赛一本通 2039：【例5.6】冒泡排序》（君义NOIP）
//       给出 4 段 AC 代码：两种下标体系（1..n、0..n-1）× 两种循环方向，
//       比较恒为 `if (a[j] < a[j+1]) swap(a[j], a[j+1]);`（即降序）。
//   [2] https://blog.csdn.net/weixin_69756179/article/details/137395600
//       《2039：【例5.6】冒泡排序【信息学奥赛一本通】》
//       同样确认「数组 + 双重 for 比较相邻元素、逆序则交换」，输出降序，每数一行。
//   [3] https://blog.csdn.net/u014117969/article/details/135640564
//       《信息学奥赛一本通：2039：【例5.6】冒泡排序》
//       AC 代码同路线（`if (a[j] < a[j+1])` 交换），验证结论一致。
//   [4] http://ybt.ssoier.cn:8088/problem_show.php?pid=2039
//       官方题面与样例（5 / 2 5 8 6 12 -> 12 8 6 5 2），用于核对语义与限制。
//
// 三个来源结论完全一致（降序冒泡，每数一行），无冲突、无歧义；
// 与题面（n<=20、值<1000）也一致，故未触发「停下报告」。
//
// 本标程相对来源的改写点：
//   - 统一用 0-based 下标 + 标准冒泡（外层 i 从 0 到 n-2，内层 j 从 0 到 n-i-2），
//     来源 [1] 的两种循环方向只是同一算法的不同写法，这里取最直观的一种；
//   - 显式读入 n 并做上界保护（n 被夹到 [0, 20]），避免脏数据越界；
//   - 用 scanf/printf（风格参考 problems/1000/std.cpp），输出每个数一行、
//     末行后一个换行，无行末多余空白；
//   - 输入不依赖行结构（用 scanf 按空白切分），对「第二行换行摆放」不敏感。
//
// 复杂度：O(n^2) <= 400 次比较，远低于 1000 ms / 64 MB 限制。

#include <cstdio>
#include <algorithm>

int a[25];   // 题面上限 n <= 20，留余量

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;      // 无输入时安全退出
    if (n < 0) n = 0;
    if (n > 20) n = 20;                      // 上界保护（题面 n <= 20）

    for (int i = 0; i < n; i++) {
        if (scanf("%d", &a[i]) != 1) a[i] = 0;
    }

    // 降序冒泡：相邻两数逆序（前 < 后）则交换，最大者逐轮"浮"到最前
    for (int i = 0; i + 1 < n; i++) {
        for (int j = 0; j + 1 < n - i; j++) {
            if (a[j] < a[j + 1]) std::swap(a[j], a[j + 1]);
        }
    }

    for (int i = 0; i < n; i++) printf("%d\n", a[i]);
    return 0;
}
