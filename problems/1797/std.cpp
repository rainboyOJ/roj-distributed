// 一本通 1797《K维斐波那契》标程
//
// 题面（来自 .ybt-import/staging/1797/content.md）：
//   F(1)=F(2)=1, F(i)=F(i-1)+F(i-2)。
//   A 是 n^k 的 k 维超立方体，1<=i_1..i_k<=n，
//   A(i_1,...,i_k) = F(i_1+i_2+...+i_k-k+1)。
//   求 A 内所有元素之和 mod 1e9+7。
//   输入：第一行 T，接下来 T 行每行 n,k。输出：每组一行答案。
//   数据范围：T<=100，n,k<=10^9。
//
// 来源说明（重要）：
//   本题在网络检索中未找到可用题解/参考代码。已尝试的检索路径（均无果）：
//     * Bing 精确短语检索「"k维斐波那契" 一本通」/「一本通 1797 题解」/「k维超立方体 斐波那契 和」
//       —— 返回的结果与本题目无关（Bing 中文结果被过滤，仅返回词典类词条）；
//     * CSDN 站内搜「1797 K维斐波那契」—— 无相关文章；
//     * 百度搜索 —— 命中「百度安全验证」拦截页；
//     * 博客园 zzk.cnblogs.com 站内搜「K维斐波那契」—— 无结果；
//     * 洛谷题库检索 —— 302 重定向，无法访问。
//   因此本标程为**自研**：由题面独立推导出闭式矩阵公式，并用题面 3 组样例逐一手算验证
//   （见文末验证注释）。无外部参考代码。
//
// ---------------------------------------------------------------------------
// 推导（全部 mod 1e9+7）：
//
// 令 F(0)=0（因为 F(2)-F(1)=0），则 [F(t+1); F(t)] = M^t [1; 0]，
// 其中 M = [[1,1],[1,0]]，故 F(t) = (M^t)_{21}（第 2 行第 1 列，1-based 记法）。
//
// 令 a_j = i_j - 1 ∈ [0, n-1]。则 i_1+...+i_k-k+1 = (a_1+...+a_k) + 1，
//   A(i_1..i_k) = F(1 + Σa_j) = (M^{1+Σa_j})_{21}。
//
// 求和：  Σ_{a_1..a_k ∈ [0,n-1]} M^{1+Σa_j}
//       = M · (Σ_{a=0}^{n-1} M^a)^k                （矩阵都是 M 的幂，可交换）
//       = M · P^k,   其中 P = Σ_{a=0}^{n-1} M^a。
//
// 而 Σ_{a=0}^{n-1} M^a = (M^n - I)·(M - I)^{-1}，且 (M-I)^{-1} = M
//   （M-I = [[0,1],[1,-1]]，det = -1，其逆恰为 [[1,1],[1,0]] = M，可直接验算）。
//   故 P = (M^n - I)·M。
//
// 于是 答案 = ( M · P^k )_{21} = ( M · (M^n - I)^k · M^k )_{21}
//            = ( (M^n - I)^k · M^{k+1} )_{21}。
//
// 用 2x2 矩阵快速幂即可：O(8·(log n + log k)) 每组，T<=100 时总计微不足道。
//
// 样例手算验证：
//   n=2,k=2: M^2-I = M，M^2·M^3 = M^5 = [[8,5],[5,3]]，(2,1)=5  == 期望 5 ✔
//   n=4,k=1: (M^4-I)·M^2 = [[4,3],[3,1]]·[[2,1],[1,1]] = [[11,7],[7,4]]，(2,1)=7 == 期望 7 ✔
//   n=1,k=3: (M-I)^3·M^4 = [[-1,2],[2,-3]]·[[5,3],[3,2]] = [[1,1],[1,0]]，(2,1)=1 == 期望 1 ✔
//   （另手算 n=2,k=2 的直接枚举：(1,1)+(1,2)+(2,1)+(2,2) 对应 F(1)+F(2)+F(2)+F(3)=1+1+1+2=5 ✔；
//     n=1,k=3 只有一个元素 F(1)=1 ✔，与矩阵公式一致。）
// ---------------------------------------------------------------------------

#include <cstdio>

typedef long long ll;

static const ll MOD = 1000000007LL;

struct Mat {
    ll a[2][2];
};

// 2x2 矩阵乘法（模 MOD）
static Mat mul(const Mat &x, const Mat &y) {
    Mat r;
    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 2; j++) {
            ll s = 0;
            for (int k = 0; k < 2; k++) {
                s = (s + x.a[i][k] * y.a[k][j]) % MOD;
            }
            r.a[i][j] = s;
        }
    }
    return r;
}

// 2x2 矩阵快速幂
static Mat mpow(Mat b, ll e) {
    Mat r;                    // 单位矩阵
    r.a[0][0] = 1; r.a[0][1] = 0;
    r.a[1][0] = 0; r.a[1][1] = 1;
    while (e > 0) {
        if (e & 1LL) r = mul(r, b);
        b = mul(b, b);
        e >>= 1;
    }
    return r;
}

int main() {
    int T;
    if (scanf("%d", &T) != 1) return 0;

    Mat M;                    // M = [[1,1],[1,0]]
    M.a[0][0] = 1; M.a[0][1] = 1;
    M.a[1][0] = 1; M.a[1][1] = 0;

    while (T--) {
        ll n, k;
        scanf("%lld %lld", &n, &k);

        Mat Mn = mpow(M, n);  // M^n

        Mat A;                // A = M^n - I
        A.a[0][0] = (Mn.a[0][0] - 1 + MOD) % MOD;
        A.a[0][1] = Mn.a[0][1];
        A.a[1][0] = Mn.a[1][0];
        A.a[1][1] = (Mn.a[1][1] - 1 + MOD) % MOD;

        // 答案 = ((M^n - I)^k · M^{k+1})_{21}
        Mat R = mul(mpow(A, k), mpow(M, k + 1));

        printf("%lld\n", R.a[1][0]);
    }
    return 0;
}
