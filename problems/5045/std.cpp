//   【题目描述】例5.11 打印杨辉三角形的前 n (2<=n<=20) 行。
//   【输入】输入行数 n。            （单组输入，只有一个整数）
//   【输出】输出如题述三角形。n 行，每行各数之间用一个空格隔开。
//   【输入样例】5
//   【输出样例】1 / 1 1 / 1 2 1 / 1 3 3 1 / 1 4 6 4 1
//
// 关键判读（题面无歧义）：
//   * 杨辉三角第 i 行第 j 列（1-indexed）即组合数 C(i-1, j-1)；递推关系
//     a[i][j] = a[i-1][j-1] + a[i-1][j]，首列 a[i][1] = 1。
//   * 输出第 i 行恰好 i 个数，数与数之间恰一个空格。题面只规定「各数之间用一个
//     空格隔开」，故本包取**行末不留空格**的严格形态（与仓库语料惯例一致：
//     staging/2034、2036、2041、2053 的 std.cpp 同样取无行末空格），
//     每行以单个 '\n' 结束。官方页样例原始字节是 CRLF 行尾（见 gen-report.md
//     风险点 3），本包按仓库惯例统一为 LF。
//   * n<=20 时最大数 C(19,9)=C(19,10)=92378，int 足够；无需任何取模。
//
// 参考来源（网络题解，本轮均实取正文核对后按题面改写，非盲抄）：
//   [1] https://blog.csdn.net/lq1990717/article/details/122159458
//       君义_noip《信息学奥赛一本通 2043：【例5.11】杨辉三角形》
//       解法1：二维数组初始化为 0，`if (j==1) a[i][j]=1; else a[i][j]=a[i-1][j]+a[i-1][j-1];`
//         —— 关键在于数组为 0，使每行最后一个 1 也能由递推自然得到；
//       解法2：`if (j==1 || j==i) a[i][j]=1; else a[i][j]=a[i-1][j]+a[i-1][j-1];`。
//       该文点明考点 = 二维数组 + 递推（状态定义 / 初始状态 / 递推关系）。
//   [2] https://blog.csdn.net/lvcheng0309/article/details/116928142
//       橙子教师《信息学奥赛一本通（2043：【例5.11】杨辉三角形）》（CSDN 站内搜索
//       命中的 C 参考代码，本轮实取正文）：`#define N 30 int a[N][N];`，先置
//       `a[i][0]=a[i][i]=1`，再对 `1<=j<i` 用 `a[i][j]=a[i-1][j-1]+a[i-1][j]`，
//       最后逐行逐列输出。与 [1] 的递推完全一致，仅下标起点不同。
//   [3] https://blog.csdn.net/fengbaolieying/article/details/126282594
//       一本通2043：【例5.11】杨辉三角形（本轮实取正文）：1-indexed 写法，
//       `a[1][1]=1;` 后 `for(i=2..n) for(j=1..i) a[i][j]=a[i-1][j]+a[i-1][j-1];`，
//       输出的内层为 `cout<<a[i][j]<<" ";`（行末带一个空格）。
//   [4] https://blog.csdn.net/wenhaoyan/article/details/132351925
//       信息学奥赛一本通2043：【例5.11】杨辉三角形（本轮实取正文）：
//       0-indexed 写法，`a[i][0]=1`、`i==j` 时 `a[i][j]=1`，其余
//       `a[i][j]=a[i-1][j-1]+a[i-1][j]`，输出遇到 0 即 break。
//   [5] https://blog.csdn.net/m0_63138149/article/details/126424057
//       2043:【例5.11】杨辉三角形（本轮实取正文）：`a[i][j]` 在 `j==0||i==j`
//       时置 1，否则相邻两数相加，随后逐行输出。
//   [6] https://blog.csdn.net/lailaike08/article/details/132214218
//       2043：【例5.11】杨辉三角形 C++（CSDN 站内搜索命中的 AC 代码条目，
//       检索摘要显示其做法为「动态规划计算每个位置的数值并输出」）。
//   [7] https://blog.csdn.net/2402_84298973/article/details/146269221
//       杨辉三角形（信息学奥赛一本通-2043）（本轮实取正文）：`const int N=1e3+10;`
//       的开大数组写法，`if (j==1||j==i) nums[i][j]=1; else ...`，边算边输出。
//   以上来源结论完全一致（相邻两数相加、每行 i 个数），与题面一致，无冲突。
//
// 本包实现与 [1] 解法1 同源（二维数组右移一列 + 0 初始化，使递推自然覆盖每行末位 1），
// 但输出改为「行首不加前导空格、数间恰一个空格、行末无空格」的严格形态。
// 已在 work/stress.py 中与 work/brute.cpp（组合数定义，独立路径）对拍 164 组通过。
//
// 数组开 40×40：题面只需 20×20，余量用于 work/stress.py 的"域外互证"（n=21..34，
// 此处最大元素 C(33,16)=1166803110 仍在 int 内；再大则 int 溢出，不属本题范围）。
#include <cstdio>

int a[40][40];

int main() {
    int n = 0;                               // 预置 0：空输入时不依赖未初始化值
    scanf("%d", &n);
    for (int i = 1; i <= n; i++) {
        a[i][1] = 1;                         // 每行首列为 1；a[i][i] 由递推得到
        for (int j = 2; j <= i; j++)
            a[i][j] = a[i - 1][j - 1] + a[i - 1][j];
    }
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= i; j++) {
            if (j > 1) putchar(' ');         // 数与数之间恰一个空格，行末不留空格
            printf("%d", a[i][j]);
        }
        putchar('\n');
    }
    return 0;
}
