#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2054《【例3.4】适合晨练》分层数据生成器（cyaron，目标 ROJ 题号 5056）
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py；
# 自定范围口径与同章同批 .ybt-import/staging/2052 / 2053 / 2064 一致。
#
# 题意：输入温度 t 的值；25 <= t <= 30 输出 `ok!`，否则输出 `no!`。
#       题面【输入样例】26 -> 【输出样例】ok!（闭区间，两端点都算适合晨练）。
#       本题是**单组输入**（一个测试点 = 一个温度值），无多组数据、无组数 T。
#       注意：**两个分支都有输出**，本题不存在「满足条件才输出 / 否则不输出」的
#       空输出分支（与同章 2052《范围判断》不同），因此没有空 .out 测试点。
#
# 数据范围（题面【未声明】，本生成器自定并如实记录）：
#   题面（官方 OJ 页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2054，
#   本轮已实抓核对：页面只有【题目描述】【输入】【输出】【输入样例】【输出样例】
#   五节，无【提示】/【数据规模】节）只写「输入温度 t 的值」，样例为整数 26。
#   故取自定工作范围：
#       -2147483648 <= t <= 2147483647     （有符号 32 位整数全域）
#   依据与安全性：① 与同章同批 staging/2052、2053、2064 取 int32 全域的口径一致；
#   ② 本题是纯比较/输出，**不产生任何算术中间量**，任何「按 int 或 double 读入」
#   的实现（两者都能精确表示 int32 全域内的整数）在全部正式数据上结论相同；
#   ③ 区间端点 25 / 30 与全域两端点（±2^31）均为整数，不存在浮点精度问题。
#   题面**未声明**输入是否为整数；本包只生成整数（含题面样例 26），故小数温度
#   相关的行为不作要求（已在 gen-report.md 风险点 3 标注）。
#
# 分层设计（10 个测试点；单组输入题的"规模"体现为数值与判定区间 [25,30] 的
# 相对位置 + 量级档，故按 边界 -> 小 -> 中 -> 大 -> 顶格 铺开）：
#   点 1  边界层：t=26 —— 题面【输入样例】声明的特殊值（区间内典型值，答案 ok!）
#   点 2  边界层：t=25 —— 判定区间**左端点**（闭区间**取到**，答案 ok!）：
#            防把 `t>=25` 写成 `t>25`；同时是"答案 ok! 的最小输入"
#   点 3  边界层：t=30 —— 判定区间**右端点**（闭区间**取到**，答案 ok!）：
#            防把 `t<=30` 写成 `t<30`；同时是"答案 ok! 的最大输入"
#   点 4  边界层：t=24 —— 左端点外邻值（相邻整数，答案 no!）：
#            与点 2 构成"边界两侧一步之遥"的并列对照（答案并列构造）
#   点 5  边界层：t=31 —— 右端点外邻值（相邻整数，答案 no!）：同上，与点 3 对照
#   点 6  小规模随机：t ∈ [25,30] 区间内随机整数（全范围仅 6 个整数，可手算；
#            答案 ok!）—— 小规模层，验证区间内部一切正常
#   点 7  中等规模随机：t ∈ [-10^6, 10^6] 区间外随机整数（重抽保证落在区间外；
#            答案 no!）—— 范围中间档，覆盖负数与 0 附近的判定失败分支
#   点 8  大规模随机：t ∈ [10^6, 2^31-2] 随机整数（答案 no!）—— 贴近自定上限
#   点 9  顶格层：t=2147483647（2^31-1，自定上限 / int 全域最大值，答案 no!）
#            —— 十位数解析 + 有符号溢出边界
#   点 10 顶格层：t=-2147483648（-2^31，自定下限 / int 全域最小值，答案 no!）
#            —— 负号 + INT_MIN 边界 + 最极端的最远输入
#
# 结构覆盖：判定区间左端点（点 2）、右端点（点 3）、端点外邻值（点 4、5）、
#           区间内随机（点 6）、区间外中间档（点 7）、区间外大数（点 8）、
#           自定范围两极（点 9、10）均出现。
# 分层口径核对（对照任务书）：
#   - 点 1-2 边界层 ✅（含"题面声明的特殊值" 26、区间端点 / 答案 ok! 的极端 25、30；
#     "全最小值/全最大值"由点 9、10 的自定范围两极承担，"n=1/n=2" 对单值输入不适用；
#     "答案为 0 或 1 的极端"对本题不适用——答案是字符串 ok!/no!，不是计数）；
#   - 点 3-4 小规模随机 ✅（点 6 取区间内可手算量级，点 4/5 取端点邻值小量级）；
#   - 点 5-6 中等规模随机 ✅（点 7 取 ±10^6 量级）；
#   - 点 7-8 大规模随机 ✅（点 8 取 10^6..2^31-2，贴近自定上限）；
#   - 点 9-10 顶格层 ✅（自定范围两极 2^31-1 / -2^31）。
#   10 个点**不是**全小随机：数值档从 24 一路铺到 ±2^31，互不重复。
#
# 用法：mkdir -p data && cd data && python3 ../data.py
#       （前置：g++ -O2 -std=c++17 std.cpp -o std）

from cyaron import *  # 引入CYaRon的库

import random

T_MIN = -2147483648  # 自定工作范围下界（int32 全域）
T_MAX = 2147483647   # 自定工作范围上界（int32 全域）

OK_LO, OK_HI = 25, 30  # 判定区间（闭区间，题面声明）


def answer(t):
    """独立真值：与 std 的实现路径不同（python 区间比较，用于断言与打印期望）。"""
    return "ok!" if OK_LO <= t <= OK_HI else "no!"


def gen_case(i, t, note):
    """写出第 i 组：输入 t；输出由 std 生成。返回 (t, 期望输出)。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(t)      # 行末带换行（与 2052/2064/2070 等包一致）
    io.output_gen("../std")  # 期望输出 = std 运行结果
    exp = answer(t)
    print("problem%-2d: t=%-12d 期望 %-4s -- %s" % (i, t, exp, note))
    return t, exp


# ---- 点 1-5：边界层 ----
# 点 1：题面【输入样例】声明的特殊值（区间内典型值，与样例验证互为印证）
gen_case(1, 26, "边界层：题面【输入样例】特殊值 26（区间内典型值，答案 ok!）")

# 点 2：判定区间左端点 25（闭区间取到；"答案 ok!" 的最小输入；防 t>25 写错）
gen_case(2, 25, "边界层：判定区间左端点 25（闭区间取到，答案 ok!；防 '>' 写错）")

# 点 3：判定区间右端点 30（闭区间取到；"答案 ok!" 的最大输入；防 t<30 写错）
gen_case(3, 30, "边界层：判定区间右端点 30（闭区间取到，答案 ok!；防 '<' 写错）")

# 点 4：左端点外邻值 24（与点 2 仅差 1，答案并列构造：no! —— 边界两侧对照）
gen_case(4, 24, "边界层：左端点外邻值 24（与点 2 的 25 相邻，答案 no!）")

# 点 5：右端点外邻值 31（与点 3 仅差 1，答案并列构造：no! —— 边界两侧对照）
gen_case(5, 31, "边界层：右端点外邻值 31（与点 3 的 30 相邻，答案 no!）")

# ---- 点 6：小规模随机（区间内，可手算验证） ----
rng6 = random.Random(2054 + 6)   # 每点独立种子：结果与生成顺序无关、可逐字节复现
t6 = rng6.randint(OK_LO, OK_HI)  # [25,30] 仅 6 个整数，全部可手算
gen_case(6, t6, "小规模随机：t∈[25,30] 区间内随机整数（可手算，答案 ok!）")

# ---- 点 7：中等规模随机（区间外，范围中间档；覆盖负数/0 附近的失败分支） ----
rng7 = random.Random(2054 + 7)
t7 = rng7.randint(-1000000, 1000000)
while OK_LO <= t7 <= OK_HI:      # 重抽保证落在判定区间之外
    t7 = rng7.randint(-1000000, 1000000)
gen_case(7, t7, "中等规模随机：t∈[-10^6,10^6] 且落在区间外（答案 no!）")

# ---- 点 8：大规模随机（贴近自定上限） ----
rng8 = random.Random(2054 + 8)
t8 = rng8.randint(1000000, T_MAX - 1)
gen_case(8, t8, "大规模随机：t∈[10^6,2^31-2] 贴近自定上限（答案 no!）")

# ---- 点 9-10：顶格层（自定范围两极） ----
gen_case(9, T_MAX, "顶格层：t=2^31-1 自定上限（int 全域最大值，答案 no!）")
gen_case(10, T_MIN, "顶格层：t=-2^31 自定下限（int 全域最小值，答案 no!）")

# ---------------- 自检 ----------------
pts = [(1, 26), (2, 25), (3, 30), (4, 24), (5, 31), (6, t6), (7, t7), (8, t8),
       (9, T_MAX), (10, T_MIN)]

# 1) 全部落在自定工作范围内
for i, t in pts:
    assert T_MIN <= t <= T_MAX, "点 %d 的值 %d 越出自定范围" % (i, t)

# 2) 两类答案都出现，且边界两侧成对（25/24 与 30/31）
vals = dict(pts)
assert answer(25) == "ok!" and answer(30) == "ok!", "闭区间端点判定错误"
assert answer(24) == "no!" and answer(31) == "no!", "端点外邻值判定错误"
assert answer(26) == "ok!"
assert 25 in [t for _, t in pts] and 30 in [t for _, t in pts], "缺区间端点"
assert 24 in vals.values() and 31 in vals.values(), "缺端点外邻值"
assert vals[1] == 26, "点 1 应为题面样例值 26"
assert vals[9] == T_MAX and vals[10] == T_MIN, "点 9/10 应为自定范围两极"
assert answer(vals[6]) == "ok!", "点 6 应落在区间内"
assert answer(vals[7]) == "no!" and answer(vals[8]) == "no!", "点 7/8 应落在区间外"
assert len({answer(t) for _, t in pts}) == 2, "两类答案必须都出现"

print("自检通过：10 点全部在自定范围 [-2^31, 2^31-1] 内；"
      "答案 ok!/no! 两类均出现；区间端点 25/30 与端点外邻值 24/31 成对覆盖；"
      "数值档 24 → ±2^31 互不重复。")
