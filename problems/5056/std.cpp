// 一本通 2054《【例3.4】适合晨练》标程（目标 ROJ 题号 5056）
// ---------------------------------------------------------------------------
// 题意：输入温度 t 的值，判断是否适合晨练：
//       - 25 <= t <= 30  ->  输出 `ok!`
//       - 否则           ->  输出 `no!`
//   输入：一行一个数（温度值）。题面未声明取值范围，本包自定工作范围见下。
//   输出：一行，`ok!` 或 `no!`。**两个分支都有输出**，本题不存在「不输出」分支。
//   样例：输入 `26` -> 输出 `ok!`（题面与官方 OJ 页一致）。
//   限制：time 1000 ms / memory 65536 KB（config.json 与官方 OJ 页一致）。
//
// 输入范围（题面【未声明】，按仓库/同批 staging 惯例自定并如实记录，见
// gen-report.md §1）：-2147483648 <= t <= 2147483647（有符号 32 位整数全域）。
//   依据：题面只写「输入温度 t 的值」，官方 OJ 页无【提示】/【数据规模】一节
//   （本轮实抓核对）；样例 `26` 为整数。自定整数全域与同章同批 staging/2052、
//   2053、2064 的处置口径一致。
//
// 做法：单次区间比较 `25 <= t && t <= 30`（来源 [1][2][3] 的一致写法）。
//   注意不能写成 `25 <= t <= 30`：C++ 会先算 `(25 <= t)` 得到 0/1 再与 30
//   比较，条件恒真（来源 [1] 特别强调过这一点）。
//   读入用 double：本包工作域是整数，int32 全域内的整数在 double 中均可精确
//   表示（|t| < 2^53），因此「读 int」与「读 double」的实现在全部正式数据上
//   结论一致，对 int 解公平；同时读 double 对小数温度也不会截断（来源 [4]
//   即用 `scanf("%lf")` 读入）。区间端点 25 / 30 可被 double 精确表示，
//   比较无精度风险；纯比较运算，无算术中间量、无溢出。复杂度 O(1)。
//
// 本文件为本包改写实现（scanf/printf 风格参考 problems/1000/std.cpp），
// 只保留来源的判定语义，未逐字照抄。
// ---------------------------------------------------------------------------
// 参考来源 URL（本轮均以 curl 实取正文核对，非盲抄）：
//   [1] https://blog.csdn.net/lq1990717/article/details/120755821
