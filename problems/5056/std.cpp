//       与三目运算符两种解法，判定均为 `t >= 25 && t <= 30`；并强调**不能**
//       写成 `25<=a<=30`。本标程采用其 if 路线（改写为 C++17 scanf/printf 风格）。
//   [2] https://blog.csdn.net/weixin_62460981/article/details/123747704
//       《【信息学奥赛】2054：【例3.4】适合晨练（C++）》—— 同一闭区间判定，
//       用 else if 把 t<25 / t>30 分别归入 no!（交叉印证两端点均含）。
//   [3] https://blog.csdn.net/meterochan/article/details/135157085
//       《【例3.4】适合晨练 —— 信息学奥赛高级题库》—— if 与三目两种写法，
//       `t>=25&&t<=30 ? "ok!" : "no!"`（交叉印证判定与输出串）。
//   [4] https://blog.csdn.net/lvcheng0309/article/details/117677200
