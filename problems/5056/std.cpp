//       https://www.dotcpp.com/oj/problem3006.html
//       题面与样例一致（该站限制 1 s / 128 MB，以一本通 1000 ms / 64 MB 为准）。
//
// 来源间冲突均以题面为准（详见 gen-report.md 风险点 1）：int/double 读入之别
// 不影响判定语义；`ok`/`no` 少 `!` 与旧快照的 `yes!` 均被题面（及官方页现行
// 正文）否决。未发现需要「停下报告」的题面歧义。
