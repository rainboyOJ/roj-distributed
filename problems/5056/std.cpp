//       来源（`scanf("%lf")` + `t>=25 && t<=30`），输出 ok!/no!（交叉印证；
//       其页面元数据里的题面旧快照把输出样例写作 `yes!`，见 gen-report.md 风险点 1）。
//   [5] https://blog.csdn.net/qq_41840843/article/details/144621424
