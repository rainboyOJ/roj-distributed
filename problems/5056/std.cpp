#include <cstdio>

int main() {
    double t;
    if (scanf("%lf", &t) != 1) return 0;   // 无输入/非法输入：不输出，直接退出

    if (25.0 <= t && t <= 30.0)            // 闭区间 [25, 30]，两端点都算适合晨练
        printf("ok!\n");
    else
        printf("no!\n");
    return 0;
}
