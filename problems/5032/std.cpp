// 本标程相对来源的改写点（逐条说明，便于复核）：
//   * 判定处从来源 [2][3][5] 的逐数试除 2..sqrt(i) 改写为 6k±1 轮式试除
//     （先排 2、3 与偶数，再从 5 起按 5,7,11,13,... 步进 6 试除 d 与 d+2）；
//     与逐数试除数学等价、结论一致，但常数更小，且把"1 不是素数"收进 n<2 一处兜底。
//   * 上界判断用 d <= n / d（等价于 d*d <= n 但避免整数溢出），零成本健壮性冗余：
//     若评测数据意外给出超过题面 20000 的值也不会出现有符号溢出 UB。
//   * 输入按 int 读入，scanf("%d %d")，容忍任意前后空白/多空格/换行分隔（与题面
//     "输入 a,b" 的单行空格格式兼容）；读不到两个数（空输入）时安全 return 0。
//   * 输出统一 printf("%d\n", n)：整数精确十进制，无浮点、无平台差异，每数一行，
//     与题面样例与语料惯例（problems/1000/std.cpp 的 scanf/printf 风格）一致。
//   * 循环写 for(n=a; n<=b; ++n)，即区间**双闭**且包含端点（a=b 时也要判定一次）。
// 复杂度：每个候选 O(sqrt(n))，n<=20000 时单点开销 < 10^6 次取模，实测 << 1000 ms。

#include <cstdio>

// 判定 n 是否为素数（n 为任意 int；n<2 一律不是素数，其中含 1）
static bool isPrime(int n) {
    if (n < 2) return false;        // 0、1 与负数都不是素数
    if (n % 2 == 0) return n == 2;  // 偶数只有 2 是素数
    if (n % 3 == 0) return n == 3;  // 3 的倍数只有 3 是素数
    for (int d = 5; d <= n / d; d += 6) {        // d = 6k-1, 试 d 与 d+2 = 6k+1
        if (n % d == 0 || n % (d + 2) == 0) return false;
    }
    return true;
}

int main() {
    int a, b;
    if (scanf("%d %d", &a, &b) != 2) return 0;   // 无输入/输入不完整：安全退出
    for (int n = a; n <= b; ++n) {               // 双闭区间 [a, b]，端点包含
        if (isPrime(n)) printf("%d\n", n);       // 由小到大，每个数占一行
    }
    return 0;
}
