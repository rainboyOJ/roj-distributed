#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2051《【例3.1】偶数》—— 测试数据生成器（cyaron，仓库惯例）
# 用法：mkdir -p data && cd data && python3 ../data.py
#
# 题意：读入一个正整数 a，若 a 为偶数输出 yes，否则什么也不输出。
# 样例：输入 12 => 输出 yes（奇数时【输出】必须是 0 字节，不是空行、不是 no）。
#
# 数据范围说明：
#   题面（content.md）与官方 OJ 页（本包已实测抓取：
#   http://ybt.ssoier.cn:8088/problem_show.php?pid=2051 ，限制 1000 ms / 65536 KB）
#   **均未声明 a 的取值范围**，仅说「一个正整数a」。参照同批次 2064 的处置口径，
#   本生成器自定工作范围：
#       1 <= a <= 2147483647 (= 2^31 - 1，自然的有符号 32 位上限)
#   - 下界取 1：题面明确「正整数」；
#   - 上界取 int32 上限：全部 8 个网络来源题解都用 int/long long 读入（见 std.cpp 头注释），
#     该范围内 int 版写法不溢出，数据对官方题解公平；
#   - std 用 long long 读入，是该范围的超集。
#   - 题面「答案为 0 或 1 的极端」这一分层项不适用：本题输出是字符串 yes / 空，
#     不是数值；与之对应的极端（最小触发/不触发、最大触发/不触发）已由点 1、2、9、10 覆盖。
#   本题为单组输入（一个测试点即一个整数 a），不存在多组数据的「组数分层」；
#   分层按 a 的量级铺开，并把奇偶两个分支在每一层都各取一次（保证两个分支都被真正评到）：
#   点 1-2   边界层：全最小值 a=1（奇数，空输出）/ 最小偶数 a=2（yes），相邻奇偶对比
#   点 3-4   小规模定点/随机：题面【输入样例】12（题面声明特殊值）/ 小奇数随机（可手算）
#   点 5-6   中等规模随机：范围中间档 1e5~1e7，奇数分支 / 偶数分支各一
#   点 7-8   大规模随机：接近上限 1e8~2^31-1，偶数分支 / 奇数分支各一
#   点 9-10  顶格层：a=2^31-1（全最大值，奇数 -> 空输出）/ a=2^31-2（最大偶数 -> yes）
from cyaron import *  # 引入CYaRon的库

import random
random.seed(2051)  # 固定种子，便于复现

AMAX = 2147483647  # 自定工作范围上限 = 2^31-1（题面未声明，理由见文件头）


def gen_case(i, a, note):
    """写出第 i 组：输入 a，用 std 生成输出；并打印可核对的期望分支。"""
    assert 1 <= a <= AMAX, "超出自定工作范围"
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(a)
    io.output_gen("../std")
    print("problem%-2d: a=%-10d 期望输出=%-6s -- %s" % (i, a, "yes" if a % 2 == 0 else "(空)", note))


def rand_odd(lo, hi):
    """返回 [lo, hi] 内的随机奇数（lo、hi 需保证区间内存在奇数）。"""
    assert lo <= hi and lo >= 1
    x = random.randint(lo, hi)
    if x % 2 == 0:
        x = x + 1 if x + 1 <= hi else x - 1
    assert lo <= x <= hi and x % 2 == 1
    return x


def rand_even(lo, hi):
    """返回 [lo, hi] 内的随机偶数（lo、hi 需保证区间内存在偶数）。"""
    assert lo <= hi and lo >= 2
    x = random.randint(lo, hi)
    if x % 2 == 1:
        x = x + 1 if x + 1 <= hi else x - 1
    assert lo <= x <= hi and x % 2 == 0
    return x


# ---- 点 1-2：边界层 ----
# 点 1：全最小值 a=1 —— 最小正整数、奇数，"什么也不输出"分支的输入下界（.out 为 0 字节）。
gen_case(1, 1, "边界层：全最小值 a=1（奇数，空输出下界）")

# 点 2：最小偶数 a=2 —— "yes" 分支能取到的最小输入；与点 1 构成相邻奇偶对比。
gen_case(2, 2, "边界层：最小偶数 a=2（yes 分支下界，与点 1 相邻奇偶对比）")

# ---- 点 3-4：小规模（可手算验证的量级） ----
# 点 3：题面【输入样例】a=12 -> yes（题面声明的特殊值，必须出现在数据里）。
gen_case(3, 12, "小规模定点：题面【输入样例】12 -> yes（题面声明特殊值）")

# 点 4：小规模随机奇数 a∈[3,999]（可手算奇偶）—— 小规模下再钉一次空输出分支。
a4 = rand_odd(3, 999)
gen_case(4, a4, "小规模随机奇数：a∈[3,999]，可手算（空输出分支）")

# ---- 点 5-6：中等规模随机（范围中间档） ----
# 点 5：中等规模随机奇数 a∈[1e5, 1e7]
a5 = rand_odd(100000, 10000000)
gen_case(5, a5, "中等规模随机奇数；范围中间档（空输出分支）")

# 点 6：中等规模随机偶数 a∈[1e5, 1e7]
a6 = rand_even(100000, 10000000)
gen_case(6, a6, "中等规模随机偶数；范围中间档（yes 分支）")

# ---- 点 7-8：大规模随机（接近上限） ----
# 点 7：大规模随机偶数 a∈[1e8, 2^31-2]
a7 = rand_even(100000000, AMAX - 1)
gen_case(7, a7, "大规模随机偶数；贴近自定上限（yes 分支）")

# 点 8：大规模随机奇数 a∈[1e8, 2^31-1]
a8 = rand_odd(100000000, AMAX)
gen_case(8, a8, "大规模随机奇数；贴近自定上限（空输出分支）")

# ---- 点 9-10：顶格层（取自定上限，构造两个方向的极端） ----
# 点 9：a = 2^31-1 = 2147483647，全最大值且为奇数 —— 顶格下的空输出极端。
gen_case(9, AMAX, "顶格层：全最大值 a=2^31-1（奇数 -> 空输出）")

# 点 10：a = 2^31-2 = 2147483646，全最大值 -1，是范围内最大的偶数 —— 顶格下的 yes 极端。
gen_case(10, AMAX - 1, "顶格层：最大偶数 a=2^31-2（yes 分支的顶格）")
