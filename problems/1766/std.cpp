// 相对来源的改写点:
//   - [1] 用记忆化递归（vis[55][55][55][55]，洛谷上需开 O2 才过）；本程序改为按区间
//     长度递增的递推 + 一维展平数组，无递归开销，n=V=50 实测约 0.02s。
//   - 状态定义等价改写：[1] 的 f(i,j,l,r) 表示「[i,j] 中取走一些数后，剩下未取的数
//     都在 [l,r] 内，且 l、r 本身一定剩下」；本程序的 F[i][j][x][y] 表示「当前这一批
//     （本层最后取走的那批）已吸收了左侧若干元素，其分数 min/max 的压缩下标为 x,y」。
//     两者描述同一个对象（都是「本层最后一批」），代价同为 a+b*(val[y]-val[x])^2，
//     转移结构也一一对应：
//       [1] f(i,j,l,r) = min_k { f(i,k,l,r)+f(k+1,j,l,r),
//                               f(i,k,l,r)+f(k+1,j,0,0),
//                               f(i,k,0,0)+f(k+1,j,l,r) }
//       本程序 (a)+(b) 即同一枚举：k 处切分，每侧要么「继续供养当前批（留在 [l,r] 内）」
//       要么「整侧先取空（= f(·,·,0,0)）」。
//   - [1] 的 f(i,j,0,0) 里还枚举了 l,r 的收尾，本程序用 base case F[j+1][j][x][y] 直接
//     结算，等价。
//   - 取值离散化同 [1]（至多 n 个不同分数）。
//
// 样例验证: 题面样例 -> 15（与题面输出样例一致）。
//
// 题意与模型:
//   每次从「当前的一叠」中抽取连续的一段发掉，剩下的按原顺序仍叠成一叠。
//   因此一个批次不要求是原序列上的连续区间：中间的一段被先抽走后，其左右两侧
//   在剩下的那一叠里就相邻了，可以并入同一批。
//   （反例对照：若误按「原序列连续区间划分」做线性 DP，样例会得到 21，而题面
//     答案是 15 —— 说明必须允许这种「跨过已抽走区间」的合并。）
//
// 合法性判定 (精确刻画 —— 只看位置, 不看分数):
//   给每张成绩单赋一个「批次时间」t（同一批时间相同，不同批不同）。设批次 B 的元素
//   在原序列中最左、最右位置分别为 L、R。则 B 在其被取走的那一刻合法
//     <=>  所有满足 L < p < R 且 p ∉ B 的位置 p 都已经先被取走（时间更小）。
//   证明:
//     ⇒ 若存在这样的 p 尚未取走，则取 B 时 p 还夹在 B 的最左与最右元素之间，
//        B 在那一叠里不连续 -> 不合法。
//     ⇐ 若所有这样的 p 都已取走，则 B 的元素在那一叠里恰好排成一个连续段 -> 合法。
//   ⚠ 注意判定用的是「位置」而不是「分数」。分数只在代价里以 (max-min)^2 出现。
//   （若误用「分数落在 [minB,maxB] 内且不属于 B 的元素都要更早」作判定，条件不充分：
//     样例中 P={1,5,6,8}(分数 7,6,7,7)、Q={2,4,7}(分数 10,10,10)、R={3}(分数 9)
//     都满足该分数式判定，但 P 要求 Q 的元素 2,4,7 更早、Q 又要求 P 的元素 5,6
//     更早，循环依赖 -> 该方案根本排不出取走顺序，可见分数式判定是错的。）
//
// 递归结构 (区间 DP):
//   对区间 [l,r] 内的元素，令 S 为其中最后被取走的那一批。S 取走时 [l,r] 内其余元素
//   已全部取走，故 S 必然合法；反过来，任何满足「[l,r] 内不属于 S 的元素都更早取走」
//   的集合 S 都能充当最后一批（此时 S 就是 [l,r] 剩下的全部，当然连续）。于是
//       cost[l,r] = ( a + b*(maxS-minS)^2 ) + Σ_{空隙} cost[空隙]
//   空隙 = S 在 [l,r] 内相邻两个位置之间那些位置的极大连续段（S 不含其中元素）。
//   各空隙是独立子问题：若有批次 B 的元素落在 S 的某个元素的两侧，则该 S 元素夹在
//   B 的两个元素之间且 ∉ B，而 S 比 B 晚取走，与 B 的合法性矛盾；故每个批次的元素
//   必整体落在同一个空隙里（或本层之外）。
//
// DP 定义 (按区间长度递增计算):
//   dp[i][j]        : 把区间 [i,j] 单独当作一叠全部抽走的最小代价 (空区间 = 0)。
//   F[i][j][x][y]   : 处理区间 [i,j] 的最小代价，已知「当前这一批」（本层最后取走的
//                     那批 S）已经吸收了 [i,j] 左侧的若干元素，其分数最小值 / 最大值的
//                     压缩下标分别为 x、y。
//                     当前批的代价只由 (分数最小值, 分数最大值) 决定，与其元素的具体
//                     位置无关 —— 位置只影响空隙的划分，而那由转移本身刻画 —— 故状态
//                     只需记 (x,y) 即可，不必记位置。
//   转移:
//     (a) i 并入当前批 : F[i+1][j][ min(x,id_i) ][ max(y,id_i) ]
//     (b) i 落入空隙   : min_{k=i..j} ( dp[i][k] + F[k+1][j][x][y] )
//         （[i,k] 整段作为当前批相邻元素之间的一个空隙，先被独立取空，再继续处理
//           [k+1,j]。允许把空隙再拆成两段只会取到不劣的合法结构：两个相邻区间的
//           独立合法结构直接拼接仍合法，故 dp[i][k] + dp[k+1][k'] >= dp[i][k']，
//           既不会低估最优值，而最优结构又可由恰好按空隙切分的路径取到。）
//     空区间收尾 F[j+1][j][x][y] = a + b*(val[y]-val[x])^2   （结算当前批）
//   dp[i][j] = min_{s=i..j} ( dp[i][s-1] + F[s+1][j][id_s][id_s] )
//              （当前批最左元素为 s；[i,s-1] 是它左边的空隙）
//
// 取值离散化: 至多 n<=50 个不同分数，压缩到 [0,V)，V<=n。
// 复杂度: 状态 O(n^2 * V^2)，转移 (b) O(n) => O(n^3 * V^2 / 2) ≈ 3e7 次内层迭代
//   （n=V=50 实测约 0.02s），远低于 3s。
// 代价上界: k<=50，每批 <= a + b*999^2。按一本通题面 (a<=100, b<=10) 总和 < 5.0e8；
//   即使按洛谷 P5336 的 a<=1500，总和 < 5.0e8 亦成立（50*(1500+10*998001)=4.99e8）。
//   故 int 足够（INF = 1<<30 ≈ 1.07e9 不会与合法值相撞，两个合法值相加 < 1.0e9 也不溢出）。
// 内存: F 为 (n+2)^2 * V^2 个 int = 52*52*50*50*4B ≈ 27MB，远低于 256MB。
// ---------------------------------------------------------------------------
#include <cstdio>
#include <cstring>
#include <algorithm>
#include <vector>
using namespace std;

static const int INF = 1 << 30;

int n, a, b;
int w[55];
int idv[55];              // 每个分数的压缩下标
int V;                    // 不同分数个数
vector<int> vals;         // 去重后的分数（升序）
vector<int> F;            // F[i][j][x][y] 展平
vector<int> dp;           // dp[i][j]

static inline int fidx(int i, int j, int x, int y) {
    return ((i * (n + 2) + j) * V + x) * V + y;
}
static inline int didx(int i, int j) {
    return i * (n + 2) + j;
}

int main() {
    if (scanf("%d %d %d", &n, &a, &b) != 3) return 0;
    for (int i = 1; i <= n; ++i) scanf("%d", &w[i]);

    vals.assign(w + 1, w + n + 1);
    sort(vals.begin(), vals.end());
    vals.erase(unique(vals.begin(), vals.end()), vals.end());
    V = (int)vals.size();
    for (int i = 1; i <= n; ++i)
        idv[i] = (int)(lower_bound(vals.begin(), vals.end(), w[i]) - vals.begin());

    dp.assign((size_t)(n + 2) * (n + 2), INF);
    F.assign((size_t)(n + 2) * (n + 2) * V * V, INF);

    // 空区间 dp[i][i-1] = 0；空区间 F[j+1][j][x][y] = 收尾结算当前批
    for (int i = 1; i <= n + 1; ++i) {
        int j = i - 1;
        dp[didx(i, j)] = 0;
        for (int x = 0; x < V; ++x)
            for (int y = x; y < V; ++y) {
                int d = vals[y] - vals[x];
                F[fidx(i, j, x, y)] = a + b * d * d;
            }
    }

    for (int len = 1; len <= n; ++len) {
        for (int i = 1; i + len - 1 <= n; ++i) {
            int j = i + len - 1;

            // ---- dp[i][j] : 当前批最左元素为 s ----
            int best = INF;
            for (int s = i; s <= j; ++s) {
                int c1 = dp[didx(i, s - 1)];
                if (c1 >= INF) continue;
                int c2 = F[fidx(s + 1, j, idv[s], idv[s])];
                if (c2 >= INF) continue;
                if (c1 + c2 < best) best = c1 + c2;
            }
            dp[didx(i, j)] = best;

            // ---- F[i][j][x][y] ----
            for (int x = 0; x < V; ++x) {
                for (int y = x; y < V; ++y) {
                    int nx = min(x, idv[i]);
                    int ny = max(y, idv[i]);
                    int res = F[fidx(i + 1, j, nx, ny)];   // (a) i 并入当前批
                    for (int k = i; k <= j; ++k) {         // (b) i 落入空隙
                        int c1 = dp[didx(i, k)];
                        if (c1 >= INF) continue;
                        int c2 = F[fidx(k + 1, j, x, y)];
                        if (c2 >= INF) continue;
                        if (c1 + c2 < res) res = c1 + c2;
                    }
                    F[fidx(i, j, x, y)] = res;
                }
            }
        }
    }

    printf("%d\n", dp[didx(1, n)]);
    return 0;
}
