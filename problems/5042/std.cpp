#include <cstdio>

static const int LIMIT = 1000000;          // 防御性上限（题面上限 1000）
static bool isComposite[LIMIT + 5];        // isComposite[i]：i 是合数（已筛掉）

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;    // 无输入（空文件）时安静退出
    if (n < 2) return 0;                   // 题面保证 n >= 2，此处仅作保护
    if (n > LIMIT) n = LIMIT;              // 越界保护，正常数据不会触发

    for (int i = 2; (long long)i * i <= n; ++i) {
        if (isComposite[i]) continue;      // 已被更小的质数筛掉，跳过
        for (int j = i * i; j <= n; j += i)
            isComposite[j] = true;         // 从 i*i 起筛（i 的较小倍数已筛过）
    }

    for (int i = 2; i <= n; ++i)
        if (!isComposite[i]) printf("%d\n", i);   // 由小到大，每行一个质数

    return 0;
}
