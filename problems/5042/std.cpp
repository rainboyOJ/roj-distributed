// 一本通 2040《【例5.7】筛选法找质数》标程（目标 ROJ 题号 5042）
// ---------------------------------------------------------------------------
// 题意：输入 n（题面范围 2 ≤ n ≤ 1000），用筛法求出 n 以内的全部质数，
//       按由小到大顺序，每行输出一个质数。
//       题面样例：n = 10  ->  2 / 3 / 5 / 7（逐行）。
//       语义确认：题面「n 以内的全部质数」= 所有满足 2 ≤ p ≤ n 的质数（含上界），
//       全部可查来源的输出循环均为 "for i = 2..n，若 i 是质数则输出 i"。
// 做法：埃拉托色尼（普通）筛法。
//       从 i = 2 起，若 i 未被标记为合数则 i 是质数；把 i 的倍数（从 i*i 起，
//       因为 2i..(i-1)i 已被更小的质因数筛过）标记为合数。
//       外层只需枚举到 sqrt(n)（i*i <= n），因为 n 以内的合数必有 ≤ sqrt(n) 的质因数。
//       复杂度 O(n log log n)，n = 1000 时瞬时完成。
// 实现细节（相对来源的改写点）：
//   * 用 cstdio 的 scanf/printf（风格参考本仓库 problems/1000/std.cpp），
//     每行一个数、行末单个 '\n'，与题面样例格式一致；
//   * 内层起点取 i*i（多数来源用 i+i，两者等价但前者常数更小；来源 [1] 亦取 i^2）；
//   * 循环变量用 int，判据写 (long long)i*i <= n，杜绝 i*i 溢出；
//   * 静态数组开到 1e6+5 并做越界保护（题面上限仅 1000，正常数据不会触发），
//     保证任何输入下都不越界、不崩溃。
// ---------------------------------------------------------------------------
// 参考来源 URL（均为网络检索所得，已 curl 实取正文/代码核对，结论互相一致）：
//   [1] https://blog.csdn.net/lq1990717/article/details/122032998
//       信息学奥赛一本通 2040：【例5.7】筛选法找质数 (普通筛 线性筛)（君义_noip）
//       给出两解：普通筛（埃筛）与线性筛（欧拉筛）；普通筛内层以 i*i 起、
//       外层 i*i <= n。本标程采用其普通筛路线（题面即要求"筛选法"）。
//   [2] https://blog.csdn.net/2402_84298973/article/details/146242544
