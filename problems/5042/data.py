#!/usr/bin/env python
# -*- coding: utf-8 -*-
#
# 一本通 2040《【例5.7】筛选法找质数》分层数据生成器（cyaron）
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py、staging/2070/data.py
#
# 题意：输入单个整数 n（题面范围 2 ≤ n ≤ 1000），用筛法求出 n 以内的全部质数，
#       由小到大每行输出一个。题面样例 n=10 -> 2/3/5/7。
#
# 本题是**单组输入**（一个测试点 = 一个 n），不存在"多组数据按组数分层"，
# 且输入域极小（合法取值仅 999 个），因此分层策略是：
#   ① 数值量级 从下界 n=2 一路铺到顶格 n=1000；
#   ② 交叉覆盖筛法的**临界结构**——内层起筛下界 i*i（完全平方数）、
#      外层 i*i<=n 判据最右端、上限邻域最后一个质数 997 的进出临界（n=996/1000）。
# 这些临界点能直接打死三类常见错解：
#   * 内层写成 j < n / j <= n 的差一（n=4、n=9、n=121、n=961 会多输出 n 本身）；
#   * 内层起点写成 i*i 却漏掉边界（n = p² 时把 p² 当质数输出）；
#   * 输出循环上界写成 i < n（丢掉 997）。
#
# 分层表（10 组，随机点用独立随机源 random.Random(2040+点号)，可复现）：
#   点 1  边界层：n=2（题面下界；答案仅 {2}，全题唯一"输出 1 行"的极端）
#   点 2  边界层：n=4=2²（内层起筛 i*i 的最小生效临界：i=2 时 2²=4 ≤ 4；
#                        也是"n 本身为完全平方"的最小情形；答案 {2,3}）
#   点 3  小规模随机：n=10（题面样例，可手算核对 -> 2/3/5/7）
#   点 4  小规模结构：n=9=3²（i=3 的 i*i ≤ n 临界；答案 2/3/5/7，可手算）
#   点 5  中等规模随机：n ∈ [100,300] 随机（中档普通随机）
#   点 6  中等规模结构：n=121=11²（中档完全平方临界，i=11；答案 30 个质数）
#   点 7  大规模随机：n ∈ [600,850] 随机（接近上限的随机）
#   点 8  大规模结构：n=961=31²（⌊√1000⌋=31，31²=961 是上限内最右的完全平方临界，
#                        即外层 i*i<=n 判据的最右端；答案 162 个质数）
#   点 9  顶格层：n=996（上限邻域临界——仍不含质数 997 的最大 n，
#                        答案 167 个质数、最后一个为 991）
#   点 10 顶格层：n=1000（题面上限顶格，答案 168 个质数、最后一个为 997，最长输出）
#
# 说明：点 2/4/6/8 是结构化的临界点而非随机点，与「小/中/大随机」交替铺设，
# 既满足规模从最小铺到顶格，也保证 10 个点各有独立设计意图、输出互不重复
# （n=996 与 n=1000 的输出大小差 1，用于验证 997 的进出临界）。

from cyaron import *  # 引入CYaRon的库

import random  # 显式引入（cyaron 的 star-import 不保证导出 random）

# (n 取值, 层次描述)；随机点用 CASE_SEED 派生独立随机源，与调用顺序无关。
CASE_SEED = 2040


def rand_between(i, lo, hi):
    """第 i 个点专用随机源（与全局 random 状态、调用顺序解耦），结果可复现。"""
    rnd = random.Random(CASE_SEED + i)
    return rnd.randint(lo, hi)


N_R5 = rand_between(5, 100, 300)   # 点 5：中等规模随机
N_R7 = rand_between(7, 600, 850)   # 点 7：大规模随机

CASES = [
    (2, "边界层（下界）：n=2，答案仅 {2}，全题唯一输出 1 行的极端；"
        "同时验证不输出 1（1 不是质数）"),
    (4, "边界层（最小完全平方）：n=4=2²，内层起筛下界 i*i 的最小生效临界"
        "（i=2, 2²=4 ≤ 4）；错解若写 j<n 会把 4 当质数输出，答案恰为 {2,3}"),
    (10, "小规模随机：n=10，即题面样例，可手算核对 -> 2/3/5/7"),
    (9, "小规模结构：n=9=3²，i=3 的 i*i ≤ n 临界（j<n 的差一会多输出 9）；"
        "答案 2/3/5/7 可手算"),
    (N_R5, "中等规模随机：n ∈ [100,300] 随机（中档普通随机，输出十几到二十几行）"),
    (121, "中等规模结构：n=121=11²，中档完全平方临界（i=11 处 i*i=121 ≤ n）；"
          "若差一把 121 当质数输出则会多一行；答案 30 个质数，最后一个为 113"),
    (N_R7, "大规模随机：n ∈ [600,850] 随机（接近上限的随机档）"),
    (961, "大规模结构：n=961=31²，⌊√1000⌋=31，是上限内最右的完全平方临界，"
          "即外层 i*i<=n 判据的最右端（i=31）；答案 162 个质数"),
    (996, "顶格层（上限邻域临界）：n=996，仍不含质数 997 的最大 n；"
          "答案 167 个质数，最后一个为 991 —— 与点 10 配对验证 997 的进出临界"),
    (1000, "顶格层（题面上限顶格）：n=1000，答案 168 个质数、最后一个 997，最长输出"),
]

for idx, (n, note) in enumerate(CASES, start=1):
    io = IO(file_prefix="problem", data_id=idx)  # problem{idx}.in / problem{idx}.out
    io.input_writeln(n)                          # 单组输入：一行一个整数 n
    io.output_gen("../std")
    print("problem%d: n=%-4d -- %s" % (idx, n, note))
