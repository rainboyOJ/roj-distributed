#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 一本通 2017《【例4.2】输出偶数》（目标 ROJ 题号 5019）—— 测试数据生成器（cyaron，仓库惯例）
# 用法：mkdir -p data && cd data && python3 ../data.py
#
# 题意：输入 n，按由小到大的顺序输出 1∼n 之间的所有偶数，一行，偶数之间用一个空格隔开。
# 样例：输入 10 => 输出 `2 4 6 8 10`。
# 数据范围（题面【提示】明示）：1 ≤ n ≤ 100。限制：time 1000 ms / memory 65536 KB。
#
# 分层设计（10 组；题面上限 100，故"大规模/顶格"即接近或等于 100）：
#   点 1     边界层：n=1（全最小值）—— 1∼n 内没有偶数，本题唯一的"空答案/退化"输入，
#            期望输出 0 字节（见 std.cpp 头注释与 gen-report.md 风险点 1 的判读依据）
#   点 2     边界层：n=2（n=2 的最小合法值）—— 最小非空答案 "2"，与点 1 相邻对比
#   点 3     小规模：n=10（题面【输入样例】声明的特殊值）—— 可手算，且与题面样例逐字节一致
#   点 4     小规模：n=3（最小奇数 n）—— 手算答案 "2"，覆盖"n 为奇数"这一分支的最小值
#   点 5     小规模随机：n ∈ [4,30]  —— 答案个数 1~15，可人工数清核对
#   点 6     中等规模随机：n ∈ [31,65] —— 范围中间档，答案个数 15~32
#   点 7     大规模随机：n ∈ [66,90] —— 接近上限，答案个数 33~45
#   点 8     大规模随机：n ∈ [91,98] —— 逼近上限的随机点（与点 9/10 的顶格值不重复）
#   点 9     顶格层：n=100（全最大值，题面上限）—— 输出最长行（50 个偶数，末项 100）
#   点 10    顶格层：n=99（上限 −1，最大奇数）—— 输出 49 个偶数，末项 98，
#            与点 9 构成"上限处奇/偶相邻对比"，检验边界处的循环终止条件（i<=n vs i<n）
#
# 说明：题面要求的"答案为 0 或 1 的极端"在本题型中不适用（输出是序列，不是数值），
#       与之等价的极端是"空答案"（点 1）与"单元素答案"（点 2、点 4），均已覆盖。
#       本题为单组输入（一个测试点即一个整数 n），不存在多组数据的"组数分层"。
#
# 生成方式：IO(file_prefix="problem", data_id=i) + io.output_gen("../std")，
#           与 problems/1000/data.py、.ybt-import/staging/2062/data.py 等既有包一致。
# 固定随机种子，数据可复现。
from cyaron import *  # 引入CYaRon的库

import random

random.seed(2017)  # 固定种子，便于复现

NMIN = 1    # 题面下界
NMAX = 100  # 题面上限


def gen_case(i, n, note):
    """写出第 i 组：输入 n，用 std 生成输出；并打印手工可核对的期望序列。"""
    assert NMIN <= n <= NMAX, "n=%d 超出题面范围 [1,100]" % n
    evens = list(range(2, n + 1, 2))
    expect = " ".join(map(str, evens))  # Python 独立参照（闭式计算）：
    #   有偶数时 std 输出 `expect + "\n"`；n=1 时为空答案，std 输出 0 字节。
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(n)  # 行末带换行（与 2052/2064/2070 等较新包一致，最兼容）
    io.output_gen("../std")
    print("problem%-2d: n=%-3d 答案个数=%-2d 期望输出=%s -- %s"
          % (i, n, len(evens), repr(expect), note))


# ---- 点 1：边界层（全最小值 n=1；1∼n 内无偶数 => 空答案） ----
gen_case(1, 1, "边界层：全最小值 n=1，空答案（0 字节输出）")

# ---- 点 2：边界层（n=2，最小非空答案） ----
gen_case(2, 2, "边界层：n=2，最小非空答案 '2'（与点 1 相邻对比）")

# ---- 点 3：小规模（题面声明的特殊值 = 输入样例值 10） ----
gen_case(3, 10, "小规模：题面【输入样例】值 n=10（与样例逐字节一致）")

# ---- 点 4：小规模（最小奇数 n=3） ----
gen_case(4, 3, "小规模：最小奇数 n=3，答案 '2'（覆盖奇数 n 分支下界）")

# ---- 点 5：小规模随机 n ∈ [4,30] ----
# 重抽以避免与点 3 的样例值 10 重复（10 组数据互不相同，除刻意成对的边界点外不重复）
n5 = random.randint(4, 30)
while n5 == 10:
    n5 = random.randint(4, 30)
gen_case(5, n5, "小规模随机：n∈[4,30]，答案个数 ≤15，可数清核对")

# ---- 点 6：中等规模随机 n ∈ [31,65] ----
gen_case(6, random.randint(31, 65), "中等规模随机：n∈[31,65]，范围中间档")

# ---- 点 7：大规模随机 n ∈ [66,90] ----
gen_case(7, random.randint(66, 90), "大规模随机：n∈[66,90]，接近上限")

# ---- 点 8：大规模随机 n ∈ [91,98] ----
gen_case(8, random.randint(91, 98), "大规模随机：n∈[91,98]，逼近上限")

# ---- 点 9：顶格层 n=100（题面上限，全最大值） ----
gen_case(9, NMAX, "顶格层：n=100（题面上限/全最大值），输出最长行（50 个偶数）")

# ---- 点 10：顶格层 n=99（上限 −1，最大奇数） ----
gen_case(10, NMAX - 1, "顶格层：n=99（上限−1 的最大奇数），末项 98，与点 9 相邻奇偶对比")
