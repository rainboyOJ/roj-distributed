// 一本通 2017《【例4.2】输出偶数》（目标 ROJ 题号 5019）标程
//
// 题意（.ybt-import/staging/2017/content.md）：
//   按照由小到大的顺序，输出 1∼n 之间的所有偶数；
//   输出为一行，各个偶数之间用一个空格隔开。
//   样例：输入 10 => 输出 2 4 6 8 10
//   数据规模：1 ≤ n ≤ 100（题面明示）。
//   限制：time 1000 ms，memory 65536 KB（config.json 与官方 OJ 页一致：
//   https://ybt.ssoier.cn/problem_show.php?pid=2017 ，
//   2026-10 本轮实测可访问，页面显示「时间限制: 1000 ms 内存限制: 65536 KB
//   提交数: 160604 通过数: 103531」，题面/样例与 content.md 逐字一致）。
//
// 参考来源（网络题解 / AC 代码，本包已逐篇实际抓取核验，然后按题面改写，非盲抄）：
//   [1] https://blog.csdn.net/lvcheng0309/article/details/116546383
//       《信息学奥赛一本通（2017：【例4.2】输出偶数）》【参考代码】（C）：
//         for(i=2;i<=n;i+=2){ if(i%2==0) printf("%d ",i); } printf("\n");
//   [2] https://blog.csdn.net/lq1990717/article/details/116675047
//       《信息学奥赛一本通 2017：【例4.2】输出偶数》：给出 for 与 while 两解，
//         for(int i=1;i<=n;++i) if(i%2==0) cout<<i<<' ';
//         while(i<=n){ if(i%2==0) cout<<i<<' '; i++; }
//   [3] https://blog.csdn.net/tflstjs/article/details/121057002
//       《一本通2017：【例4.2】输出偶数》：
//         for(int i=2;i<=n;i=i+2){ cout<<i<<" "; }
//   [4] https://blog.csdn.net/wsm20040523/article/details/121722664
//       《信息学奥赛一本通2017：【例4.2】输出偶数》（C）：
//         for(a=1;a<=n;a++){ if(a%2==0) printf("%d ",a); }
//   [5] https://blog.csdn.net/bbbb8989/article/details/127658368
//       《C语言打印偶数程序》（对应本题）：
//         for(i=2;i<=n;i+=2){ if(i%2==0) printf("%d ",i); } printf("\n");
//   [6] https://blog.csdn.net/cora_loose/article/details/116722661
//       《信息学奥赛一本通C语言——2017：【例4.2】输出偶数》：
//         for(i=2;i<=n;i+=2) printf("%d\n",i);   ← 每个数换行，与样例
//         「2 4 6 8 10」同行的格式不符，**不采用**（仅记录为反例）。
//   [7] 教材原始出处（例4.2 的两种解法，穷举 & 步长 2）：
//       https://github.com/Lucifer-ww/NOIP_ReC 「第4章 循环结构(C++版).ppt」
//       （信奥一本通配套光盘课件）：方法1 `for(i=1;i<=100;i++) if(i%2==0) cout<<i<<"  ";`
//       方法2 `for(i=2;i<=100;i+=2) cout<<i<<"  ";`（教材示例固化为 1~100，
//       泛化为「输入 n」即本题）。
//
// 多来源结论核对（无冲突）：
//   * 算法只有两种等价写法：① 穷举 1..n 判断 i%2==0；② 从 2 起步长 2（教材方法1/方法2）。
//   * 输出都是「偶数 + 单个空格」；来源 [1][5] 在循环后额外打印一个 '\n'，
//     [3][4] 则不打印。两者对 n≥2 在忽略行末空白的判题器（本仓库用 `diff -b`）
//     下等价；差异只在 n=1（无偶数）时出现，处置见下。
//
// 本包实现（C++17，stdin→stdout，风格参考 problems/1000/std.cpp）：
//   * 采用教材方法2（步长 2，O(n/2)），与暴力参照 work/brute.cpp（穷举判断，
//     教材方法1）构成两条独立实现路径，供对拍交叉验证。
//   * 分隔符用「先判断再输出」的写法，保证行末**没有**多余空格（对 `diff -b`
//     以及对「行末空格敏感」的严格判题器都安全）。
//   * 行末换行：有输出（n ≥ 2）时输出一个 '\n'，与仓库语料惯例一致
//     （.ybt-import/staging 内 4000+ 个非空 .out 全部以换行结尾）；
//     n = 1（1..n 内没有偶数）时**不输出任何字节**，期望输出为 0 字节空文件。
//     —— 这是本包唯一存在实现分歧的边界，理由与风险见 gen-report.md「风险点 1」：
//        教材代码与多数题解 [2][3][4] 在无偶数时都不输出任何字符（循环体不执行，
//        循环后没有打印语句），故 n=1 取「0 字节」是与教材/多数 AC 解一致的判读。
//        若主控确认官方数据对 n=1 期望「一个空行」（1 字节 '\n'，即来源 [1][5] 的写法），
//        只需把下面 `if (printed) putchar('\n');` 改成无条件 putchar('\n')（或删掉判据），
//        重跑 data.py 即可，仅点 1 受影响。
//   * 复杂度 O(n/2) 时间、O(1) 空间；n ≤ 100，耗时远低于 1 ms / 1000 ms、内存 ~1 MB / 64 MB。

#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;  // 读入 n；无输入时静默退出（题面保证有输入）

    bool printed = false;                // 是否已经输出过至少一个偶数
    for (int i = 2; i <= n; i += 2) {    // 教材方法2：从最小的偶数 2 起，步长 2
        if (printed) putchar(' ');       // 偶数之间用一个空格隔开（行首/行末不留空格）
        printf("%d", i);
        printed = true;
    }
    if (printed) putchar('\n');          // 有偶数时以换行结束；n=1 时保持 0 字节输出

    return 0;
}
