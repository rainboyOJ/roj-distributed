#!/usr/bin/env python
# cyaron 数据生成器 —— 一本通 1674《堆蛋糕》
# 题面范围：n ≤ 3,000,000，R_i ≤ n。
# 分层设计（10 个测试点，从最小铺到顶格）：
#   点1  边界：n=1（单蛋糕，答案 0）
#   点2  边界：n=2 与 n=3 全同半径（答案 0）；n=3 三互异（答案 1）—— 多用例拼接由单组实现，
#        本点取 n=3 全同（答案 0）+ 顶部特殊值；实际以 n=2 全同为主（答案 0 极端）
#   点3  小规模随机：n≤10，可手算
#   点4  小规模随机：n≤2000（40% 档），含重复值域
#   点5  中等随机：n=100000（60% 档），均匀值域
#   点6  中等随机：n=100000，小值域高重复（卡计数）
#   点7  大规模随机：n=2,000,000，均匀 [1,n]
#   点8  大规模随机：n=3,000,000，随机值域 [1, n]（顶格）
#   点9  顶格构造：n=3,000,000，k,k,k 精确三元组（答案恰 1e6，指针满负荷回填）
#   点10 顶格构造：n=3,000,000，计数阶梯（最大计数 ~2.4e6，答案 0 或极小，最坏指针回填结构）
#        —— 采用"单一种半径占绝对多数"的极端结构：最大计数 2,999,998，答案 0，
#        同时桶统计上限达到顶格，检验 cnt[] 计数与 bucket[3e6] 越界。
# 每个测试点规模/意图见各处注释。不允许全部为小随机。

from cyaron import *

def gen_point(i):
    if i == 1:
        # 边界层：n=1，只有 1 个蛋糕，无法堆三层，答案 0；
        # 另含 n=2 全同的“答案为 0”极端（不足三种半径）不可与 n=1 同点，
        # 故本点取最小规模 n=1（R 取题面最小值 1）。
        n = 1
        R = [1]
    elif i == 2:
        # 边界层：全最大值/答案为 1 的极端。n=3，R 全部取题面上限内的最大重复：
        # 三个互不相同的半径（1,2,3）→ 答案恰为 1（最小非零解），
        # 同时 R_i 达到 n（顶格值）。再补一组 n=2 全同不可行，故本点取“答案=1”极端。
        n = 3
        R = [1, 2, 3]
    elif i == 3:
        # 小规模随机：n∈[3,10]，值域小保证大量重复，可手算验证
        n = randint(3, 10)
        R = [randint(1, max(1, n // 2)) for _ in range(n)]
    elif i == 4:
        # 小规模随机（40% 档顶格）：n=2000，混合值域（一半均匀 [1,n]，一半小值域高重复）
        n = 2000
        R = [randint(1, n) for _ in range(n // 2)] + \
            [randint(1, 20) for _ in range(n - n // 2)]
    elif i == 5:
        # 中等规模随机（60% 档顶格）：n=100000，均匀 [1,n]
        n = 100000
        R = [randint(1, n) for _ in range(n)]
    elif i == 6:
        # 中等规模随机：n=100000，双重结构——前一半小值域（K≈173，高重复计数），
        # 后一半阶梯计数（k,k,k-1,k-2,...，制造非均衡桶，逼贪心做多次回填）
        n = 100000
        R = [randint(1, 173) for _ in range(n // 2)]
        v = 1000
        k = 500
        while len(R) < n:
            R += [v] * k
            v += 1
            k = max(1, k - 3)
        R = R[:n]
    elif i == 7:
        # 大规模随机：n=2,000,000，均匀 [1,n]
        n = 2000000
        R = [randint(1, n) for _ in range(n)]
    elif i == 8:
        # 大规模随机（100% 顶格 n）：n=3,000,000，随机 [1,n]
        n = 3000000
        R = [randint(1, n) for _ in range(n)]
    elif i == 9:
        # 顶格构造：1e6 组精确三元组 (k,k,k)，答案恰为 1000000，
        # 三指针每轮都要从最大桶取满，回填量最大
        n = 3000000
        R = []
        for j in range(1, 1000001):
            R += [3 * j - 2, 3 * j - 1, 3 * j]
    elif i == 10:
        # 顶格构造（最坏结构）：单一半径占 2,999,998 个 + 两个各 1 个，
        # 最大计数达到 n-2 ≈ 顶格，bucket[2999998] 被写到最高下标；
        # 不同半径种数 K=3 但两桶为 1，答案 1（贪心取 1 次后枯竭），
        # 验证大计数下的指针移动与边界终止
        n = 3000000
        R = [1] * (n - 2) + [2, 3]
    return n, R

for i in range(1, 11):
    io = IO(file_prefix="problem", data_id=i)
    n, R = gen_point(i)
    io.input_writeln(n)
    io.input_writeln(R)
    io.output_gen("../std")
