#!/usr/bin/env python

from cyaron import *  # 引入CYaRon的库

# 一本通 1685《新版方格取数》数据生成器
# 题面范围：m,n 为正整数，m*n <= 16；格内数为非负整数且 < 100000（即 0..99999）。
# 特殊约定：题面说明“方格边缘”指四周一圈；第一个数必须从边缘取。
# 数据分层（10 个测试点，从最小铺到顶格）：
#   点1  边界层：m=1,n=1（单格，答案=a[0]），全 0 权
#   点2  边界层：m=1,n=2 / m=2,n=1 极小 + 全最大权 99999（答案结构可手算）
#   点3  边界层：m=1,n=16（1 行 16 列链，扁极端形状，交替 99999/0）
#   点4  小规模随机：m*n<=6，权 0..9，可手算
#   点5  小规模随机：m*n<=9（对应 50% 数据 m*n<=9），权 0..100
#   点6  中等规模随机：m*n<=12，权 0..99999
#   点7  大规模随机：m*n=14，权一半顶格 99999
#   点8  大规模随机：m*n=15，权 0..99999 全域随机
#   点9  顶格层：m*n=16（4x4），“中心大边缘小”最坏结构（卡“离开重进”）
#   点10 顶格层：m*n=16（4x4）全 99999（最大答案 + 转移最密集，卡时/卡溢出）


def gen(i, m, n, vals):
    """生成第 i 个测试点：写 m 行 n 列方格并调用 std 产出 .out。"""
    io = IO(file_prefix="problem", data_id=i)
    io.input_writeln(m, n)
    for r in range(m):
        io.input_writeln([vals[r * n + c] for c in range(n)])
    io.output_gen("../std")


# ---------- 点1：m=n=1 单格 + 全 0 ----------
# 意图：最小规模边界；单格必取，答案=a[0]；全 0 网格答案恒 0，验证 0 分路径。
# 期望答案：0（取走唯一格得 1*0 = 0）。
gen(1, 1, 1, [0])

# ---------- 点2：1x2 全最大权 99999 ----------
# 意图：最小多格边界 + 权值顶格（99999）；相邻顺序取，
# 期望答案：1*99999 + 2*99999 = 299997，同时检验 int 乘积边界（不溢出 long long）。
gen(2, 1, 2, [99999, 99999])

# ---------- 点3：1 行 16 列链（m*n=16 极扁形状） ----------
# 意图：链状只能顺序取（相邻转移为主），交替 99999/0 的权值使最优为
# 从 0 值端开始吃、大数尽量晚取；m*n=16 顶格但结构特殊（链）。
gen(3, 1, 16, [99999 if i % 2 == 0 else 0 for i in range(16)])

# ---------- 点4：小规模随机（m*n<=6，权 0..9） ----------
# 意图：可手算的小随机，覆盖 50% 档以下的小数据。
import random as _r
_r.seed(168504)
m, n = 2, 3
vals = [_r.randint(0, 9) for _ in range(m * n)]
gen(4, m, n, vals)

# ---------- 点5：小规模随机（m*n<=9，权 0..100） ----------
# 意图：对应题面 50% 数据上限 m*n=9（3x3），随机权中档。
_r.seed(168505)
m, n = 3, 3
vals = [_r.randint(0, 100) for _ in range(m * n)]
gen(5, m, n, vals)

# ---------- 点6：中等规模随机（m*n<=12，权 0..99999） ----------
# 意图：范围中间档 3x4=12，权值开到全域。
_r.seed(168506)
m, n = 3, 4
vals = [_r.randint(0, 99999) for _ in range(m * n)]
gen(6, m, n, vals)

# ---------- 点7：大规模随机（m*n=14，权顶格 99999 混合） ----------
# 意图：接近上限的规模 2x7=14；一半权取 99999（顶格权值 + 溢出压力）。
_r.seed(168507)
m, n = 2, 7
vals = [_r.choice([99999, _r.randint(0, 99999)]) for _ in range(m * n)]
gen(7, m, n, vals)

# ---------- 点8：大规模随机（m*n=15，权 0..99999 全域随机） ----------
# 意图：接近上限的满域随机数据 5x3=15。
_r.seed(168508)
m, n = 5, 3
vals = [_r.randint(0, 99999) for _ in range(m * n)]
gen(8, m, n, vals)

# ---------- 点9：顶格层（m*n=16，“中心大边缘小”最坏结构） ----------
# 意图：4x4=16 顶格；中心 4 格权极大、边缘权极小，
# 逼出“边缘绕圈/离开重进把大数留到靠后序号”的策略，卡贪心与转移完备性。
_r.seed(168509)
m, n = 4, 4
vals = []
for i in range(m):
    for j in range(n):
        if i in (1, 2) and j in (1, 2):
            vals.append(_r.randint(90000, 99999))  # 中心 4 格极大
        else:
            vals.append(_r.randint(0, 100))        # 边缘极小
gen(9, m, n, vals)

# ---------- 点10：顶格层（m*n=16 全 99999 极端构造） ----------
# 意图：4x4 全 99999：期望答案 = 99999*Σ_{i=1..16} i = 13599864（最大可能答案），
# 状态转移最密集（每个状态边缘格都可“离开重进”），检验最坏时间与答案上限。
m, n = 4, 4
vals = [99999] * (m * n)
gen(10, m, n, vals)
