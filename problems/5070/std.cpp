// 一本通 2069《【例2.12】糖果游戏》（目标 ROJ 题号 5070）标程
//
// 题意：5 个小朋友 1~5 号围坐圆桌（环形相邻：1 的邻居是 2、5）。
//   从 1 号开始依次轮到 5 号，轮到某人时：把手中糖果均分三份（不能整除时
//   多余的糖果当场吃掉，即只保留 floor(c/3) 的倍数），自己留一份，
//   另外两份分别给左右两个相邻的小朋友。问一轮（1→5 各操作一次）后
//   每人手上的糖果数，按 5 位宽度输出。
//
// 参考来源（网络 C++ 题解，已联网取回原文、本机编译并按题面样例验证后改写，
// 非盲抄）：
//   1. https://blog.csdn.net/lq1990717/article/details/120002033
//      《信息学奥赛一本通 2069：【例2.12】糖果游戏》
//      原文代码：int a,b,c,d,e; cin>>a>>b>>c>>d>>e;
//                a/=3; b+=a; e+=a;  b/=3; a+=b; c+=b;  ... e/=3; d+=e; a+=e;
//                cout<<setw(5)<<a<<setw(5)<<b<<...;
//   2. https://blog.csdn.net/tflstjs/article/details/119838213
//      《一本通2069：【例2.12 】糖果游戏》
//      原文代码与来源 1 等价（a=a/3;b=b+a;e=e+a; ... 逐行展开，setw(5) 输出）。
//   3. 官方题面（核对输入输出格式与 1000 ms / 65536 KB 限制，题面未声明取值范围）：
//      http://ybt.ssoier.cn:8088/problem_show.php?pid=2069
//
// 说明：两个来源的思路完全一致 —— 用五个变量按“1 号先分、再 2~5 号”的顺序
// 显式模拟，因为每个小朋友分糖果时只用到当前（已被前面操作更新过的）手上数量，
// 所以顺序写下来的赋值即为唯一正确语义。以题面样例核对：8 9 10 11 12 ->
// 11 7 9 11 6（与【输出样例】一致）。
//
// 本题为顺序结构入门题，规模固定为 5 个输入、操作 5 次，复杂度 O(1)。
// 题面/官方 OJ 页均未声明糖果数的取值范围；本标程用 long long 读入计算以
// 兼容 int 及以上范围，避免任何溢出；数据侧自定工作范围 0 <= a_i <= 10000
// （见 data.py 注释），此时按“每人分三份”的口径，总糖果数单调不增，
// 最终任一人的糖果数 <= 5*10000 = 50000，仍是 5 位以内，5 位宽度输出始终成立。
#include <cstdio>

int main() {
    long long a, b, c, d, e;
    if (scanf("%lld %lld %lld %lld %lld", &a, &b, &c, &d, &e) != 5) return 0;

    // 1 号：自己留一份，另两份给 2 号、5 号（圆桌相邻）
    a /= 3; b += a; e += a;
    // 2 号：给 1 号、3 号
    b /= 3; a += b; c += b;
    // 3 号：给 2 号、4 号
    c /= 3; b += c; d += c;
    // 4 号：给 3 号、5 号
    d /= 3; c += d; e += d;
    // 5 号：给 4 号、1 号
    e /= 3; d += e; a += e;

    // 按题面要求：5 位宽度、右对齐输出，五个数之间无额外分隔（与样例一致）
    printf("%5lld%5lld%5lld%5lld%5lld\n", a, b, c, d, e);
    return 0;
}
