#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2069《【例2.12】糖果游戏》数据生成器（cyaron，目标 ROJ 题号 5070）
#
# 题意：5 个小朋友 1~5 号围圆桌（环形相邻：1 的邻居是 2 与 5）。从 1 号起依次
#       轮到 5 号，轮到某人时把手中糖果均分三份（不能整除时多余的糖果当场吃掉，
#       即每人得 floor(c/3) 颗），自己留一份、另两份分别给左右相邻的小朋友。
#       输出一轮后 5 人的糖果数，按 5 位宽度右对齐输出。
# 输入：一行 5 个整数（5 个小朋友的初始糖果数）。单组输入（一个测试点即 5 个数）。
#
# 数据范围（题面未声明，本生成器自定并如实记录）：
#   题面只说到「身上都有若干个糖果(键盘输入)」，未声明取值范围；官方 OJ 页
#   （http://ybt.ssoier.cn:8088/problem_show.php?pid=2069）同样未声明，
#   题面无特殊值声明、无多组数据。按题面「按 5 位宽度输出」这一硬性格式要求，
#   本生成器自定工作范围：
#       0 <= a_i <= 10000   (i = 1..5；0 表示这个小朋友一开始没有糖果)
#   上界的依据：糖果只会被吃掉、不会凭空产生，故任一人手上的数量始终不超过
#   初始总和 5 × 10000 = 50000 < 10^5，这样「5 位宽度」输出对任何合法输入都不越界
#   （若把上界提到 10^5，总和可达 5×10^5，可能出现需 6 位才装得下的值，与题面
#   输出格式矛盾）。下界取 0：题面「若干个糖果」未明确禁止 0，且 std 对 0 输入
#   天然正确（0/3 = 0，分给邻居 0）。
#
# 分层设计（10 个测试点；单组输入，故按数值量级与极端结构从最小铺到顶格）：
#   点 1-2  边界层：全最小值（0×5，答案全 0）/ 全最大值（10000×5，全相等重复值）
#   点 3-4  小规模：题面【输入样例】（题面声明的特殊值，可与输出样例逐字符核对）
#           + 最小量级手算例 1 1 1 1 3（答案含 0 与 1 的极端 + 余数吃糖）
#   点 5-6  中等规模随机：范围中间档 a_i∈[1e2,1e3] / [1e3,5e3]
#   点 7-8  大规模随机：接近上限 a_i∈[5e3,9999] / [5e3,1e4]
#   点 9-10 顶格层：以自定上限 10000 构造最坏/极端结构 —— 极端不均衡（糖全在
#           1 号）与交替极端（奇数号顶格、偶数号为 0），覆盖环上各种邻居关系
# 说明：点 5~8 为独立随机，天然可能出现相等值（重复值结构）。

from cyaron import *  # 引入CYaRon的库

import random
random.seed(2069)  # 固定种子，便于复现

MAXC = 10000  # 自定工作范围上限（题面未声明，依据见上）


def gen(i, vals, note):
    """写出第 i 组：一行 5 个整数（input_writeln 结尾带换行）；输出由 std 生成。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(*vals)
    io.output_gen("../std")
    print("problem%d: %s -- %s" % (i, " ".join(map(str, vals)), note))


def rnd(lo, hi):
    """5 个独立随机的整数（含相等，天然覆盖重复值结构）。"""
    return [randint(lo, hi) for _ in range(5)]


# ---- 点 1-2：边界层 ----
# 点 1：全最小值 a_i = 0（自定下限）：五人都没有糖果，一轮后仍全为 0 ——
#       「答案为 0」的极端；同时是「0 分三份仍是 0、分给邻居 0」的退化结构。
gen(1, [0, 0, 0, 0, 0],
    "边界层：全最小值 0 0 0 0 0（自定下限），答案 0 0 0 0 0（答案为 0 的极端）")

# 点 2：全最大值 a_i = 10000（自定上限顶格）+ 全相等重复值结构。
gen(2, [MAXC] * 5,
    "边界层：全最大值（自定上限）10000×5，全相等；答案 13867 9258 9752 11028 6090")

# ---- 点 3-4：小规模（可手算验证） ----
# 点 3：题面【输入样例】8 9 10 11 12（题面声明的特殊值）；期望输出与题面
#       【输出样例】`   11    7    9   11    6` 逐字符一致。
gen(3, [8, 9, 10, 11, 12],
    "小规模：题面输入样例 8 9 10 11 12，期望 11 7 9 11 6（与题面输出样例一致）")

# 点 4：1 1 1 1 3 —— 最小正档手算例：1、2、3、4 号各只有 1 颗（不足 3 颗
#       当场吃掉，分给邻居 0 颗），5 号 3 颗自留 1 颗、给 4 号与 1 号各 1 颗；
#       答案 1 0 0 1 1 同时含「答案为 0」与「答案为 1」两个极端，且是
#       「余数被吃掉」在最小规模下体现得最清楚的结构（5 人次操作共吃掉 4 颗）。
gen(4, [1, 1, 1, 1, 3],
    "小规模：1 1 1 1 3（最小余数吃糖结构，可手算），答案 1 0 0 1 1（答案含 0/1 极端）")

# ---- 点 5-6：中等规模随机（范围中间档） ----
# 点 5：a_i ∈ [100, 1000]
gen(5, rnd(100, 1000),
    "中等规模随机：a_i ∈ [1e2,1e3]，范围中间偏下档")

# 点 6：a_i ∈ [1000, 5000]
gen(6, rnd(1000, 5000),
    "中等规模随机：a_i ∈ [1e3,5e3]，范围中间档")

# ---- 点 7-8：大规模随机（接近上限） ----
# 点 7：a_i ∈ [5000, 9999]
gen(7, rnd(5000, 9999),
    "大规模随机：a_i ∈ [5e3,9999]，接近上限")

# 点 8：a_i ∈ [5000, 10000]，贴近上限；各值独立随机，余数分布随机
gen(8, rnd(5000, MAXC),
    "大规模随机：a_i ∈ [5e3,1e4]，贴近上限，余数分布随机")

# ---- 点 9-10：顶格层（上限 10000 + 最坏/极端结构） ----
# 点 9：极端不均衡构造 —— 全部糖果集中在 1 号（10000），其余四人为 0；
#       1 号一轮内先后被 2 号、5 号分回的糖改变，是最不均衡的权值分布。
gen(9, [MAXC, 0, 0, 0, 0],
    "顶格层：1 号独大 10000 0 0 0 0（极端不均衡 + 大量 0 值），"
    "答案 5596 1481 493 1275 1152")

# 点 10：交替极端构造 —— 奇数号顶格 10000、偶数号为 0；奇数号彼此不相邻且各
#        有两个「空」邻居，配合 1→5 的顺序把环上各类邻居关系都走一遍。
gen(10, [MAXC, 0, MAXC, 0, MAXC],
    "顶格层：交替极端 10000 0 10000 0 10000（奇数号顶格/偶数号为空），"
    "答案 9299 4814 4937 6089 4855")

print("done: 10 test cases (problem1..problem10)")
