# -*- coding: utf-8 -*-
# 一本通 2072《【例2.15】歌手大奖赛》—— 测试数据生成器（cyaron，仓库惯例）
# 目标 ROJ 题号 5073；用法（在 .ybt-import/staging/2072/ 下）：
#     g++ -O2 -std=c++17 std.cpp -o std
#     mkdir -p data && cd data && python3 ../data.py
# 参考同款：problems/5006/data.py（无输入题只出 1 组）、.ybt-import/staging/2060|2061|2063。
#
# ---------------------------------------------------------------------------
# 题意：6 名评委给一位参赛者打分，6 人平均分 9.6 分；去掉一个最高分后平均分 9.4 分；
#       去掉一个最低分后平均分 9.8 分；问去掉一个最高分和一个最低分后的平均分。
#   推导：总分 T = 6*9.6 = 57.6；最高分 H = T - 5*9.4 = 10.6；最低分 L = T - 5*9.8 = 8.6；
#         答案 = (T - H - L) / 4 = 38.4 / 4 = 9.6，按 %5.2f 输出 => " 9.60"（含 1 个前导空格）。
#
# 输入输出与范围（题面 content.md / config.json / 官方页 pid=2072 一致）：
#   【输入】：（无）—— 本题**没有任何输入量**，因此不存在「每个输入量的取值范围」，
#             也不存在数据组数（无多组数据概念）。
#   【输出】：使用 %5.2f 按实数格式输出，保留 2 位小数 —— 输出为确定值 " 9.60"。
#   【输入样例】/【输出样例】均为（无）。
#   config.json：time 1000 ms / memory 64 MB（官方页 1000 ms / 65536 KB，一致）。
#
# ---------------------------------------------------------------------------
# 为什么只生成 1 组（而不是 10 组）：
#   任务书原文：「**无输入的题目**（输出恒定）按语料惯例只生成 **1 组** problem1.in/.out
#   （参考 problems/5006/data.py），不要生成重复的空测试点。」
#   本题正是"无输入、输出恒定"：输出恒为 " 9.60"，任意测试点内容完全相同，
#   生成 10 组只会得到 10 份字节一致的重复数据，没有区分度也无法覆盖任何边界。
#   本仓先例一致：problems/5006（Hello World）、staging/2060/2061/2063 均只出 1 组。
#   官方旁证（本轮实测抓取）：官方 OJ status 页
#   http://ybt.ssoier.cn:8088/status.php?showpid=2072&showres=Accepted
#   的每条 Accepted 记录都是 `Accepted|10:AC|...`，AC 明细只有 1 条（总分 10 分、
#   单个测试点），即**官方数据本身也只有 1 个测试点**；对照同站 10 测试点的题
#   （如 pid=4185，记录为 `Accepted|100:AC|...` 且带 10 条 AC 明细）可确认该解析口径。
#
# 分层说明（"为什么 10 组分层在这里不适用"）：
#   「边界层（n=1/n=2/全最小/全最大/答案为 0 或 1 的极端）/小规模随机/中等规模随机/
#     大规模随机/顶格层」这一整套分层的前提是"存在某个可铺开的输入量"。本题输入为（无），
#   没有任何可铺开的量（无 n、无数组、无权值），所以各层在本题上不适用/退化为同一个点。
#   唯一测试点覆盖的"等价边界"清单（由 work/stress.py 逐条断言，见 gen-report.md）：
#     * 题面声明的特殊值：题面未给出特殊值；题面给出的 9.6/9.4/9.8 是唯一参数组，
#       即数据只有这一种情形（"题面上限=题面下限"的退化顶格）；
#     * 答案为 0 的极端：不适用（题面参数固定，答案恒为 9.6）；
#     * 全最小/全最大值：不适用（无输入）；
#     * 顶格：已顶格 —— 数据不可能比"题面唯一情形"更大。
#
# 参考实现：problems/5006/data.py（无输入题的定式写法）。

from cyaron import *  # 引入CYaRon的库

# 本题无输入，输出恒为固定值 " 9.60"（%5.2f 格式），所有测试点内容完全相同，
# 因此按题目实际情况只生成 1 组数据，避免重复的空测试点。
io = IO(file_prefix="problem", data_id=1)  # problem1.in / problem1.out
# 无输入：problem1.in 保持为空文件（0 字节，与 problems/5006/problem1.in 一致）
io.input_write()
io.output_gen("../std")
