// 题意：6 名评委给一位参赛者打分：
//         6 人平均分 9.6 分；去掉一个最高分后 5 人平均分 9.4 分；
//         去掉一个最低分后 5 人平均分 9.8 分；
//       问去掉一个最高分和一个最低分后，剩下 4 人的平均分是多少。
//       输入：无；输出：按 %5.2f 格式输出（保留 2 位小数）。
//
// 推导（来源 1 给的"分步计算"思路，全部来源结论一致）：
//   总分        T = 6 * 9.6 = 57.6
//   最高分      H = T - 5 * 9.4 = 57.6 - 47.0 = 10.6
//   最低分      L = T - 5 * 9.8 = 57.6 - 49.0 =  8.6
//   去掉一高一低后 4 人的总分 = T - H - L = 38.4
//   答案 = 38.4 / 4 = 9.6  ->  按 %5.2f 输出为 " 9.60"
//   （"9.60" 占 4 个字符，场宽 5 需左侧补 1 个空格 —— 题面要求的就是这个前导空格）
//
// 参考来源 URL（本轮逐篇实际抓取原文核对，只借鉴思路/结论，代码为本包自写，非盲抄）：
