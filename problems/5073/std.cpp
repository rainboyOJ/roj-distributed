//      （考点：算术应用题 + 限定场宽输出，setw(5) 与 %5.2f 等价）
//   2. https://blog.csdn.net/qq214936qq/article/details/136426673
//      《信息学奥赛一本通 2072：【例2.15】歌手大奖赛》
//      double s1=9.6*6, s2=9.4*5, s3=9.8*5; max=s1-s2; min=s1-s3;
