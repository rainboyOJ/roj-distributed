//   3. https://blog.csdn.net/qq_36455276/article/details/128747960
//      《一本通-2072：歌手大奖赛》—— 与来源 2 同式的分步写法（s1/s2/s3/max/min）。
//   4. https://blog.csdn.net/lvcheng0309/article/details/118051338
//      《信息学奥赛一本通（2072：【例2.15】歌手大奖赛）》
//      double sc_all=6*9.6, sc_high=5*9.4, sc_low=5*9.8;
//      high=sc_all-sc_high; low=sc_all-sc_low; ans=(sc_all-high-low)/4;
//      printf("%5.2lf\n", ans);   // 带换行
//   5. https://blog.csdn.net/tflstjs/article/details/119851782
