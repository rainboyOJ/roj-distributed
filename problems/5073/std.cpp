//
//   来源结论冲突核查：10 个来源的数学结论完全一致（答案 9.6），且都要求前导空格；
//   仅"是否在末尾加换行"有差异：来源 1/2/6/8/9/10 无换行，来源 4/5 带 "\n"，
//   来源 7 硬编码无换行。本包按仓库语料惯例输出一行 + 行末换行（与 2061/2063/2069 一致；
//   本仓判题以 `diff -b` 比对，行末换行差异不影响判定）。
//
// 浮点安全（对照 staging/2066 的 -0.00 教训逐条核查）：
//   (1) 折点风险：本题答案 9.6，离 0 很远，**不存在 -0.00 / +0.00 折点**问题
//       （2066 的坑源于答案数学上恰为 0，且被编译器 FMA 收缩成 -4.4e-15）。
//   (2) 舍入风险：double 计算得 9.6000000000000014211（与 9.6 偏差 1.4e-15），
//       而 printf("%5.2f") 的判定容差是 0.005 —— 偏差比容差小 12 个数量级，
//       任何正常实现都必然打印 "9.60"；即使被收缩成 FMA 也只是 1e-15 量级扰动。
//       （实测 5 种等价写法 × {-O0,-O2,-O3,-Ofast} × Apple clang / Homebrew g++-16
//         共 40 个二进制，输出全部逐字节为 " 9.60\n"。）
//   (3) 因此本标程**不做**任何 round/归零改写：答案 9.6 不是 0.1 的"可疑折点"，
//       多余归一化反而会在"答案非 0.1 整数倍"的泛化情形引入错误（见 work/formula.cpp 注释）；
//       这里直接按全部 10 个来源的写法 printf 输出，语义最忠实。
//   (4) 取证补充（work/stress.py 的 D 部分）：把本文件同构的浮点算法（work/formula.cpp）
//       拿来跑 40 组"答案恰为 0"的可行参数，确实会复现 2066 同类的 `-0.00`（与优化等级相关：
//       clang -O0/-O2/-O3 与 Homebrew GCC 16 都复现，clang -Ofast 不复现）。
//       这证明该风险类别真实存在、本包的验证确实有判别力；但 **2072 用不上它**：
//       本题无输入、答案恒为 9.6，std 永远不会落在该折点（已用 6 组极端/退化 stdin 断言
//       std 0 次输出 -0.00）。若日后把本文件的模式搬到"答案可能为 0"的题上，
//       必须像 2066 那样另行处理该折点（如 `if (fabs(ans) < 1e-6) ans = 0;`）。
//   运行 0.00 s、常驻内存 ~1.3 MB，远低于 1000 ms / 64 MB 限制。
// ---------------------------------------------------------------------------
#include <cstdio>

int main() {
    // 6 名评委的总分
    double total = 6 * 9.6;                  // 57.6
    // 去掉一个最高分后剩 5 人，其总分 5 * 9.4，故最高分 = 总分 - 5 * 9.4
    double high = total - 5 * 9.4;           // 10.6
    // 去掉一个最低分后剩 5 人，其总分 5 * 9.8，故最低分 = 总分 - 5 * 9.8
    double low = total - 5 * 9.8;            // 8.6
    // 去掉一个最高分和一个最低分后，剩下 4 人的平均分
    double ans = (total - high - low) / 4;   // 38.4 / 4 = 9.6

    // 题面要求：使用 %5.2f 按实数格式输出，保留 2 位小数。
    // 9.60 占 4 个字符，场宽 5 => 左侧补 1 个空格，输出 " 9.60"（+ 行末换行）。
    printf("%5.2f\n", ans);
    return 0;
}
