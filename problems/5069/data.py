#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2068《【例2.6】鸡兔同笼》数据生成器
#
# 题面输入：一行两个整数 x(头数) y(脚数)；输出：鸡 兔（空格隔开）。
# 题面【未声明数据范围】，按 int32 安全自定工作范围并保证有唯一解：
#     1 <= x <= 10^6,  2x <= y <= 4x,  y 为偶数
# 本题为单组输入（一个测试点即一对 (x, y)），故不存在多组数据的"组数分层"，
# 分层按 x 的量级与 (鸡,兔) 极端权值铺开：
#   点 1-2  边界层（全最小值 / 答案 0、1 极端）
#   点 3-4  小规模随机（可手算验证）
#   点 5-6  中等规模随机（范围中间档）
#   点 7-8  大规模随机（接近上限）
#   点 9-10 顶格层（取自定上限 x=10^6，极端权值构造：全鸡 / 全兔）

from cyaron import *  # 引入CYaRon的库

XMAX = 1000000  # 自定工作范围上限（题面未声明）

import random
random.seed(2068)  # 固定种子，便于复现


def gen_case(i, x, r, note):
    """写出第 i 组：x 个头、r 只兔、(x-r) 只鸡；y = 2*(x-r) + 4*r。"""
    y = 2 * (x - r) + 4 * r
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(x, y)
    io.output_gen("../std")
    print("problem%d: x=%d y=%d (鸡=%d 兔=%d) -- %s" % (i, x, y, x - r, r, note))


# ---- 点 1-2：边界层 ----
# 点 1：全最小值（x=1 最小头数、y=2 最小合法脚数），答案 1 0（答案含 0 极端）
gen_case(1, 1, 0, "边界层：全最小值 x=1,y=2，全鸡，答案 1 0（答案为 0 的极端）")

# 点 2：x=1 全兔（y=4），答案 0 1（答案同时含 0 与 1 两个极端；题面无特殊值可声明）
gen_case(2, 1, 1, "边界层：x=1,y=4，全兔，答案 0 1（答案为 0/1 的极端）")

# ---- 点 3-4：小规模随机（量级小，可手工验证） ----
# 点 3：x ∈ [2, 30]，兔数随机
i = 3
x = randint(2, 30)
gen_case(i, x, randint(0, x), "小规模随机：x∈[2,30]，兔数随机，可手算核对")

# 点 4：x ∈ [2, 200]，兔数随机
x = randint(2, 200)
gen_case(4, x, randint(0, x), "小规模随机：x∈[2,200]，兔数随机，可手算核对")

# ---- 点 5-6：中等规模随机（范围中间档） ----
# 点 5：x ∈ [1000, 10000]
x = randint(1000, 10000)
gen_case(5, x, randint(0, x), "中等规模随机：x∈[1e3,1e4]，兔数随机")

# 点 6：x ∈ [10000, 100000]
x = randint(10000, 100000)
gen_case(6, x, randint(0, x), "中等规模随机：x∈[1e4,1e5]，兔数随机")

# ---- 点 7-8：大规模随机（接近上限） ----
# 点 7：x ∈ [100000, 500000]
x = randint(100000, 500000)
gen_case(7, x, randint(0, x), "大规模随机：x∈[1e5,5e5]，兔数随机")

# 点 8：x ∈ [500000, 10^6]，贴近上限
x = randint(500000, XMAX)
gen_case(8, x, randint(0, x), "大规模随机：x∈[5e5,1e6]，兔数随机，接近上限")

# ---- 点 9-10：顶格层（取上限 x=10^6，极端权值 / 重复构造） ----
# 点 9：顶格 + 极端权值：y=2x（合法最小脚数），全鸡，答案 10^6 0
gen_case(9, XMAX, 0, "顶格层：x=1e6,y=2x 全鸡（极端权值：脚数取合法最小），答案 1000000 0")

# 点 10：顶格 + 极端权值：y=4x（合法最大脚数），全兔，答案 0 10^6
gen_case(10, XMAX, XMAX, "顶格层：x=1e6,y=4x 全兔（极端权值：脚数取合法最大），答案 0 1000000")
