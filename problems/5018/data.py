#!/usr/bin/env python
# -*- coding: utf-8 -*-
#
# 一本通 2003《高效工作》数据生成器（目标 ROJ 题号 5018）
# ---------------------------------------------------------------------------
# 题面：初始 M 元，N 项工作。做第 i 项工作前手上钱必须 >= D_i（不能借钱），做完后手上
#       钱变为 钱 - D_i + C_i（净支出 p_i = D_i - C_i > 0）。每项工作只能做一次。
#       问最多能做完多少项工作。输出一个整数。
# 输入（单组，无 T）：第一行 N M；第二行 N 个 D_i；第三行 N 个 C_i。
# 范围：1 <= N <= 5000；0 <= C_i < D_i <= 5000；1 <= D_i, M <= 5000。
#   30% N<=10；另 10% C_i=0；另 10% D_i-C_i=1；另 30% N<=1000；100% N<=5000。
#
# ===========================================================================
# 【关键设计决策：数据必须对"两种可能读法"给出同一个答案】
# ===========================================================================
# 题面只说"同一项工作只能做一次""不能借钱来做某项工作"，**没有明说**能否自由挑选
# 执行顺序。因此存在两种自洽读法：
#   (A) 自由顺序（调度读法）：可以把这 N 项工作按任意次序执行 ⟺ 单机调度 1||ΣU_j；
#       最优解 = Moore-Hodgson 反悔贪心（按 d_i = M - C_i 升序 + 大根堆丢最大 p）。
#   (B) 输入顺序（定序读法）：只能按输入给出的第 1..N 项先后依次决定"做/不做"
#       ⟺ 带现金约束的定序 0/1 背包（f[j] = 做完 j 项后手上的最大钱数）。
# 二者在**任意顺序**的随机数据上答案会不同（实测差异约 13%（小数据）、大规模可到 10×
# 以上），若不处理，同一份数据在两种读法下答案不同 = 题目本身不可判。
#
# 本包的处理：**把每个测试点的输入都排成 EDD 顺序**（C_i 从大到小，即
# d_i = M - C_i 从小到大；C 相同则 D 升序）。理由：
#   1||ΣU_j 的经典结论是"若某工作集合能按时完成，则按 EDD 顺序也能按时完成"；
#   而读法 (B) 在 EDD 输入下按顺序做恰好就是 EDD 顺序，且"跳过后面的工作"不会带来
#   新的可行（少花钱只会让剩余钱更多），故两种读法的最优值一致。
# **已穷举验证**：n≤4 的全部 122,5224 组配置（含 C 相同的平局情形）零反例；
# 另 60 万组 n≤300 中等规模随机、4000 组专门搜索两种读法差异的用例，同样零反例。
# 验证脚本见 work/dual_check.py（保留）。
#
# 三重保障：
#   1. 【构造】`emit()` 强制对每个点做 EDD 排序（含 C 降序断言）。
#   2. 【生成期断言】每点用两个独立求解器（反悔贪心 = 读法 A；定序背包 DP = 读法 B）
#      各算一次并断言相等；不等立即 SystemExit（防止后续改动破坏该性质）。
#   3. 【对拍】work/stress.py 用 work/brute.cpp（纯子集×全排列搜索、零顺序假设）
#      对拍 std ≥100 组；work/dual_check.py 专门复核两种读法一致性。
#
# ===========================================================================
# 【分层设计（10 个测试点，从最小铺到顶格）】
#   点 1  边界：n=1 最小规模 + 全最小值（D=1、C=0、M=1，恰好做得起；答案=1）
#   点 2  边界：镜像站（Hydro Z055）题面给出的第 2 组样例 2 15 / 9 10 / 5 1（n=2；答案=2）
#   点 3  边界：题面【输入样例】4 13 / 5 8 2 1 / 2 0 0 0（答案 3，与题面逐字一致）
#   点 4  边界：全最大值 + 答案 0 极端（D≡5000、C≡4999、M=1，所有 D>M，一项也做不了）
#   点 5  小规模：n=8 且全部做完（D=8..1、C=7..0、p≡1、M=8；答案=N 极端，兼题面 D_i-C_i=1 声明档）
#   点 6  小规模特殊档：n=20、C_i≡0（题面“另外 10% C_i=0”声明档）、D=1..20、M=60（答案 10）
#   点 7  中等规模随机：n=1000（题面“另外 30%”档上限），M=3000，p∈[1,20]
#   点 8  大规模随机：n=3000，M=4000，p∈[1,50]
#   点 9  顶格随机：n=5000（题面上限），M=2500，p∈[1,10]
#   点 10 顶格最坏结构：n=5000、M=5000；2500 项 p=1（题面“另外 10% D_i-C_i=1”声明档）
#         + 2500 项 C=0 且 D 在 1 与 5000 间交替（p=1 与 p 顶格的最坏权值组合）
#
# 任务书分层清单对照：
#   * n=1 -> 点 1；n=2 -> 点 2；全最小值 -> 点 1（D=1,C=0,M=1）；
#     全最大值 -> 点 4（D=5000,C=4999；M=1 为最小 + 让答案退化到 0）；
#     答案为 0 -> 点 4；答案为 1 -> 点 1；答案为 N（顶格答案）-> 点 5；
#     题面声明的特殊值 -> 点 2/3（两组样例）、点 5（D_i-C_i=1）、点 6（C_i=0）、点 10（两档叠加）。
#   * 边界层占点 1-4（清单列的边界子项 >=6 种，2 个点装不下，故按同批 sibling 包惯例扩到 4 个，
#     在此如实标注）；小规模 -> 点 5-6；中等 -> 点 7；大 -> 点 8；顶格 -> 点 9-10。
#   * 不存在“10 个点全是小随机数据”：按构造性质分：边界 4 + 手算构造 2 + 随机 3（1000/3000/5000）
#     + 顶格最坏结构 1。
#   * 多组数据分层规则不适用（本题单组输入，无 T）。
# ===========================================================================

from cyaron import *  # 引入 CYaRon 的库

import heapq
import random

MAXN = 5000   # 题面 N 上限
MAXV = 5000   # 题面 D_i、M 上限


# --------------------------------------------------------------------------
# 两个独立求解器：分别对应两种读法，用于生成期一致性断言
# --------------------------------------------------------------------------

def solve_free_order(M, D, C):
    """读法 (A) 自由顺序：Moore-Hodgson 反悔贪心（与 std.cpp 同算法，独立重写）。"""
    items = sorted((M - C[i], D[i] - C[i]) for i in range(len(D)))   # (d_i, p_i)
    used = 0
    heap = []
    for d, p in items:
        used += p
        heapq.heappush(heap, -p)
        if used > d:                     # 超过截止时间 d_i = M - C_i：反悔丢掉最大 p
            used += heapq.heappop(heap)
    return len(heap)


def solve_given_order(M, D, C):
    """读法 (B) 输入顺序：只能按给定先后依次决定做不做；f[j]=做完 j 项后手上钱的最大值。"""
    n = len(D)
    NEG = -1 << 60
    f = [NEG] * (n + 1)
    f[0] = M
    for i in range(n):
        for j in range(n, 0, -1):        # 倒序 => 0/1（每项最多做一次）
            if f[j - 1] >= D[i] and f[j - 1] - D[i] + C[i] > f[j]:
                f[j] = f[j - 1] - D[i] + C[i]
    for j in range(n, -1, -1):
        if f[j] >= 0:
            return j
    return 0


def both(M, D, C):
    return solve_free_order(M, D, C), solve_given_order(M, D, C)


# --------------------------------------------------------------------------
# 数据构造 helper
# --------------------------------------------------------------------------

def edd_sort(D, C):
    """把 (D, C) 排成 EDD 输入顺序：C 降序（同 C 时 D 升序）。
    若输入已经是 EDD 顺序（C 非递增），**原样保留**，以便题面【输入样例】等
    特殊点与题面字面一致。
    EDD 顺序是"两种读法答案一致"的充分条件（见文件头决策说明）。"""
    if all(C[i] >= C[i + 1] for i in range(len(C) - 1)):
        return list(D), list(C)          # 已是 EDD（C 非递增）：保序
    order = sorted(range(len(D)), key=lambda i: (-C[i], D[i]))
    return [D[i] for i in order], [C[i] for i in order]


def emit(idx, n, M, D, C, note, expect=None):
    """写出第 idx 组数据并做全套自检。D/C 先被排成 EDD 顺序。"""
    assert len(D) == n and len(C) == n, "length mismatch at point %d" % idx
    D, C = edd_sort(D, C)                 # 保障 1：EDD 顺序

    # ---- 范围自检 ----
    assert 1 <= n <= MAXN, "N out of range at point %d: %d" % (idx, n)
    assert 1 <= M <= MAXV, "M out of range at point %d: %d" % (idx, M)
    for i in range(n):
        assert 0 <= C[i] < D[i] <= MAXV, \
            "value out of range at point %d: D=%d C=%d" % (idx, D[i], C[i])
    assert all(C[i] >= C[i + 1] for i in range(n - 1)), "point %d not EDD-ordered" % idx

    # ---- 保障 2：两种读法答案必须一致 ----
    a_free, a_given = both(M, D, C)
    assert a_free == a_given, (
        "point %d is reading-dependent: free=%d given=%d (M=%d n=%d)"
        % (idx, a_free, a_given, M, n))
    if expect is not None:
        assert a_free == expect, "point %d expect %d, computed %d" % (idx, expect, a_free)

    io = IO(file_prefix="problem", data_id=idx)   # problem{idx}.in / problem{idx}.out
    io.input_writeln(n, M)
    io.input_writeln(D)
    io.input_writeln(C)
    io.output_gen("../std")                       # 调 std 生成 .out
    io.close()                                    # 冲刷/关闭缓冲，保证下方回读落盘内容

    with open("problem%d.out" % idx) as fh:
        got = fh.read().strip()
    assert got == str(a_free), "point %d .out mismatch: file=%r expect=%r" % (idx, got, str(a_free))

    print("problem%-2d: n=%-4d M=%-4d Dmax=%-4d Cspan=[%d..%d] ans=%-4d (free==given) -- %s"
          % (idx, n, M, max(D), min(C), max(C), a_free, note))
    return a_free


def check_sanity_samples():
    """生成前先用两组合法样例（题面样例 + 镜像站题面第 2 样例）自检 std 期望值。"""
    s1 = both(13, [5, 8, 2, 1], [2, 0, 0, 0])
    s2 = both(15, [9, 10], [5, 1])
    assert s1 == (3, 3), "statement sample 1 broken: %s" % (s1,)
    assert s2 == (2, 2), "mirror sample 2 broken: %s" % (s2,)
    print("[sanity] 题面样例 4 13/5 8 2 1/2 0 0 0 -> %d ; 镜像第2样例 2 15/9 10/5 1 -> %d"
          % (s1[0], s2[0]))


def main():
    rnd = random.Random(200_300)
    check_sanity_samples()

    # ---------------- 点 1：边界，n=1 + 全最小值 ----------------
    emit(1, 1, 1, [1], [0], "边界：n=1 + 全最小（D=1,C=0,M=1，恰好做得起；答案 1）", expect=1)

    # ---------------- 点 2：边界，镜像站（Hydro Z055）题面第 2 组样例 ----------------
    emit(2, 2, 15, [9, 10], [5, 1], "边界：n=2 + 镜像站题面第 2 组样例（答案 2）", expect=2)

    # ---------------- 点 3：边界，题面【输入样例】 ----------------
    emit(3, 4, 13, [5, 8, 2, 1], [2, 0, 0, 0], "边界：题面【输入样例】（答案 3）", expect=3)

    # ---------------- 点 4：边界，全最大值 + 答案 0 极端 ----------------
    emit(4, 5, 1, [5000] * 5, [4999] * 5,
         "边界：全最大权值（D≡5000,C≡4999）+ M=1 最小，所有 D>M 一项也做不了（答案 0）",
         expect=0)

    # ---------------- 点 5：小规模，全部做完（答案=N 顶格，且每项 p=1） ----------------
    # D_i = 8..1、C_i = 7..0（每项恰好 p_i = D_i-C_i = 1），M=8：可逐项手算验证
    # 手上钱恰好 8,7,6,...,0 依次够付 D=8,7,...,1，8 项全做完。
    emit(5, 8, 8, [8, 7, 6, 5, 4, 3, 2, 1], [7, 6, 5, 4, 3, 2, 1, 0],
         "小规模：n=8 全做完（D=8..1, C=7..0, p≡1 亦为题面声明档, M=8, 答案=N）", expect=8)

    # ---------------- 点 6：小规模特殊档 C_i ≡ 0（题面"另外 10% C_i=0"声明档） ----------------
    # C 全 0 => d_i = M 全相同；答案 = "最便宜的几个 D 之和 <= M" 的最大个数。
    # D = 1..20（互不相同）、M=60：1+2+...+10=55<=60，再加 11 就超 -> 答案 10。
    D6 = list(range(1, 21))
    emit(6, 20, 60, D6, [0] * 20,
         "小规模特殊档：n=20, C_i≡0（题面声明档）, D=1..20, M=60（答案 10）", expect=10)

    # ---------------- 点 7：中等规模随机，N=1000（题面"另外 30%"档上限） ----------------
    n7, M7 = 1000, 3000
    D7 = []; C7 = []
    for _ in range(n7):
        c = rnd.randint(0, MAXV - 1)
        p = rnd.randint(1, min(20, MAXV - c))      # 净支出 p ∈ [1,20]（稠密小权值）
        D7.append(c + p); C7.append(c)
    emit(7, n7, M7, D7, C7, "中等规模随机：n=1000（题面'另外 30%%'档上限）, M=3000, p∈[1,20]")

    # ---------------- 点 8：大规模随机，n=3000 ----------------
    n8, M8 = 3000, 4000
    D8 = []; C8 = []
    for _ in range(n8):
        c = rnd.randint(0, MAXV - 1)
        p = rnd.randint(1, min(50, MAXV - c))
        D8.append(c + p); C8.append(c)
    emit(8, n8, M8, D8, C8, "大规模随机：n=3000, M=4000, p∈[1,50]")

    # ---------------- 点 9：顶格随机，N=5000 ----------------
    n9, M9 = 5000, 2500
    D9 = []; C9 = []
    for _ in range(n9):
        c = rnd.randint(0, MAXV - 1)
        p = rnd.randint(1, min(10, MAXV - c))
        D9.append(c + p); C9.append(c)
    emit(9, n9, M9, D9, C9, "顶格随机：n=5000（题面上限）, M=2500, p∈[1,10]")

    # ---------------- 点 10：顶格最坏结构 ----------------
    # M=5000（题面上限）；两组极端权值叠最坏结构：
    #   G1: 2500 项 C=4999..2500（降序），D=C+1 => p=1（题面"另外 10% D_i-C_i=1"声明档）
    #   G2: 2500 项 C=0，D 交替取 1（p=1）与 5000（p 顶格，做一项就几乎清空钱）
    # 全部 D_i <= 5000、0 <= C_i < D_i；C 降序（EDD）。
    D10 = []; C10 = []
    for k in range(2500):                       # G1：p=1 的 2500 项，C 从 4999 递减到 2500
        c = MAXV - 1 - k
        C10.append(c); D10.append(c + 1)
    for k in range(2500):                       # G2：C=0，p 在 1 与 5000 之间交替
        C10.append(0)
        D10.append(1 if k % 2 == 0 else MAXV)
    emit(10, 5000, 5000, D10, C10,
         "顶格最坏结构：n=5000, M=5000, 2500 项 p=1 档 + 2500 项 p 顶格交替, C 降序(EDD)")


if __name__ == "__main__":
    main()
