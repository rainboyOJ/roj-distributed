#include <cstdio>
#include <vector>
#include <algorithm>
#include <queue>

int main() {
    int n = 0, M = 0;
    if (scanf("%d %d", &n, &M) != 2) return 0;

    std::vector<int> D(n), C(n);
    for (int i = 0; i < n; ++i) scanf("%d", &D[i]);
    for (int i = 0; i < n; ++i) scanf("%d", &C[i]);

    // (截止时间 d = M - C, 处理时间 p = D - C)，按 d 升序（即 C 降序）处理
    std::vector<std::pair<int, int> > items(n);
    for (int i = 0; i < n; ++i) {
        items[i].first  = M - C[i];   // d_i = M - C_i
        items[i].second = D[i] - C[i]; // p_i = D_i - C_i > 0
    }
    std::sort(items.begin(), items.end()); // 先按 d 升序，同 d 再按 p 升序（任意打破平局均可）

    // 已安排工作的总处理时间；堆中保存已安排工作的 p（大根堆，便于反悔丢最大的）
    long long used = 0;
    std::priority_queue<int> pq;
    for (int i = 0; i < n; ++i) {
        int d = items[i].first, p = items[i].second;
        used += p;
        pq.push(p);
        if (used > d) {           // 当前截止时间已经装不下，反悔丢掉最大的一项
            used -= pq.top();
            pq.pop();
        }
    }

    printf("%d\n", (int)pq.size());
    return 0;
}
