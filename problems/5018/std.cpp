//
// 【题意】初始有 M 元，有 N 项工作；做第 i 项工作前手上必须有 >= D_i 元（不能借钱），
//         做完后手上的钱变成 花掉的钱 - D_i + C_i，即净支出 p_i = D_i - C_i > 0。
//         每项工作只能做一次，问最多能做完多少项。
//         范围：1 <= N <= 5000，0 <= C_i < D_i <= 5000，1 <= D_i, M <= 5000。
//
// 【算法】把「做工作」等价转成经典单机调度模型：
//         设 p_i = D_i - C_i（处理时间，= 做这项工作净减少的钱），
//         做第 i 项工作（排在它前面的工作集合为 S，总净支出 sum_{j in S} p_j）当且仅当
//              M - sum_{j in S} p_j >= D_i   <=>   sum_{j in S} p_j <= M - D_i
//         即「必须在时刻 M - D_i 之前开始第 i 项工作」，
//         等价于「必须在时刻 d_i = M - D_i + p_i = M - C_i 之前完成第 i 项工作」。
//         于是问题化为：单机、全部 0 时刻释放、每项工作处理时间 p_i、截止时间 d_i，
//         最多能按时完成几项工作 —— 经典 1||ΣU_j（最小化误期工作数）。
//         结论：按 d_i 升序（本题即 C_i 从大到小）依次考虑，先把工作接进来；
//         一旦已安排工作的总处理时间超过当前截止时间 d_i，就丢掉已安排工作中
//         p 最大的那一项（反悔贪心 / Moore-Hodgson）。堆里剩下的个数就是答案。
//         正确性依据（交换论证）：若某个工作集合能被完成，则它按截止时间升序（EDD）
//         也一定能被完成；故按 EDD 处理 + 误期时丢最大 p 是 1||ΣU_j 的标准最优算法。
//         复杂度 O(N log N)，最大点瞬时。
//
