// 来源结论核对（无冲突）：全部来源的算法思想一致——从小到大逐个试除，找到因子就输出并
//   把 n 反复除以该因子（保证后续得到的因子仍是质数），直到 n 归 1；
//   输出格式一致为 "n=" + 因子以 '*' 连接（最后一个因子后**不能**多打 '*'）；
//   质数输入（如 2、19997）输出 "n=n"，即分解式中只含它本身；
//   题面无歧义（"质因数必须由小到大"），未触发"停下报告"条件。
//
// 本标程相对来源的改写点（逐条说明，便于复核）：
//   * 主体保留来源 [2][3] 的教学思想（从 2 起试除、命中即反复除尽），但改写为
//     "先打印 n= 前缀 → 迭代试除打印 → 循环后把剩余 >1 的商补打一次"，
//     用 first 标志控制 '*' 的位置，避免 [4][5][7] 那种"因子后补星号"写法
//     在最后一因子处的心智负担；数学与输出结论完全一致。
//   * 试除上界用 d <= m / d（等价 d*d <= m 但避免 int 乘法溢出），零成本健壮性冗余。
//   * 剩余商 m>1 时单独补打：这一步替掉了"试除到 n 本身"（来源 [3][6]）或
//     "递归到底"（来源 [9]）的最后一段，对 n 为质数/含大质因子的情形同样正确。
//   * 输出用 printf 精确十进制（无浮点，跨平台逐字节一致），与语料惯例
//     （problems/1000/std.cpp 的 scanf/printf 风格）统一，行末单个 '\n'。
//   * 越界防御（题面保证 2<=n<=20000，不在评测范围）：n<2 时按空乘积约定输出 "n=n"，
//     不进入试除循环（避免 n=0 时的死循环），保证任何输入都不崩不挂。
// 复杂度：试除到 sqrt(n)，n<=20000 时不超过约 141 次外层迭代，实测远低于 1000 ms。

#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;  // 空/损坏输入：安全退出，不输出垃圾
    printf("%d=", n);

    if (n < 2) {  // 越界防御（题面保证 n>=2；1 视为空乘积）
        printf("%d\n", n);
        return 0;
    }

    int m = n;
    bool first = true;
    for (int d = 2; d <= m / d; ++d) {      // 只试除到 sqrt(m)，且避免 d*d 溢出
        while (m % d == 0) {                // 除尽该因子（重复因子按出现次数逐个输出）
            if (!first) printf("*");        // 乘号印在因子**之前**，首个因子不带
            first = false;
            printf("%d", d);
            m /= d;
        }
    }
    if (m > 1) {                            // 剩余商必为质数（> sqrt(原 m) 的大质因子）
        if (!first) printf("*");
        printf("%d", m);
    }
    printf("\n");
    return 0;
}
