#include <cstdio>

int main() {
    for (int n = 100; n <= 999; ++n) {
        int a = n / 100;          // 百位
        int b = n / 10 % 10;      // 十位
        int c = n % 10;           // 个位
        if (a * a * a + b * b * b + c * c * c == n) {
            printf("%d\n", n);
        }
    }
    return 0;
}
