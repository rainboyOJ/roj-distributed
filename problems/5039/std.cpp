// 一本通 2037《【例5.4】约瑟夫问题》标程（目标 ROJ 题号 5039）
//
// 题意：N 个人围成一圈，从第 1 个人开始报数，报到 M 的人出圈；
//       再由下一个人从 1 重新报数，报到 M 的人出圈；……
//       按出圈次序输出这 N 个人的编号。数据范围 2 <= N, M <= 1000。
//
// 参考来源（思路/写法改写自以下公开题解，未逐字复制）：
//   [1] https://blog.csdn.net/lq1990717/article/details/121588714
//       《信息学奥赛一本通 2037：【例5.4】约瑟夫问题 | 1334：【例2-3】围圈报数 |
//         洛谷 P1996 约瑟夫问题》
//       给出三种解法：循环遍历数组（bool 标记 + 下标回绕）、队列、循环链表；
//       其中"循环遍历数组"即本标程采用的 O(N*M) 标记模拟路线。
//   [2] https://blog.csdn.net/xiang20100794/article/details/123458411
//       《信奥赛一本通 C++题解 2037【例5.4】约瑟夫问题》
//       数组标记 + 位置回绕（p==n 后 p=0）的 AC 写法，与本标程等价。
//   [3] http://ybt.ssoier.cn:8088/problem_show.php?pid=2037
//       官方题面与样例（输入 8 5 -> 输出 5 2 8 7 1 4 6 3），用于核对语义与限制
//       （1000 ms / 65536 KB）。
//
// 算法（与来源 [1] 解法 1 同路线，自己重写）：
//   用 bool 数组 out[] 标记"已出圈"；指针 pos 在 0..N-1 上循环（0-based 编号）。
//   每轮从当前 pos 起向后跳过已出圈的人，在圈中人数满 M 个时，第 M 个即本轮出圈者：
//   输出其编号（+1 转 1-based），置 out 标记为真，pos 指向其下一个位置开始新一轮。
//   共执行 N 轮。复杂度 O(N*M) <= 1e6，远小于 1000 ms / 64 MB 的限制。
//
// 输出格式：编号之间以单个空格分隔，行末一个换行（无行末多余空格）。

#include <cstdio>

int main() {
    int n, m;
    if (scanf("%d %d", &n, &m) != 2) return 0;

    static bool out[1005];   // 下标 0..n-1 表示编号 1..n 的人是否已出圈

    int pos = 0;             // 当前轮到报数的人（尚未报数）
    for (int k = 0; k < n; k++) {
        int cnt = 0;
        while (true) {                 // 从 pos 起找第 m 个在圈中的人
            if (!out[pos]) {
                cnt++;
                if (cnt == m) break;
            }
            pos++;
            if (pos == n) pos = 0;     // 下标回绕，圈成环
        }
        out[pos] = true;               // 第 m 个在圈中的人出圈
        printf("%d", pos + 1);
        printf(k + 1 == n ? "\n" : " ");
        pos++;                         // 由"下一个人"重新从 1 开始报数
        if (pos == n) pos = 0;
    }
    return 0;
}
