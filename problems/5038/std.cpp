// 一本通 2036《【例5.3】开关门》— 标程（C++17，stdin -> stdout）
// 题号：ybt 2036 / 目标 ROJ 5038
// 限制：time 1000 ms，memory 65536 KB（config.json 的 64 MB 与官方页实测的 65536 KB 一致）
//
// 题意：n(2<=n<=1000) 个房间编号 1..n。第 1 个服务员把所有的门都打开（等价于对
//   所有门做一次"相反处理"）；第 j(2..n) 个服务员把所有编号为 j 的倍数的房间做
//   "相反处理"（原来开着的关上，原来关上的打开）。问第 n 个服务员来过后哪几扇门
//   是打开的：一行，由小到大的房间序号，各序号之间用一个空格隔开。
//   样例：输入 "100" -> 输出 "1 4 9 16 25 36 49 64 81 100"。
//
// 关键推导（全部来源一致）：门 i 的"相反处理"次数 = i 在 [1,n] 内的倍数关系次数；
//   由于 i <= n，凡 d | i 的 d 都满足 d <= i <= n，故第 i 扇门恰被"编号为 i 的
//   全部因数"的服务员各操作一次，共 d(i)（约数个数）次。门初态为关，于是：
//       门 i 最终开着  <=>  d(i) 为奇数  <=>  i 是完全平方数。
//   （完全平方数的因数按 d 与 i/d 成对出现，只有 √i 与自身配对，故因数个数为奇数。）
//   输出即 1^2, 2^2, 3^2, ... 直到不超过 n。n<=1000 时最大项为 31^2=961
//   （32^2=1024>1000），共 31 项。
//
// 参考来源 URL（本轮均用 curl 实取页面正文/代码块核对后改写，非盲抄搜索摘要）：
//   [1] 官方题面（样例 100 -> 1 4 9 ... 100、时间限制 1000 ms、内存限制 65536 KB、
//       范围 2<=n<=1000）
//       http://ybt.ssoier.cn:8088/problem_show.php?pid=2036
//   [2] CSDN · 墨衍《信奥赛一本通 C++题解 2036【例5.3】开关门》
//       完全平方数解法：`#include <cmath>` + `m=sqrt(n); for(i=1;i<=m;i++) cout<<i*i<<" ";`
//       （n<=1000 时 sqrt 无误差，结论正确；本包改为整数写法，见下）
//       https://blog.csdn.net/xiang20100794/article/details/123458395
//   [3] CSDN · 君义NOIP《信息学奥赛一本通 2036：【例5.3】开关门》
//       两解：(A) bool 数组模拟"相反处理"；(B) 不建数组，对每扇门统计
//       "1..i 中是 i 的因数的个数"，奇数则输出——与本标程的推导同源
//       https://blog.csdn.net/lq1990717/article/details/121576637
//   [4] CSDN ·《开关门（信息学奥赛一本通-2036）》（2402_84298973）
//       解法一：`for (int i = 1; i * i <= n; i++) cout << i * i << ' ';`
//       解法二：完整模拟每个服务员对倍数的开/关翻转
//       https://blog.csdn.net/2402_84298973/article/details/145097021
//   [5] CSDN ·《【信息学奥赛一本通】2036：【例5.3】开关门》（gybusfan）
//       完全平方数解法：`for(int i = 1;i*i<=n;i++){ cout<<i*i<<" "; }`
//       https://blog.csdn.net/gybusfan/article/details/136603798
//   [6] CSDN ·《2036：【例5.3】开关门》（h1727548）
//       C 语言版：编号数组 + 状态数组 b[j]=-b[j] 变号表示"相反处理"，
//       最后输出 b[i]==1 的房间号；C++ 版用 judge 变量变号
//       https://blog.csdn.net/h1727548/article/details/128583908
//   [7] CSDN ·《信息学奥赛一本通答案dj开关门2036》（m0_73220913）
//       `bool a[1001]={};` 置初值全关，对 i=2..n 翻转 j%i==0 的门，最后输出 a[i]==0 者
//       https://blog.csdn.net/m0_73220913/article/details/129387151
//
// 来源结论核对（无冲突）：所有来源输出集合一致（n 以内的完全平方数，由小到大）；
//   算法分两派——(a) 直接输出 i*i（[2][4] 解法一、[5]）与 (b) 按题面模拟"相反处理"
//   再收集开着的门（[3] 解法一、[4] 解法二、[6][7]），[3] 解法二则用约数个数奇偶性
//   把两派打通。两派在本题范围内结论完全相同（模拟即约数个数奇偶性，奇数⟺平方数），
//   题面本身无歧义，未触发"停下报告"条件。
//
// 本标程相对来源的改写点（逐条说明，便于复核）：
//   * 采用来源 [2][4][5] 的"直接枚乘输出 i*i"路线，但循环条件写 i <= n / i
//     （等价于 i*i <= n，避免 i*i 的有符号溢出 UB：对域外的大 n 也安全），
//     从而**完全不使用浮点**——来源 [2] 的 `sqrt(n)` 在 n<=1000 时虽无误差，
//     但整数写法无 <cmath> 依赖与取整边界问题，属等价稳健化改写。
//   * 输出用"先判断再输出分隔符"的写法：元素之间恰一个空格，**行末无多余空格**，
//     最后补单个 '\n'（与题面样例 `1 4 9 ... 100` 及仓库语料惯例一致；
//     来源 [2][4][5] 的 `cout<<i*i<<" "` 会留下行末空格，本包取更严格的形态）。
//   * 读入后未读到整数（空输入）静默退出；n<1（域外）时输出 0 字节，
//     不作任何越界访问（防御性，题面保证 2<=n<=1000 不会发生）。
//   * stdin->stdout，`scanf/printf` 风格对齐 problems/1000/std.cpp。
// 复杂度：O(√n) 时间、O(1) 空间；n=1000 时 <1 µs，远低于 1000 ms / 64 MB。

#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;  // 无输入时静默退出（题面保证有输入）

    bool first = true;                   // 是否已输出过元素（控制分隔符）
    for (int i = 1; i <= n / i; ++i) {   // i*i <= n，且无溢出风险（n<1 时循环不执行）
        if (!first) putchar(' ');        // 元素之间恰一个空格，行首/行末不留空格
        printf("%d", i * i);             // i=1..floor(√n)，即全部开着的门号（升序）
        first = false;
    }
    if (first) return 0;                 // 域外 n<1：没有任何门开着，输出 0 字节
    putchar('\n');                       // 一行结束（题面：一行，序号间用一个空格隔开）
    return 0;
}
