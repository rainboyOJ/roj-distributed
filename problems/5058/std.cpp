// 一本通 2056《【例3.7】最大的数》标程（C++17，stdin → stdout）
//
// 题意：输入三个数，输出其中最大的数。样例：1.01 2 3.22 -> 3.22。
//   单组输入（一行三个数），无多组数据、无组数 T。
//
// ── 参考来源（本轮均以 curl 实取正文逐字核对，非盲抄；改写点见文末）───────────
//   1) https://blog.csdn.net/lq1990717/article/details/120769709
//      「信息学奥赛一本通 2056：【例3.7】最大的数」（君义_NOIP）
//      给出三种写法：解法1 if 语句嵌套、解法2 if…else if 逻辑表达式、解法3 max(max(a,b),c)。
//      —— 本标程采用其【解法 1：if 语句嵌套】的判定结构（该文注明三种写法均 AC）。
//   2) https://blog.csdn.net/weixin_70576261/article/details/161629588
//      「【最大数】信息学奥赛一本通C语言解法（题号2056）」
//      原文：double max; scanf("%lf %lf %lf",&a,&b,&c); max=a; if(max<b)max=b;
//            if(max<c)max=c; printf("%g",max);
//      —— 本标程的输出格式 printf("%g", …) 取自该来源（与来源 1 的 cout<< 默认精度
//            6 位有效数字等价；见下「输出格式」一节）。
//   3) https://blog.csdn.net/2301_79128218/article/details/132168823
//      「2056：【例3.7】最大的数」—— double 数组 + 遍历打擂台（s 初值 0.0）。
//   4) https://blog.csdn.net/weixin_62460981/article/details/123768696
//      「【信息学奥赛】2056：【例3.7】最大的数（C++）」—— 三次比较交换后输出 c。
//   5) https://blog.csdn.net/jhgcjw/article/details/119675246
//      「c++一本通：程序的控制结构：第一节 if选择结构 2056」—— float x,y,z,n; n=x;
//      if(y>n)n=y; if(z>n)n=z; cout<<n<<endl;
//   6) https://blog.csdn.net/u014117969/article/details/135316151
//      「信息学奥赛一本通：2056：【例3.7】最大的数」—— float + 两次三目运算。
//   官方题面（核对题意/输入输出/样例/限制 1000 ms、65536 KB）：
//      http://ybt.ssoier.cn:8088/problem_show.php?pid=2056   （HTTP 200，实抓）
//
// ── 来源结论一致性 ─────────────────────────────────────────────────────────
//   6 个来源在算法结论上完全一致：三个数取最大者并输出。分歧只在两处细节：
//     (a) max 初值：来源 3 取 0.0，来源 5/6/1/2 取「第一个数」。题面是「三个数」、
//         样例含正数，但**未声明只含正数**；取 0.0 初值在「三个数全为负」时会把
//         答案错算成 0，故选「取第一个数」的路线（与教材 if 嵌套一致）。
//     (b) 输出格式：printf("%g") 与 cout<< 默认（precision 6）在本标程声明的数据域内
//         逐字节等价（已实测，见 gen-report.md 第五节）；无来源使用固定小数位输出。
//   → 无来源冲突到需要停下的程度，故未触发「停下报告」。
//
// ── 本标程相对来源的改写点 ────────────────────────────────────────────────
//   * 采用来源 1 解法 1 的 if 嵌套骨架，但把「判定」与「输出」解耦：4 个叶子分支
//     只给 m 赋值，最后统一一次 printf("%g\n", m)。这样输出格式只有一处，
//     不会出现「某个分支多打空格/漏换行」的不对称错误。
//   * 读写用 double（来源 1/3/4 为 double，来源 5/6 为 float）：在本标程声明的
//     数据域（见 data.py：≤6 位有效数字、|x| ≤ 999999）内 double/float 的判定与
//     %g 输出结果一致，故对 float 版官方风格解法同样公平（对拍脚本有专门交叉验证）。
//   * scanf 返回值检查（读不满 3 个数即退出），与仓库 problems/1000/std.cpp 风格一致。
//   * 复杂度 O(1)：无循环、无数组、无算术运算，只有 3 次比较。
//
// ── 输出格式（本题唯一的隐性坑）─────────────────────────────────────────────
//   答案就是「三个输入数之一」，用 %g（默认 6 位有效数字）输出即得该数的最简体
//   十进制写法：1.01 -> "1.01"、2 -> "2"、3.22 -> "3.22"、0 -> "0"、999999 -> "999999"。
//   与 cout << 的默认格式（precision 6）逐字符一致；而若用 "%.2f" 输出，输入样例
//   恰好照样例（3.22 就是两位小数）过关，但整数值（如 2）会打成 "2.00" 而 WA。
//   本标程按来源 2/1 的 %g/cout 口径输出，数据生成器并已用 Python 第三方真值
//   独立复算每个测试点的 .out（见 work/stress.py）。
//
// 编译：g++ -O2 -std=c++17 -Wall -Wextra std.cpp -o std
// 样例：printf '1.01 2 3.22\n' | ./std   →   3.22
#include <cstdio>

int main() {
    double a, b, c;
    if (scanf("%lf %lf %lf", &a, &b, &c) != 3) return 0;  // 单组输入：一行三个数

    double m;
    if (a >= b) {                 // 来源 1 解法 1：if 语句嵌套，4 个叶子分支
        if (a >= c) m = a;        // 分支 1：a 最大（并列时取 a，值相同不影响答案）
        else        m = c;        // 分支 2：a >= b 且 c > a → c 最大
    } else {
        if (b >= c) m = b;        // 分支 3：b > a 且 b >= c → b 最大
        else        m = c;        // 分支 4：b > a 且 c > b → c 最大
    }

    printf("%g\n", m);            // 来源 2 的 %g 口径：输出「最大的那个数」本身
    return 0;
}
