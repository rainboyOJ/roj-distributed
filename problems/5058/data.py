# -*- coding: utf-8 -*-
# 一本通 2056《【例3.7】最大的数》—— 测试数据生成器（cyaron，仓库惯例）
# 目标 ROJ 题号 5058（落地由主控脚本完成；本子任务未接触 problems/）
#
# 用法（在本目录下）：
#     g++ -O2 -std=c++17 -Wall -Wextra std.cpp -o std
#     mkdir -p data && cd data && python3 ../data.py
# 参考同款：problems/1000/data.py（IO(file_prefix="problem", data_id=i) + output_gen("../std")）、
#           .ybt-import/staging/2053/data.py（分层 + 生成期自检）。
#
# ---------------------------------------------------------------------------
# 题意（content.md / 官方页 pid=2056 实抓一致）：
#   【题目描述】输入三个数，输出其中最大的数。
#   【输入】输入三个数。   【输出】其中最大的数。
#   【输入样例】1.01 2 3.22        【输出样例】3.22
#   config.json：time 1000 ms / memory 64 MB（官方页 1000 ms / 65536 KB，一致）
#   结构：单组输入（一行三个数），无多组数据、无组数 T、无 n。
#
# ---------------------------------------------------------------------------
# ★ 数据范围考证（题面未声明，本题唯一的信息缺失；如实记录）
#
#   题面与官方 OJ 页均**未声明**三个数的取值范围、类型或符号约定（无【数据规模】节）。
#   由【输入样例】1.01 2 3.22 可知：既含整数也含小数，即读入的「数」是实数
#   （全部 6 个网络来源都用 double/float 读入）。按仓库惯例（staging/2053、2064、2071）
#   自定工作范围并如实记录：
#
#       值 ∈ 整数档 {m : m ∈ Z, |m| <= 999999}
#          ∪ 小数档 {k / 100 : k ∈ Z, |k| <= 999999}   （即至多两位小数，|x| <= 9999.99）
#
#   三条依据：
#   1. **有效数字 ≤ 6**。答案本身就是「三个输入数之一」，而 C/C++ 的默认实数输出
#      （printf("%g") 与 cout << 默认精度）都是 6 位有效数字：只有取值 ≤ 6 位有效数字时，
#      输出才是该数的**最简十进制写法**，且「%g 型」与「cout 型」与「原样回显输入 token 型」
#      三种实现输出逐字节相同 —— 这正是让数据对实现风格公平的关键（见下游自检 assert）。
#      反例：若取值 1234567（7 位）或 0.00001234，则期望输出文本本身在 %g（"1.23457e+06"）
#      与回显之间就有歧义，属于题目固有的不可判点，故主动排除。
#   2. **至多两位小数**。与【输入样例】的 1.01 / 3.22 同风格（一本通第三章实数入门题
#      的通行口径）；且两位小数在 int32 与 double 下都无表示/舍入风险。
#   3. **必须含负数**。题面写「三个数」而非「三个正数」，且同章 2053/2064 均不假设正数。
#      含负数还能逮住一类经典错解：把 max 初值写成 0.0（来源 3 的写法），
#      输入全负时会错答 0（本数据点 2 专治）。
#
#   范围假设的风险（已写入 gen-report.md）：若评测方真实数据超出上述量级，
#   本包 10 个点仍然全部合法（它们都落在任何合理范围内），只是「顶格点」的位置不同；
#   且 std 用 double 读写，到 1e15 量级也不溢出。
#
# ---------------------------------------------------------------------------
# 分层设计（10 个测试点，从最小铺到顶格；每点规模与设计意图逐条注明）
#
#   点 1  边界层  题面【输入样例】1.01 2 3.22（题面唯一声明的特殊值，必须逐字节一致）
#   点 2  边界层  整数档**下界**三重并列 -999999（全最小 = 最负；且全负，
#                 专治「max 初值 0.0」型错解）
#   点 3  边界层  整数档**上界**三重并列 999999（全最大；6 位有效数字顶格，
#                 并考「整数输出不带小数点」）
#   点 4  小规模  答案 = 1 的极端：-3.22 1 0.99（可手算；最大者位居第 2）
#   点 5  小规模  答案 = 0 的极端：-0.5 -9999.99 0（可手算；0 最大且全负围栏）
#   点 6  小规模随机  两位小数 ±9.99，**两数并列最大**（b = c = max，最大者在末位）
#   点 7  中等规模随机  两位小数 ±999.99，三互异，最大者在**首位**
#   点 8  中等规模随机  整数 ±999999（全域、无小数点），最大者在首位
#   点 9  大规模随机  两位小数贴近上限 |x| ∈ [6000, 9999.99]（大规模，贴近小数档顶格），
#                 三互异，最大者在**末位**（完全逆序）
#   点 10 顶格层  极值混排 -9999.99 9999.99 9999.98：
#                 小数档下界 / 上界同场 + 相邻差 0.01（最坏位置的「最大者在中间」结构）
#
#   与任务书分层清单的对照（不适用项如实说明，不硬凑）：
#     - 「n=1 / n=2 的组数分层」：本题为**单组输入**（一个测试点 = 一行三个数），
#       不存在 n、不存在组数维度，不适用；该清单项针对多组数据题。
#     - 「答案含 0 或 1 的极端」：点 4（1）、点 5（0）覆盖。
#     - 「全相等 / 重复值」：三并列（点 2、3）、两数并列（点 6）。
#     - 「有序 / 逆序」：点 7（降序已序 a>b>c）、点 9（最大者在末位 = 完全逆序）
#       、点 10（最小者在首、最大者在中间）。
#     - 「顶格」：整数档上界（点 3）、小数档上界（点 10）、大规模贴近上限（点 9）。
#
# ---------------------------------------------------------------------------
# 生成期自检（生成器末尾 assert，任一失败即中止；口径与 staging/2053 的 data.py 一致）：
#   (a) 每个数值 token 都是**最简十进制写法**：'%g' % float(tok) == tok
#       （即：无尾随 0、无 "+"、无 ".0"、无科学计数法、无 -0）；
#   (b) 每个 token 的有效数字 ≤ 6、绝对值不超过所属档上限；
#   (c) std 实际写出的 problem<i>.out 与 Python 独立真值 max(float(t)) 完全一致
#       （即正式数据本身也经过第三方复算，不依赖 std 自证）；
#   (d) 四个判定分支（std.cpp 的 4 个叶子）在 10 个点中全部被走到。

from cyaron import *  # 引入CYaRon的库

import random

# ---- 自定工作范围（见文件头「数据范围考证」）----
INT_LIMIT = 999999   # 整数档：|x| <= 999999
DEC_LIMIT_K = 999999  # 小数档：值 = k/100，|k| <= 999999（即 |x| <= 9999.99）


def dec2(k):
    """把「百分之 k」写成最简两位小数文本（无尾随 0、无 -0）。k 为 int。"""
    if k == 0:
        return "0"
    sign = "-" if k < 0 else ""
    q, r = divmod(abs(k), 100)
    if r == 0:
        return "%s%d" % (sign, q)
    if r % 10 == 0:
        return "%s%d.%d" % (sign, q, r // 10)
    return "%s%d.%02d" % (sign, q, r)


def fmt_int(m):
    return str(m)


def sig_digits(tok):
    """token 的有效数字个数（用于 assert，排除前导/尾随 0）。"""
    d = tok.lstrip("-").replace(".", "").lstrip("0")
    return len(d) if d else 1


def check_token(tok, kind):
    """自检 (a)(b)：最简写法 + 有效数字 ≤ 6 + 不超所属档上限。"""
    assert tok == tok.strip(), tok
    assert tok[0] != "+" and "e" not in tok and "E" not in tok, tok
    assert not (tok.startswith("-0") and set(tok[1:]) <= set("0.")), "不许出现 -0：%s" % tok
    assert ("%g" % float(tok)) == tok, "非最简十进制写法：%s（%g）" % (tok, float(tok))
    assert sig_digits(tok) <= 6, "有效数字超过 6 位：%s" % tok
    v = float(tok)
    if kind == "int":
        assert "." not in tok, tok
        assert abs(v) <= INT_LIMIT, tok
    else:
        k = round(v * 100)
        assert abs(k - v * 100) < 1e-6, tok
        assert abs(k) <= DEC_LIMIT_K, tok
    return v


# ---- std.cpp 4 个叶子分支的同构复算（自检 (d)）----
def branch_id(a, b, c):
    if a >= b:
        return 1 if a >= c else 2
    return 3 if b >= c else 4


_pts = []  # (i, tokens, kind, note)


def gen(i, tokens, kind, note):
    """写出第 i 组：输入由 tokens 拼成一行，输出由 std 生成；并做自检 (a)(b)(c)。"""
    vals = [check_token(t, kind) for t in tokens]
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(*tokens)
    io.output_gen("../std")

    # (c) 与 Python 独立真值复算（按数值取最大；并列时文本相同，故取首个即可）
    # 注意：cyaron 的 output_file 是带缓冲的 Python 文件对象，须先从缓冲区读回。
    truth = tokens[vals.index(max(vals))]
    io.output_file.flush()
    io.output_file.seek(0)
    got = io.output_file.read()
    assert got == truth + "\n", "点 %d: std 输出 %r != Python 真值 %r" % (i, got, truth + "\n")
    _pts.append((i, tokens, kind, branch_id(*vals), note))
    print("problem%-2d: %-34s -> %-9s 分支%d  %s"
          % (i, " ".join(tokens), truth, branch_id(*vals), note))


# ---- 点 1：边界层 —— 题面【输入样例】（题面唯一声明的特殊值）----
# 混合「整数 + 两位小数」，正是样例的形态；答案 3.22 在末位（分支 4）。
gen(1, ["1.01", "2", "3.22"], "dec",
    "边界层：题面输入样例（整数与两位小数混合，最大者在末位）")

# ---- 点 2：边界层 —— 整数档下界三重并列 + 全负 ----
# 全最小（域下界）×3（三数并列）；全负，专治「max 初值取 0.0」型错解（来源 3 写法）。
gen(2, [fmt_int(-INT_LIMIT)] * 3, "int",
    "边界层：整数档下界三并列 + 全负（治 max 初值 0.0）")

# ---- 点 3：边界层 —— 整数档上界三重并列（6 位有效数字顶格）----
gen(3, [fmt_int(INT_LIMIT)] * 3, "int",
    "边界层：整数档上界三并列（全最大，顶格 + 整数输出格式）")

# ---- 点 4：小规模（可手算）—— 答案为 1 的极端 ----
gen(4, ["-3.22", "1", "0.99"], "dec",
    "小规模：答案 = 1 的极端（手算：1 > 0.99 > -3.22）")

# ---- 点 5：小规模（可手算）—— 答案为 0 的极端 ----
gen(5, ["-0.5", "-9999.99", "0"], "dec",
    "小规模：答案 = 0 的极端（0 最大，其余全负）")

# ---- 点 6：小规模随机 —— 两位小数 ±9.99，两数并列最大（b = c），最大者在末位 ----
rng6 = random.Random(2056 + 6)
m6 = rng6.randint(-599, 999)                  # 百分之数：|m| <= 9.99
a6 = m6 - rng6.randint(1, 400)                # 严格小于 m，且 >= -999（仍落在 ±9.99 内）
gen(6, [dec2(a6), dec2(m6), dec2(m6)], "dec",
    "小规模随机：±9.99，两数并列最大 b=c，最大者在末位")

# ---- 点 7：中等规模随机 —— 两位小数 ±999.99，三互异，最大者在首位（降序已序）----
rng7 = random.Random(2056 + 7)
xs7 = set()
while len(xs7) < 3:
    xs7.add(rng7.randint(-99999, 99999))       # 百分之数：|x| <= 999.99
hi7, mid7, lo7 = sorted(xs7, reverse=True)
gen(7, [dec2(hi7), dec2(mid7), dec2(lo7)], "dec",
    "中等规模随机：±999.99 三互异，降序已序（最大者在首位）")

# ---- 点 8：中等规模随机 —— 整数 ±999999（全域、无小数点）----
rng8 = random.Random(2056 + 8)
xs8 = set()
while len(xs8) < 3:
    xs8.add(rng8.randint(-INT_LIMIT, INT_LIMIT))
hi8, mid8, lo8 = sorted(xs8, reverse=True)
gen(8, [fmt_int(hi8), fmt_int(mid8), fmt_int(lo8)], "int",
    "中等规模随机：整数全域 ±999999，无小数点（考整数输出格式）")

# ---- 点 9：大规模随机 —— 两位小数贴近上限（|x| ∈ [6000, 9999.99]），最大者在末位（完全逆序）----
rng9 = random.Random(2056 + 9)
xs9 = set()
while len(xs9) < 3:
    k = rng9.randint(600000, DEC_LIMIT_K)              # 百分之数：6000.00 <= |x| <= 9999.99
    xs9.add(k * (1 if rng9.random() < 0.5 else -1))
hi9, mid9, lo9 = sorted(xs9, reverse=True)
gen(9, [dec2(mid9), dec2(lo9), dec2(hi9)], "dec",
    "大规模随机：两位小数贴近上限 |x|∈[6000,9999.99]，最大者在末位（完全逆序）")

# ---- 点 10：顶格层 —— 小数档下界 / 上界同场 + 相邻差 0.01（最大者在中间）----
gen(10, ["-9999.99", "9999.99", "9999.98"], "dec",
     "顶格层：小数档下界与上界同场、相邻差 0.01，最大者在中间")

# ---- 自检 (d)：std 的 4 个叶子分支必须全部被走到 ----
covered = sorted({p[3] for p in _pts})
assert covered == [1, 2, 3, 4], "分支覆盖不全：%s" % covered
print("\n自检通过：%d 组数据；std 的 4 个判定分支全覆盖 %s；"
      "全部 token 为最简写法（'%%g' %% float(tok) == tok 且有效数字 <= 6）。"
      % (len(_pts), covered))
