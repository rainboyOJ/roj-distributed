// 一本通 1785《简单的期望》 标程（目标 ROJ 题号 1785）
//
// ============================ ⚠ 题面自相矛盾（已在 gen-report.md 记录） ============================
// content.md（与官方 OJ 页 http://ybt.ssoier.cn:8088/problem_show.php?pid=1785 逐字一致）的
// 【题目描述】写的是：p% 的概率令 x = x/2，(100-p)% 的概率令 x = x+1。
// 但该题面给出的三个官方样例**只有 x = x*2 这一读法能同时对上**：
//     样例1 "1 1 50"  -> 1.0000000000   （x/2 读法：1→0，d(0) 无定义；任何 d(0) 约定都得不到 1.0 之外的
//                                         一致结果：d(0)=1 才能让样例1 成立，却与样例3 冲突）
//     样例2 "5 3 0"   -> 3.0000000000   （两种读法都成立：p=0 时恒 +1，5→6→7→8，v2(8)=3）
//     样例3 "5 3 25"  -> 1.9218750000 = 123/64
// 本标程按 x = x*2 实现（穷举 2^3 条路径逐一核对，见 gen-report.md §3）：
//   ×××:40(v2=3,1/64) ××+:21(0,3/64) ×+×:22(1,3/64) ×++:12(2,9/64)
//   +××:24(3,3/64) +×+:13(0,9/64) ++×:14(1,9/64) +++:8(3,27/64)  => 123/64 = 1.921875 ✅
// 而 x/2 读法在 x=1 时一步就得到 0（v2(0) 无定义），且 n≤200 时 30 步后必为 0，20%/30%/50% 的
// 子任务（n≤20/50/100）也失去意义 —— 故判定【题目描述】中的 "/" 是 "*" 的排版笔误，
// 样例与同源题（JZOJ5805，见下）均为 x = x*2。
// ================================================================================================
//
// 参考来源（经本机编译 + 题面三个样例验证后**改写**，非盲抄）：
//   1. https://blog.csdn.net/lijf2001/article/details/81637699
//      《JZOJ5805. 【2018.08.12提高A组模拟】 简单的期望》—— 同源题：题面/样例/数据规模
//      （x≤1e9, n≤200, 0≤p≤100）与本题**逐字一致**，其题面写作 x = x*2，并给出完整 AC 代码：
//      状态 f[i][s][k][t] = 第 i 步后「低 8 位 = s，第 9 位起连续相同位个数 = k，第 9 位值 = t」
//      的概率；+1 与 ×2 两个转移；统计时 s≠0 取 v2(s)，s=0 且 t=0 取 8+k，s=0 且 t=1 取 8。
//      本标程的骨架（8 位分块 + 高位游程压缩）与此一致，但做了下述改写（见「实现差异」）。
//   2. http://ybt.ssoier.cn:8088/problem_show.php?pid=1785
//      **官方 OJ 页**：题名、时间 1000 ms / 内存 524288 KB、题面全文（实测其描述同样写作 x/2）、
//      三个样例、数据规模；用于确认「题面描述的 / 与样例的 × 冲突」是官方题面本身的笔误。
//   3. 补充检索入口：CSDN 站内搜索 API https://so.csdn.net/api/v3/search?q=...
//      （用特征句「从前有个变量 初始值已给出 质因数分解中2的次数 期望」与样例输出
//        "1.9218750000" 定位到来源 1；洛谷/cnblogs 未检索到本题的其他公开题解）。
//
// 算法（位 DP，O(n · 2^8 · (k0+n)) 时间，O(2^8 · (k0+n)) 空间）：
//   d = v2(w) 就是 w 的二进制末尾 0 的个数。x ≤ 1e9、n ≤ 200 ⇒ w ≤ x·2^n，数值本身可达 2^230，
//   无法直接存值，但「末尾 0 的个数」只取决于两件事：
//     (a) w 的低 8 位 s：若 s ≠ 0，则 d = v2(s)（精确，末尾 0 必落在低 8 位内）；
//     (b) 若 s = 0，则 w = 2^8 · hi，d = 8 + (hi 的末尾 0 个数)。而 hi 只会被 ×2 不断左移、
//         被 +1 的进位影响；由于 hi 的高位只以「第 9 位起连续相同的位」形式影响末尾 0，
//         只需记录 (t, k)：t = 第 9 位（bit 8）的值，k = 从 bit 8 起连续等于 t 的位数。
//         于是 s = 0 时：t = 1 ⇒ d = 8（bit 8 已是 1）；t = 0 ⇒ d = 8 + k。
//   转移（当前状态 (s,k,t)，操作一次）：
//     x = x + 1：s+1 < 2^8 时 (s+1, k, t)；s+1 = 2^8（即 s = 255，进位）时 s' = 0，
//                t' = t^1；若 t = 1（bit 8..8+k-1 全是 1、bit 8+k = 0）则进位后
//                bit 8..8+k-1 变 0、bit 8+k 变 1 ⇒ k' = k；若 t = 0 则 bit 8 变 1、
//                bit 9 仍是 0 ⇒ k' = 1。
//     x = x * 2：整体左移 1 位 ⇒ s' = (s<<1) & 255，进入 bit 8 的是旧 bit 7 = (s>>7)&1；
//                若该位 == t 则游程延续 (t, k+1)，否则游程重置为 (该位, 1)。
//   k 的上界：初值游程 k0（≤ 22，因为 x>>8 < 2^22）+ 每步 ×2 至多 +1 ⇒ k ≤ k0 + n，
//   故开 k ∈ [1, k0+n+2]，**不写死常数**，随题面上限 n ≤ 200 自动伸缩（安全系数 +2）。
//
// 实现差异（相对来源 1）：
//   - 来源 1 把 f[203][260][303][2] 写成全局静态数组（≈ 63 MB double），且 k 维写死 303、
//     循环上界写死 m=n+kk；本标程改用**滚动两层** std::vector（≈ 0.9 MB）并把 k 维按
//     k0+n+2 动态分配，空间与上限解耦。
//   - 来源 1 的初值游程用 `for(;x%2==tt&&x>0;kk++)x>>=1;` 就地改 x，且用 `if(kk==0)kk=1;`
//     兜底；本标程用独立临时变量 h 计算 k0（不改动原数），语义更明确。
//   - 来源 1 用 `printf("%.13lf")`；本标程输出 10 位小数（题面样例同为 10 位，误差限 1e-6）。
//   - 来源 1 只在 s=0 时用 k；本标程对 s≠0 一律取 v2(s)，对 s=0 分 t 讨论，与之一致但写法显式。
//
// 边界约定：x ≥ 1（题面只给上界 x ≤ 1e9，未给下界）。若 x = 0，则值恒为 0 或 1，
//   v2(0) 在数学上无定义，本标程按 DP 的自然口径给出 8+k0 = 9（与来源 1 行为一致）。
//   数据中不生成 x = 0。

#include <cstdio>
#include <vector>
#include <algorithm>

int main() {
    long long x = 0;
    int n = 0, p = 0;
    if (scanf("%lld %d %d", &x, &n, &p) != 3) return 0;

    const int B = 8;                 // 分块位数
    const int SZ = 1 << B;           // 低 B 位的状态数 256
    const int MASK = SZ - 1;

    // ---- 初始状态：(s0, k0, t0) ----
    int s0 = (int)(x & MASK);
    long long hi = x >> B;
    int t0 = (int)(hi & 1);
    int k0 = 0;
    for (long long h = hi; h > 0 && (h & 1) == t0; h >>= 1) k0++;
    if (k0 == 0) k0 = 1;             // x < 2^B（hi = 0）时按「高位全是 0」记 1
    int K = k0 + n + 2;              // k 的上界（安全系数 +2）

    const int NK = K + 1;
    const size_t SZDP = (size_t)SZ * NK * 2;
    std::vector<double> cur(SZDP, 0.0), nxt(SZDP, 0.0);
    cur[((size_t)s0 * NK + k0) * 2 + t0] = 1.0;

    const double q = p / 100.0;      // x = x * 2 的概率
    const double r = 1.0 - q;        // x = x + 1 的概率

    for (int step = 0; step < n; step++) {
        std::fill(nxt.begin(), nxt.end(), 0.0);
        for (int s = 0; s < SZ; s++) {
            for (int k = 1; k <= K; k++) {
                for (int t = 0; t < 2; t++) {
                    double pr = cur[((size_t)s * NK + k) * 2 + t];
                    if (pr <= 0.0) continue;
                    if (r > 0.0) {                       // ---- x = x + 1 ----
                        int ns, nk, nt;
                        if (s == MASK) {                 // 低 8 位溢出，进位到 bit 8
                            ns = 0; nt = t ^ 1;
                            nk = (t == 1) ? k : 1;
                        } else {
                            ns = s + 1; nt = t; nk = k;
                        }
                        nxt[((size_t)ns * NK + nk) * 2 + nt] += pr * r;
                    }
                    if (q > 0.0) {                       // ---- x = x * 2 ----
                        int bit7 = (s >> (B - 1)) & 1;   // 左移后进入 bit 8 的那一位
                        int ns = (s << 1) & MASK;
                        int nt, nk;
                        if (bit7 == t) { nt = t; nk = k + 1; }
                        else { nt = bit7; nk = 1; }
                        nxt[((size_t)ns * NK + nk) * 2 + nt] += pr * q;
                    }
                }
            }
        }
        cur.swap(nxt);
    }

    // ---- 统计答案：s ≠ 0 取 v2(s)；s = 0 时 t=1 → 8，t=0 → 8+k ----
    double ans = 0.0;
    for (int s = 1; s < SZ; s++) {
        int z = 0;
        for (int v = s; (v & 1) == 0; v >>= 1) z++;
        if (z == 0) continue;
        for (int k = 1; k <= K; k++)
            for (int t = 0; t < 2; t++)
                ans += cur[((size_t)s * NK + k) * 2 + t] * z;
    }
    for (int k = 1; k <= K; k++) {
        ans += cur[((size_t)0 * NK + k) * 2 + 0] * (double)(B + k);
        ans += cur[((size_t)0 * NK + k) * 2 + 1] * (double)B;
    }

    printf("%.10f\n", ans);
    return 0;
}
