# 一本通 2073《【例2.16】三角形面积》数据生成器（cyaron，目标 ROJ 题号 5074）
#
# 题意：给定三角形三边长 a、b、c，用海伦公式 s = sqrt(p(p-a)(p-b)(p-c))（p=(a+b+c)/2）
#       求面积，输出保留 3 位小数。输入一行三个数，单组输入（题面样例 2.1 3.1 4.1 -> 3.179）。
#       题面**无图**（candidate.json 的 pictures 为空），不是"固定输入题"，正常生成 10 组。
#
# 数据范围（题面与官方 OJ 页 http://ybt.ssoier.cn:8088/problem_show.php?pid=2073 均
# 【未声明】三边的取值范围与小数位数，只有 1000 ms / 65536 KB 限制）。本包据此自定
# 工作范围，并与同批次题（2064/2066/2069/2070/2071）的处置口径一致，在报告中如实记录：
#     0.1 <= a, b, c <= 1000.0，一位小数（至多一位），且满足严格三角不等式
#     （a+b>c 等三条），保证题面语义"已知△ABC"成立；
#     面积范围 [0.004, 433012.702]，与"保留 3 位小数"的输出格式自洽。
#   - 取至多一位小数：题面样例（2.1 3.1 4.1）即为一位小数，是本包唯一的小数形态线索；
#     std 用 double 读入，整数/小数输入均兼容。
#   - 不生成"退化/非法"输入（如 1 2 3）：题面保证是三角形；对退化输入各 AC 实现
#     （不加保护的朴素海伦公式）会输出 nan 或 -0.000，属于题面未定义行为，不应作为
#     测试点。对拍中另行用小样本确认了 std 在该情形下的防御性输出。
#
# 分层设计（单组输入题：一个测试点即一组 (a,b,c)，"规模"体现为数值量级与结构）：
#   点 1-2   边界层  ：全最小值 0.1 0.1 0.1（面积最小 0.004）/ 全最大值 1000 1000 1000
#                      （面积最大 433012.702，等边结构）
#   点 3-4   小规模  ：题面【输入样例】2.1 3.1 4.1（题面声明的特殊值）/
#                      4 2.5 2.5（面积恰为整数 3.000 的等腰构造，考察 ".000" 三位补零）
#   点 5-6   小/中随机：一位小数 [0.1,2.0] / 一位小数 [1.0,100.0]
#   点 7-8   大规模随机：一位小数 [100.0,800.0] / 一位小数 [500.0,1000.0]（贴近上限）
#   点 9-10  顶格层  ：1000.0 1000.0 0.1（极端不等边近退化；面积 49.9999999375，
#                      与两个 3 位小数分界（49.9995 / 50.0005）都相距约 5e-4，
#                      但中间量 p-a=0.05 极小，考察瘦长三角形下的数值稳定性）/996.4 996.9 999.7（全顶格 +
#                      最坏舍入结构：精确面积 430991.59049980546，距 0.0005 分界线仅
#                      1.9e-7，是通篇最苛刻的"第三位小数"判定点；已用 10 种独立实现
#                      变体（含 long double / Kahan 稳定式 / 坐标法）确认输出一致）。
#
# 自检：每组生成后用纯整数算术（math.isqrt，与 std 的浮点路线无关）预测期望输出，
#       并读回 problemN.out 逐字节比对，不一致立即报错退出。

from cyaron import *  # 引入CYaRon的库

import math
import os
import random

random.seed(2073)  # 固定种子，便于复现

LO = 1        # 十分位下限 0.1
HI = 10000    # 十分位上限 1000.0


def exact_millis(A, B, C):
    """纯整数精确预测 area*1000 的四舍五入结果（A,B,C 为十分位整数）。

    推导：P=A+B+C，f1=P-2A, f2=P-2B, f3=P-2C（=20(p-a) 等），N=P*f1*f2*f3，
          area = sqrt(N)/400，area*1000 = sqrt(25N)/2。
    记 M=25N，q=isqrt(M)：非边界时 floor(sqrt(M)/2) = (q+1)//2；
    M 为奇平方数时真值恰在 0.5 分界线上，采用与 glibc printf 一致的 half-even。
    """
    P = A + B + C
    f1, f2, f3 = P - 2 * A, P - 2 * B, P - 2 * C
    if min(f1, f2, f3) <= 0:
        return 0
    N = P * f1 * f2 * f3
    M = 25 * N
    q = math.isqrt(M)
    if q * q == M and q % 2 == 1:
        k = (q - 1) // 2
        return k if k % 2 == 0 else k + 1
    return (q + 1) // 2


def fmt_millis(millis):
    return "%d.%03d" % (millis // 1000, millis % 1000)


def valid(A, B, C):
    return A + B > C and A + C > B and B + C > A


def rand_triangle(lo, hi):
    """在十分位区间 [lo,hi] 内拒绝采样一个严格三角形（三边独立均匀）。"""
    while True:
        A, B, C = random.randint(lo, hi), random.randint(lo, hi), random.randint(lo, hi)
        if valid(A, B, C):
            return A, B, C


def gen(i, A, B, C, note):
    """写出第 i 组输入（三边各按 %.1f 格式），调用 std 生成 .out，并回读自检。"""
    assert LO <= min(A, B, C) and max(A, B, C) <= HI, "超出 0.1~1000.0 自定工作范围"
    assert valid(A, B, C), "非严格三角形"
    inp = "%.1f %.1f %.1f" % (A / 10.0, B / 10.0, C / 10.0)
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln("%.1f" % (A / 10.0), "%.1f" % (B / 10.0), "%.1f" % (C / 10.0))
    io.output_gen("../std")                    # 用 std 产出输出
    io.close()                                 # 关闭缓冲，保证下方回读的是落盘内容

    expect = fmt_millis(exact_millis(A, B, C))
    got = open("problem%d.out" % i).read().strip()
    assert got == expect, "第 %d 组自检失败: std=%r 精确期望=%r" % (i, got, expect)
    print("problem%-2d: %-24s 期望=%-12s -- %s" % (i, inp, expect, note))


# ---- 点 1-2：边界层 ----
gen(1, 1, 1, 1,
    "边界层：全最小值 0.1 0.1 0.1（等边，面积为全体最小 0.004）")
gen(2, HI, HI, HI,
    "边界层：全最大值 1000.0 1000.0 1000.0（顶格等边，面积为全体最大 433012.702）")

# ---- 点 3-4：小规模定点（可手算 / 结构特殊） ----
gen(3, 21, 31, 41,
    "小规模：题面【输入样例】2.1 3.1 4.1（题面声明特殊值，期望 3.179）")
gen(4, 40, 25, 25,
    "小规模：4 2.5 2.5 等腰，面积恰为整数 3.000（考察 3 位补零）")

# ---- 点 5-6：小 / 中等规模随机 ----
A, B, C = rand_triangle(1, 20)         # [0.1, 2.0]
gen(5, A, B, C, "小规模随机：一位小数 [0.1,2.0]（可手算核对）")
A, B, C = rand_triangle(10, 1000)      # [1.0, 100.0]
gen(6, A, B, C, "中等规模随机：一位小数 [1.0,100.0]")

# ---- 点 7-8：大规模随机（接近上限） ----
A, B, C = rand_triangle(1000, 8000)    # [100.0, 800.0]
gen(7, A, B, C, "大规模随机：一位小数 [100.0,800.0]")
A, B, C = rand_triangle(5000, 10000)   # [500.0, 1000.0]
gen(8, A, B, C, "大规模随机：一位小数 [500.0,1000.0]，贴近上限")

# ---- 点 9-10：顶格层（上限 + 最坏结构） ----
gen(9, 10000, 10000, 1,
    "顶格层：1000.0 1000.0 0.1 极端不等边（瘦长近退化）；"
    "精确面积 49.9999999375，中间量 p-a 仅 0.05，测浮点稳定性")
gen(10, 9964, 9969, 9997,
    "顶格层：996.4 996.9 999.7 全顶格最坏舍入结构；"
    "精确面积 430991.59049980546，距 0.0005 分界线仅 1.9e-7")

print("done: 10 test cases (problem1..problem10), all self-checked against exact integer math")
