// 一本通 2021《【例4.6】最大公约数》标程（目标 ROJ 题号 5023）
//
// 题面：求两个正整数 m，n 的最大公约数。输入一行 m n；输出 m，n 的最大公约数。
// 数据范围：对于全部数据 m, n < 4000000。单组输入，无多测。
//
// 算法：辗转相除法（欧几里得算法）gcd(m, n) = gcd(n, m mod n)，余数为 0 时收敛。
//   复杂度 O(log max(m,n))，最坏情形（相邻斐波那契数）也只需约 31 次迭代，
//   远低于本题 1000 ms 限制。
//
// 参考来源（均已 curl 实取正文核对，本文件为改写实现，非盲抄）：
//   1. 君义_noip《信息学奥赛一本通 2021：【例4.6】最大公约数》
//      https://blog.csdn.net/lq1990717/article/details/117027098
//      —— 给出两解：解法 1「枚举」取较小数的值从大到小试除（本题教学点 · while 循环）；
//         解法 2「辗转相减法 / 辗转相除法」。本标程取解法 2 的辗转相除法。
//   2. 《信息学奥赛一本通（2021：【例4.6】最大公约数）》
//      https://blog.csdn.net/mydream8/article/details/122361913
//      —— AC 代码：循环中先 swap 保证 a >= b，再 a = a % b，循环条件 a != 0，末态输出 b。
//         与本实现等价（本实现以余数 r 为循环变量，避免多余的交换分支）。
//   3. 《【信息学奥赛-C++】2021：【例4.6】最大公约数》
//      https://blog.csdn.net/qq_43779149/article/details/129015383
//      —— 明确「m 和 n 的最大公约数等于 n 和 m % n 的最大公约数」这一递归/迭代依据；
//         其实现 r = m % n; while (r != 0) { m = n; n = r; r = m % n; } 输出 n。
//   4. 《2021：【例4.6】最大公约数 信息学奥赛一本通（C++版）》
//      https://blog.csdn.net/m0_63998667/article/details/130663410
//      —— 同为辗转相除（da=xiao; xiao=yu 版），结论一致。
//   5. 官方题面（核对语义/样例/范围）：http://ybt.ssoier.cn:8088/problem_show.php?pid=2021
//      （实抓核对：时间限制 1000 ms、内存 65536 KB、样例 4 6 → 2、范围 m,n<4000000；提交数 111968、通过数 72901）
//
// 各来源结论完全一致（辗转相除 / 枚举试除均正确），不存在冲突或题意歧义。
//
// 相对来源的改写点：
//   - 用 long long 读入（来源 1、2 用 int）；m,n < 4·10^6 时 int 本就足够，
//     用 long long 只是零成本的健壮性冗余，不影响结果；
//   - 归一化取绝对值（题面保证正整数，此处仅为防御性写法）；
//   - 单行输出答案并带换行（与题面【输出样例】2 一致）；
//   - 余数为 0 时直接归约为 gcd(m, n) = n（保证输入 1 也能得到答案 1）。
//
// 用法：g++ -O2 -std=c++17 std.cpp -o std && echo "4 6" | ./std  → 2

#include <cstdio>

int main() {
    long long m, n;
    if (scanf("%lld %lld", &m, &n) != 2) return 0;

    if (m < 0) m = -m;          // 防御性：题面保证 m, n 为正整数
    if (n < 0) n = -n;

    // 辗转相除法：gcd(m,n) = gcd(n, m % n)，直到余数为 0
    while (n != 0) {
        long long r = m % n;
        m = n;
        n = r;
    }
    // 循环结束时 m 即最大公约数（含 m=n 的情形；输入 m=n=1 时得 1）

    printf("%lld\n", m);
    return 0;
}
