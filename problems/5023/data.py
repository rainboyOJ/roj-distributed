#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2021《【例4.6】最大公约数》数据生成器（目标 ROJ 题号 5023）
#
# 题面：求两个正整数 m，n 的最大公约数。
#       输入一行 m n（单组输入，无多测）；输出一行 gcd(m, n)。
#       数据范围：对于全部数据 m, n < 4000000 ⇒ 合法取值 1 <= m, n <= 3999999
#       （题面写明"两个正整数"，故下界为 1，不存在 0 / 负数输入）。
#       限制：time 1000 ms，memory 64 MB（config.json）。
#
# ---------------------------------------------------------------------------
# 分层设计（10 个测试点，从最小铺到顶格）
# ---------------------------------------------------------------------------
#   点 1     边界层    ：全最小值且相等 m=n=1（答案 1，最小可能答案；验证 m=n 不得输出 0）
#   点 2     边界层    ：题面【输入样例】4 6（答案 2，m<n 顺序；题面唯一声明的特殊值）
#   点 3     小规模随机：[2,100] 独立均匀随机（量级小到可手算；自然取值）
#   点 4     小规模构造：小规模互质对 [10,100]（答案恰为 1，可手算）
#   点 5     中等规模随机：[1e3,1e4] 独立均匀随机（范围中间档）
#   点 6     中等规模构造：倍数关系 n=k*m（答案=较小数 m，检验整除早停）
#   点 7     大规模随机：[1e5,1e6] 独立均匀随机（接近上限）
#   点 8     大规模构造：贴上限 [2e6,3999999] 且公因数 nontrivial（答案十万级，m>n 顺序）
#   点 9     顶格层    ：全最大值且相等 3999999 3999999（答案 3999999，最大可能答案）
#   点 10    顶格层    ：相邻斐波那契数 3524578 2178309（辗转相除法迭代次数理论最坏结构，
#                        拉梅定理；两值互质 ⇒ 答案 1，m>n 顺序）
#
# ---------------------------------------------------------------------------
# 为什么"随机点"之外还配了构造点？（数据区分度说明）
# ---------------------------------------------------------------------------
#   两个 [1,4e6] 内随机整数互质的概率约 6/pi^2 ≈ 61%，纯随机数据里绝大多数答案
#   都是 1，一个"恒输出 1"的错误程序能蒙混过关。因此：
#     - 点 3/5/7 保留题面要求的"自然随机"（每档一个，如实记录其自然答案）；
#     - 点 4/6/8 采用受控构造，让"互质 / 倍数 / 大公因数"三类结构各有非平凡答案；
#     - 点 1/2/9/10 覆盖最小答案 1、样例、最大答案、辗转相除最坏结构。
#   互质（4/10）、倍数（6）、相等（1/9）、顶格构造（8/9/10）四类题面要求全覆盖。
#   输入顺序三种情况均覆盖：m<n（点 2）、m>n（点 8、10）、m=n（点 1、9）。
#
# ---------------------------------------------------------------------------
# 与任务书通用分层清单的对照（不适用/越界项如实说明，不强行凑数）
# ---------------------------------------------------------------------------
#   - "n=1 / n=2 的组数分层"：本题为**单组输入**（一个测试点一对 (m,n)），
#     不存在"数据组数"，该项针对多测题，不适用。
#   - "答案为 0 的极端"：m,n 为正整数，gcd 恒 >= 1，答案为 0 在数学上不可能；
#     改以"答案 1"（点 1/4/10）与"答案取最大可能值 3999999"（点 9）两端覆盖。
#   - "不允许 10 个点全是小随机数据"：点 5-10 覆盖 1e3~4e6 三个量级档 + 顶格构造，
#     满足。
#
# 随机性：每个随机点使用独立的 random.Random(2021 + 点号)，与调用顺序无关、
#         重新运行可**逐字节复现**。构造点（1/2/9/10）为确定性取值。
#
# 自检（文件末尾）：逐点断言 math.gcd 真值与 .out 精确一致、取值落在 1..3999999、
#   无两点重复、区分度（答案>1 与答案=1 均不少于 3 个点）。

from cyaron import *  # 引入CYaRon的库

import math
import random

MAXV = 3999999          # 题面上限：m, n < 4000000 ⇒ 最大合法值
_pts = []               # (点号, m, n, gcd, 层次)


def gen(i, m, n, layer, note):
    """生成一个测试点：写 problem{i}.in，调用 ../std 生成 problem{i}.out。"""
    assert 1 <= m <= MAXV and 1 <= n <= MAXV, "点 %d 取值越出题面范围" % i
    g = math.gcd(m, n)  # Python 大整数真值，用于自检
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(m, n)
    io.output_gen("../std")
    _pts.append((i, m, n, g, layer))
    print("problem%-2d [%s] m=%-8d n=%-8d gcd=%-8d -- %s" % (i, layer, m, n, g, note))


def rnd_pair(i, lo, hi):
    """在 [lo,hi] 内独立均匀随机取一对不同的数（自然随机，不做任何约束修饰）。"""
    rng = random.Random(2021 + i)
    a = rng.randint(lo, hi)
    b = rng.randint(lo, hi)
    while b == a:           # 相等情形已由点 1/9 覆盖，随机点保证两数不同
        b = rng.randint(lo, hi)
    return a, b


# ---------------- 点 1-2 边界层 ----------------
# 点 1：全最小值 + 相等，答案 1（最小可能答案；验证 m=n 时不得输出 0）
gen(1, 1, 1, "边界层", "全最小值且 m=n=1，答案 1（最小可能答案；m=n 不得输出 0）")

# 点 2：题面【输入样例】——题面唯一声明的特殊值，答案 2，且 m<n 顺序
gen(2, 4, 6, "边界层", "题面【输入样例】4 6，答案 2；m<n 顺序")

# ---------------- 点 3-4 小规模（可手算） ----------------
# 点 3：小规模自然随机 [2,100]，量级小到可手算核对
m3, n3 = rnd_pair(3, 2, 100)
gen(3, m3, n3, "小规模随机", "取值 [2,100] 独立均匀随机，量级小到可手算验证")

# 点 4：小规模构造·互质对（gcd 恰为 1，可手算）
rng4 = random.Random(2021 + 4)
while True:
    m4 = rng4.randint(10, 100)
    n4 = rng4.randint(10, 100)
    if m4 != n4 and math.gcd(m4, n4) == 1:
        break
gen(4, m4, n4, "小规模构造", "小规模互质对（答案 1，可手算）；覆盖'答案为 1'情形")

# ---------------- 点 5-6 中等规模 ----------------
# 点 5：中等规模自然随机 [1e3,1e4]
m5, n5 = rnd_pair(5, 1000, 10000)
gen(5, m5, n5, "中等规模随机", "取值 [1e3,1e4] 独立均匀随机，范围中间档")

# 点 6：中等规模构造·倍数关系 n = k*m（答案恰为较小数 m，检验整除早停）
rng6 = random.Random(2021 + 6)
m6 = rng6.randint(10000, 200000)
k6 = rng6.randint(2, 19)
n6 = m6 * k6
assert n6 <= MAXV
gen(6, m6, n6, "中等规模构造", "倍数关系 n=%d*m（答案=m=%d），检验整除早停" % (k6, m6))

# ---------------- 点 7-8 大规模 ----------------
# 点 7：大规模自然随机 [1e5,1e6]
m7, n7 = rnd_pair(7, 100000, 1000000)
gen(7, m7, n7, "大规模随机", "取值 [1e5,1e6] 独立均匀随机，接近上限前档")

# 点 8：贴上限构造·公因数 g ∈ [1e5,2e5]、倍率 ∈ [11,19]，保证两数均 ∈ [2e6,3999999]
rng8 = random.Random(2021 + 8)
while True:
    g8 = rng8.randint(100000, 200000)
    a8 = rng8.randint(11, 19)
    b8 = rng8.randint(11, 19)
    m8, n8 = g8 * a8, g8 * b8
    if a8 != b8 and math.gcd(a8, b8) == 1 \
       and 2000000 <= m8 <= MAXV and 2000000 <= n8 <= MAXV:
        break
if m8 < n8:                      # 固定为 m>n 顺序，与点 2 的 m<n 互补
    m8, n8 = n8, m8
gen(8, m8, n8, "大规模构造", "贴上限 [2e6,3999999]，公因数 g=%d，答案=%d，m>n 顺序" % (g8, g8))

# ---------------- 点 9-10 顶格层 ----------------
# 点 9：全最大值 + 相等 ⇒ 答案 = 3999999，题目允许的最大可能输出
gen(9, MAXV, MAXV, "顶格层", "全最大值且相等，答案 3999999（最大可能答案；m=n）")

# 点 10：相邻斐波那契数（F33=3524578, F32=2178309）——
#        辗转相除法迭代次数的理论最坏结构（拉梅定理），且两值互质 ⇒ 答案 1
gen(10, 3524578, 2178309, "顶格层",
    "相邻斐波那契数（辗转相除迭代次数最坏结构，拉梅定理），互质 ⇒ 答案 1；m>n")

# ---------------- 自检 ----------------
print("-" * 74)
assert len(_pts) == 10, "必须恰好 10 个测试点"
assert len({(m, n) for _, m, n, _, _ in _pts}) == 10, "存在重复的输入对"
for i, m, n, g, layer in _pts:
    assert 1 <= m <= MAXV and 1 <= n <= MAXV, "点 %d 越界" % i
    got = open("problem%d.out" % i, encoding="utf-8").read().strip()
    assert got == str(g), "点 %d：.out 为 %r，math.gcd 真值为 %d" % (i, got, g)
    assert g == math.gcd(m, n)
n_multi = sum(1 for p in _pts if p[3] > 1)   # 答案 nontrivial 的点
n_one = sum(1 for p in _pts if p[3] == 1)    # 答案为 1 的点
n_same = sum(1 for p in _pts if p[1] == p[2])
assert n_multi >= 3 and n_one >= 3 and n_same >= 2, "覆盖不足"
print("自检通过：10 点的 .out 与 Python math.gcd 真值逐一精确一致，取值全落在 1..%d" % MAXV)
print("区分度：答案>1 的点 %d 个、答案=1 的点 %d 个、m=n 的点 %d 个" % (n_multi, n_one, n_same))
print("层次分布：" + "、".join("%s(%d)" % (l, sum(1 for p in _pts if p[4] == l))
                              for l in ["边界层", "小规模随机", "小规模构造", "中等规模随机",
                                        "中等规模构造", "大规模随机", "大规模构造", "顶格层"]))
