// 一本通 2033《【例4.19】阶乘之和》— 标程（C++17，stdin -> stdout）
// 题号：ybt 2033 / 目标 ROJ 5035  |  限制：time 1000 ms，memory 65536 KB
//      （config.json 与官方页实测一致：时间限制 1000 ms，内存限制 65536 KB）
//
// 题意：输入 n，计算 S = 1! + 2! + 3! + ... + n! 的末 6 位（不含前导 0）。
//   样例：输入 10 -> 输出 37913（S(10) = 4037913，末 6 位 37913）。
// 数据范围（题面【提示】明文）：1 <= n <= 999999。
//   注意【题目描述】写的是 n <= 10^6，而【数据范围】给的是 n <= 999999；
//   本包以上限 999999 造顶格数据（同时满足两种口径），并把 10^6 作为越界探针
//   纳入对拍（见 work/stress.py），std 对该值同样给出正确结果 940313，无风险。
//
// 参考来源 URL（本轮均用 curl 实取页面正文与代码块核对后改写，非盲抄搜索摘要）：
//   [1] 官方题面页（样例 10 -> 37913、1000 ms / 65536 KB、1<=n<=999999）
//       http://ybt.ssoier.cn:8088/problem_show.php?pid=2033
//   [2] CSDN · 君义NOIP《信息学奥赛一本通 2033：【例4.19】阶乘之和》
//       同余定理：(a*b)%m = ((a%m)*(b%m))%m，(a+b)%m = ((a%m)+(b%m))%m；
//       核心代码：num = num*i%M; sum = (sum+num)%M;（M=1000000），O(n) 单重循环；
//       并指出双层循环 O(n^2) 在 n=10^6 时会超时
//       https://blog.csdn.net/lq1990717/article/details/121408809
//   [3] CSDN · 枪亡小白（bbbb8989）《2033：【例4.19】阶乘之和（信奥一本通）》
//       先求每个 f[i] = f[i-1]*i % N（N=1000000，f[1]=1），再累加 s = (s+f[i]) % N
//       https://blog.csdn.net/bbbb8989/article/details/127864033
//   [4] CSDN · 橙子教师（lvcheng0309）《信息学奥赛一本通（2033：【例4.19】阶乘之和）》
