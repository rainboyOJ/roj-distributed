//   [9] CSDN · Sicily 3913 题解（同题的不同 OJ 版本，模数同为 10^6）
//       明确指出：24! 之后末 6 位全为 0，故 n>=24 时答案恒为 940313 —— 用于本包
//       "饱和阈值"边界点（点 4/5）的构造依据
//       https://blog.csdn.net/weixin_33877092/article/details/86189409
//   [10] CSDN · 同余定理与阶乘取模（2033 题 O(n) 解法详解）——暴力 O(n^2) /
//       递推 O(n) / 预处理表 / 周期性剪枝四种解法对比，结论与 [2][6] 一致
//       https://blog.csdn.net/culh2177/article/details/108389431
//
// 来源结论核对（无冲突）：全部来源算法一致 —— 用同余定理把阶乘与求和都压在 mod 10^6 内，
//   借上一项递推：term_i = term_{i-1} * i % 10^6，sum_i = (sum_{i-1} + term_i) % 10^6，
//   单重循环 O(n) 通过；所有来源都强调"不能算完再取模"（会溢出）与"不能双层循环"（会超时）。
//   输出口径一致：输出末 6 位整数本身、不补前导 0（题面"不含前导0"），末尾无额外内容。
//   本题 1 <= n <= 999999 时答案集合为 23 个值，最小值 1（n=1），永不为 0，无前导 0 争议。
//   题面本身无歧义，未触发任务书的"停下报告"条件（n<=10^6 与 <=999999 的差异见上，已按更紧者造数据）。
//
// 本标程相对来源的改写点（逐条说明，便于复核）：
//   * 累加/累乘变量用 long long（来源 [2][5][6][8] 用 int）：形式上看 `term * i` 可能达到
//     10^6 * 10^6 = 10^12 > INT_MAX，但本题有一个关键事实 —— 25! 起末 6 位恒为 0
//     （24! = 620448401733239439360000 已含 10^6 因子，实算 24!%10^6 = 360000），
//     故 int 版实际遇到的中间积最大值仅 16640000（本机全值域实测扫描），并未溢出；
//     也就是说来源的 int 写法在本数据范围内「恰好安全」，但这一安全性依赖上述额外论证。
//     本标程改用 long long：乘积上界 10^12 < 2^63-1，安全性不依赖任何额外事实，零成本。
//     实证（本机 g++ -O2）：int 版与 long long 版在 n=1..999999 全值域输出逐字节一致
//     （见 work/stress.py [E] 节），即此选择不改变任何输入的判定结果。
//   * 输出用 printf("%lld\n")（来源 [2] 用 cout<<sum 无换行）：仓库语料惯例
//     （problems/1000/std.cpp 的 scanf/printf 风格）+ 行末换行更友好；roj 评测用 diff -b
//     忽略行尾空白，两种写法等价。
//   * 输入 scanf("%d", &n)，读不到（空文件）时安全 return 0。
//   * 复杂度 O(n)、额外空间 O(1)：n=999999 时约 10^6 次取模，实测 < 10 ms（见 gen-report.md 第五节）。
//     注：i >= 24 后 term 恒为 0（24! 含因子 10^6），其后每轮只做两次加法/取模，属空转但开销极小；
//     若想极致可加 `if (term == 0) break;`（结果不变），本标程保持定义直白不加此剪枝。
#include <cstdio>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;  // 无输入/非法输入：安全退出

    const long long MOD = 1000000LL;     // 末 6 位 = 对 10^6 取模
    long long term = 1;                  // term：当前项 i! mod 10^6
    long long sum = 0;                   // sum：1!+2!+...+i! mod 10^6
    for (int i = 1; i <= n; ++i) {
        term = term * i % MOD;           // 同余定理：i! % M = ((i-1)! % M * i) % M
        sum = (sum + term) % MOD;        // 同余定理：累加和同样随时取模
    }
    printf("%lld\n", sum);
    return 0;
}
