# ---- 独立真值 1：Python 任意精度整数（与 C 的定长整数无关，路径完全不同）----
#   n<=30 用 math.factorial 精确求和；
#   n>=31 用"模块化递推"独立复算一遍（Python 单遍，仍是与 std 不同的实现与语言）；
#   两者在重叠区（n=24..30）必须一致 —— 双路自证。
_ANS = {}


def exact_sum_mod(n):
    """精确求和后取末 6 位：sum_{k=1..n} k! （CPython 大整数，任意精度）。"""
    return sum(math.factorial(k) for k in range(1, n + 1)) % 1000000


def mod_recurrence_upto(nmax):
    """模块化递推一遍算出 n=1..nmax 全部答案（第三条独立实现：Python + 逐步取模）。"""
    out = [0] * (nmax + 1)
    term = 1
    s = 0
    for i in range(1, nmax + 1):
        term = term * i % 1000000
        s = (s + term) % 1000000
        out[i] = s
    return out


def build_truth():
    small = {n: exact_sum_mod(n) for n in range(1, 31)}
    full = mod_recurrence_upto(max(n for _, n, _, _ in CASES))
    for n in range(1, 31):
        assert small[n] == full[n], "真值两路不一致 n=%d: %d != %d" % (n, small[n], full[n])
    # 饱和定理断言：n>=24 起答案恒为常量（24! 起末 6 位只由 S(24) 决定）
    const = exact_sum_mod(24)  # 该常量应等于 940313
    assert math.factorial(24) % 1000000 == 360000, "24! % 10^6 应为 360000"
    assert math.factorial(25) % 1000000 == 0, "25! % 10^6 应为 0"
    assert full[24] != full[23], "n=23 与 n=24 的答案必须不同（饱和阈值的判别依据）"
    assert all(full[n] == const for n in range(24, len(full))), \
        "n>=24 的答案应恒为常量 %d" % const
    vals = sorted(set(full[1:]))
    assert len(vals) == 23 and 0 not in vals, "全值域应有 23 个互异非零答案，实得 %d 个" % len(vals)
    assert full[1] == 1, "n=1 答案应为 1（全值域最小值）"
    assert full[10] == 37913, "题面样例 n=10 应为 37913，实得 %d" % full[10]
    assert full[23] == 580313 and const == 940313, "饱和临界值应为 580313 / 常量 940313"
    print("真值自证：n=1..30 精确大整数 == 模块化递推；n>=24 恒为 %d；"
          "全值域 %d 个互异非零答案（min=%d, max=%d）" % (const, len(vals), vals[0], vals[-1]))
    return {n: full[n] for n in range(1, len(full))}   # 字典：n -> 答案


def truth(n):
    """返回 n 的独立真值（需先调用 build_truth() 填充 _ANS）。"""
    if not _ANS:
        _ANS.update(build_truth())
    return _ANS[n]


def gen_case(data_id, n, layer, note):
    io = IO(file_prefix="problem", data_id=data_id)   # problem{data_id}.in / .out
    io.input_writeln(n)                               # 单行输入 "n\n"
    io.output_gen("../std")                           # .out 由 std 生成
    print("problem%-2d: n=%-6d 期望答案=%-6d [%s] %s" % (data_id, n, _ANS[n], layer, note))


def self_check():
    """生成后立即审计：成对齐全、输入格式合规、std 输出与独立真值逐字节一致。"""
    bad = 0
    for data_id, n, _layer, _note in CASES:
        in_path, out_path = "problem%d.in" % data_id, "problem%d.out" % data_id
        try:
            raw_in = open(in_path, "r", encoding="utf-8").read()
            raw_out = open(out_path, "r", encoding="utf-8").read()
        except OSError as exc:
            print("MISSING pair for point %d: %s" % (data_id, exc))
            bad += 1
            continue
        if raw_in != "%d\n" % n:
            print("BAD INPUT problem%d.in: %r (expect %r)" % (data_id, raw_in, "%d\n" % n))
            bad += 1
        want = "%d\n" % _ANS[n]
        if raw_out != want:
            print("OUTPUT != TRUTH problem%d: got %r expect %r (n=%d)" % (data_id, raw_out, want, n))
            bad += 1
    # 题面样例逐字节核对（点 3）
    sample_out = open("problem3.out", encoding="utf-8").read()
    if sample_out != "37913\n":
        print("SAMPLE MISMATCH: problem3.out=%r expect '37913\\n'" % sample_out)
        bad += 1
    if bad:
        print("SELF-CHECK FAILED: %d issue(s)" % bad)
        raise SystemExit(1)
    print("SELF-CHECK OK: 10/10 pairs, inputs well-formed, outputs == 独立真值"
          "（大整数精确求和 + 模块化递推 双路），含题面样例 10 -> 37913\\n 逐字节比对")
    print("分层覆盖：边界 5 点（1/2/10/23/24） + 小规模随机 1 + 中等随机 1 + 大规模随机 1"
          " + 顶格 2（999998/999999），n 单调从 1 铺到 999999")


