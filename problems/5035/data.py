# 一本通 2033《【例4.19】阶乘之和》分层数据生成器（cyaron）
# 用法：g++ -O2 -std=c++17 std.cpp -o std && mkdir -p data && cd data && python3 ../data.py
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py、.ybt-import/staging/2026/data.py
#
# 题意：输入 n，计算 S = 1! + 2! + 3! + ... + n! 的末 6 位（不含前导 0）。
#   样例：n=10 -> 37913（S(10) = 4037913）。
# 数据范围（题面【提示】明文）：1 <= n <= 999999。
#   【题目描述】写的是 n <= 10^6，【数据范围】给的是 n <= 999999 —— 本包按**更紧者**
#   999999 造顶格点（同时满足两种口径会自然满足），并把 10^6 作为越界探针放进
#   work/stress.py 观察（std 在该值上同样输出 940313，无风险）。
# 限制：time 1000 ms / memory 65536 KB（config.json 与官方 OJ 页一致）。
#
# ---------------------------------------------------------------------------
# 本题的两条独立"难度轴"（决定了分层怎么切）
# ---------------------------------------------------------------------------
#   轴 A（数值正确性）：答案 = S(n) mod 10^6，其关于 n 的**函数形状**完全由 n=1..24 决定：
#       24! 已含因子 10^6（24! % 10^6 = 360000），25! % 10^6 = 0，此后 term 恒为 0，
#       故 n >= 25 答案恒为 940313；又恰好 S(24) % 10^6 = 940313，于是
#       **n >= 24 全部输出同一个常数 940313**，n=1..23 给出另 23 个互不相同的值
#       （全值域共 23 个不同答案；最小值 1（n=1），**永不为 0**，故"不含前导 0"无歧义）。
#       ⇒ 只有 n < 24 的点能区分"累加漏项 / 阈值写错 / 少算最后一项"这类数值错误，
#         它们必须作为边界层被**精确覆盖**。
#   轴 B（卡常/性能）：n 越大循环越长；O(n) 递推（正解）在 n=999999 只需 ~10^6 次运算，
#       而按定义的双层循环 O(n^2) 需要 ~5*10^11 次内层运算（来源 [7] 实测超时），
#       故**只有顶格点**能判掉二次复杂度实现（决定区分度的是点 10）。
#   分层因此是"边界密集 + 大跨度随机 + 顶格卡常"三段式（见下表）。
#
# ---- 分层表（10 组；单组输入题：一个测试点 = 一个 n）----
#   点 1 ｜边界层｜n=1       全最小值；答案是全值域**最小值 1**（"答案为 1 的极端"）；
#                             仅 1 轮循环，检验 term/sum 初值与"漏掉 1!"（漏了会输出 0）。
#   点 2 ｜边界层｜n=2       最小非平凡值；答案 3=1!+2!（只算 2! 会得 2，只算 n! 会得 2；
#                             与点 1 相邻差分可抓"只加最后一项"与"累加起点错 1"）。
#   点 3 ｜边界层（题面声明的特殊值）｜n=10  【输入样例】原样；输出必须**逐字节**等于
#                             【输出样例】"37913\n"（S(10)=4037913）。
#   点 1 ｜边界层｜n=1       全最小值；答案是全值域**最小值 1**（"答案为 1 的极端"）；
#                             仅 1 轮循环，检验 term/sum 初值与"漏掉 1!"（漏了会输出 0）。
#   点 2 ｜边界层｜n=2       最小非平凡值；答案 3=1!+2!（只算 n! 会得 2；与点 1 相邻差分
#                             可抓"只加最后一项"与"累加起点错 1"）。
#   点 3 ｜边界层（题面声明的特殊值）｜n=10  【输入样例】原样；输出必须**逐字节**等于
#                             【输出样例】"37913\n"（S(10)=4037913）。
#   点 4 ｜小规模随机｜n=16  未饱和区随机值（种子 2033，[3,22]），答案 524313，
#                             S(16)=22324392524313 可手算核对。
#   点 5 ｜边界层（饱和临界·饱和前最后一个值）｜n=23  答案 580313（≠ 940313）：
#                             它是"还能看出非饱和"的最大 n；专门判掉"提前剪枝到 24 /
#                             把阈值写成 i<23 / 直接对 n>=24 特判"等错误实现。
#   点 6 ｜边界层（饱和阈值）｜n=24  24! % 10^6 = 360000 ≠ 0 而 25! % 10^6 = 0，
#                             故 n=24 是答案**首次**变成常量 940313 的点（阈值 off-by-one
#                             判别点：把饱和写成 i>=24 continue 的实现会在点 5 挂掉）。
#   点 7 ｜中等规模随机｜n=17677  中段规模随机（种子 2033，[301,100000]）；循环量万级。
#   点 8 ｜大规模随机（接近上限）｜n=826876  近上限随机（种子 2033，[800000,999998]）。
#   点 9 ｜顶格层（上限邻域）｜n=999998  题面上限 - 1：与点 10 相邻，判"上限写死成
#                             999998 / n<999999"这类 off-by-one。
#   点 10｜顶格层（题面上限·最坏卡常点）｜n=999999  题面【数据范围】上限、也是
#                             全值域最大循环量：O(n^2) 双层实现在此点必挂（轴 B 的唯一
#                             判决点），同时承担边界清单的"全最大值"。
#
#   层次计数：边界 5 点（n=1 / 2 / 23 / 24 + 题面特殊值 n=10）+ 小规模随机 1（n=16）
#   + 中等规模随机 1（n=17677）+ 大规模随机 1（n=826876）+ 顶格 2（999998 / 999999）= 10。
#   **不是** 10 个小随机点：n 从 1 严格单调铺到 999999（跨 6 个数量级），无重复、无空转点。
#   对任务书"点 1-2 边界 / 3-4 小规模 / 5-6 中等 / 7-8 大规模 / 9-10 顶格"的**顺延说明**
#   （与 staging/2030 的处置一致）：本题边界清单里有 5 个互斥的必需取值（n=1 最小值、n=2、
#   题面特殊值 n=10、以及本题特有的饱和拐点 n=23 / n=24），2 个点装不下；由于要求规模
#   单调递增，边界层拆成**前后两段**——点 1-3 取最小端的三项（1/2/10），点 5-6 取
#   数值函数拐点（23/24，两者都把随机段夹在中间），小/中/大随机与顶格层顺延其后。
#   清单项"全最大值"落在点 10，"答案为 1 的极端"落在点 1（全值域最小值 1），
#   "答案为 0"在本题**不可能出现**（每项 i! ≥ 1，S(n) ≥ 1，全值域 23 个互异答案无一为 0）。
#
# ---- 精度口径 ----
#   全程整数运算、无浮点：不存在 %g / printf 尾零那类跨平台文本差异；输出是精确十进制
#   整数 + 单个换行（不含前导 0 —— 本题答案永不为 0 且默认 %d/%lld 不补零），
#   macOS / glibc / Windows 逐字节一致，无需"平台安全过滤"。
#   点 3 的输出与题面【输出样例】逐字节比对（"37913\n"）。

