#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2064《【例2.1】交换值》数据生成器（cyaron）
#
# 题意：输入两个正整数 a b，交换二者的值后输出（输出 b a）。题面样例 2 3 -> 3 2。
# 题面【未声明数据范围】（官方 OJ 页也只有 1000ms/65536KB 限制，无取值区间），
# 按有符号 int（32 位）的自然上限自定工作范围：1 <= a, b <= 2147483647（2^31-1）。
# std 使用 long long 读写，工作范围内绝不会溢出。
#
# 本题为单组输入（一个测试点即一对 (a, b)），不存在"多组数据的组数分层"，
# 故分层按 a、b 的量级与极端结构铺开：
#   点 1-2  边界层：全最小值 / 全最大值（且两数相等，交换前后不可区分）
#   点 3-4  小规模随机：可手算验证的量级
#   点 5-6  中等规模随机：范围中间档
#   点 7-8  大规模随机：接近自定上限
#   点 9-10 顶格层：取自定上限 + 极端不对称 / 相邻逆序结构

from cyaron import *  # 引入CYaRon的库

import random
random.seed(2064)  # 固定种子，便于复现

MAX = 2147483647  # 自定工作范围上限（2^31-1；题面未声明范围，等价于 int 上限）


def gen_case(i, a, b, note):
    """写出第 i 组：输入 'a b'，输出由 std 生成的交换后结果 'b a'。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(a, b)
    io.output_gen("../std")
    print("problem%d: a=%d b=%d (期望输出 %d %d) -- %s" % (i, a, b, b, a, note))


# ---- 点 1-2：边界层 ----
# 点 1：全最小值 a=b=1，且两数相等（交换前后不可区分）；答案含 1 的极端。
gen_case(1, 1, 1,
         "边界层：a=b=1 全最小值 + 相等值（交换不可见），答案为 1 的极端")

# 点 2：全最大值 a=b=2^31-1（自定上限顶格），且两数相等。
gen_case(2, MAX, MAX,
         "边界层：a=b=2^31-1 全最大值（自定上限） + 相等值（交换不可见）")

# ---- 点 3-4：小规模随机（量级小，可手工验证） ----
# 点 3：a,b ∈ [1,100]
gen_case(3, random.randint(1, 100), random.randint(1, 100),
         "小规模随机：a,b∈[1,100]，可手算核对")

# 点 4：a,b ∈ [1,999]
gen_case(4, random.randint(1, 999), random.randint(1, 999),
         "小规模随机：a,b∈[1,999]，可手算核对")

# ---- 点 5-6：中等规模随机（范围中间档） ----
# 点 5：a,b ∈ [1,10^6]
gen_case(5, random.randint(1, 1000000), random.randint(1, 1000000),
         "中等规模随机：a,b∈[1,1e6]")

# 点 6：a,b ∈ [10^5,10^7]
gen_case(6, random.randint(100000, 10000000), random.randint(100000, 10000000),
         "中等规模随机：a,b∈[1e5,1e7]")

# ---- 点 7-8：大规模随机（接近自定上限） ----
# 点 7：a,b 在 [1,2^31-1] 全域随机
gen_case(7, random.randint(1, MAX), random.randint(1, MAX),
         "大规模随机：a,b 在 [1,2^31-1] 全域随机")

# 点 8：a,b ∈ [2^30,2^31-1]，贴近上限
gen_case(8, random.randint(MAX // 2, MAX), random.randint(MAX // 2, MAX),
         "大规模随机：a,b∈[2^30,2^31-1]，贴近上限")

# ---- 点 9-10：顶格层（自定上限 + 极端结构） ----
# 点 9：a=上限、b=最小值——极端不对称（最大值与最小值互换）
gen_case(9, MAX, 1,
         "顶格层：a=2^31-1（上限）、b=1（最小值）——极端不对称")

# 点 10：a=上限、b=上限-1——相邻逆序（a>b），防 ±1 类错误
gen_case(10, MAX, MAX - 1,
         "顶格层：a=2^31-1，b=2^31-2 相邻逆序（a>b），验证不丢 1")
