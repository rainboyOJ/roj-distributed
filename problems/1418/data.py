#!/usr/bin/env python3
# -*- coding: utf-8 -*-

# 一本通 1418《猴子选大王》数据生成器
#
# 题意：N 只猴子围成一圈（编号 1..N），每只猴子对应一个报数次数 Xi（1 ≤ Xi ≤ 100）。
#       从第 1 号开始报数，数到当前起始猴子对应的 Xi 的那只猴子出队，再从下一位继续
#       从 1 报数，如此循环直到只剩下一只，输出其编号。
# 数据范围（来源：https://blog.csdn.net/ACMer_QJ/article/details/113884787）：
#       N ≤ 1000000；每个 Xi ≤ 100。
#
# 分层设计（10 组）：
#   点 1    边界层：题面样例（N=5, X=1 2 3 4 5），答案 2
#   点 2    边界层：N=1，答案 1（唯一猴子直接当选）
#   点 3    边界层：N=2，覆盖“圈内只剩一只”的临界淘汰
#   点 4    小规模：N=10，X 随机，可用 std 独立验证量级
#   点 5    小规模：N=100，X 全为 1（每轮必淘汰当前起始猴子）
#   点 6    小规模：N=100，X 全为 100（每轮数满一圈，报数次数最大）
#   点 7    中等规模：N=10000，X 随机 [1,100]
#   点 8    中等规模：N=100000，X 随机 [1,100]
#   点 9    大规模：N=1000000，X 全为 1（最坏报数次数 = N 量级）
#   点 10   顶格层：N=1000000，X 全为 100（报数次数顶格 ≈ 1e8，卡时间上限）

from cyaron import IO  # 引入CYaRon的库
import random

random.seed(1418)  # 固定种子，便于复现

MAXN = 1000000
XMAX = 100


def write_case(i, n, xs, note):
    """写出第 i 组：第一行 N，第二行 N 个 Xi。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(n)
    io.input_writeln(xs)
    io.output_gen("../std")
    with open("problem%d.out" % i) as f:
        ans = f.read().strip()
    print("problem%-2d: n=%-7d ans=%s -- %s" % (i, n, ans, note))


def rand_xs(n, lo=1, hi=XMAX):
    return [random.randint(lo, hi) for _ in range(n)]


# ---- 点 1：边界层（题面样例），答案 2 ----
write_case(1, 5, [1, 2, 3, 4, 5],
           "边界层：题面样例 N=5, X=1 2 3 4 5，答案 2")

# ---- 点 2：边界层 N=1，唯一猴子直接当选 ----
write_case(2, 1, [1], "边界层：N=1，答案 1")

# ---- 点 3：边界层 N=2，临界淘汰一轮 ----
write_case(3, 2, [2, 2], "边界层：N=2，只剩一只前的临界淘汰")

# ---- 点 4：小规模随机，N=10 ----
write_case(4, 10, rand_xs(10), "小规模：N=10 随机 X[1,100]")

# ---- 点 5：小规模，X 全为 1（每轮必淘汰当前起始猴子） ----
write_case(5, 100, [1] * 100, "小规模：N=100，X 全为 1（每轮淘汰起始猴子）")

# ---- 点 6：小规模，X 全为 100（每轮数满一圈） ----
write_case(6, 100, [100] * 100, "小规模：N=100，X 全为 100（每轮数满一圈）")

# ---- 点 7：中等规模随机，N=10000 ----
write_case(7, 10000, rand_xs(10000), "中等规模：N=10000 随机 X[1,100]")

# ---- 点 8：中等规模随机，N=100000 ----
write_case(8, 100000, rand_xs(100000), "中等规模：N=100000 随机 X[1,100]")

# ---- 点 9：大规模，X 全为 1 ----
write_case(9, MAXN, [1] * MAXN, "大规模：N=1000000，X 全为 1（最坏报数次数 N 量级）")

# ---- 点 10：顶格层，N 与 X 均顶格 ----
# N=1e6，X 全为 100：每轮数满一圈，总报数次数 ≈ (N-1)*100 ≈ 1e8，卡 500ms 上限。
write_case(10, MAXN, [100] * MAXN,
           "顶格层：N=1000000，X 全为 100（报数次数顶格 ≈1e8，卡时间上限）")
