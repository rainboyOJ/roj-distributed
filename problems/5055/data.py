#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2053《【例3.3】三个数》分层数据生成器（cyaron，目标 ROJ 题号 5055）
# 参考仓库惯例：problems/1000/data.py、problems/5006/data.py；自定范围口径参考
# 同章同批 .ybt-import/staging/2064（交换 a、b 的值：同样自定 int32 全域）。
#
# 题意：输入一行三个整数，按从大到小的顺序输出（数与数之间一个空格）。
#       题面样例：`3 2 1` -> `3 2 1`。
#       本题是**单组输入**（一个测试点 = 一个三元组），无多组数据、无测试组数 T。
#
# 数据范围（题面【未声明】，本生成器自定并如实记录）：
#   题面与官方 OJ 页（http://ybt.ssoier.cn:8088/problem_show.php?pid=2053，
#   本轮已实抓核对：页面只有【题目描述】【输入】【输出】【输入样例】【输出样例】五节，
#   无【提示】/【数据规模】节）均未给出取值范围。故取：
#       -2147483648 <= a, b, c <= 2147483647     （有符号 32 位整数全域）
#   依据与安全性：① 题面只写「输入三个整数」，未限定为正；② 本题是纯比较/输出，
#   **不产生任何算术中间量**（无加减乘除），因此 int32 全域内所有「按 int 读写」的
#   官方题解都不会溢出、不会被判错 —— 全域恰好是 int 解仍然正确的最大范围，
#   取全域对 int 解最公平；③ 与同章同批 staging/2064 取到 2^31-1 的口径一致。
#
# 分层设计（10 个测试点；单组输入题的"规模"体现为数值量级 + 大小关系结构，
# 故按 域边界 -> 小 -> 中 -> 大 -> 顶格 铺开，并把 std 的 6 个条件分支显式全覆盖）：
#   点 1     边界层：三元全取域最小值 -2147483648（域下界；三重并列；分支 1）
#   点 2     边界层：三元全取域最大值 2147483647（域上界顶格；三重并列；分支 1）
#   点 3     小规模：题面【输入样例】3 2 1（题面声明的特殊值，逐字符可核对；
#             降序已序 = 输出即输入的最快路径；分支 1）
#   点 4     小规模：-1 0 1（最小量级混合符号；升序 = 对降序输出而言的完全逆序输入；
#             答案为 `1 0 -1`，覆盖「答案含 0 与 1 的极端」；分支 6）
#   点 5     中等规模随机：三互异随机值 ∈ [-10^3, 10^3]，按 c>a>=b 排列（分支 3）
#   点 6     中等规模随机（并列）：b>a=c 的两数并列结构，值 ∈ [-10^6, 10^6]（分支 4）
#   点 7     大规模随机：三互异随机值 ∈ [-10^7, 10^7]，按 b>c>a 排列（分支 5）
#   点 8     大规模随机（并列）：b=c 的两数并列结构，全域量级 ∈ [-10^9, 10^9]（分支 1 或 5）
#   点 9     顶格层：2147483647 -2147483648 2147483647 —— 域两极混排 + 大值两数并列
#             （a=c；分支 2）
#   点 10    顶格层：-2147483648 -2147483647 2147483647 —— 域最小值/次小值/最大值各一，
#             最极端量级跨度的完全逆序输入（分支 6）
#
# 结构覆盖：三重并列（点 1、2）、两数并列 a=c（点 6、9）、两数并列 b=c（点 8）、
#           三互异（点 5、7）、降序已序（点 3）、升序/完全逆序（点 4、10）均出现。
# 分支覆盖自检：std 的 if 嵌套共 6 个叶子分支，本文件末尾用与 std 同构的判定逻辑
# 复算 10 个点的分支号，assert 6 个分支全部出现（见文件尾部 assert）。

from cyaron import *  # 引入CYaRon的库

import random

INT_MIN = -2147483648  # 自定工作范围下界（int32 全域）
INT_MAX = 2147483647   # 自定工作范围上界（int32 全域）


def branch_id(a, b, c):
    """与 std.cpp 的 if 嵌套同构的分支编号（1..6），用于覆盖自检。"""
    if a >= b:
        if b >= c:
            return 1        # a >= b >= c
        if a >= c:
            return 2        # a >= c > b
        return 3            # c > a >= b
    if a >= c:
        return 4            # b > a >= c
    if b >= c:
        return 5            # b >= c > a
    return 6                # c > b > a


def gen(i, a, b, c, note):
    """写出第 i 组：输入 a b c，输出由 std 生成的降序结果。"""
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_writeln(a, b, c)
    io.output_gen("../std")
    print("problem%d: %d %d %d  (branch %d) -- %s"
          % (i, a, b, c, branch_id(a, b, c), note))


def three_distinct(rng, lo, hi):
    """取三个互异随机值，返回升序列表 [x0 < x1 < x2]（极小概率重抽保证互异）。"""
    while True:
        v = sorted([rng.randint(lo, hi) for _ in range(3)])
        if v[0] < v[1] < v[2]:
            return v


# ---- 点 1-2：边界层（域下界全等 / 域上界全等）----
gen(1, INT_MIN, INT_MIN, INT_MIN,
    "边界层：三元全取域最小值 -2147483648，三重并列，答案=输入（域下界）")

gen(2, INT_MAX, INT_MAX, INT_MAX,
    "边界层：三元全取域最大值 2147483647，三重并列，答案=输入（域上界顶格）")

# ---- 点 3-4：小规模（题面样例 + 最小量级混合符号的完全逆序）----
gen(3, 3, 2, 1,
    "小规模：题面【输入样例】3 2 1（题面声明的特殊值；降序已序，最快路径）")

gen(4, -1, 0, 1,
    "小规模：最小量级混合符号 -1 0 1，升序=完全逆序；答案为 `1 0 -1`（含 0/1 极端）")

# ---- 点 5-6：中等规模随机（范围中间档；点 6 含两数并列结构）----
rng5 = random.Random(2053 + 5)  # 每点独立种子：结果与生成顺序无关、可逐字节复现
# 三互异随机值升序 [x0<x1<x2] 后按 c>a>=b 重排 => std 走分支 3
v5 = three_distinct(rng5, -1000, 1000)
gen(5, v5[1], v5[0], v5[2],
    "中等规模随机：三互异值 ∈ [-10^3,10^3]，按 c>a>=b 排列")

rng6 = random.Random(2053 + 6)
x6 = rng6.randint(-1000000, 1000000)  # b（最大）
y6 = rng6.randint(-1000000, 1000000)  # a = c（并列）
while y6 >= x6:                       # 保证 b>a=c，走分支 4
    x6 = rng6.randint(-1000000, 1000000)
    y6 = rng6.randint(-1000000, 1000000)
gen(6, y6, x6, y6,
    "中等规模随机（并列结构）：b>a=c，值 ∈ [-10^6,10^6]，两数并列")

# ---- 点 7-8：大规模随机（接近上限 / 全域量级并列）----
rng7 = random.Random(2053 + 7)
# 三互异随机值升序 [x0<x1<x2] 后按 b>c>a 重排 => std 走分支 5
v7 = three_distinct(rng7, -10000000, 10000000)
gen(7, v7[0], v7[2], v7[1],
    "大规模随机：三互异值 ∈ [-10^7,10^7]，按 b>c>a 排列")

rng8 = random.Random(2053 + 8)
t8 = rng8.randint(-1000000000, 1000000000)  # b = c（并列）
a8 = rng8.randint(-1000000000, 1000000000)  # a（与并列值不同）
while a8 == t8:
    a8 = rng8.randint(-1000000000, 1000000000)
gen(8, a8, t8, t8,
    "大规模随机（并列结构）：b=c，全域量级 ∈ [-10^9,10^9]，两数并列")

# ---- 点 9-10：顶格层（域两极混排 + 域两极同现）----
gen(9, INT_MAX, INT_MIN, INT_MAX,
    "顶格层：域两极混排 + 大值两数并列（a=c=2147483647，b=-2147483648）")

gen(10, INT_MIN, INT_MIN + 1, INT_MAX,
    "顶格层：域最小值、次小值、域最大值各一，最极端量级跨度的完全逆序输入")

# ---------------- 自检 ----------------
pts = [(INT_MIN, INT_MIN, INT_MIN), (INT_MAX, INT_MAX, INT_MAX), (3, 2, 1), (-1, 0, 1),
       (v5[1], v5[0], v5[2]), (y6, x6, y6), (v7[0], v7[2], v7[1]), (a8, t8, t8),
       (INT_MAX, INT_MIN, INT_MAX), (INT_MIN, INT_MIN + 1, INT_MAX)]

seen = {branch_id(*p) for p in pts}
assert seen == {1, 2, 3, 4, 5, 6}, "std 的 6 个分支未被数据全覆盖：%s" % sorted(seen)

# 结构覆盖自检
assert branch_id(INT_MIN, INT_MIN, INT_MIN) == 1, "点 1 应为三重并列"
assert branch_id(INT_MAX, INT_MAX, INT_MAX) == 1, "点 2 应为三重并列"
assert branch_id(y6, x6, y6) == 4, "点 6 应为两数并列 a=c（且 b 最大）"
assert branch_id(INT_MAX, INT_MIN, INT_MAX) == 2, "点 9 应为两数并列 a=c（大值并列）"
assert branch_id(-1, 0, 1) == 6, "点 4 应为完全逆序（分支 6）"
assert branch_id(v7[0], v7[2], v7[1]) == 5, "点 7 应为分支 5"
# 点 8 的并列结构自检：b=c 为并列值；若 a 最大走分支 1，否则 b 最大走分支 5
assert branch_id(a8, t8, t8) in (1, 5), "点 8 应为 a>=b>=c 或 b>=c>a"

# 越界自检：10 点全部落在自定范围 [INT_MIN, INT_MAX] 内
for (a, b, c) in pts:
    for x in (a, b, c):
        assert INT_MIN <= x <= INT_MAX, "值 %d 越出自定范围" % x
# 点 8 的并列结构自检
assert (a8, t8, t8)[1] == (a8, t8, t8)[2] and a8 != t8, "点 8 应为 b=c 两数并列"

print("自检通过：6 个分支全覆盖 %s；三重并列/两数并列(a=c,b=c)/三互异/降序已序/升序逆序结构均出现"
      % sorted(seen))
