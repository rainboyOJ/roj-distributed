// 一本通 2053《【例3.3】三个数》标程（目标 ROJ 题号 5055）
// ---------------------------------------------------------------------------
// 题意：输入三个整数，按从大到小的顺序输出。
//   输入：一行三个整数（题面未声明取值范围，本包自定工作范围见下）。
//   输出：一行三个整数，从大到小，数与数之间以一个空格分隔。
//   样例：输入 `3 2 1` -> 输出 `3 2 1`。
//   （题意与输出格式唯一确定：六种排列各有确定的输出，不存在多解/歧义。）
//
// 输入范围（题面【未声明】，按仓库惯例自定并如实记录，见 gen-report.md）：
//   -2147483648 <= a, b, c <= 2147483647   （即有符号 32 位整数全域）
//   依据：题面只写「输入三个整数」；官方 OJ 页
//   http://ybt.ssoier.cn:8088/problem_show.php?pid=2053 同样无【提示】/【数据规模】
//   一节（本轮已实抓核对，页面只有【题目描述】【输入】【输出】【输入样例】【输出样例】）。
//   取 int32 全域与同章同批 staging/2064《交换 a、b 的值》的处置口径一致
//   （那里同样取到 2^31-1）。排序三数不产生算术中间量，故全域内 int 写法亦安全。
//
// 做法：读入 a、b、c，用 if 嵌套把「三者的大小关系」分成 6 种互斥情形
//       （来源 [1] 解法 1 的判定结构），每种情形把结果写进 hi/mid/lo 三元组，
//       最后**只在一处**统一 printf 输出 —— 这样输出格式不存在「某个分支
//       多打空格/漏换行」的不对称风险。三数比较不涉及算术，不存在溢出/精度问题；
//       复杂度 O(1)。
//       本文件为本包改写实现（scanf/printf 风格参考 problems/1000/std.cpp），
//       只保留来源的思路与分支语义，未逐字照抄。
// ---------------------------------------------------------------------------
// 参考来源 URL（本轮均以 curl 实取正文核对，非盲抄）：
//   [1] https://blog.csdn.net/lq1990717/article/details/120730862
//       《信息学奥赛一本通 2053：【例3.3】三个数》（君义NOIP）。
//       解法 1「if 语句嵌套」= 本标程采用的路线（a>=b 时再分 b>=c / c>b，
//       再各自细分 a 与 c 的大小），本轮实测其 6 个叶子分支输出全部正确。
//       解法 2「if…else if 六分支」与该文思路说明一致，但**其分支 4 的代码
//       有实际错误**（条件 `b>=c && c>=a` 却输出 `a c b`，正确应为 `b c a`）：
//       本包实际编译运行该文原文，输入 `1 3 2` 得 `1 2 3`（错，应为 `3 2 1`），
//       在 {-3..3}^3 全域 343 组里错 56 组，已弃用其代码（见 gen-report.md 风险点 2）。
//   [2] https://blog.csdn.net/tflstjs/article/details/119881887
//       《一本通 2053：【例3.3】三个数》——三次 `if(...>...) swap(...)` 升序整理后
//       反序输出 `cout << c << " " << b << " " << a;`，结论与降序语义一致（交叉印证）。
//   [3] https://blog.csdn.net/2301_79128218/article/details/132163910
//       《信息学奥赛一本通 2053：【例3.3】三个数》——`if(a<=b) swap(a,b); if(a<=c) swap(a,c);
//       if(b<=c) swap(b,c);` 后直接输出 a b c，同为降序语义（交叉印证）。
//   [4] https://blog.csdn.net/weixin_70576261/article/details/161598421
//       《【三个数】信息学奥赛一本通C语言解法（题号2053）》——C 语言版三次比较交换
//       （严格 `>` 版），最终 `printf("%d %d %d",c,b,a)`，同为降序语义（交叉印证）。
//   [5] 官方题面（核对题意/格式/限制）：
//       http://ybt.ssoier.cn:8088/problem_show.php?pid=2053
//       本轮实抓：时间限制 1000 ms、内存限制 65536 KB、样例 `3 2 1`->`3 2 1`。
//       各来源在算法结论上无冲突（均为三数降序输出）；唯一冲突是来源 [1] 解法 2
//       的代码笔误，已按题面语义取正确输出，未触发「停下报告」条件。
