#include <cstdio>

int main() {
    long long a, b, c;
    if (scanf("%lld %lld %lld", &a, &b, &c) != 3) return 0;  // 读满三个整数

    long long hi, mid, lo;  // 降序三元组 hi >= mid >= lo

    if (a >= b) {
        if (b >= c) {            // a >= b >= c
            hi = a; mid = b; lo = c;
        } else if (a >= c) {     // a >= c > b
            hi = a; mid = c; lo = b;
        } else {                 // c > a >= b
            hi = c; mid = a; lo = b;
        }
    } else {                     // a < b
        if (a >= c) {            // b > a >= c
            hi = b; mid = a; lo = c;
        } else if (b >= c) {     // b >= c > a
            hi = b; mid = c; lo = a;
        } else {                 // c > b > a
            hi = c; mid = b; lo = a;
        }
    }

    printf("%lld %lld %lld\n", hi, mid, lo);
    return 0;
}
