#!/usr/bin/env python
# -*- coding: utf-8 -*-

# 一本通 2066《【例2.3】买图书》数据生成器
#
# 题面：已知小明有 n 元，他买了一本书，这本书原价为 m 元，现在打 8 折出售。
#       求小明还剩多少钱（保留 2 位小数）。
# 输入：一行两个数 n m（小明的钱、书原价）。输出：n - m*0.8，保留 2 位小数。
#
# 数据范围说明：
#   题面与官方 OJ 页面（http://ybt.ssoier.cn:8088/problem_show.php?pid=2066）
#   均【未声明】n、m 的取值范围与类型。参照同批次 2068/2064 的处置口径
#   （题面缺范围时自定工作范围并在报告中如实记录），本生成器约定：
#       0 <= n, m <= 10^6（整数），且 n >= 0.8*m（买书后手中钱不为负）
#   - 取整数：题面样例为整数、全部网络题解均按整数/浮点直接读入，原题数据域大概率为整数；
#     若真含小数，std 用 double 读入亦兼容，但自产数据不引入小数，避免超出原题数据域。
#   - 保证 n >= 0.8*m：题面语义是"买了书还剩钱"，剪掉"钱不够"这一题面未定义的边界，
#     不让普通公式解（不判负）在本数据集上吃亏。
#
# 分层设计（单组输入题目：一个测试点即一对 (n, m)，规模=数值量级）：
#   点 1-2   边界层：全最小值 0 0（答案 0）/ 答案为 1 的极端（81 100）
#   点 3-4   小规模定点：题面【输入样例】100 100（题面声明的特殊值）/
#                        答案恰为 0 的 8 折折点 80 100（对拍暴露的 -0.00 风险回归用例）
#   点 5-6   小规模随机：可手算验证的量级
#   点 7     中等规模随机：范围中间档
#   点 8     大规模随机：贴近自定上限
#   点 9-10  顶格层：极端权值构造（全最大 n=m=10^6 / 答案最大 n=10^6, m=0）
from cyaron import *  # 引入CYaRon的库

import random

random.seed(2066)  # 固定种子，便于复现

CAP = 1000000  # 自定工作范围上限（题面未声明）


def gen_case(i, n, m, note):
    """写出第 i 组输入 n m，并调用 std 生成 .out。"""
    assert 0 <= n <= CAP and 0 <= m <= CAP, "超出自定工作范围"
    assert n * 10 >= m * 8, "不满足 n >= 0.8*m（买书后钱不为负）"
    io = IO(file_prefix="problem", data_id=i)  # problem{i}.in / problem{i}.out
    io.input_write(n, m)
    io.output_gen("../std")
    print("problem%-2d: n=%-7d m=%-7d 期望=%.2f -- %s" % (i, n, m, n - m * 0.8, note))


def rand_pair(n_lo, n_hi, m_hi):
    """随机 (n, m)：n 取自 [n_lo, n_hi]，m 取自 [1, min(m_hi, floor(5n/4))]，保证 n >= 0.8m。"""
    n = random.randint(n_lo, n_hi)
    m_cap = min(m_hi, n * 5 // 4)
    m = random.randint(1, max(1, m_cap))
    return n, m


# ---- 点 1-2：边界层 ----
# 点 1：全最小值 n=m=0（题面未声明下界，取 0），答案恰为 0；
#       同时回归验证 std 的零附近归一化（不得输出 -0.00）。
gen_case(1, 0, 0, "边界层：全最小值 n=m=0，答案为 0 的极端（-0.00 回归）")

# 点 2：答案为 1 的极端——n - 0.8*m 恰为 1 元（0.8*100=80，n=81），可手算。
gen_case(2, 81, 100, "边界层：答案为 1 的极端（81-80=1）")

# ---- 点 3-4：小规模定点（量级小，可手算验证） ----
# 点 3：题面【输入样例】100 100 -> 20.00（题面声明的特殊值，必须出现在数据里）。
gen_case(3, 100, 100, "小规模定点：题面样例 100 100 -> 20.00（题面声明特殊值）")

# 点 4：答案恰为 0 的 8 折折点（n = 0.8*m，输入非全零），可手算；
#       浮点舍入会使 n - m*0.8 得到 ±4e-15，是 -0.00 缺陷的关键回归用例。
gen_case(4, 80, 100, "小规模定点：8 折折点 80 100 -> 0.00（输入非零且答案为 0）")

# ---- 点 5-6：小规模随机（可手算验证量级） ----
n, m = rand_pair(1, 200, 200)
gen_case(5, n, m, "小规模随机：n∈[1,200]，m∈[1,min(200,1.25n)]，可手算核对")

n, m = rand_pair(1, 2000, 2000)
gen_case(6, n, m, "小规模随机：n∈[1,2000]，m∈[1,min(2000,1.25n)]，可手算核对")

# ---- 点 7：中等规模随机（范围中间档） ----
n, m = rand_pair(10000, 100000, 100000)
gen_case(7, n, m, "中等规模随机：n∈[1e4,1e5]，m∈[1,min(1e5,1.25n)]")

# ---- 点 8：大规模随机（贴近自定上限） ----
n, m = rand_pair(500000, CAP, CAP)
gen_case(8, n, m, "大规模随机：n∈[5e5,1e6]，m∈[1,min(1e6,1.25n)]，贴近上限")

# ---- 点 9-10：顶格层（按题型构造极端权值） ----
# 点 9：n、m 同时取上限 -> 全最大值，答案 200000.00。
gen_case(9, CAP, CAP, "顶格层全最大：n=m=1e6 -> 200000.00")

# 点 10：n 取上限、m 取下界 0 -> 答案最大 1000000.00（极端权值：m 最小 / 答案最大）。
gen_case(10, CAP, 0, "顶格层极端权值：n=1e6 顶格、m=0 下界 -> 答案最大 1000000.00")
