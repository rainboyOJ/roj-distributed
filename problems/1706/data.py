#!/usr/bin/env python3
# -*- coding: utf-8 -*-
#
# 一本通 1706《串包含问题》分层数据生成器（cyaron）
# ---------------------------------------------------------------------------
# 题意：给定正整数 m 与 n 个 01 串 s_1..s_n，求长度为 2m 的「反对称」串中、
#       包含全部 n 个模式串作为子串的个数，对 998244353 取模。
#       反对称：对 1<=i<=|s| 有 s[i] != s[|s|-i+1]。
#
# 结构（生成器与标程共用的关键事实）：
#   长度 2m 的反对称串由前 m 位 T 完全确定：S = T + ~reverse(T)，
#   其中 ~reverse(T) = complement(reverse(T))。故答案 = #T in {0,1}^m，S 含全部模式。
#
# 数据范围（题面【数据规模】）：
#   10%  m <= 15
#   40%  n <= 4, |s_i| <= 20
#   60%  n <= 6, |s_i| <= 30, m <= 100
#   另 20%  n = 1
#   100% n <= 6, |s_i| <= 100, m <= 500
#   （time 1000ms / memory 256MB）
#
# 设计原则（本文件相对旧版重做）：**绝大多数测试点答案非 0**。
#   做法：先随机取目标 T0，令 S0 = anti(T0)，再让模式串取自 S0 的**窗口**
#   （window 函数），于是 S0 本身必然是合法解，答案 >= 1；
#   同时通过 where 参数控制窗口落在左半 / 右半 / **跨中点**，
#   从而稳定覆盖标程里三条命中路径（左半子串、右半逆补子串、横跨中点）。
#   只有点 2 是刻意构造的「答案为 0」边界。
#
# 分层表（10 组，随机数均用 random.Random(1706*10+i) 独立种子，可复现）：
#   点 1  边界层：n=1, m=1, s="0"        —— 最小规模；手算答案 2
#   点 2  边界层：n=1, m=1, s="00"       —— |s|=2m 但本身不反对称；手算答案 0
#   点 3  边界层：n=1, m=2, s="0011"     —— |s|=2m 且自身反对称，唯一解；手算答案 1
#   点 4  小规模结构：n=2, m=4, s="0","1" —— 任意反对称串 0/1 均出现；手算答案 2^4=16
#   点 5  小规模随机：n=4, m=15, |s_i|∈[16,20] 全部跨中点
#                     —— 同时顶格 10%(m<=15) 与 40%(n<=4,|s|<=20) 两档
#   点 6  中等规模随机：n=6, m=100, |s_i|<=30，含「一模式是另一模式的子串」
#                     —— 顶格 60% 档，检验"包含关系"下的集合掩码
#   点 7  大规模随机：n=6, m=300, 长度混合 1/17/55/100/100/3
#   点 8  大规模长模式：n=6, m=400, |s_i|∈[50,100]，含 2m=800 附近的长串
#   点 9  顶格层：n=6, m=500, |s_i|=100 全部顶格，窗口覆盖 左/右/跨中点 三路
#   点 10 顶格结构层：n=6, m=500, |s_i|=100，全 0 串 / 全 1 串 / 周期 "01"*50 /
#                     中点两侧 0^50+1^50 / 重复值 —— 卡结构 + 重复模式去重
# ---------------------------------------------------------------------------

from cyaron import *  # 引入CYaRon的库

import random  # 显式引入（cyaron 的 star-import 不保证导出 random）

CASE_SEED = 1706


# ---------------------------------------------------------------- 基础工具
def comp(s):
    """按位取反。"""
    return ''.join('1' if c == '0' else '0' for c in s)


def revc(s):
    """~reverse(s)：先反转再取反。"""
    return comp(s)[::-1]


def anti(T):
    """由前 m 位 T 生成唯一确定的长度 2m 反对称串：S = T + ~reverse(T)。"""
    return T + revc(T)


def rnd01(L, rnd):
    return ''.join(rnd.choice('01') for _ in range(L))


def window(S, L, rnd, where="any"):
    """取 S 中长度 L 的随机窗口。
    where="left"  : 窗口整体落在左半段 [0,m)
    where="right" : 窗口整体落在右半段 [m,2m)
    where="cross" : 窗口横跨中点（同时含 m-1 与 m 两个位置）
    where="any"   : 任意位置
    越界时自动退化为 any，保证总能取到窗口。
    """
    m = len(S) // 2
    lo, hi = 0, len(S) - L
    if where == "cross":
        l2, h2 = max(0, m - L + 1), min(hi, m - 1)
        if l2 <= h2:
            lo, hi = l2, h2
    elif where == "left":
        h2 = min(hi, m - L)
        if 0 <= h2:
            lo, hi = 0, h2
    elif where == "right":
        lo = m
    return S[rnd.randint(lo, hi):][:L]


def write_case(i, n, m, pats, note):
    """写出 problem<i>.in 并用标程生成 problem<i>.out。"""
    assert len(pats) == n
    assert all(1 <= len(p) <= 100 for p in pats), (i, [len(p) for p in pats])
    io = IO(file_prefix="problem", data_id=i)  # problem<i>.in / problem<i>.out
    io.input_writeln(n, m)
    for p in pats:
        io.input_writeln(p)
    io.output_gen("../std")  # 用已编译的标程生成答案
    print(f"[{i:2d}] n={n} m={m} lens={[len(p) for p in pats]}  {note}")


# ---------------------------------------------------------------- 点 1-4：边界层 / 小规模结构
# 点 1：n=1, m=1, s="0"。S ∈ {01,10} 均含 "0" -> 答案 2（手算）。
write_case(1, 1, 1, ["0"], "边界最小：n=1,m=1；手算答案 2")

# 点 2：n=1, m=1, s="00"。|s|=2=2m，唯一候选 S 只能是 "00" 本身，
# 而 "00" 不满足反对称（s[1]==s[2]）-> 答案 0（手算）。全题唯一答案 0 的点。
write_case(2, 1, 1, ["00"], "边界：|s|=2m 且不反对称；手算答案 0")

# 点 3：n=1, m=2, s="0011"。2m=4，唯一的 4 个反对称串是 0011/0101/1010/1100，
# 只有 0011 含该模式 -> 答案 1（手算）。「答案为 1」的极端。
write_case(3, 1, 2, ["0011"], "边界：|s|=2m 且自身反对称，唯一解；手算答案 1")

# 点 4：n=2, m=4, s="0","1"。任意反对称串长度 2m 上都有 s[i]!=s[2m+1-i]，
# 故 0 与 1 必然都出现 -> 答案 = 2^m = 16（手算）。
write_case(4, 2, 4, ["0", "1"], "小规模结构：全 1 位模式；手算答案 2^4=16")

# ---------------------------------------------------------------- 点 5：小规模随机（跨中点）
# n=4, m=15, |s_i| ∈ [16,20] 全部 > m：模式无法整体落在任一半段，
# 必须走「横跨中点」路径。同时顶格 m<=15（10%档）与 n<=4,|s|<=20（40%档）。
r5 = random.Random(CASE_SEED * 10 + 5)
T5 = rnd01(15, r5)
S5 = anti(T5)
lens5 = [16, 18, 20, 17]
pats5 = [window(S5, L, r5, "cross") for L in lens5]
write_case(5, 4, 15, pats5, "40%顶格 + 全部跨中点（|s|>m）")

# ---------------------------------------------------------------- 点 6：中等规模（60%档顶格）
# n=6, m=100, |s_i| <= 30：顶格 60% 档。其中 pats[1] 是 pats[0] 的子串，
# 检验「包含关系」下掩码必须把所有位都覆盖到。
r6 = random.Random(CASE_SEED * 10 + 6)
T6 = rnd01(100, r6)
S6 = anti(T6)
base6 = window(S6, 30, r6, "any")
pats6 = [base6, base6[5:12], window(S6, 22, r6), window(S6, 15, r6),
         window(S6, 9, r6, "cross"), window(S6, 25, r6)]
write_case(6, 6, 100, pats6, "60%档顶格；含模式包含关系（s2 是 s1 的子串）")

# ---------------------------------------------------------------- 点 7：大规模随机
# n=6, m=300，模式长度混合 1 / 17 / 55 / 100 / 100 / 3，窗口位置混合
# 左半 / 右半 / 跨中点，覆盖标程三条命中路径。
r7 = random.Random(CASE_SEED * 10 + 7)
T7 = rnd01(300, r7)
S7 = anti(T7)
pats7 = [window(S7, 1, r7, "right"), window(S7, 17, r7, "left"),
         window(S7, 100, r7, "cross"), window(S7, 55, r7, "right"),
         window(S7, 100, r7, "left"), window(S7, 3, r7, "cross")]
write_case(7, 6, 300, pats7, "大规模随机；长度 1~100 混合，三路命中")

# ---------------------------------------------------------------- 点 8：大规模长模式
# n=6, m=400, |s_i| ∈ [50,100]，全部为长模式（相对 m 仍较短），
# 其中 2 条 100 长跨中点；另含一条取自右半段的 100 长串（走"右半 = 逆补"路径）。
r8 = random.Random(CASE_SEED * 10 + 8)
T8 = rnd01(400, r8)
S8 = anti(T8)
pats8 = [window(S8, 50, r8, "left"), window(S8, 100, r8, "cross"),
         window(S8, 73, r8, "right"), window(S8, 100, r8, "right"),
         window(S8, 99, r8, "cross"), window(S8, 61, r8, "left")]
write_case(8, 6, 400, pats8, "大规模长模式（|s|∈[50,100]，含跨中点）")

# ---------------------------------------------------------------- 点 9：顶格层（题面上限）
# n=6, m=500, |s_i|=100：n、m、|s| 三项全部顶格。窗口分配
# 2 左半 + 2 右半 + 2 跨中点，三条命中路径各覆盖两次。
r9 = random.Random(CASE_SEED * 10 + 9)
T9 = rnd01(500, r9)
S9 = anti(T9)
pats9 = [window(S9, 100, r9, "left"), window(S9, 100, r9, "right"),
         window(S9, 100, r9, "cross"), window(S9, 100, r9, "cross"),
         window(S9, 100, r9, "left"), window(S9, 100, r9, "right")]
write_case(9, 6, 500, pats9, "顶格：n=6,m=500,|s|=100；左/右/跨中 三路各 2 条")

# ---------------------------------------------------------------- 点 10：顶格结构层（卡结构）
# n=6, m=500, |s_i|=100，显式构造 T0 使其分块极规整，再取 S0 = anti(T0) 的固定窗口：
#   T0[0:150]   = 0^150     -> 窗口 [0,100)    : 全 0 串 0^100
#   T0[150:300] = 1^150     -> 窗口 [150,250)  : 全 1 串 1^100
#   T0[300:400] = "01"*50   -> 窗口 [300,400)  : 纯周期串 "01"*50
#   T0[400:450] = "10"*25, T0[450:500] = 0^50 -> 窗口 [450,550): 恰在中点处
#                                               由 0^50 切到 1^50（"0^50+1^50"）
#   窗口 [475,575)          : 偏中点的普通串
#   s6 = s1（重复值）        : 重复模式必须只占一个语义位（答案与不重复时同解集）
# 全部窗口都取自同一个 S0，故答案 >= 1；同时 6 条模式两两不同前缀多，
# 使 AC 自动机节点数接近上限（2*sum|s| = 1200）——卡常/卡状态数结构。
r10 = random.Random(CASE_SEED * 10 + 10)
T10 = '0' * 150 + '1' * 150 + '01' * 50 + '10' * 25 + '0' * 50
assert len(T10) == 500, len(T10)
S10 = anti(T10)
pats10 = [S10[0:100], S10[150:250], S10[300:400],
          S10[450:550], S10[475:575], S10[0:100]]
assert pats10[0] == '0' * 100
assert pats10[2] == '01' * 50
assert pats10[3] == '0' * 50 + '1' * 50
write_case(10, 6, 500, pats10, "顶格结构：全0/全1/周期/中点切分/重复值")
